package stuntgres_test

import (
	"context"
	"fmt"
	"strings"
	"stuntgres"
	"testing"
)

func TestSerialDeferredDefaultRestoreAtomicity(t *testing.T) {
	for _,definition := range []string{`nextval('missing')`,`nextval('consumer')`,`nextval('producer_id_seq')+1`,`7`,`NULL`,`nextval($1)`} {
		t.Run(fmt.Sprint(definition),func(t *testing.T) {
			db := openLocal(t,stuntgres.NewDriver(),t.Name())
			tableCoreExec(t,db,false,`CREATE TABLE sentinel(id SERIAL)`,0)
			tableCoreExec(t,db,false,`INSERT INTO sentinel DEFAULT VALUES`,1)
			rows,err := db.Query(`SELECT id FROM sentinel`)
			if err != nil { t.Fatal(err) }; defer rows.Close()
			dump := `CREATE TABLE producer(id BIGINT GENERATED BY DEFAULT AS IDENTITY); CREATE TABLE consumer(id INT); ALTER TABLE consumer ALTER id SET DEFAULT `+definition+`;`
			if err := stuntgres.Restore(context.Background(),db,strings.NewReader(dump)); err==nil { t.Fatal("accepted invalid deferred default",definition) }
			if !rows.Next() { t.Fatal("failed restore invalidated held rows",rows.Err()) }
			var old int64
			if err := rows.Scan(&old); err != nil || old!=1 { t.Fatal(old,err) }
			rows.Close()
			tableCoreExec(t,db,true,`INSERT INTO sentinel DEFAULT VALUES`,1)
			wantTuples(t,db,`SELECT id FROM sentinel ORDER BY id`,[][]any{{int64(1)},{int64(2)}})
			if _,err := db.Exec(`CREATE TABLE producer(id SERIAL)`); err!=nil { t.Fatal("failed restore leaked candidate relations",err) }
		})
	}
}
