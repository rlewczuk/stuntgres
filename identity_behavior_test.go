func TestIdentityOverride(t *testing.T) {
	for _, prepared := range []bool{false, true} {
		t.Run(fmt.Sprint(prepared), func(t *testing.T) {
			db := openLocal(t, stuntgres.NewDriver(), t.Name())
			exec := func(q string, n int64) { tableCoreExec(t, db, prepared, q, n) }
			exec(`CREATE TABLE a(id INT GENERATED ALWAYS AS IDENTITY,p INT DEFAULT 7)`, 0)
			_, err := db.Exec(`INSERT INTO a VALUES(99,8)`)
			typeCoreDiagnostic(t, err, stuntgres.Error{Code: "428C9", Message: `cannot insert a non-DEFAULT value into column "id"`, Detail: `Column "id" is an identity column defined as GENERATED ALWAYS.`, Hint: "Use OVERRIDING SYSTEM VALUE to override."})
			exec(`INSERT INTO a OVERRIDING SYSTEM VALUE VALUES(99,8)`, 1)
			exec(`INSERT INTO a DEFAULT VALUES`, 1)
			exec(`INSERT INTO a OVERRIDING USER VALUE VALUES(99,9)`, 1)
			exec(`INSERT INTO a VALUES(DEFAULT,DEFAULT)`, 1)
			wantTuples(t, db, `SELECT * FROM a ORDER BY id`, [][]any{{int64(1), int64(7)}, {int64(2), int64(9)}, {int64(3), int64(7)}, {int64(99), int64(8)}})
			exec(`CREATE TABLE b(id INT GENERATED BY DEFAULT AS IDENTITY)`, 0)
			exec(`INSERT INTO b DEFAULT VALUES`, 1)
			exec(`INSERT INTO b VALUES(99)`, 1)
			exec(`INSERT INTO b VALUES(DEFAULT)`, 1)
			wantTuples(t, db, `SELECT * FROM b ORDER BY id`, [][]any{{int64(1)}, {int64(2)}, {int64(99)}})
		})
	}
}

func TestIdentityOptions(t *testing.T) {
	db := openLocal(t, stuntgres.NewDriver(), t.Name())
	c := sequenceConn(t, db)
	sequenceExec(t, c, `CREATE TABLE opt(id INT GENERATED BY DEFAULT AS IDENTITY(START 7 INCREMENT 3 CACHE 1))`)
	for range 2 {
		tableCoreExec(t, db, false, `INSERT INTO opt DEFAULT VALUES`, 1)
	}
	sequenceExec(t, c, `ALTER TABLE opt ALTER id SET START 20`)
	tableCoreExec(t, db, false, `INSERT INTO opt DEFAULT VALUES`, 1)
	sequenceExec(t, c, `ALTER TABLE opt ALTER id RESTART`)
	tableCoreExec(t, db, false, `INSERT INTO opt DEFAULT VALUES`, 1)
	wantTuples(t, db, `SELECT * FROM opt ORDER BY id`, [][]any{{int64(7)}, {int64(10)}, {int64(13)}, {int64(20)}})
	sequenceExec(t, c, `CREATE TABLE narrow(id SMALLINT GENERATED ALWAYS AS IDENTITY)`)
	sequenceExec(t, c, `ALTER SEQUENCE narrow_id_seq AS bigint MAXVALUE 100000 RESTART WITH 32768`)
	if _, err := c.ExecContext(context.Background(), `INSERT INTO narrow DEFAULT VALUES`); err != nil {
		t.Fatal(err)
	}
	sequenceValue(t, c, `SELECT id FROM narrow`, -32768)
	sequenceValue(t, c, `SELECT currval('narrow_id_seq')`, 32768)
}

func TestIdentityAlter(t *testing.T) {
	db := openLocal(t, stuntgres.NewDriver(), t.Name())
	c := sequenceConn(t, db)
	sequenceExec(t, c, `CREATE TABLE a(id INT NOT NULL)`)
	tableCoreExec(t, db, false, `INSERT INTO a VALUES(40)`, 1)
	sequenceExec(t, c, `ALTER TABLE a ALTER id ADD GENERATED BY DEFAULT AS IDENTITY`)
	held, err := c.PrepareContext(context.Background(), `INSERT INTO a DEFAULT VALUES`)
	if err != nil {
		t.Fatal(err)
	}
	defer held.Close()
	if _, err = held.ExecContext(context.Background()); err != nil {
		t.Fatal(err)
	}
	sequenceExec(t, c, `ALTER TABLE a ALTER id SET GENERATED ALWAYS SET INCREMENT 3 RESTART WITH 20`)
	if _, err = held.ExecContext(context.Background()); err != nil {
		t.Fatal(err)
	}
	wantTuples(t, db, `SELECT * FROM a ORDER BY id`, [][]any{{int64(1)}, {int64(20)}, {int64(40)}})
	sequenceExec(t, c, `ALTER TABLE a ALTER id DROP IDENTITY`)
	_, err = held.ExecContext(context.Background())
	if err == nil {
		t.Fatal("dropped identity generated")
	}
	tableCoreExec(t, db, false, `INSERT INTO a VALUES(55)`, 1)
}

func TestIdentityTransactions(t *testing.T) {
	db := openLocal(t, stuntgres.NewDriver(), t.Name())
	c := sequenceConn(t, db)
	ctx := context.Background()
	sequenceExec(t, c, `CREATE TABLE txi(id INT GENERATED ALWAYS AS IDENTITY)`)
	insert := func() {
		t.Helper()
		if _, err := c.ExecContext(ctx, `INSERT INTO txi DEFAULT VALUES`); err != nil {
			t.Fatal(err)
		}
	}
	insert()
	sequenceExec(t, c, `BEGIN`)
	sequenceExec(t, c, `ALTER TABLE txi ALTER id RESTART WITH 100`)
	insert()
	sequenceExec(t, c, `ROLLBACK`)
	insert()
	sequenceExec(t, c, `BEGIN`)
	sequenceExec(t, c, `SAVEPOINT s`)
	sequenceExec(t, c, `ALTER TABLE txi ALTER id DROP IDENTITY`)
	sequenceExec(t, c, `ROLLBACK TO s`)
	insert()
	sequenceExec(t, c, `COMMIT`)
	sequenceExec(t, c, `BEGIN`)
	insert()
	sequenceExec(t, c, `ROLLBACK`)
	insert()
	wantTuples(t, db, `SELECT * FROM txi ORDER BY id`, [][]any{{int64(1)}, {int64(2)}, {int64(3)}, {int64(5)}})
}

func TestIdentityLifecycle(t *testing.T) {
	db := openLocal(t, stuntgres.NewDriver(), t.Name())
	c := sequenceConn(t, db)
	sequenceExec(t, c, `CREATE TABLE life(a INT GENERATED ALWAYS AS IDENTITY,b INT,c INT GENERATED BY DEFAULT AS IDENTITY)`)
	_, err := c.ExecContext(context.Background(), `DROP SEQUENCE life_a_seq CASCADE`)
	typeCoreDiagnostic(t, err, stuntgres.Error{Code: "2BP01", Message: "cannot drop sequence life_a_seq because column a of table life requires it", Hint: "You can drop column a of table life instead."})
	_, err = c.ExecContext(context.Background(), `ALTER SEQUENCE life_a_seq OWNED BY NONE`)
	typeCoreDiagnostic(t, err, stuntgres.Error{Code: "0A000", Message: "cannot change ownership of identity sequence", Detail: `Sequence "life_a_seq" is linked to table "life".`})
	sequenceExec(t, c, `ALTER TABLE life DROP COLUMN b`)
	sequenceExec(t, c, `ALTER TABLE life RENAME COLUMN c TO other`)
	tableCoreExec(t, db, false, `INSERT INTO life DEFAULT VALUES`, 1)
	wantTuples(t, db, `SELECT * FROM life`, [][]any{{int64(1), int64(1)}})
	sequenceExec(t, c, `ALTER TABLE life DROP COLUMN a`)
	sequenceExec(t, c, `DROP TABLE life`)
	_, err = c.ExecContext(context.Background(), `SELECT nextval('life_c_seq')`)
	if err == nil {
		t.Fatal("owned sequence survives")
	}
}

