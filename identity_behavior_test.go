func TestIdentityDiagnostics(t *testing.T) {
	db := openLocal(t, stuntgres.NewDriver(), t.Name())
	tableCoreExec(t, db, false, `CREATE TABLE diag(id INT GENERATED ALWAYS AS IDENTITY)`, 0)
	for _, q := range []string{`INSERT INTO diag VALUES(NULL)`, `INSERT INTO diag SELECT 99 FROM diag WHERE false`} {
		_, err := db.Exec(q)
		typeCoreDiagnostic(t, err, stuntgres.Error{Code: "428C9", Message: `cannot insert a non-DEFAULT value into column "id"`, Detail: `Column "id" is an identity column defined as GENERATED ALWAYS.`, Hint: "Use OVERRIDING SYSTEM VALUE to override."})
	}
	stmt, err := db.Prepare(`INSERT INTO diag VALUES($1)`)
	if stmt != nil {
		stmt.Close()
	}
	if err == nil {
		t.Fatal("ALWAYS prepared supplied value accepted")
	}
	for _, q := range []string{`ALTER TABLE diag ALTER id DROP NOT NULL`, `ALTER TABLE diag ALTER id SET DEFAULT 4`, `ALTER TABLE diag ALTER id DROP DEFAULT`} {
		_, err := db.Exec(q)
		if err == nil {
			t.Fatal(q)
		}
	}
}

