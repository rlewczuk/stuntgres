func TestIdentityControls(t *testing.T) {
	db := openLocal(t, stuntgres.NewDriver(), t.Name())
	ctx := context.Background()
	tableCoreExec(t, db, false, `CREATE TABLE narrow(id SMALLINT GENERATED ALWAYS AS IDENTITY)`, 0)
	tableCoreExec(t, db, false, `ALTER SEQUENCE narrow_id_seq AS bigint MAXVALUE 100000 RESTART WITH 32768`, 0)
	tableCoreExec(t, db, false, `INSERT INTO narrow DEFAULT VALUES`, 1)
	var dump bytes.Buffer
	if err := stuntgres.Dump(ctx, db, &dump); err != nil {
		t.Fatal(err)
	}
	if err := stuntgres.Reset(ctx, db); err != nil {
		t.Fatal(err)
	}
	if err := stuntgres.Restore(ctx, db, bytes.NewReader(dump.Bytes())); err != nil {
		t.Fatal(err)
	}
	var again bytes.Buffer
	if err := stuntgres.Dump(ctx, db, &again); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(dump.Bytes(), again.Bytes()) {
		t.Fatalf("redump mismatch\n%s\n%s", dump.Bytes(), again.Bytes())
	}
	tableCoreExec(t, db, false, `INSERT INTO narrow DEFAULT VALUES`, 1)
	wantTuples(t, db, `SELECT * FROM narrow ORDER BY id`, [][]any{{int64(-32768)}, {int64(-32767)}})
	if err := stuntgres.Restore(ctx, db, bytes.NewBufferString(`CREATE TABLE replacement(id INT GENERATED ALWAYS AS IDENTITY); INSERT INTO replacement VALUES(9);`)); err == nil {
		t.Fatal("malformed restore accepted")
	}
	wantTuples(t, db, `SELECT * FROM narrow ORDER BY id`, [][]any{{int64(-32768)}, {int64(-32767)}})
}
