package stuntgres_test

import (
	"bytes"
	"context"
	"stuntgres"
	"testing"
)

func TestSerialDefaultIdentityDumpOrdering(t *testing.T) {
	for _,cycle := range []bool{false,true} {
		t.Run(map[bool]string{false:"later-provider",true:"legal-cycle"}[cycle],func(t *testing.T) {
			db := openLocal(t,stuntgres.NewDriver(),t.Name())
			queries := []string{`CREATE TABLE consumer(id SERIAL)`,`CREATE TABLE producer(id BIGINT GENERATED BY DEFAULT AS IDENTITY)`,`ALTER TABLE consumer ALTER id SET DEFAULT nextval('producer_id_seq')`,`SELECT setval('producer_id_seq',7,true)`,`INSERT INTO consumer VALUES(40)`}
			if cycle {
				queries = []string{`CREATE TABLE lhs(id BIGINT GENERATED BY DEFAULT AS IDENTITY,s SERIAL)`,`CREATE TABLE rhs(id BIGINT GENERATED BY DEFAULT AS IDENTITY,s SERIAL)`,`ALTER TABLE lhs ALTER s SET DEFAULT nextval('rhs_id_seq')`,`ALTER TABLE rhs ALTER s SET DEFAULT nextval('lhs_id_seq')`,`SELECT setval('lhs_id_seq',7,true)`,`SELECT setval('rhs_id_seq',20,true)`,`INSERT INTO lhs VALUES(100,200)`,`INSERT INTO rhs VALUES(300,400)`}
			}
			for _,q := range queries { if _,err := db.Exec(q); err != nil { t.Fatal(q,err) } }
			var dump bytes.Buffer
			ctx := context.Background()
			if err := stuntgres.Dump(ctx,db,&dump); err != nil { t.Fatal("supported identity-provider dump",err) }
			if err := stuntgres.Reset(ctx,db); err != nil { t.Fatal(err) }
			if err := stuntgres.Restore(ctx,db,bytes.NewReader(dump.Bytes())); err != nil { t.Fatal("identity-provider dump is not replayable",err) }
			if cycle {
				tableCoreExec(t,db,false,`INSERT INTO lhs DEFAULT VALUES`,1)
				tableCoreExec(t,db,true,`INSERT INTO rhs DEFAULT VALUES`,1)
				wantTuples(t,db,`SELECT * FROM lhs ORDER BY id`,[][]any{{int64(8),int64(21)},{int64(100),int64(200)}})
				wantTuples(t,db,`SELECT * FROM rhs ORDER BY id`,[][]any{{int64(22),int64(9)},{int64(300),int64(400)}})
			} else {
				tableCoreExec(t,db,true,`INSERT INTO consumer DEFAULT VALUES`,1)
				tableCoreExec(t,db,false,`INSERT INTO producer DEFAULT VALUES`,1)
				wantTuples(t,db,`SELECT * FROM consumer ORDER BY id`,[][]any{{int64(8)},{int64(40)}})
				wantTuples(t,db,`SELECT * FROM producer`,[][]any{{int64(9)}})
			}
		})
	}
}
