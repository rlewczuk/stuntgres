func TestReferenceIdentityControlsCurrentDefinitions(t *testing.T) {
	p := newReferencePair(t)
	for _, db := range []*sql.DB{p.memory, p.postgres} {
		identityRefExec(t, db, `CREATE ROLE identity_owner`, 0)
	}
	for _, q := range []string{`CREATE SCHEMA owned AUTHORIZATION identity_owner CREATE TABLE i(id INT CONSTRAINT id_nn GENERATED ALWAYS AS IDENTITY(START 7 INCREMENT 3 CACHE 2),p INT DEFAULT 4) CREATE TABLE u(id INT GENERATED BY DEFAULT AS IDENTITY(UNLOGGED START 9))`, `COMMENT ON TABLE owned.i IS 'identity table'`, `COMMENT ON COLUMN owned.i.id IS 'identity attribute'`, `COMMENT ON SEQUENCE owned.i_id_seq IS 'identity sequence'`, `INSERT INTO owned.i DEFAULT VALUES`, `INSERT INTO owned.i OVERRIDING SYSTEM VALUE VALUES(99,8)`, `INSERT INTO owned.u VALUES(88)`} {
		count := int64(0)
		if len(q) >= 6 && q[:6] == "INSERT" {
			count = 1
		}
		identityRefExec(t, p.memory, q, count)
	}
	var dump bytes.Buffer
	if err := stuntgres.Dump(p.ctx, p.native, &dump); err != nil {
		t.Fatal(err)
	}
	if _, err := p.postgres.ExecContext(p.ctx, dump.String()); err != nil {
		t.Fatal(err)
	}
	if err := stuntgres.Reset(p.ctx, p.native); err != nil {
		t.Fatal(err)
	}
	if err := stuntgres.Restore(p.ctx, p.native, bytes.NewReader(dump.Bytes())); err != nil {
		t.Fatal(err)
	}
	for _, db := range []*sql.DB{p.memory, p.postgres} {
		identityRefRows(t, db, `SELECT * FROM owned.i ORDER BY id`, [][]int64{{7, 4}, {99, 8}})
		identityRefExec(t, db, `INSERT INTO owned.i DEFAULT VALUES`, 1)
		identityRefExec(t, db, `INSERT INTO owned.u DEFAULT VALUES`, 1)
		identityRefRows(t, db, `SELECT * FROM owned.i ORDER BY id`, [][]int64{{7, 4}, {13, 4}, {99, 8}})
		identityRefRows(t, db, `SELECT * FROM owned.u ORDER BY id`, [][]int64{{9}, {88}})
	}
	var tableOwner, sequenceOwner, persistence, comment string
	if err := p.postgres.QueryRowContext(p.ctx, `SELECT pg_get_userbyid(relowner) FROM pg_class WHERE oid='owned.i'::regclass`).Scan(&tableOwner); err != nil {
		t.Fatal(err)
	}
	if err := p.postgres.QueryRowContext(p.ctx, `SELECT pg_get_userbyid(relowner),obj_description(oid) FROM pg_class WHERE oid='owned.i_id_seq'::regclass`).Scan(&sequenceOwner, &comment); err != nil {
		t.Fatal(err)
	}
	if tableOwner != "identity_owner" || sequenceOwner != tableOwner || comment != "identity sequence" {
		t.Fatal(tableOwner, sequenceOwner, comment)
	}
	if err := p.postgres.QueryRowContext(p.ctx, `SELECT relpersistence FROM pg_class WHERE oid='owned.u_id_seq'::regclass`).Scan(&persistence); err != nil || persistence != "u" {
		t.Fatal(persistence, err)
	}
}

func TestReferenceIdentityInsertOnlyAuthority(t *testing.T) {
	p := newReferencePair(t)
	c, err := p.postgres.Conn(p.ctx)
	if err != nil {
		t.Fatal(err)
	}
	defer c.Close()
	for _, q := range []string{`CREATE TABLE secured(id INT GENERATED ALWAYS AS IDENTITY)`, `CREATE ROLE identity_writer`, `GRANT USAGE ON SCHEMA public TO identity_writer`, `GRANT INSERT ON secured TO identity_writer`, `SET ROLE identity_writer`} {
		sequenceProbeExec(t, p.ctx, c, q)
	}
	identityRefConnExec(t, p.ctx, c, `INSERT INTO secured DEFAULT VALUES`, 1)
	_, err = c.ExecContext(p.ctx, `SELECT nextval('secured_id_seq')`)
	want := controlsReferenceDiagnostic("42501", "permission denied for sequence secured_id_seq")
	referenceAssertDiagnostic(t, err, &want)
	sequenceProbeExec(t, p.ctx, c, `RESET ROLE`)
	sequenceProbeValue(t, p.ctx, c, `SELECT id FROM secured`, 1)
}
