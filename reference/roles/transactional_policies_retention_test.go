package reference_test

import (
	"stuntgres/reference/fixture"
	"testing"
)

func TestReferenceTransactionalPoliciesRetention(t *testing.T) {
	transactionalPolicyMatrix(t, []string{"sql", "go"}, func(s *transactionalPolicies, mode string) {
		s.exec("CREATE POLICY p ON t AS PERMISSIVE FOR SELECT TO tp_group USING(id<=2)")
		s.exec("CREATE POLICY r ON t AS RESTRICTIVE FOR SELECT TO PUBLIC USING(allowed)")
		s.exec("CREATE POLICY up ON t FOR UPDATE TO tp_reader USING(id=1) WITH CHECK(id>0)")
		s.exec("CREATE POLICY ins ON t FOR INSERT TO tp_reader WITH CHECK(allowed)")
		s.exec("CREATE POLICY del ON t FOR DELETE TO tp_reader USING(id=1)")
		s.ids(1)
		finish := s.begin(mode)
		p := s.oid("t", "p")
		up := s.oid("t", "up")
		s.ddl("ALTER POLICY p ON t TO tp_other")
		s.facts("t", "p", "r", true, "tp_other", "(id <= 2)", "")
		s.ids()
		s.ddl("ALTER POLICY p ON t TO PUBLIC")
		s.facts("t", "p", "r", true, "public", "(id <= 2)", "")
		s.ids(1)
		s.ddl("ALTER POLICY p ON t TO tp_reader")
		s.ids(1)
		s.ddl("ALTER POLICY p ON t TO tp_group")
		s.ids(1)
		s.exec("REVOKE INHERIT OPTION FOR tp_group FROM tp_reader")
		s.ids()
		s.exec("GRANT tp_group TO tp_reader WITH INHERIT TRUE")
		s.ids(1)
		s.ddl("ALTER POLICY up ON t TO PUBLIC")
		s.ddl("ALTER POLICY up ON t USING(id<=2)")
		s.ddl("ALTER POLICY up ON t WITH CHECK(id=1)")
		s.ddl("ALTER POLICY up ON t RENAME TO updated")
		s.sameOID("t", "updated", up)
		s.facts("t", "updated", "w", true, "public", "(id <= 2)", "(id = 1)")
		s.sameOID("t", "p", p)
		s.exec("SET ROLE tp_reader")
		s.run(fixture.Exec("UPDATE t SET allowed=TRUE WHERE id=2", 0))
		s.run(fixture.Exec("UPDATE t SET allowed=TRUE WHERE id=1", 1))
		s.run(fixture.Exec("INSERT INTO t VALUES(4,TRUE)", 1))
		s.exec("SAVEPOINT invalid_insert")
		s.failure("INSERT INTO t VALUES(5,FALSE)", "42501", `new row violates row-level security policy for table "t"`)
		s.exec("ROLLBACK TO invalid_insert")
		s.failure("INSERT INTO t VALUES(5,NULL)", "42501", `new row violates row-level security policy for table "t"`)
		s.exec("ROLLBACK TO invalid_insert")
		s.failure("UPDATE t SET id=7 WHERE id=1", "42501", `new row violates row-level security policy for table "t"`)
		s.exec("ROLLBACK TO invalid_insert")
		s.run(fixture.Exec("DELETE FROM t WHERE id=1", 1))
		s.exec("RESET ROLE")
		s.ids()
		finish(false)
		s.ids(1)
		s.sameOID("t", "up", up)
		s.facts("t", "up", "w", true, "tp_reader", "(id = 1)", "(id > 0)")
		// Absent CHECK uses USING on NEW, unlike an explicitly retained CHECK.
		finish = s.begin(mode)
		s.ddl("DROP POLICY up ON t")
		s.ddl("CREATE POLICY up ON t FOR UPDATE TO tp_reader USING(id=1)")
		s.facts("t", "up", "w", true, "tp_reader", "(id = 1)", "")
		s.exec("SET ROLE tp_reader")
		s.exec("SAVEPOINT fallback")
		s.failure("UPDATE t SET id=2 WHERE id=1", "42501", `new row violates row-level security policy for table "t"`)
		s.exec("ROLLBACK TO fallback")
		s.exec("RESET ROLE")
		finish(false)
		// Table flags remain transactional and disabling RLS retains policies.
		finish = s.begin(mode)
		s.ddl("ALTER POLICY p ON t USING(FALSE)")
		s.ids()
		s.exec("ALTER TABLE t DISABLE ROW LEVEL SECURITY")
		s.facts("t", "p", "r", true, "tp_group", "false", "")
		s.ids(1, 2, 3)
		s.exec("ALTER TABLE t ENABLE ROW LEVEL SECURITY")
		s.ids()
		s.exec("ALTER TABLE t FORCE ROW LEVEL SECURITY")
		s.run(fixture.Select("SELECT count(*) FROM t", []string{"count"}, []string{"INT8"}, [][]any{{int64(3)}}))
		s.exec("ALTER TABLE t NO FORCE ROW LEVEL SECURITY")
		finish(false)
		s.ids(1)
	})
}
