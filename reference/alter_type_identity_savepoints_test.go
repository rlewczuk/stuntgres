func alterTypeIdentityOldRows(t *testing.T, rows *sql.Rows, declaration string, seed int64) {
	t.Helper()
	typ := "INT4"
	if strings.HasPrefix(declaration, "BIGINT") {
		typ = "INT8"
	}
	metadata, err := rows.ColumnTypes()
	if err != nil || len(metadata) != 1 || metadata[0].DatabaseTypeName() != typ {
		t.Fatal(metadata, err)
	}
	if nullable, known := metadata[0].Nullable(); !known || nullable {
		t.Fatal(nullable, known)
	}
	if !rows.Next() {
		t.Fatal(rows.Err())
	}
	var value int64
	if err := rows.Scan(&value); err != nil || value != seed {
		t.Fatal(value, seed, err)
	}
	if rows.Next() || rows.Err() != nil {
		t.Fatal(rows.Err())
	}
	if err := rows.Close(); err != nil {
		t.Fatal(err)
	}
}

func TestReferenceAlterTypeIdentityPrivateSavepoints(t *testing.T) {
	for _, cache := range []int{1, 5} {
		for _, commit := range []bool{false, true} {
			t.Run(fmt.Sprint(cache, commit), func(t *testing.T) {
				p := newReferenceScenario(t)
				for _, b := range p.backends() {
					t.Run(b.name, func(t *testing.T) {
						c, err := b.db.Conn(p.ctx)
						if err != nil {
							t.Fatal(err)
						}
						defer c.Close()
						defer c.ExecContext(p.ctx, "ROLLBACK")
						run := func(s referenceStep) { referenceRunStep(t, p.ctx, c, b.recorder, s) }
						run(referenceExec(fmt.Sprintf("CREATE TABLE t(c INT GENERATED BY DEFAULT AS IDENTITY(CACHE %d))", cache), 0))
						run(referenceExec("INSERT INTO t DEFAULT VALUES", 1))
						for _, q := range []string{"BEGIN", "SAVEPOINT before_type", "ALTER TABLE t ALTER c TYPE BIGINT", "SAVEPOINT after_type"} {
							run(referenceExec(q, 0))
						}
						run(referenceExec("INSERT INTO t DEFAULT VALUES", 1))
						next, last := int64(2), int64(1)
						if cache == 5 {
							next, last = 6, 5
						}
						for _, q := range []string{"ROLLBACK TO before_type", "ROLLBACK TO before_type"} {
							run(referenceExec(q, 0))
						}
						run(referenceSelect("SELECT c FROM t", []string{"c"}, []string{"INT4"}, [][]any{{int64(1)}}))
						run(referenceSelect("SELECT last_value FROM t_c_seq", []string{"last_value"}, []string{"INT8"}, [][]any{{last}}))
						run(referenceSelect("SELECT currval('t_c_seq')", []string{"currval"}, []string{"INT8"}, [][]any{{next}}))
						for _, q := range []string{"ALTER TABLE t ALTER c TYPE BIGINT", "SAVEPOINT type_again", "ALTER TABLE t ALTER c TYPE SMALLINT", "ROLLBACK TO type_again"} {
							run(referenceExec(q, 0))
						}
						run(referenceExec("INSERT INTO t DEFAULT VALUES", 1))
						action, typ, want := "ROLLBACK", "INT4", [][]any{{int64(1)}}
						if commit {
							action, typ, want = "COMMIT", "INT8", [][]any{{int64(1)}, {next}}
						}
						run(referenceExec(action, 0))
						run(referenceSelect("SELECT c FROM t ORDER BY c", []string{"c"}, []string{typ}, want))
					})
				}
			})
		}
	}
}
