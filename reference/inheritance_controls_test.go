func TestReferenceInheritanceFeatureSmoke(t *testing.T) { inheritanceScenario(t, inheritanceSmoke) }
func TestReferenceInheritanceControls(t *testing.T) {
	inheritanceScenario(t, func(s *inheritanceCase) {
		inheritanceSmoke(s)
		s.exec("CREATE TABLE root(a INT DEFAULT 7 NOT NULL,CONSTRAINT root_ck CHECK(a>0))", 0)
		s.exec("CREATE TABLE left_branch(l TEXT) INHERITS(root)", 0)
		s.exec("CREATE TABLE right_branch(r BOOL) INHERITS(root)", 0)
		s.exec("CREATE TABLE diamond(a INT DEFAULT NULL) INHERITS(left_branch,right_branch)", 0)
		s.exec("INSERT INTO diamond VALUES(3,'left',true)", 1)
		s.exec("CREATE TABLE null_p(a INT DEFAULT 7)", 0)
		s.exec("CREATE TABLE null_q(a INT DEFAULT 8)", 0)
		s.exec("CREATE TABLE null_child(a INT DEFAULT NULL) INHERITS(null_p,null_q)", 0)
		s.exec("INSERT INTO null_child DEFAULT VALUES", 1)
		s.exec("CREATE TABLE local_child(a INT CONSTRAINT own_nn NOT NULL DEFAULT 10,CONSTRAINT root_ck CHECK(a>0),UNIQUE(a)) INHERITS(root)", 0)
		s.exec("INSERT INTO local_child DEFAULT VALUES", 1)
		s.exec("CREATE TABLE generated_p(a INT DEFAULT 6,g INT GENERATED ALWAYS AS(a*2) STORED)", 0)
		s.exec("CREATE TABLE generated_c() INHERITS(generated_p)", 0)
		s.exec("INSERT INTO generated_c DEFAULT VALUES", 1)
		s.exec("CREATE TABLE serial_p(id SERIAL)", 0)
		s.exec("CREATE TABLE serial_c() INHERITS(serial_p)", 0)
		s.exec("INSERT INTO serial_c DEFAULT VALUES", 1)
		s.exec("CREATE TABLE identity_p(id BIGINT GENERATED BY DEFAULT AS IDENTITY)", 0)
		s.exec("CREATE TABLE identity_c() INHERITS(identity_p)", 0)
		s.exec("INSERT INTO identity_c VALUES(99)", 1)
		s.exec("CREATE SCHEMA inheritance_moved", 0)
		defer func() {
			if _, err := s.c.ExecContext(s.p.ctx, "DROP SCHEMA IF EXISTS inheritance_moved CASCADE"); err != nil {
				s.t.Error(err)
			}
			if s.p.postgres != nil {
				if _, err := s.p.postgres.ExecContext(s.p.ctx, "DROP SCHEMA IF EXISTS inheritance_moved CASCADE"); err != nil {
					s.t.Error(err)
				}
			}
		}()
		s.exec("ALTER TABLE p1 RENAME TO renamed_p1", 0)
		s.exec("ALTER TABLE renamed_p1 SET SCHEMA inheritance_moved", 0)
		checks := []referenceStep{
			inheritanceSmokeRows(),
			referenceSelect("SELECT * FROM local_child", []string{"a"}, []string{"INT4"}, [][]any{{int64(10)}}),
			referenceSelect("SELECT * FROM diamond", []string{"a", "l", "r"}, []string{"INT4", "TEXT", "BOOL"}, [][]any{{int64(3), "left", true}}),
			referenceSelect("SELECT * FROM null_child", []string{"a"}, []string{"INT4"}, [][]any{{nil}}),
			referenceSelect("SELECT * FROM generated_c", []string{"a", "g"}, []string{"INT4", "INT4"}, [][]any{{int64(6), int64(12)}}),
			referenceSelect("SELECT * FROM serial_c", []string{"id"}, []string{"INT4"}, [][]any{{int64(1)}}),
			referenceSelect("SELECT * FROM identity_c", []string{"id"}, []string{"INT8"}, [][]any{{int64(99)}}),
		}
		for _, check := range checks {
			s.run(check)
		}
		if s.b.pg {
			return
		}
		inheritanceRoundTrip(s, checks)
		s.edges("c", "p2", "renamed_p1")
		s.edges("diamond", "left_branch", "right_branch")
		s.exec("INSERT INTO null_child DEFAULT VALUES", 1)
		s.values("SELECT * FROM null_child", []string{"a"}, []string{"INT4"}, [][]any{{nil}, {nil}})
		s.exec("INSERT INTO generated_c(a) VALUES(8)", 1)
		s.values("SELECT * FROM generated_c ORDER BY a", []string{"a", "g"}, []string{"INT4", "INT4"}, [][]any{{int64(6), int64(12)}, {int64(8), int64(16)}})
		s.exec("INSERT INTO serial_c DEFAULT VALUES", 1)
		s.values("SELECT * FROM serial_c ORDER BY id", []string{"id"}, []string{"INT4"}, [][]any{{int64(1)}, {int64(2)}})
		s.fail("INSERT INTO identity_c DEFAULT VALUES", inheritanceNullDiagnostic("identity_c", "id", "null"))
		s.fail("ALTER TABLE diamond ALTER a DROP NOT NULL", referenceDiagnostic{Code: "42P16", Message: `cannot drop inherited constraint "root_a_not_null" of relation "diamond"`})
		s.constraints("local_child", [][]any{{"local_child_a_key", "u"}, {"own_nn", "n"}, {"root_ck", "c"}})
		s.fail("INSERT INTO local_child VALUES(10)", referenceDiagnostic{Code: "23505", Message: `duplicate key value violates unique constraint "local_child_a_key"`, Detail: "Key (a)=(10) already exists.", Schema: "public", Table: "local_child", Constraint: "local_child_a_key"})
	})
}

func TestReferenceInheritanceLocalExclusionReplay(t *testing.T) {
	inheritanceScenario(t, func(s *inheritanceCase) {
		s.exec("CREATE TABLE exclusion_parent(a INT DEFAULT 7)", 0)
		s.exec("CREATE TABLE exclusion_child(CONSTRAINT child_ex EXCLUDE USING btree(a WITH =)) INHERITS(exclusion_parent)", 0)
		s.exec("INSERT INTO exclusion_child DEFAULT VALUES", 1)
		rows := referenceSelect("SELECT * FROM exclusion_child", []string{"a"}, []string{"INT4"}, [][]any{{int64(7)}})
		conflict := referenceErrorDiagnostic("INSERT INTO exclusion_child DEFAULT VALUES", exclusionReferenceConflict("exclusion_child", "child_ex", "a", "7", "7"))
		s.run(rows)
		s.run(conflict)
		s.edges("exclusion_child", "exclusion_parent")
		if s.b.pg {
			return
		}
		s.exec("CREATE TEMP TABLE retained_exclusion_parent(v INT)", 0)
		s.exec("CREATE TEMP TABLE retained_exclusion_child(CONSTRAINT temp_child_ex EXCLUDE USING btree(v WITH =)) INHERITS(retained_exclusion_parent)", 0)
		s.exec("INSERT INTO retained_exclusion_child VALUES(9)", 1)
		var originalOID int64
		if err := s.c.QueryRowContext(s.p.ctx, "SELECT oid FROM pg_constraint WHERE conname='temp_child_ex'").Scan(&originalOID); err != nil {
			s.t.Fatal(err)
		}
		var dump bytes.Buffer
		if err := stuntgres.Dump(s.p.ctx, s.p.native, &dump); err != nil {
			s.t.Fatal(err)
		}
		if err := stuntgres.Reset(s.p.ctx, s.p.native); err != nil {
			s.t.Fatal(err)
		}
		if err := stuntgres.Restore(s.p.ctx, s.p.native, bytes.NewReader(dump.Bytes())); err != nil {
			s.t.Fatal(err)
		}
		s.run(rows)
		s.run(conflict)
		s.edges("exclusion_child", "exclusion_parent")
		var retainedOID int64
		if err := s.c.QueryRowContext(s.p.ctx, "SELECT oid FROM pg_constraint WHERE conname='temp_child_ex'").Scan(&retainedOID); err != nil {
			s.t.Fatal(err)
		}
		if retainedOID != originalOID {
			s.t.Fatalf("retained temporary exclusion identity changed: %d -> %d", originalOID, retainedOID)
		}
		s.values("SELECT * FROM retained_exclusion_child", []string{"v"}, []string{"INT4"}, [][]any{{int64(9)}})
		s.run(referenceError("INSERT INTO retained_exclusion_child VALUES(9)", "23P01"))
		s.edges("retained_exclusion_child", "retained_exclusion_parent")
		if s.p.postgres != nil {
			if _, err := s.p.postgres.ExecContext(s.p.ctx, "DROP SCHEMA public CASCADE; CREATE SCHEMA public"); err != nil {
				s.t.Fatal(err)
			}
			if _, err := s.p.postgres.ExecContext(s.p.ctx, dump.String()); err != nil {
				s.t.Fatal(err)
			}
			for _, step := range []referenceStep{rows, conflict} {
				step.prepared = s.prepared
				referenceRunStep(s.t, s.p.ctx, s.p.postgres, s.p.postgresRecord, step)
			}
		}
	})
}

func inheritanceSmoke(s *inheritanceCase) {
	s.exec("CREATE TABLE p1(a INT CONSTRAINT first_nn NOT NULL DEFAULT 7,x TEXT,CONSTRAINT ck CHECK(a>0),UNIQUE(a))", 0)
	s.exec("CREATE TABLE p2(y BOOL,a INT CONSTRAINT second_nn NOT NULL DEFAULT 7,CONSTRAINT ck CHECK(a>0))", 0)
	s.notice("CREATE TABLE c(z BIGINT,a INT DEFAULT 9) INHERITS(p1,p2)", inheritanceMergeNotice("a"), inheritanceLocalNotice("a", true))
	s.constraints("c", [][]any{{"ck", "c"}, {"first_nn", "n"}})
	names, types := []string{"a", "x", "y", "z"}, []string{"INT4", "TEXT", "BOOL", "INT8"}
	s.values("SELECT * FROM c", names, types, nil)
	referenceTableDDLMetadata(s.t, s.p.ctx, s.c, s.b.pg, s.prepared, "SELECT * FROM c", names, types, []bool{false, true, true, true}, 0)
	s.exec("INSERT INTO c(z) VALUES($1)", 1, 11)
	s.exec("INSERT INTO c(a,x,y,z) VALUES($1,$2,$3,$4)", 1, 2, "two", true, 22)
	s.exec("INSERT INTO c(a,z) VALUES(2,33)", 1)
	want := inheritanceSmokeRows()
	s.run(want)
	referenceTableDDLMetadata(s.t, s.p.ctx, s.c, s.b.pg, s.prepared, want.query, names, types, []bool{false, true, true, true}, 3)
	s.fail("INSERT INTO c(a) VALUES(-1)", inheritanceCheckDiagnostic("c", "ck", "-1, null, null, null"))
	s.fail("INSERT INTO c(a) VALUES(NULL)", inheritanceNullDiagnostic("c", "a", "null, null, null, null"))
	s.fail("INSERT INTO c(a,z) VALUES(4,44),(-1,55)", inheritanceCheckDiagnostic("c", "ck", "-1, null, null, 55"))
	s.run(want)
	s.fail("DROP TABLE p1 RESTRICT", inheritanceDropDiagnostic("p1", "c"))
	s.run(want)
	if !s.b.pg {
		inheritanceRoundTrip(s, []referenceStep{want})
		s.exec("INSERT INTO c(z) VALUES(44)", 1)
		s.values("SELECT a FROM c WHERE z=44", []string{"a"}, []string{"INT4"}, [][]any{{int64(9)}})
		s.fail("INSERT INTO c(a) VALUES(-1)", inheritanceCheckDiagnostic("c", "ck", "-1, null, null, null"))
		s.fail("INSERT INTO c(a) VALUES(NULL)", inheritanceNullDiagnostic("c", "a", "null, null, null, null"))
	}
	if !s.b.pg {
		s.fail("DROP TABLE p1 RESTRICT", inheritanceDropDiagnostic("p1", "c"))
		s.exec("DELETE FROM c WHERE z=44", 1)
		s.run(want)
	}
}

func inheritanceSmokeRows() referenceStep {
	return referenceSelect("SELECT * FROM c ORDER BY z", []string{"a", "x", "y", "z"}, []string{"INT4", "TEXT", "BOOL", "INT8"}, [][]any{{int64(9), nil, nil, int64(11)}, {int64(2), "two", true, int64(22)}, {int64(2), nil, nil, int64(33)}})
}

// This consumes the actual native stream, not a reconstructed SQL equivalent.
func inheritanceRoundTrip(s *inheritanceCase, checks []referenceStep) {
	s.t.Helper()
	var dump bytes.Buffer
	heldConn, err := s.p.native.Conn(s.p.ctx)
	if err != nil {
		s.t.Fatal(err)
	}
	defer heldConn.Close()
	var held driver.Rows
	if err = heldConn.Raw(func(raw any) error {
		var e error
		held, e = raw.(driver.QueryerContext).QueryContext(s.p.ctx, "SELECT * FROM c ORDER BY z", nil)
		return e
	}); err != nil {
		s.t.Fatal(err)
	}
	defer held.Close()
	stmt, err := s.c.PrepareContext(s.p.ctx, "SELECT a FROM c WHERE z=$1")
	if err != nil {
		s.t.Fatal(err)
	}
	defer stmt.Close()
	if err = stuntgres.Dump(s.p.ctx, s.p.native, &dump); err != nil {
		s.t.Fatal(err)
	}
	if err = stuntgres.Reset(s.p.ctx, s.p.native); err != nil {
		s.t.Fatal(err)
	}
	s.absent("c")
	if err = stuntgres.Restore(s.p.ctx, s.p.native, bytes.NewReader(dump.Bytes())); err != nil {
		s.t.Fatal(err)
	}
	for _, check := range checks {
		s.run(check)
	}
	var a int64
	if err = stmt.QueryRowContext(s.p.ctx, 11).Scan(&a); err != nil || a != 9 {
		s.t.Fatalf("held prepared result %d %v", a, err)
	}
	for _, suffix := range []string{"; CREATE TABLE bad() INHERITS(missing)", "; CREATE TABLE bad(a TEXT) INHERITS(p2)", "; INSERT INTO c(a) VALUES(-1)"} {
		if err = stuntgres.Restore(s.p.ctx, s.p.native, strings.NewReader(dump.String()+suffix)); err == nil {
			s.t.Fatal("invalid restore accepted", suffix)
		}
		for _, check := range checks {
			s.run(check)
		}
	}
	canceled, cancel := context.WithCancel(s.p.ctx)
	cancel()
	if err = stuntgres.Restore(canceled, s.p.native, bytes.NewReader(dump.Bytes())); !errors.Is(err, context.Canceled) {
		s.t.Fatal(err)
	}
	for _, check := range checks {
		s.run(check)
	}
	names, types := []string{"a", "x", "y", "z"}, []string{"INT4", "TEXT", "BOOL", "INT8"}
	if !reflect.DeepEqual(held.Columns(), names) {
		s.t.Fatal(held.Columns())
	}
	meta, ok := held.(driver.RowsColumnTypeDatabaseTypeName)
	if !ok {
		s.t.Fatal("held eager metadata unavailable")
	}
	for i, typ := range types {
		if meta.ColumnTypeDatabaseTypeName(i) != typ {
			s.t.Fatal("held eager type", i, meta.ColumnTypeDatabaseTypeName(i))
		}
	}
	cells := make([]driver.Value, 4)
	for _, row := range inheritanceSmokeRows().rows {
		if err = held.Next(cells); err != nil || !reflect.DeepEqual([]any{cells[0], cells[1], cells[2], cells[3]}, row) {
			s.t.Fatal(cells, row, err)
		}
	}
	if err = held.Next(cells); err != io.EOF {
		s.t.Fatal(err)
	}
	// Independently prove replayed graph and definitions on pinned PostgreSQL.
	if s.p.postgres != nil {
		if _, err = s.p.postgres.ExecContext(s.p.ctx, "DROP SCHEMA public CASCADE; DROP SCHEMA IF EXISTS inheritance_moved CASCADE; CREATE SCHEMA public"); err != nil {
			s.t.Fatal(err)
		}
		if _, err = s.p.postgres.ExecContext(s.p.ctx, dump.String()); err != nil {
			s.t.Fatal("actual native inheritance dump replay", err)
		}
		for _, check := range checks {
			check.prepared = s.prepared
			referenceRunStep(s.t, s.p.ctx, s.p.postgres, s.p.postgresRecord, check)
		}
		for _, check := range []referenceStep{
			referenceSelect("SELECT attname,attislocal,attinhcount FROM pg_attribute WHERE attrelid='c'::regclass AND attnum>0 AND NOT attisdropped ORDER BY attnum", []string{"attname", "attislocal", "attinhcount"}, []string{"NAME", "BOOL", "INT2"}, [][]any{{"a", true, int64(2)}, {"x", false, int64(1)}, {"y", false, int64(1)}, {"z", true, int64(0)}}),
			referenceSelect("SELECT conname,conislocal,coninhcount FROM pg_constraint WHERE conrelid='c'::regclass ORDER BY conname", []string{"conname", "conislocal", "coninhcount"}, []string{"NAME", "BOOL", "INT2"}, [][]any{{"ck", false, int64(2)}, {"first_nn", false, int64(2)}}),
		} {
			check.prepared = s.prepared
			referenceRunStep(s.t, s.p.ctx, s.p.postgres, s.p.postgresRecord, check)
		}
		check := referenceExec("INSERT INTO c(z) VALUES(77)", 1)
		check.prepared = s.prepared
		referenceRunStep(s.t, s.p.ctx, s.p.postgres, s.p.postgresRecord, check)
		check = referenceSelect("SELECT a FROM c WHERE z=77", []string{"a"}, []string{"INT4"}, [][]any{{int64(9)}})
		check.prepared = s.prepared
		referenceRunStep(s.t, s.p.ctx, s.p.postgres, s.p.postgresRecord, check)
		if _, err = s.p.postgres.ExecContext(s.p.ctx, "DROP SCHEMA public CASCADE; DROP SCHEMA IF EXISTS inheritance_moved CASCADE; CREATE SCHEMA public"); err != nil {
			s.t.Fatal(err)
		}
	}
}
