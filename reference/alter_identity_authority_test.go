package reference_test

import (
	"database/sql"
	"testing"
)

func TestReferenceAlterIdentityAuthorization(t *testing.T) {
	roleReferenceCleanup(t, []string{"alter_identity_guest"})
	alterIdentityScenario(t, func(t *testing.T, p *referencePair, b referenceBackend, c *sql.Conn) {
		run := func(s referenceStep) { referenceRunStep(t, p.ctx, c, b.recorder, s) }
		for _, q := range []string{`CREATE ROLE alter_identity_guest`, `CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY)`, `CREATE TABLE a(id INT NOT NULL)`} {
			run(referenceExec(q, 0))
		}
		// The PostgreSQL fixture restricts public-schema visibility. Native's
		// public namespace is already available and has no SQL GRANT capability.
		// This oracle setup grant is not part of the shared ALTER contract.
		if b.pg {
			run(referenceExec(`GRANT USAGE ON SCHEMA public TO alter_identity_guest`, 0))
		}
		run(referenceExec(`INSERT INTO i DEFAULT VALUES`, 1))
		run(referenceExec(`SET ROLE alter_identity_guest`, 0))
		defer c.ExecContext(p.ctx, `RESET ROLE`)
		for _, q := range []string{`ALTER TABLE a ALTER id ADD GENERATED ALWAYS AS IDENTITY`, `ALTER TABLE i ALTER id DROP IDENTITY`, `ALTER TABLE i ALTER id SET GENERATED BY DEFAULT`, `ALTER TABLE i ALTER id SET CACHE 2`, `ALTER TABLE i ALTER id RESTART 100`} {
			table := "i"
			if q == `ALTER TABLE a ALTER id ADD GENERATED ALWAYS AS IDENTITY` {
				table = "a"
			}
			for _, prepared := range []bool{false, true} {
				s := referenceImplicitError(q, referenceDiagnostic{Code: "42501", Message: `must be owner of table ` + table})
				s.prepared = prepared
				s.errorStage = "execute"
				run(s)
			}
		}
		run(referenceExec(`RESET ROLE`, 0))
		for _, q := range []string{`ALTER TABLE a ALTER id ADD GENERATED ALWAYS AS IDENTITY`, `ALTER TABLE i ALTER id DROP IDENTITY`, `ALTER TABLE i ALTER id SET GENERATED BY DEFAULT`, `ALTER TABLE i ALTER id SET CACHE 2`, `ALTER TABLE i ALTER id RESTART 100`} {
			run(referenceExec(`BEGIN READ ONLY`, 0))
			s := referenceImplicitError(q, referenceDiagnostic{Code: "25006", Message: "cannot execute ALTER TABLE in a read-only transaction"})
			s.errorStage = "execute"
			run(s)
			run(referenceExec(`ROLLBACK`, 0))
		}
		run(referenceImplicitError(`INSERT INTO i VALUES(99)`, identityAlwaysDiagnostic()))
		run(referenceSelect(`SELECT * FROM i`, []string{"id"}, []string{"INT4"}, [][]any{{int64(1)}}))
		run(referenceSelect(`SELECT last_value,is_called FROM i_id_seq`, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(1), true}}))
		alterIdentityMissing(t, p, b, c, "a_id_seq")
		run(referenceExec(`ALTER TABLE i ALTER id RESTART 20`, 0))
		run(referenceExec(`INSERT INTO i DEFAULT VALUES`, 1))
	})
}
