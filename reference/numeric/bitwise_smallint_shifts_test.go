func TestReferenceBitwiseSmallintCompleteShiftGrid(t *testing.T) {
	p := fixture.NewScenario(t)
	p.Step(t, fixture.Exec("CREATE TABLE one(v INTEGER)", 0))
	p.Step(t, fixture.Exec("INSERT INTO one VALUES(1)", 1))
	for _, tc := range referenceBitwiseSmallintShiftCases {
		step := fixture.Select("SELECT "+tc.expr+" FROM one", []string{"?column?"}, []string{"INT2"}, [][]any{{tc.want}})
		p.Step(t, step)
		p.Step(t, fixture.Prepared(step))
	}
}
