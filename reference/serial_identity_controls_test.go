func serialIdentitySetup(cycle bool) []referenceStep {
	if cycle {
		return []referenceStep{
			referenceExec(`CREATE TABLE lhs(id BIGINT GENERATED BY DEFAULT AS IDENTITY,s SERIAL)`, 0),
			referenceExec(`CREATE TABLE rhs(id BIGINT GENERATED BY DEFAULT AS IDENTITY,s SERIAL)`, 0),
			referenceExec(`ALTER TABLE lhs ALTER s SET DEFAULT nextval('rhs_id_seq')`, 0),
			referenceExec(`ALTER TABLE rhs ALTER s SET DEFAULT nextval('lhs_id_seq')`, 0),
			referenceSelect(`SELECT setval('lhs_id_seq',7,true)`, []string{"setval"}, []string{"INT8"}, [][]any{{int64(7)}}),
			referenceSelect(`SELECT setval('rhs_id_seq',20,true)`, []string{"setval"}, []string{"INT8"}, [][]any{{int64(20)}}),
			referenceExec(`INSERT INTO lhs VALUES(100,200)`, 1), referenceExec(`INSERT INTO rhs VALUES(300,400)`, 1),
		}
	}
	return []referenceStep{
		referenceExec(`CREATE TABLE consumer(id SERIAL)`, 0),
		referenceExec(`CREATE TABLE producer(id BIGINT GENERATED BY DEFAULT AS IDENTITY)`, 0),
		referenceExec(`ALTER TABLE consumer ALTER id SET DEFAULT nextval('producer_id_seq')`, 0),
		referenceSelect(`SELECT setval('producer_id_seq',7,true)`, []string{"setval"}, []string{"INT8"}, [][]any{{int64(7)}}),
		referenceExec(`INSERT INTO consumer VALUES(40)`, 1),
	}
}

func serialIdentityFuture(cycle bool) []referenceStep {
	if cycle {
		return []referenceStep{
			referenceExec(`INSERT INTO lhs DEFAULT VALUES`, 1), referencePrepared(referenceExec(`INSERT INTO rhs DEFAULT VALUES`, 1)),
			referenceSelect(`SELECT * FROM lhs ORDER BY id`, []string{"id", "s"}, []string{"INT8", "INT4"}, [][]any{{int64(8), int64(21)}, {int64(100), int64(200)}}),
			referenceSelect(`SELECT * FROM rhs ORDER BY id`, []string{"id", "s"}, []string{"INT8", "INT4"}, [][]any{{int64(22), int64(9)}, {int64(300), int64(400)}}),
		}
	}
	return []referenceStep{
		referencePrepared(referenceExec(`INSERT INTO consumer DEFAULT VALUES`, 1)), referenceExec(`INSERT INTO producer DEFAULT VALUES`, 1),
		referenceSelect(`SELECT * FROM consumer ORDER BY id`, []string{"id"}, []string{"INT4"}, [][]any{{int64(8)}, {int64(40)}}),
		referenceSelect(`SELECT * FROM producer`, []string{"id"}, []string{"INT8"}, [][]any{{int64(9)}}),
	}
}

func TestReferenceSerialDefaultIdentityProviders(t *testing.T) {
	for _, cycle := range []bool{false, true} {
		t.Run(fmt.Sprint(cycle), func(t *testing.T) {
			serialReferenceStreams(t, false, func(bool) []referenceStep { return append(serialIdentitySetup(cycle), serialIdentityFuture(cycle)...) })
		})
	}
}

func TestReferenceSerialDefaultIdentityDumpReplay(t *testing.T) {
	for _, cycle := range []bool{false, true} {
		for _, source := range []bool{false, true} {
			t.Run(fmt.Sprintf("cycle=%t/source=%t", cycle, source), func(t *testing.T) {
				p := newReferenceScenario(t)
				for _, step := range serialIdentitySetup(cycle) {
					if source && step.selectRows {
						step.selectRows = false
						step.affected = 1
					}
					step.nonContext = source
					referenceRunStep(t, p.ctx, p.memory, p.memoryRecord, step)
				}
				var dump bytes.Buffer
				if err := stuntgres.Dump(p.ctx, p.native, &dump); err != nil {
					t.Fatal("supported default dependency dump", err)
				}
				if p.postgres != nil {
					if _, err := p.postgres.ExecContext(p.ctx, dump.String()); err != nil {
						t.Fatal("pinned replay", err)
					}
				}
				if err := stuntgres.Reset(p.ctx, p.native); err != nil {
					t.Fatal(err)
				}
				if err := stuntgres.Restore(p.ctx, p.native, bytes.NewReader(dump.Bytes())); err != nil {
					t.Fatal("native replay", err)
				}
				for _, step := range serialIdentityFuture(cycle) {
					step.nonContext = source
					p.step(t, step)
				}
			})
		}
	}
}
