package reference_test

import (
	"database/sql"
	"testing"
)

func TestReferenceTableLikeIdentity(t *testing.T) {
	tableLikeScenario(t, func(t *testing.T, p *referencePair, b referenceBackend, c *sql.Conn, prepared bool, run func(referenceStep)) {
		run(referenceExec("CREATE TABLE src(id BIGINT GENERATED BY DEFAULT AS IDENTITY(START 7 INCREMENT 3 MINVALUE 1 MAXVALUE 100 CACHE 1 NO CYCLE))", 0))
		run(referenceExec("INSERT INTO src DEFAULT VALUES", 1))
		run(referenceExec("INSERT INTO src DEFAULT VALUES", 1))
		run(referenceExec("ALTER TABLE src ALTER COLUMN id RESTART WITH 40", 0))
		run(referenceExec("ALTER SEQUENCE src_id_seq SET UNLOGGED", 0))
		run(referenceExec("CREATE TABLE clone(LIKE src INCLUDING IDENTITY)", 0))
		run(referenceSelect("SELECT pg_get_serial_sequence('src','id')<>pg_get_serial_sequence('clone','id') AS independent", []string{"independent"}, []string{"BOOL"}, [][]any{{true}}))
		run(referenceSelect("SELECT last_value,is_called FROM clone_id_seq", []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(7), false}}))
		run(referenceSelect("SELECT seqstart,seqincrement,seqmin,seqmax,seqcache,seqcycle FROM pg_sequence WHERE seqrelid='clone_id_seq'::regclass::oid", []string{"seqstart", "seqincrement", "seqmin", "seqmax", "seqcache", "seqcycle"}, []string{"INT8", "INT8", "INT8", "INT8", "INT8", "BOOL"}, [][]any{{int64(7), int64(3), int64(1), int64(100), int64(1), false}}))
		if b.pg {
			run(referenceSelect("SELECT relpersistence::text AS persistence FROM pg_class WHERE oid='clone_id_seq'::regclass", []string{"persistence"}, []string{"TEXT"}, [][]any{{"p"}}))
		}
		run(referenceSelect("SELECT d.refobjid='clone'::regclass::oid AS owned,d.refobjsubid FROM pg_depend d WHERE d.objid='clone_id_seq'::regclass::oid AND d.deptype='i'", []string{"owned", "refobjsubid"}, []string{"BOOL", "INT4"}, [][]any{{true, int64(1)}}))
		run(referenceExec("INSERT INTO clone DEFAULT VALUES", 1))
		run(referenceExec("INSERT INTO clone DEFAULT VALUES", 1))
		run(referenceExec("INSERT INTO src DEFAULT VALUES", 1))
		run(referenceSelect("SELECT * FROM clone ORDER BY id", []string{"id"}, []string{"INT8"}, [][]any{{int64(7)}, {int64(10)}}))
		run(referenceSelect("SELECT * FROM src ORDER BY id", []string{"id"}, []string{"INT8"}, [][]any{{int64(7)}, {int64(10)}, {int64(40)}}))
		run(referenceExec("CREATE TABLE excluded(LIKE src INCLUDING ALL EXCLUDING IDENTITY)", 0))
		run(tableLikeError("INSERT INTO excluded DEFAULT VALUES", referenceDiagnostic{Code: "23502", Message: `null value in column "id" of relation "excluded" violates not-null constraint`, Detail: "Failing row contains (null).", Schema: "public", Table: "excluded", Column: "id"}))
		run(referenceExec("CREATE TABLE always_src(id INT GENERATED ALWAYS AS IDENTITY)", 0))
		run(referenceExec("CREATE TABLE always_clone(LIKE always_src INCLUDING IDENTITY)", 0))
		run(tableLikeError("INSERT INTO always_clone VALUES(9)", referenceDiagnostic{Code: "428C9", Message: `cannot insert a non-DEFAULT value into column "id"`, Detail: `Column "id" is an identity column defined as GENERATED ALWAYS.`, Hint: "Use OVERRIDING SYSTEM VALUE to override."}))
		run(referenceExec("INSERT INTO always_clone OVERRIDING SYSTEM VALUE VALUES(9)", 1))
		run(referenceExec("DROP TABLE src,always_src", 0))
		run(referenceExec("ALTER TABLE clone RENAME TO renamed", 0))
		run(referenceExec("INSERT INTO renamed DEFAULT VALUES", 1))
		run(referenceSelect("SELECT * FROM renamed ORDER BY id", []string{"id"}, []string{"INT8"}, [][]any{{int64(7)}, {int64(10)}, {int64(13)}}))
	})
}

func TestReferenceTableLikeDefaultSequenceLinkage(t *testing.T) {
	tableLikeScenario(t, func(t *testing.T, p *referencePair, b referenceBackend, c *sql.Conn, prepared bool, run func(referenceStep)) {
		run(referenceExec("CREATE TABLE src(id SERIAL)", 0))
		run(referenceExec("CREATE TABLE clone(LIKE src INCLUDING DEFAULTS INCLUDING IDENTITY)", 0))
		run(referenceSelect("SELECT pg_get_serial_sequence('clone','id') AS seq", []string{"seq"}, []string{"TEXT"}, [][]any{{nil}}))
		run(referenceExec("INSERT INTO src DEFAULT VALUES", 1))
		run(referenceExec("INSERT INTO clone DEFAULT VALUES", 1))
		run(referenceExec("INSERT INTO src DEFAULT VALUES", 1))
		run(referenceSelect("SELECT id FROM src ORDER BY id", []string{"id"}, []string{"INT4"}, [][]any{{int64(1)}, {int64(3)}}))
		run(referenceSelect("SELECT id FROM clone", []string{"id"}, []string{"INT4"}, [][]any{{int64(2)}}))
		run(tableLikeError("DROP TABLE src RESTRICT", referenceDiagnostic{Code: "2BP01", Message: "cannot drop table src because other objects depend on it", Detail: "default value for column id of table clone depends on sequence src_id_seq", Hint: "Use DROP ... CASCADE to drop the dependent objects too."}))
		run(referenceExec("DROP TABLE src CASCADE", 0))
		run(referenceExec("INSERT INTO clone VALUES(9)", 1))
		run(tableLikeError("INSERT INTO clone DEFAULT VALUES", referenceDiagnostic{Code: "23502", Message: `null value in column "id" of relation "clone" violates not-null constraint`, Detail: "Failing row contains (null).", Schema: "public", Table: "clone", Column: "id"}))
		run(referenceSelect("SELECT id FROM clone ORDER BY id", []string{"id"}, []string{"INT4"}, [][]any{{int64(2)}, {int64(9)}}))
	})
}
