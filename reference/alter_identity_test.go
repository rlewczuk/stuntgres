package reference_test

import (
	"database/sql"
	"reflect"
	"testing"
)

func alterIdentityScenario(t *testing.T, body func(*testing.T, *referencePair, referenceBackend, *sql.Conn)) {
	t.Helper()
	p := newReferenceScenario(t)
	for _, b := range p.backends() {
		t.Run(b.name, func(t *testing.T) { body(t, p, b, identityConnection(t, p.ctx, b.db)) })
	}
}

func alterIdentityMissing(t *testing.T, p *referencePair, b referenceBackend, c referenceExecutor, name string) {
	t.Helper()
	s := referenceImplicitError(`SELECT * FROM `+name, referenceDiagnostic{Code: "42P01", Message: `relation "` + name + `" does not exist`, Position: "15"})
	s.selectRows = true
	referenceRunStep(t, p.ctx, c, b.recorder, s)
}

func TestReferenceAlterIdentityTransitions(t *testing.T) {
	alterIdentityScenario(t, func(t *testing.T, p *referencePair, b referenceBackend, c *sql.Conn) {
		run := func(s referenceStep) { referenceRunStep(t, p.ctx, c, b.recorder, s) }
		run(referenceExec(`CREATE TABLE a(id INT NOT NULL)`, 0))
		run(referenceExec(`INSERT INTO a VALUES(40)`, 1))
		run(referencePrepared(referenceExec(`ALTER TABLE a ALTER id ADD GENERATED BY DEFAULT AS IDENTITY(START 7 INCREMENT 3 CACHE 1)`, 0)))
		omitted := identityHeld(t, p.ctx, c, `INSERT INTO a DEFAULT VALUES`)
		explicit := identityHeld(t, p.ctx, c, `INSERT INTO a VALUES($1)`)
		referenceRunStep(t, p.ctx, omitted, b.recorder, referenceExec(omitted.query, 1))
		referenceRunStep(t, p.ctx, explicit, b.recorder, referenceExec(explicit.query, 1, 99))
		run(referenceExec(`INSERT INTO a VALUES(DEFAULT)`, 1))
		run(referenceExec(`ALTER TABLE a ALTER id SET GENERATED ALWAYS`, 0))
		referenceRunStep(t, p.ctx, explicit, b.recorder, referenceImplicitError(explicit.query, identityAlwaysDiagnostic(), 99))
		run(referenceExec(`INSERT INTO a OVERRIDING SYSTEM VALUE VALUES(101)`, 1))
		referenceRunStep(t, p.ctx, omitted, b.recorder, referenceExec(omitted.query, 1))
		run(referencePrepared(referenceExec(`ALTER TABLE a ALTER id SET GENERATED BY DEFAULT`, 0)))
		referenceRunStep(t, p.ctx, explicit, b.recorder, referenceExec(explicit.query, 1, 102))
		run(referenceExec(`ALTER TABLE a ALTER id RESTART WITH 20`, 0))
		for range 2 {
			referenceRunStep(t, p.ctx, omitted, b.recorder, referenceExec(omitted.query, 1))
		}
		run(referenceSelect(`SELECT * FROM a ORDER BY id`, []string{"id"}, []string{"INT4"}, [][]any{{int64(7)}, {int64(10)}, {int64(13)}, {int64(20)}, {int64(23)}, {int64(40)}, {int64(99)}, {int64(101)}, {int64(102)}}))
		identityEmptyMetadata(t, p.ctx, b, true, `SELECT * FROM a WHERE false`, []string{"id"}, []string{"INT4"}, []bool{false})
		rows, err := c.QueryContext(p.ctx, `ALTER TABLE a ALTER id SET GENERATED ALWAYS`)
		if err != nil {
			t.Fatal(err)
		}
		defer rows.Close()
		cols, err := rows.Columns()
		if err != nil || len(cols) != 0 || rows.Next() || rows.Err() != nil {
			t.Fatal("DDL row metadata", cols, err, rows.Err())
		}
	})
}

func TestReferenceAlterIdentityDropLifecycle(t *testing.T) {
	alterIdentityScenario(t, func(t *testing.T, p *referencePair, b referenceBackend, c *sql.Conn) {
		run := func(s referenceStep) { referenceRunStep(t, p.ctx, c, b.recorder, s) }
		for _, q := range []string{`CREATE SEQUENCE unrelated START 80`, `CREATE TABLE a(id INT NOT NULL)`, `ALTER TABLE a ALTER id ADD GENERATED BY DEFAULT AS IDENTITY`} {
			run(referenceExec(q, 0))
		}
		run(referenceExec(`INSERT INTO a VALUES(40)`, 1))
		held := identityHeld(t, p.ctx, c, `INSERT INTO a DEFAULT VALUES`)
		referenceRunStep(t, p.ctx, held, b.recorder, referenceExec(held.query, 1))
		run(referenceExec(`ALTER TABLE a ALTER id SET GENERATED ALWAYS SET INCREMENT 3 RESTART WITH 20`, 0))
		referenceRunStep(t, p.ctx, held, b.recorder, referenceExec(held.query, 1))
		run(referenceImplicitError(`DROP SEQUENCE a_id_seq CASCADE`, referenceDiagnostic{Code: "2BP01", Message: `cannot drop sequence a_id_seq because column id of table a requires it`, Hint: "You can drop column id of table a instead."}))
		run(referenceImplicitError(`ALTER SEQUENCE a_id_seq OWNED BY NONE`, referenceDiagnostic{Code: "0A000", Message: `cannot change ownership of identity sequence`, Detail: `Sequence "a_id_seq" is linked to table "a".`}))
		for _, q := range []string{`BEGIN`, `SAVEPOINT s`, `ALTER TABLE a ALTER id RESTART WITH 100`, `ROLLBACK TO s`, `ALTER TABLE a ALTER id DROP IDENTITY`, `ROLLBACK`} {
			run(referenceExec(q, 0))
		}
		referenceRunStep(t, p.ctx, held, b.recorder, referenceExec(held.query, 1))
		want := [][]any{{int64(1)}, {int64(20)}, {int64(23)}, {int64(40)}}
		run(referenceSelect(`SELECT * FROM a ORDER BY id`, []string{"id"}, []string{"INT4"}, want))
		run(referenceExec(`CREATE VIEW linked AS SELECT last_value FROM a_id_seq`, 0))
		run(referenceImplicitError(`ALTER TABLE a ALTER id DROP IDENTITY`, referenceDiagnostic{Code: "2BP01", Message: "cannot drop sequence a_id_seq because other objects depend on it", Detail: "view linked depends on sequence a_id_seq", Hint: "Use DROP ... CASCADE to drop the dependent objects too."}))
		run(referenceExec(`DROP VIEW linked`, 0))
		run(referencePrepared(referenceExec(`ALTER TABLE a ALTER id DROP IDENTITY`, 0)))
		run(referenceSelect(`SELECT * FROM a ORDER BY id`, []string{"id"}, []string{"INT4"}, want))
		alterIdentityMissing(t, p, b, c, "a_id_seq")
		identityEmptyMetadata(t, p.ctx, b, true, `SELECT * FROM a WHERE false`, []string{"id"}, []string{"INT4"}, []bool{false})
		referenceRunStep(t, p.ctx, held, b.recorder, referenceImplicitError(held.query, referenceDiagnostic{Code: "23502", Message: `null value in column "id" of relation "a" violates not-null constraint`, Detail: "Failing row contains (null).", Schema: "public", Table: "a", Column: "id"}))
		run(referenceExec(`INSERT INTO a VALUES(55)`, 1))
		run(referenceImplicitError(`ALTER TABLE a ALTER id DROP IDENTITY`, referenceDiagnostic{Code: "55000", Message: `column "id" of relation "a" is not an identity column`}))
		var notices []referenceDiagnostic
		_, nc, nr := noticeReferencePool(t, p, b.pg, &notices)
		referenceRunStep(t, p.ctx, nc, nr, referenceExec(`ALTER TABLE a ALTER id DROP IDENTITY IF EXISTS`, 0))
		n := referenceDiagnostic{Severity: "NOTICE", SeverityUnlocalized: "NOTICE", Code: "00000", Message: `column "id" of relation "a" is not an identity column, skipping`}
		if !reflect.DeepEqual(notices, []referenceDiagnostic{n}) {
			t.Fatal(notices)
		}
		run(referenceImplicitError(`ALTER TABLE a ALTER missing DROP IDENTITY IF EXISTS`, referenceDiagnostic{Code: "42703", Message: `column "missing" of relation "a" does not exist`}))
		run(referenceExec(`ALTER TABLE a ALTER id ADD GENERATED BY DEFAULT AS IDENTITY`, 0))
		referenceRunStep(t, p.ctx, held, b.recorder, referenceExec(held.query, 1))
		run(referenceSelect(`SELECT * FROM a ORDER BY id`, []string{"id"}, []string{"INT4"}, [][]any{{int64(1)}, {int64(1)}, {int64(20)}, {int64(23)}, {int64(40)}, {int64(55)}}))
		run(referenceSelect(`SELECT last_value,is_called FROM unrelated`, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(80), false}}))
		run(referenceExec(`DROP TABLE a`, 0))
		alterIdentityMissing(t, p, b, c, "a_id_seq")
	})
}
