func pgcryptoPasswordSaltShape(t *testing.T, salt string, cost int) {
	t.Helper()
	if len(salt) != 29 || !strings.HasPrefix(salt, fmt.Sprintf("$2a$%02d$", cost)) {
		t.Fatalf("salt shape/cost: %q, cost %d", salt, cost)
	}
	for _, ch := range salt[7:] {
		if !strings.ContainsRune("./ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789", ch) {
			t.Fatalf("salt alphabet: %q", salt)
		}
	}
	if !strings.ContainsRune(".Oeu", rune(salt[28])) {
		t.Fatalf("noncanonical salt: %q", salt)
	}
}

func pgcryptoPasswordGenerated(t *testing.T, p *fixture.Pair, c *sql.Conn, r *fixture.Recorder, query, cryptName string, cost int) string {
	t.Helper()
	var salt string
	if err := c.QueryRowContext(p.Ctx, query).Scan(&salt); err != nil {
		t.Fatal(query, err)
	}
	pgcryptoPasswordSaltShape(t, salt, cost)
	// Generated bytes are not goldens: assert usability independently of their
	// unpredictable value, and never complete a high-cost crypt.
	if cost == 4 {
		usable := fmt.Sprintf("SELECT length(%s('password',$1)) AS size,%s('password',%s('password',$1))=%s('password',$1) AS verified", cryptName, cryptName, cryptName, cryptName)
		fixture.RunStep(t, p.Ctx, c, r, fixture.Select(usable, []string{"size", "verified"}, []string{"INT4", "BOOL"}, [][]any{{int64(60), true}}, salt))
	}
	return salt
}

func TestReferencePgcryptoPasswordSaltGeneration(t *testing.T) {
	pgcryptoCase(t, true, func(t *testing.T, p *fixture.Pair, c *sql.Conn, r *fixture.Recorder, pg bool) {
		for _, v := range []struct {
			query string
			cost  int
		}{
			{"SELECT gen_salt('bf')", 6}, {"SELECT gen_salt('bf',0)", 6}, {"SELECT gen_salt('BF',4)", 4}, {"SELECT gen_salt('bF',31)", 31},
		} {
			pgcryptoPasswordGenerated(t, p, c, r, v.query, "crypt", v.cost)
		}
		q := "SELECT gen_salt($1,$2) AS value"
		stmt, err := c.PrepareContext(p.Ctx, q)
		if err != nil {
			t.Fatal(err)
		}
		defer stmt.Close()
		seen := map[string]bool{}
		for range 12 {
			var salt string
			if err := stmt.QueryRowContext(p.Ctx, "bf", 4).Scan(&salt); err != nil {
				t.Fatal(err)
			}
			pgcryptoPasswordSaltShape(t, salt, 4)
			if seen[salt] {
				t.Fatal("reused salt entropy", salt)
			}
			seen[salt] = true
		}
		pool := p.Memory
		if pg {
			pool = p.Postgres
		}
		other, err := pool.Conn(p.Ctx)
		if err != nil {
			t.Fatal(err)
		}
		defer other.Close()
		fresh := pgcryptoPasswordGenerated(t, p, other, r, "SELECT gen_salt('bf',4)", "crypt", 4)
		if seen[fresh] {
			t.Fatal("cross-session entropy shared")
		}
		for range 2 {
			fixture.RunStep(t, p.Ctx, c, r, fixture.Select("SELECT setseed(0.25)", []string{"setseed"}, []string{"VOID"}, [][]any{{""}}))
			salt := pgcryptoPasswordGenerated(t, p, c, r, "SELECT gen_salt('bf',4)", "crypt", 4)
			if seen[salt] {
				t.Fatal("SQL random seed reused strong salt entropy")
			}
			seen[salt] = true
		}
		for _, name := range []string{"des", "md5", "xdes", "sha256crypt", "sha512crypt"} {
			q := "SELECT gen_salt($1) IS NOT NULL AS value"
			if pg {
				fixture.RunStep(t, p.Ctx, c, r, fixture.Select(q, []string{"value"}, []string{"BOOL"}, [][]any{{true}}, name))
			} else {
				s := fixture.ImplicitError(q, fixture.Diagnostic{Code: "0A000", Message: "gen_salt: unsupported salt algorithm"}, name)
				fixture.RunStep(t, p.Ctx, c, r, s)
				fixture.RunStep(t, p.Ctx, c, r, fixture.Prepared(s))
			}
		}
		fixture.RunStep(t, p.Ctx, c, r, fixture.Exec("CREATE TABLE pgcrypto_entropy(id integer,s text DEFAULT gen_salt('bf',4))", 0))
		fixture.RunStep(t, p.Ctx, c, r, fixture.Exec("INSERT INTO pgcrypto_entropy(id) VALUES(1),(2),(3)", 3))
		fixture.RunStep(t, p.Ctx, c, r, fixture.Select("SELECT count(DISTINCT s) AS salts FROM pgcrypto_entropy", []string{"salts"}, []string{"INT8"}, [][]any{{int64(3)}}))
		for _, args := range [][]any{{nil, 4}, {"bf", nil}, {nil, nil}} {
			fixture.RunStep(t, p.Ctx, fixture.HeldStatement{Executor: c, Statement: stmt, SQL: q}, r, fixture.Select(q, []string{"value"}, []string{"TEXT"}, [][]any{{nil}}, args...))
		}
		pgcryptoPasswordText(t, p, c, r, "SELECT gen_salt(NULL::text) AS value", nil)
	})
}
