package reference_test

// PostgreSQL REL_18_6 pg_cast.dat, restricted to executable builtin identities.
// Generic IO, domain and array element conversions have no pg_cast row.
func pgCastReleasedFacts(rows [][]any) [][]any {
	add := func(s, t, f int64, c, m string) {
		for _, r := range rows {
			if r[0] == s && r[1] == t {
				return
			}
		}
		rows = append(rows, []any{s, t, f, c, m})
	}
	for _, r := range []struct {
		s, t, f int64
		c       string
	}{
		{19, 25, 406, "i"}, {19, 1042, 408, "a"}, {19, 1043, 1401, "a"}, {25, 19, 407, "i"}, {1043, 19, 1400, "i"}, {1042, 19, 409, "i"},
		{18, 1042, 860, "a"}, {18, 1043, 946, "a"}, {25, 18, 944, "a"}, {1043, 18, 944, "a"}, {1042, 18, 944, "a"}, {18, 23, 77, "e"}, {23, 18, 78, "e"},
		{25, 2205, 1079, "i"}, {1043, 2205, 1079, "i"},
		{21, 17, 6367, "e"}, {23, 17, 6368, "e"}, {20, 17, 6369, "e"}, {17, 21, 6370, "e"}, {17, 23, 6371, "e"}, {17, 20, 6372, "e"},
		{1186, 1083, 1419, "a"}, {23, 1560, 1683, "e"}, {20, 1560, 2075, "e"}, {1560, 23, 1684, "e"}, {1560, 20, 2076, "e"}, {1560, 1560, 1685, "i"}, {1562, 1562, 1687, "i"},
		{829, 774, 4123, "i"}, {774, 829, 4124, "i"}, {869, 650, 1715, "a"},
		{3802, 16, 3556, "e"}, {3802, 1700, 3449, "e"}, {3802, 21, 3450, "e"}, {3802, 23, 3451, "e"}, {3802, 20, 3452, "e"}, {3802, 700, 3453, "e"}, {3802, 701, 2580, "e"},
		{600, 603, 4091, "a"}, {601, 600, 1532, "e"}, {602, 604, 1449, "a"}, {603, 600, 1534, "e"}, {603, 601, 1541, "e"}, {603, 604, 1448, "a"}, {603, 718, 1479, "e"},
		{604, 600, 1540, "e"}, {604, 602, 1447, "a"}, {604, 603, 1446, "e"}, {604, 718, 1474, "e"}, {718, 600, 1416, "e"}, {718, 603, 1480, "e"}, {718, 604, 1544, "e"},
		{3904, 4451, 4281, "e"}, {3906, 4532, 4284, "e"}, {3926, 4536, 4296, "e"},
	} {
		add(r.s, r.t, r.f, r.c, "f")
	}
	for _, r := range [][2]int64{{24, 2202}, {2202, 24}, {2203, 2204}, {2204, 2203}, {650, 869}, {1560, 1562}, {1562, 1560}} {
		add(r[0], r[1], 0, "i", "b")
	}
	for _, alias := range []int64{26, 2205, 2206, 24, 2202, 4096, 2203, 2204, 4191, 4089, 3734, 3769} {
		add(21, alias, 313, "i", "f")
		add(23, alias, 0, "i", "b")
		add(20, alias, 1287, "i", "f")
		add(alias, 23, 0, "a", "b")
		add(alias, 20, 1288, "a", "f")
		if alias != 26 {
			add(26, alias, 0, "i", "b")
			add(alias, 26, 0, "i", "b")
		}
	}
	for _, source := range []int64{16, 869, 650} {
		f := int64(730)
		if source == 16 {
			f = 2971
		}
		for _, target := range []int64{25, 1043, 1042} {
			add(source, target, f, "a", "f")
		}
	}
	return rows
}
