const attrdefRawQuery = "SELECT oid,adrelid,adnum,adbin FROM pg_catalog.pg_attrdef WHERE adrelid=$1 ORDER BY adnum"

func attrdefMetadata(t *testing.T, pg bool, columns []*sql.ColumnType) {
	t.Helper()
	fixture.TableDDLColumnTypes(t, pg, columns, []string{"oid", "adrelid", "adnum", "adbin"}, []string{"OID", "OID", "INT2", "PG_NODE_TREE"}, []bool{false, false, false, false})
	for _, c := range columns {
		if n, ok := c.Length(); n != 0 || ok {
			t.Fatalf("%s Length=(%d,%t)", c.Name(), n, ok)
		}
		if p, s, ok := c.DecimalSize(); p != 0 || s != 0 || ok {
			t.Fatalf("%s DecimalSize=(%d,%d,%t)", c.Name(), p, s, ok)
		}
	}
}

// Inspect actual raw cells independently of fixture normalization. The opaque
// structural carrier is deliberately not compared between backends.
func attrdefRead(t *testing.T, p *fixture.Pair, b fixture.Backend, x fixture.Executor, owner int64, nums []int64, prepared bool) [][]any {
	t.Helper()
	var rows *sql.Rows
	var err error
	if prepared {
		stmt, e := x.PrepareContext(p.Ctx, attrdefRawQuery)
		if e != nil {
			t.Fatal(e)
		}
		defer stmt.Close()
		rows, err = stmt.QueryContext(p.Ctx, owner)
	} else {
		rows, err = x.QueryContext(p.Ctx, attrdefRawQuery, owner)
	}
	if err != nil {
		t.Fatal(err)
	}
	defer rows.Close()
	columns, err := rows.ColumnTypes()
	if err != nil {
		t.Fatal(err)
	}
	attrdefMetadata(t, b.PG, columns)
	var cells [][]any
	seen := map[int64]bool{}
	for rows.Next() {
		var raw [4]any
		if err := rows.Scan(&raw[0], &raw[1], &raw[2], &raw[3]); err != nil {
			t.Fatal(err)
		}
		var id, relation int64
		if b.PG {
			for _, i := range []int{0, 1, 3} {
				if _, ok := raw[i].([]byte); !ok {
					t.Fatalf("raw field %d: %T", i, raw[i])
				}
			}
			id, err = strconv.ParseInt(string(raw[0].([]byte)), 10, 64)
			if err != nil {
				t.Fatal(err)
			}
			relation, err = strconv.ParseInt(string(raw[1].([]byte)), 10, 64)
			if err != nil {
				t.Fatal(err)
			}
		} else {
			var ok bool
			id, ok = raw[0].(int64)
			if !ok {
				t.Fatalf("OID %T", raw[0])
			}
			relation, ok = raw[1].(int64)
			if !ok {
				t.Fatalf("owner %T", raw[1])
			}
			if _, ok := raw[3].(string); !ok {
				t.Fatalf("tree %T", raw[3])
			}
		}
		num, ok := raw[2].(int64)
		if !ok || len(cells) >= len(nums) || num != nums[len(cells)] {
			t.Fatalf("attribute %v, expected %v", raw[2], nums)
		}
		if id <= 0 || id > 4294967295 || id == owner || seen[id] || relation != owner || fixture.Normalize(raw[3]) == "" {
			t.Fatalf("invalid definition: %v", raw)
		}
		seen[id] = true
		cells = append(cells, []any{id, relation, num, fixture.Normalize(raw[3])})
	}
	if rows.Err() != nil {
		t.Fatal(rows.Err())
	}
	if len(cells) != len(nums) {
		t.Fatalf("rows=%v, expected attributes %v", cells, nums)
	}
	if err := rows.Close(); err != nil {
		t.Fatal(err)
	}
	attrdefMetadata(t, b.PG, columns)
	return cells
}

func attrdefSemantics(owner int64, nums []int64, expressions []string) fixture.Step {
	var want [][]any
	for i, n := range nums {
		want = append(want, []any{n, expressions[i]})
	}
	return fixture.Select("SELECT adnum,pg_get_expr(adbin,adrelid) FROM pg_catalog.pg_attrdef WHERE adrelid=$1 ORDER BY adnum", []string{"adnum", "pg_get_expr"}, []string{"INT2", "TEXT"}, want, owner)
}

func TestReferenceAttrdefDefaults(t *testing.T) {
	p := fixture.NewScenario(t)
	for _, b := range p.Backends() {
		t.Run(b.Name, func(t *testing.T) {
			conn, err := b.DB.Conn(p.Ctx)
			if err != nil {
				t.Fatal(err)
			}
			defer conn.Close()
			run := func(s fixture.Step) { fixture.RunStep(t, p.Ctx, conn, b.Recorder, s) }
			run(fixture.Exec(`CREATE TABLE attrdef_values(plain INT,ordinary INT DEFAULT 7,null_default INT DEFAULT NULL,typed_null INT DEFAULT NULL::integer,nullable_expr INT DEFAULT COALESCE(NULL::integer,NULL::integer),generated INT GENERATED ALWAYS AS(plain+1) STORED,generated_null INT GENERATED ALWAYS AS(NULL) STORED,ident INT GENERATED BY DEFAULT AS IDENTITY)`, 0))
			run(fixture.Exec("INSERT INTO attrdef_values(plain) VALUES(2),(NULL)", 2))
			owner := fixture.DeparseDefinitionID(t, conn, "SELECT oid FROM pg_catalog.pg_class WHERE relname='attrdef_values'")
			for _, prepared := range []bool{false, true} {
				attrdefRead(t, p, b, conn, owner, []int64{2, 5, 6, 7}, prepared)
				s := attrdefSemantics(owner, []int64{2, 5, 6, 7}, []string{"7", "COALESCE(NULL::integer, NULL::integer)", "(plain + 1)", "NULL::integer"})
				data := fixture.Select("SELECT plain,ordinary,nullable_expr,generated,generated_null FROM attrdef_values", []string{"plain", "ordinary", "nullable_expr", "generated", "generated_null"}, []string{"INT4", "INT4", "INT4", "INT4", "INT4"}, [][]any{{int64(2), int64(7), nil, int64(3), nil}, {nil, int64(7), nil, nil, nil}})
				data.Bag = true
				if prepared {
					s = fixture.Prepared(s)
					data = fixture.Prepared(data)
				}
				run(s)
				run(data)
			}
			run(fixture.Exec("CREATE TABLE attrdef_deferred(v INT DEFAULT 2147483648)", 0))
			deferred := fixture.DeparseDefinitionID(t, conn, "SELECT oid FROM pg_catalog.pg_class WHERE relname='attrdef_deferred'")
			for _, prepared := range []bool{false, true} {
				attrdefRead(t, p, b, conn, deferred, []int64{1}, prepared)
				s := attrdefSemantics(deferred, []int64{1}, []string{"'2147483648'::bigint"})
				if prepared {
					s = fixture.Prepared(s)
				}
				run(s)
			}
		})
	}
}

func attrdefSame(t *testing.T, got, want [][]any) {
	t.Helper()
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("catalog changed: got %v want %v", got, want)
	}
}
