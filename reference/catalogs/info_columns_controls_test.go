func icControlRows(database string) [][]any {
	base := icRow(database, "ic_scope", "ctl", "a", 1, "integer", "pg_catalog", "int4", icIntFields())
	base = icPatch(base, map[string]any{"column_default": "7", "is_nullable": "NO"})
	identity := icRow(database, "ic_scope", "ctl", "id", 2, "integer", "pg_catalog", "int4", icIntFields())
	identity = icPatch(identity, map[string]any{"is_nullable": "NO", "is_identity": "YES", "identity_generation": "BY DEFAULT", "identity_start": "5", "identity_increment": "2", "identity_minimum": "1", "identity_maximum": "99", "identity_cycle": "NO"})
	generated := icRow(database, "ic_scope", "ctl", "g", 3, "integer", "pg_catalog", "int4", icIntFields())
	generated = icPatch(generated, map[string]any{"is_generated": "ALWAYS", "generation_expression": "(a + 1)"})
	return [][]any{base, identity, generated,
		icRow(database, "ic_scope", "domain_t", "v", 1, "character varying", "pg_catalog", "varchar", map[string]any{"domain_catalog": database, "domain_schema": "ic_scope", "domain_name": "word", "character_maximum_length": int64(4), "character_octet_length": int64(16)}),
		icRow(database, "ic_scope", "part", "a", 1, "integer", "pg_catalog", "int4", icIntFields()),
		icRow(database, "ic_scope", "part_child", "a", 1, "integer", "pg_catalog", "int4", icIntFields()),
		icRow(database, "ic_scope", "view_t", "a", 1, "integer", "pg_catalog", "int4", icIntFields()),
	}
}

func TestReferenceInfoColumnsNativeControls(t *testing.T) {
	icScenario(t, func(c *icCase) {
		t := c.t
		c.exec("CREATE DOMAIN ic_scope.word AS varchar(4)", "CREATE TABLE ic_scope.ctl(a integer NOT NULL DEFAULT 7,id integer GENERATED BY DEFAULT AS IDENTITY(START WITH 5 INCREMENT BY 2 MINVALUE 1 MAXVALUE 99),g integer GENERATED ALWAYS AS(a+1) STORED)", "CREATE TABLE ic_scope.domain_t(v ic_scope.word)", "CREATE TABLE ic_scope.part(a integer) PARTITION BY RANGE(a)", "CREATE TABLE ic_scope.part_child PARTITION OF ic_scope.part FOR VALUES FROM(0) TO(10)", "CREATE VIEW ic_scope.view_t AS SELECT a FROM ic_scope.ctl")
		where := "table_schema='ic_scope'"
		want := icControlRows(c.database)
		s := icProjection(c.b.PG, where, want)
		c.run(c.conn, s)
		c.run(c.conn, fixture.Prepared(s))
		if c.b.PG {
			return
		} // controls are a public process-local API, not SQL.
		var dump bytes.Buffer
		if err := stuntgres.Dump(c.p.Ctx, c.p.Native, &dump); err != nil {
			t.Fatal(err)
		}
		if dump.Len() == 0 {
			t.Fatal("empty Dump")
		}
		old, err := c.conn.QueryContext(c.p.Ctx, s.Query)
		if err != nil {
			t.Fatal(err)
		}
		defer old.Close()
		if err := stuntgres.Reset(c.p.Ctx, c.p.Native); err != nil {
			t.Fatal(err)
		}
		c.run(c.conn, icProjection(false, where, nil))
		c.run(c.conn, fixture.Select("SELECT column_name FROM information_schema.columns WHERE table_schema='information_schema' AND table_name='columns' ORDER BY ordinal_position", []string{"column_name"}, []string{"NAME"}, func() [][]any {
			var rows [][]any
			for _, name := range icColumns {
				rows = append(rows, []any{name})
			}
			return rows
		}()))
		c.consume(old, want)
		for range 2 {
			if err := stuntgres.Restore(c.p.Ctx, c.p.Native, bytes.NewReader(dump.Bytes())); err != nil {
				t.Fatal(err)
			}
			c.run(c.conn, s)
			c.run(c.conn, fixture.Prepared(s))
		}
		connector, err := stuntgres.NewDriver().OpenConnector("ic-fresh-controls")
		if err != nil {
			t.Fatal(err)
		}
		fresh := sql.OpenDB(connector)
		defer fresh.Close()
		if err := stuntgres.Restore(c.p.Ctx, fresh, bytes.NewReader(dump.Bytes())); err != nil {
			t.Fatal(err)
		}
		var freshDatabase string
		if err := fresh.QueryRowContext(c.p.Ctx, "SELECT current_database()").Scan(&freshDatabase); err != nil {
			t.Fatal(err)
		}
		freshStep := icProjection(false, where, icControlRows(freshDatabase))
		// The fresh driver has no fixture interceptor. Observe through its own
		// recorded pool, never the original backend's same-SQL history.
		recordedFresh, freshRecorder := fixture.InsertSelectRecordedPool(t, connector)
		fixture.RunStep(t, c.p.Ctx, recordedFresh, freshRecorder, freshStep)
		fixture.RunStep(t, c.p.Ctx, recordedFresh, freshRecorder, fixture.Prepared(freshStep))
		// Replay the actual emitted bytes, never a handwritten substitute.
		if c.p.Postgres != nil {
			if _, err := c.p.Postgres.ExecContext(c.p.Ctx, "DROP SCHEMA IF EXISTS ic_scope CASCADE"); err != nil {
				t.Fatal(err)
			}
			if _, err := c.p.Postgres.ExecContext(c.p.Ctx, dump.String()); err != nil {
				t.Fatal(err)
			}
			var database string
			if err := c.p.Postgres.QueryRowContext(c.p.Ctx, "SELECT current_database()").Scan(&database); err != nil {
				t.Fatal(err)
			}
			fixture.RunStep(t, c.p.Ctx, c.p.Postgres, c.p.PostgresRecord, icProjection(true, where, icControlRows(database)))
			if _, err := c.p.Postgres.ExecContext(c.p.Ctx, "DROP SCHEMA ic_scope CASCADE"); err != nil {
				t.Fatal(err)
			}
		}
		c.exec("CREATE TABLE ic_scope.sentinel(v integer)")
		c.run(c.conn, fixture.Exec("INSERT INTO ic_scope.sentinel VALUES(91)", 1))
		full := append([][]any(nil), want[:len(want)-1]...)
		full = append(full, c.integer("sentinel", "v", 1), want[len(want)-1])
		unchanged := func() {
			c.run(c.conn, icProjection(false, where, full))
			c.run(c.conn, fixture.Select("SELECT * FROM ic_scope.sentinel", []string{"v"}, []string{"INT4"}, [][]any{{int64(91)}}))
			c.run(c.conn, fixture.Select("SELECT nspname FROM pg_namespace WHERE nspname='ic_staged'", []string{"nspname"}, []string{"NAME"}, nil))
		}
		bad := "CREATE SCHEMA ic_staged; CREATE TABLE ic_staged.bad(v integer); INSERT INTO ic_staged.bad VALUES('bad');"
		err = stuntgres.Restore(c.p.Ctx, c.p.Native, strings.NewReader(bad))
		d := fixture.ControlsReferenceDiagnostic("22P02", `invalid input syntax for type integer: "bad"`)
		d.Position = fixture.Position(strings.Index(bad, "'bad'") + 1)
		fixture.AssertDiagnostic(t, err, &d)
		unchanged()
		ctx, cancel := context.WithCancel(c.p.Ctx)
		cancel()
		if err := stuntgres.Restore(ctx, c.p.Native, bytes.NewReader(dump.Bytes())); !errors.Is(err, context.Canceled) {
			t.Fatalf("canceled Restore=%v", err)
		}
		unchanged()
		c.exec("CREATE ROLE ic_reader", "GRANT SELECT ON ic_scope.ctl TO ic_reader")
		var rejected bytes.Buffer
		if err := stuntgres.Dump(c.p.Ctx, c.p.Native, &rejected); err == nil || rejected.Len() != 0 {
			t.Fatalf("explicit ACL Dump error=%v bytes=%d", err, rejected.Len())
		}
		unchanged()
	})
}
