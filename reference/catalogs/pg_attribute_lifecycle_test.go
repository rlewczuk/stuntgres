func pgAttributeDropped(row []any) []any {
	out := append([]any(nil), row...)
	out[1] = fmt.Sprintf("........pg.dropped.%d........", row[4])
	out[2], out[11], out[12], out[13], out[15], out[16] = int64(0), false, false, false, "", true
	for i := 20; i < 25; i++ {
		out[i] = nil
	}
	return out
}

func TestReferencePGAttributeDropped(t *testing.T) {
	pgAttributeScenario(t, func(t *testing.T, p *fixture.Pair, b fixture.Backend) {
		fixture.PGClassExec(t, p, b, b.DB, "CREATE DOMAIN pa18_drop_domain AS varchar(7)", "CREATE TABLE pa18_drop(a integer,b varchar(7) COLLATE \"C\" NOT NULL DEFAULT 'x',c integer[][],d integer GENERATED ALWAYS AS IDENTITY,e integer GENERATED BY DEFAULT AS IDENTITY,f integer GENERATED ALWAYS AS(a+1) STORED,g pa18_drop_domain)")
		id := pgAttributeID(t, p, b.DB, "pa18_drop")
		var domain int64
		if err := b.DB.QueryRowContext(p.Ctx, "SELECT 'pa18_drop_domain'::regtype::oid").Scan(&domain); err != nil {
			t.Fatal(err)
		}
		want := [][]any{
			pgAttributeRow(id, "a", 23, 4, 1, -1, 0, true, "i", "p", false, 0),
			pgAttributeRow(id, "b", 1043, -1, 2, 11, 0, false, "i", "x", true, 950),
			pgAttributeRow(id, "c", 1007, -1, 3, -1, 2, false, "i", "x", false, 0),
			pgAttributeRow(id, "d", 23, 4, 4, -1, 0, true, "i", "p", true, 0),
			pgAttributeRow(id, "e", 23, 4, 5, -1, 0, true, "i", "p", true, 0),
			pgAttributeRow(id, "f", 23, 4, 6, -1, 0, true, "i", "p", false, 0),
			pgAttributeRow(id, "g", domain, -1, 7, -1, 0, false, "i", "x", false, 100),
		}
		want[1][12], want[5][12], want[3][14], want[4][14], want[5][15] = true, true, "a", "d", "s"
		pgAttributeRead(t, p, b, b.DB, id, " AND attnum>0", want)
		q := "SELECT * FROM pg_attribute WHERE attrelid=$1 AND attnum>0 ORDER BY attnum"
		held := fixture.ViewHold(t, p, b, q)
		for i, name := range []string{"b", "c", "d", "e", "f", "g"} {
			fixture.PGClassExec(t, p, b, b.DB, "ALTER TABLE pa18_drop DROP "+name)
			want[i+1] = pgAttributeDropped(want[i+1])
			pgAttributeRead(t, p, b, b.DB, id, " AND attnum>0", want)
			fixture.PGAttributeCheck(t, p, b, held, fixture.Select(q, fixture.PGAttributeColumns, pgAttributeTypes, want, id))
		}
		fixture.PGClassExec(t, p, b, b.DB, "DROP DOMAIN pa18_drop_domain", "ALTER TABLE pa18_drop ADD h text")
		want = append(want, pgAttributeRow(id, "h", 25, -1, 8, -1, 0, false, "i", "x", false, 100))
		pgAttributeRead(t, p, b, b.DB, id, " AND attnum>0", want)
		fixture.PGAttributeCheck(t, p, b, held, fixture.Select(q, fixture.PGAttributeColumns, pgAttributeTypes, want, id))
	})
}

func TestReferencePGAttributeLifecycle(t *testing.T) {
	pgAttributeScenario(t, func(t *testing.T, p *fixture.Pair, b fixture.Backend) {
		fixture.PGClassExec(t, p, b, b.DB, "CREATE TABLE pa18_life(a integer,b integer DEFAULT 7,c integer GENERATED BY DEFAULT AS IDENTITY)")
		id := pgAttributeID(t, p, b.DB, "pa18_life")
		q := "SELECT * FROM pg_attribute WHERE attrelid=$1 AND attnum>0 ORDER BY attnum"
		held := fixture.ViewHold(t, p, b, q)
		want := [][]any{pgAttributeRow(id, "a", 23, 4, 1, -1, 0, true, "i", "p", false, 0), pgAttributeRow(id, "b", 23, 4, 2, -1, 0, true, "i", "p", false, 0), pgAttributeRow(id, "c", 23, 4, 3, -1, 0, true, "i", "p", true, 0)}
		want[1][12], want[2][14] = true, "d"
		initial := make([][]any, len(want))
		for i := range want {
			initial[i] = append([]any(nil), want[i]...)
		}
		check := func() {
			pgAttributeRead(t, p, b, b.DB, id, " AND attnum>0", want)
			fixture.PGAttributeCheck(t, p, b, held, fixture.Select(q, fixture.PGAttributeColumns, pgAttributeTypes, want, id))
		}
		check()
		var old *sql.Rows
		var descriptions []*sql.ColumnType
		if !b.PG {
			var err error
			old, err = p.Native.QueryContext(p.Ctx, q, id)
			if err != nil {
				t.Fatal(err)
			}
			defer old.Close()
			descriptions, err = old.ColumnTypes()
			if err != nil {
				t.Fatal(err)
			}
		}
		fixture.PGClassExec(t, p, b, b.DB, "ALTER TABLE pa18_life RENAME TO pa18_life_renamed", "ALTER TABLE pa18_life_renamed RENAME a TO renamed")
		if pgAttributeID(t, p, b.DB, "pa18_life_renamed") != id {
			t.Fatal("rename changed relation identity")
		}
		want[0][1] = "renamed"
		check()
		fixture.PGClassExec(t, p, b, b.DB, "ALTER TABLE pa18_life_renamed ALTER renamed SET NOT NULL", "ALTER TABLE pa18_life_renamed ALTER b DROP DEFAULT", "ALTER TABLE pa18_life_renamed ALTER c SET GENERATED ALWAYS")
		want[0][11], want[1][12], want[2][14] = true, false, "a"
		check()
		fixture.PGClassExec(t, p, b, b.DB, "ALTER TABLE pa18_life_renamed ALTER renamed DROP NOT NULL", "ALTER TABLE pa18_life_renamed ALTER b SET DEFAULT 9", "ALTER TABLE pa18_life_renamed ALTER c DROP IDENTITY")
		want[0][11], want[1][12], want[2][14] = false, true, ""
		check()
		fixture.PGClassExec(t, p, b, b.DB, "ALTER TABLE pa18_life_renamed ALTER renamed TYPE bigint")
		want[0] = pgAttributeRow(id, "renamed", 20, 8, 1, -1, 0, true, "d", "p", false, 0)
		check()
		failure := fixture.ImplicitError("ALTER TABLE pa18_life_renamed ALTER b SET NOT NULL, ALTER missing SET NOT NULL", fixture.Diagnostic{Code: "42703", Message: "column \"missing\" of relation \"pa18_life_renamed\" does not exist"})
		fixture.RunStep(t, p.Ctx, b.DB, b.Recorder, failure)
		check()
		fixture.PGClassExec(t, p, b, b.DB, "DROP TABLE pa18_life_renamed")
		want = nil
		check()
		if old != nil {
			var retained [][]any
			for old.Next() {
				row := make([]any, 25)
				ptrs := make([]any, 25)
				for i := range row {
					ptrs[i] = &row[i]
				}
				if err := old.Scan(ptrs...); err != nil {
					t.Fatal(err)
				}
				retained = append(retained, row)
			}
			if old.Err() != nil {
				t.Fatal(old.Err())
			}
			if !reflect.DeepEqual(retained, initial) {
				t.Fatal("retained capture changed", retained, initial)
			}
			if descriptions[24].DatabaseTypeName() != "ANYARRAY" {
				t.Fatal("retained descriptor changed")
			}
		}
	})
}

func TestReferencePGAttributeTransactions(t *testing.T) {
	pgAttributeScenario(t, func(t *testing.T, p *fixture.Pair, b fixture.Backend) {
		fixture.PGClassExec(t, p, b, b.DB, "CREATE TABLE pa18_tx(a integer,b varchar(7))")
		id := pgAttributeID(t, p, b.DB, "pa18_tx")
		a, observer := fixture.LockConnections(t, p.Ctx, b.DB)
		q := "SELECT * FROM pg_attribute WHERE attrelid=$1 AND attnum>0 ORDER BY attnum"
		stmt, err := a.PrepareContext(p.Ctx, q)
		if err != nil {
			t.Fatal(err)
		}
		defer stmt.Close()
		held := fixture.HeldStatement{Executor: a, Statement: stmt, SQL: q}
		original := [][]any{pgAttributeRow(id, "a", 23, 4, 1, -1, 0, true, "i", "p", false, 0), pgAttributeRow(id, "b", 1043, -1, 2, 11, 0, false, "i", "x", false, 100)}
		changed := [][]any{append([]any(nil), original[0]...), pgAttributeDropped(original[1])}
		changed[0][11] = true
		check := func(db fixture.Executor, rows [][]any) {
			fixture.PGAttributeCheck(t, p, b, db, fixture.Select(q, fixture.PGAttributeColumns, pgAttributeTypes, rows, id))
		}
		fixture.PGClassExec(t, p, b, a, "BEGIN", "SAVEPOINT pa18_before", "ALTER TABLE pa18_tx ALTER a SET NOT NULL, DROP b")
		defer a.ExecContext(context.Background(), "ROLLBACK")
		check(a, changed)
		check(held, changed)
		check(observer, original)
		fixture.PGClassExec(t, p, b, a, "ROLLBACK TO pa18_before")
		check(held, original)
		fixture.PGClassExec(t, p, b, a, "COMMIT")
		check(observer, original)
		fixture.PGClassExec(t, p, b, a, "BEGIN", "ALTER TABLE pa18_tx ALTER a SET NOT NULL, DROP b", "ROLLBACK")
		check(held, original)
		check(observer, original)
		fixture.PGClassExec(t, p, b, a, "BEGIN", "ALTER TABLE pa18_tx ALTER a SET NOT NULL, DROP b", "COMMIT")
		check(held, changed)
		check(observer, changed)
	})
}

func TestReferencePGAttributeTemporary(t *testing.T) {
	pgAttributeScenario(t, func(t *testing.T, p *fixture.Pair, b fixture.Backend) {
		a, observer := fixture.LockConnections(t, p.Ctx, b.DB)
		fixture.PGClassExec(t, p, b, a, "CREATE TEMP TABLE pa18_temp(a integer[][])")
		defer a.ExecContext(p.Ctx, "DROP TABLE IF EXISTS pa18_temp")
		id := pgAttributeID(t, p, a, "pa18_temp")
		want := [][]any{pgAttributeRow(id, "a", 1007, -1, 1, -1, 2, false, "i", "x", false, 0)}
		pgAttributeRead(t, p, b, a, id, " AND attnum>0", want)
		// Committed TEMP descriptors are catalog-visible across sessions in both
		// engines; that visibility does not permit resolving or reading the table.
		pgAttributeRead(t, p, b, observer, id, " AND attnum>0", want)
		denied := fixture.ImplicitError("SELECT * FROM pa18_temp", fixture.Diagnostic{Code: "42P01", Message: "relation \"pa18_temp\" does not exist", Position: "15"})
		denied.SelectRows, denied.ErrorStage = true, "execute"
		fixture.RunStep(t, p.Ctx, observer, b.Recorder, denied)
		fixture.PGClassExec(t, p, b, a, "DROP TABLE pa18_temp")
		pgAttributeRead(t, p, b, a, id, "", nil)
		pgAttributeRead(t, p, b, observer, id, "", nil)
	})
}

func TestReferencePGAttributeDiagnostics(t *testing.T) {
	fixture.RoleReferenceCleanup(t, []string{"pa18_diag_reader"})
	pgAttributeScenario(t, func(t *testing.T, p *fixture.Pair, b fixture.Backend) {
		for _, tc := range []struct{ query, code, message, position string }{
			{"SELECT missing FROM pg_catalog.pg_attribute", "42703", "column \"missing\" does not exist", "8"},
			{"SELECT missing FROM pg_catalog.pg_attribute WHERE FALSE", "42703", "column \"missing\" does not exist", "8"},
			{"SELECT /*é*/ missing FROM pg_catalog.pg_attribute", "42703", "column \"missing\" does not exist", "14"},
			{"SELECT 'bad'::oid FROM pg_attribute WHERE FALSE", "22P02", "invalid input syntax for type oid: \"bad\"", "8"},
			{"SELECT '4294967296'::oid FROM pg_attribute", "22003", "value \"4294967296\" is out of range for type oid", "8"},
		} {
			for _, prepared := range []bool{false, true} {
				s := fixture.ImplicitError(tc.query, fixture.Diagnostic{Code: tc.code, Message: tc.message, Position: tc.position})
				s.SelectRows, s.Prepared, s.ErrorStage = true, prepared, "execute"
				if prepared {
					s.ErrorStage = "prepare"
				}
				fixture.RunStep(t, p.Ctx, b.DB, b.Recorder, s)
			}
		}
		q := "SELECT attname FROM pg_attribute WHERE attrelid=$1 AND attnum>0 ORDER BY attnum"
		held := fixture.ViewHold(t, p, b, q)
		for _, value := range []string{"bad", ""} {
			for _, prepared := range []bool{false, true} {
				s := fixture.PGCastParameterError(q, "oid", value, value)
				s.Prepared = prepared
				fixture.RunStep(t, p.Ctx, b.DB, b.Recorder, s)
			}
			fixture.RunStep(t, p.Ctx, held, b.Recorder, fixture.PGCastParameterError(q, "oid", value, value))
		}
		for _, value := range []any{nil, int64(4294967295)} {
			s := fixture.Select(q, []string{"attname"}, []string{"NAME"}, nil, value)
			fixture.PGAttributeCheck(t, p, b, b.DB, s)
			fixture.PGAttributeCheck(t, p, b, b.DB, fixture.Prepared(s))
			fixture.PGAttributeCheck(t, p, b, held, s)
		}
		for _, declaration := range []string{"ctid integer", "\"ctid\" integer"} {
			s := fixture.ImplicitError("CREATE TABLE pa18_reserved("+declaration+")", fixture.Diagnostic{Code: "42701", Message: "column name \"ctid\" conflicts with a system column name"})
			fixture.RunStep(t, p.Ctx, b.DB, b.Recorder, s)
			fixture.PGAttributeCheck(t, p, b, b.DB, fixture.Select("SELECT relname FROM pg_class WHERE relname='pa18_reserved'", []string{"relname"}, []string{"NAME"}, nil))
		}
		if !b.PG {
			for _, tc := range []struct{ query, stage string }{{"INSERT INTO pg_attribute(attrelid,attname) VALUES(1,'fake')", "execute"}, {"UPDATE pg_attribute SET attname='fake' WHERE FALSE", "prepare"}, {"DELETE FROM pg_attribute WHERE FALSE", "execute"}} {
				for _, prepared := range []bool{false, true} {
					s := fixture.ImplicitError(tc.query, fixture.Diagnostic{Code: "0A000", Message: "catalog source mutation is unsupported"})
					s.Prepared, s.ErrorStage = prepared, "execute"
					if prepared {
						s.ErrorStage = tc.stage
					}
					fixture.RunStep(t, p.Ctx, b.DB, b.Recorder, s)
				}
			}
			for _, prepared := range []bool{false, true} {
				s := fixture.ImplicitError("SELECT * FROM pg_attribute WHERE FALSE FOR UPDATE", fixture.Diagnostic{Code: "0A000", Message: "row locking is not supported for virtual catalog relations"})
				s.SelectRows, s.Prepared, s.ErrorStage = true, prepared, "execute"
				fixture.RunStep(t, p.Ctx, b.DB, b.Recorder, s)
			}
			canceled, cancel := context.WithCancel(p.Ctx)
			cancel()
			rows, err := b.DB.QueryContext(canceled, q, int64(1249))
			if rows != nil {
				rows.Close()
				t.Fatal("canceled direct execution returned rows")
			}
			if !errors.Is(err, context.Canceled) {
				t.Fatal(err)
			}
			stmt, err := b.DB.PrepareContext(canceled, q)
			if stmt != nil {
				stmt.Close()
				t.Fatal("canceled prepare returned statement")
			}
			if !errors.Is(err, context.Canceled) {
				t.Fatal(err)
			}
			rows, err = held.Statement.QueryContext(canceled, int64(1249))
			if rows != nil {
				rows.Close()
				t.Fatal("canceled held execution returned rows")
			}
			if !errors.Is(err, context.Canceled) {
				t.Fatal(err)
			}
		}
		if b.PG {
			owner := fixture.SequenceCoreConn(t, p.Ctx, b.DB)
			fixture.PGClassExec(t, p, b, owner, "CREATE ROLE pa18_diag_reader", "SET ROLE pa18_diag_reader")
			defer owner.ExecContext(p.Ctx, "RESET ROLE")
			for _, query := range []string{"INSERT INTO pg_attribute(attrelid,attname) VALUES(1,'fake')", "UPDATE pg_attribute SET attname='fake' WHERE FALSE", "DELETE FROM pg_attribute WHERE FALSE"} {
				for _, prepared := range []bool{false, true} {
					s := fixture.ImplicitError(query, fixture.Diagnostic{Code: "42501", Message: "permission denied for table pg_attribute"})
					s.Prepared, s.ErrorStage = prepared, "execute"
					fixture.RunStep(t, p.Ctx, owner, b.Recorder, s)
				}
			}
			fixture.PGClassExec(t, p, b, owner, "RESET ROLE")
		}
		want := make([][]any, 25)
		for i, name := range fixture.PGAttributeColumns {
			want[i] = []any{name}
		}
		fixture.PGAttributeCheck(t, p, b, held, fixture.Select(q, []string{"attname"}, []string{"NAME"}, want, int64(1249)))
	})
}
