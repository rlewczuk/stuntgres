package reference_test

import (
	"database/sql"
	"fmt"
	"testing"

	"stuntgres"
	"stuntgres/reference/fixture"
)

type insertDefaultControl struct {
	name, declaration, suffix string
	oids                      []uint32
	uses                      [][]any
	rows                      [][]string
}

var insertDefaultControls = []insertDefaultControl{
	{"values", "id int DEFAULT 7,c int", "(c) VALUES($1)", []uint32{23}, [][]any{{2}, {12}}, [][]string{{"7", "2"}, {"7", "12"}}},
	{"full_targets", "id int DEFAULT 7,c int", "(id,c) SELECT $1,$2", []uint32{23, 23}, [][]any{{3, 3}, {13, 13}}, [][]string{{"3", "3"}, {"13", "13"}}},
	{"supplied_null", "id int DEFAULT 7,c int", "(id,c) SELECT $1,$2", []uint32{23, 23}, [][]any{{nil, 10}, {nil, 11}}, [][]string{{"<NULL>", "10"}, {"<NULL>", "11"}}},
	{"no_parameters", "id int DEFAULT 7,c int", "(c) SELECT 4", nil, [][]any{nil, nil}, [][]string{{"7", "4"}, {"7", "4"}}},
	{"no_default", "id int,c int", "(c) SELECT $1", []uint32{23}, [][]any{{5}, {15}}, [][]string{{"<NULL>", "5"}, {"<NULL>", "15"}}},
	{"identity", "id int GENERATED BY DEFAULT AS IDENTITY,c int", "(c) SELECT $1", []uint32{23}, [][]any{{6}, {16}}, [][]string{{"1", "6"}, {"2", "16"}}},
}

func TestReferenceServerInsertSelectDefaultParamsControls(t *testing.T) {
	f := fixture.NewServerFixture(t)
	for _, backend := range f.Backends() {
		t.Run(backend.Name, func(t *testing.T) {
			dsn := f.DSNFor(backend)
			for _, control := range insertDefaultControls {
				for _, named := range []bool{false, true} {
					for _, explicit := range []bool{false, true} {
						t.Run(fmt.Sprintf("raw/%s/named_%t/transaction_%t", control.name, named, explicit), func(t *testing.T) {
							w, peer := serverAuthenticated(t, dsn), serverAuthenticated(t, dsn)
							table := fmt.Sprintf("control_%s_%t_%t", control.name, named, explicit)
							insertDefaultCommand(t, w, "CREATE TABLE "+table+" ("+control.declaration+")", "CREATE TABLE", 'I')
							ready := byte('I')
							if explicit {
								insertDefaultCommand(t, w, "BEGIN", "BEGIN", 'T')
								ready = 'T'
							}
							name := ""
							if named {
								name = "control"
							}
							insertDefaultPrepare(t, w, name, "INSERT INTO "+table+control.suffix, control.oids, false, ready)
							insertDefaultHealthy(t, w, table, 0, ready)
							for i, args := range control.uses {
								insertDefaultExecute(t, w, name, insertDefaultArgs(args...), 1, ready)
								insertDefaultHealthy(t, w, table, i+1, ready)
							}
							if explicit {
								serverScalar(t, peer, "SELECT count(*) FROM "+table, "0")
								insertDefaultCommand(t, w, "COMMIT", "COMMIT", 'I')
							}
							insertDefaultRead(t, peer, "SELECT id,c FROM "+table+" ORDER BY c", []string{"id", "c"}, []uint32{23, 23}, control.rows, 'I')
						})
					}
				}
				for _, route := range []string{"query", "exec", "prepared", "pgx"} {
					for _, explicit := range []bool{false, true} {
						t.Run(fmt.Sprintf("%s/%s/transaction_%t", route, control.name, explicit), func(t *testing.T) {
							w := serverAuthenticated(t, dsn)
							table := fmt.Sprintf("client_control_%s_%s_%t", route, control.name, explicit)
							insertDefaultCommand(t, w, "CREATE TABLE "+table+" ("+control.declaration+")", "CREATE TABLE", 'I')
							insertDefaultWithClient(t, f.Ctx, dsn, route, explicit, func(client insertDefaultClient) {
								for i, args := range control.uses {
									client.exec("INSERT INTO "+table+control.suffix, args, 1)
									insertDefaultClientCount(t, client, table, int64(i+1))
								}
								client.query("SELECT id,c FROM "+table+" ORDER BY c", func(rows insertDefaultRows) {
									i := 0
									for rows.Next() {
										if i >= len(control.rows) {
											t.Fatal("extra control row")
										}
										var id sql.NullInt64
										var c int64
										if err := rows.Scan(&id, &c); err != nil {
											t.Fatal(err)
										}
										want := control.rows[i]
										idText := "<NULL>"
										if id.Valid {
											idText = fmt.Sprint(id.Int64)
										}
										if idText != want[0] || fmt.Sprint(c) != want[1] {
											t.Fatalf("typed control row=(%s,%d) want=%v", idText, c, want)
										}
										i++
									}
									if i != len(control.rows) {
										t.Fatalf("control rows=%d want=%d", i, len(control.rows))
									}
								})
							})
							insertDefaultRead(t, w, "SELECT id,c FROM "+table+" ORDER BY c", []string{"id", "c"}, []uint32{23, 23}, control.rows, 'I')
						})
					}
				}
			}
			for _, explicit := range []bool{false, true} {
				t.Run(fmt.Sprintf("sql_prepare/transaction_%t", explicit), func(t *testing.T) {
					w := serverAuthenticated(t, dsn)
					table := fmt.Sprintf("control_sql_prepare_%t", explicit)
					insertDefaultCommand(t, w, "CREATE TABLE "+table+" (id int DEFAULT 7,c int)", "CREATE TABLE", 'I')
					ready := byte('I')
					if explicit {
						insertDefaultCommand(t, w, "BEGIN", "BEGIN", 'T')
						ready = 'T'
					}
					insertDefaultCommand(t, w, "PREPARE p AS INSERT INTO "+table+"(c) SELECT $1", "PREPARE", ready)
					insertDefaultCommand(t, w, "EXECUTE p(8)", "INSERT 0 1", ready)
					insertDefaultCommand(t, w, "EXECUTE p(9)", "INSERT 0 1", ready)
					insertDefaultHealthy(t, w, table, 2, ready)
					if explicit {
						insertDefaultCommand(t, w, "COMMIT", "COMMIT", 'I')
					}
					insertDefaultRead(t, w, "SELECT id,c FROM "+table+" ORDER BY c", []string{"id", "c"}, []uint32{23, 23}, [][]string{{"7", "8"}, {"7", "9"}}, 'I')
				})
			}
		})
	}
	// Explicit native API control: a separate public embedded driver is not the
	// regression transport and never replaces either backend's wire witnesses.
	t.Run("native_embedded_control", func(t *testing.T) {
		connector, err := stuntgres.NewDriver().OpenConnector(t.Name())
		if err != nil {
			t.Fatal(err)
		}
		db := sql.OpenDB(connector)
		t.Cleanup(func() { db.Close() })
		conn, err := db.Conn(f.Ctx)
		if err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() { conn.Close() })
		if _, err := conn.ExecContext(f.Ctx, "CREATE TABLE embedded_control(id int DEFAULT 7,c int)"); err != nil {
			t.Fatal(err)
		}
		insertDefaultSQLAdapter(t, f.Ctx, conn, "exec").exec("INSERT INTO embedded_control(c) SELECT $1", []any{8}, 1)
		insertDefaultSQLAdapter(t, f.Ctx, conn, "prepared").exec("INSERT INTO embedded_control(c) SELECT $1", []any{9}, 1)
		insertDefaultClientPairs(t, insertDefaultSQLAdapter(t, f.Ctx, conn, "exec"), "SELECT id,c FROM embedded_control ORDER BY c", [][2]int64{{7, 8}, {7, 9}})
	})
}
