func TestReferenceTableLikeDiagnostics(t *testing.T) {
	fixture.TableLikeScenario(t, func(t *testing.T, p *fixture.Pair, b fixture.Backend, c *sql.Conn, prepared bool, run func(fixture.Step)) {
		run(fixture.Exec("CREATE TABLE src(a INT GENERATED BY DEFAULT AS IDENTITY UNIQUE,b TEXT)", 0))
		run(fixture.Exec("COMMENT ON COLUMN src.b IS 'copied'", 0))
		run(fixture.Exec("CREATE SEQUENCE seq", 0))
		run(fixture.Exec("CREATE INDEX idx ON src(b)", 0))
		for _, tc := range []struct {
			q string
			d fixture.Diagnostic
		}{
			{"CREATE TABLE clone (LIKE missing INCLUDING ALL)", fixture.Diagnostic{Code: "42P01", Message: `relation "missing" does not exist`, Position: "26"}},
			{"/*é*/ CREATE TABLE clone (LIKE missing INCLUDING ALL)", fixture.Diagnostic{Code: "42P01", Message: `relation "missing" does not exist`, Position: "32"}},
			{`CREATE TABLE clone (LIKE "a""b" INCLUDING ALL)`, fixture.Diagnostic{Code: "42P01", Message: `relation "a"b" does not exist`, Position: "26"}},
			{`CREATE TABLE clone (LIKE "a\b" INCLUDING ALL)`, fixture.Diagnostic{Code: "42P01", Message: `relation "a\b" does not exist`, Position: "26"}},
			{"CREATE TABLE clone (LIKE seq INCLUDING ALL)", fixture.Diagnostic{Code: "42809", Message: `relation "seq" is invalid in LIKE clause`, Detail: "This operation is not supported for sequences.", Position: "26"}},
			{"CREATE TABLE clone (LIKE idx INCLUDING ALL)", fixture.Diagnostic{Code: "42809", Message: `relation "idx" is invalid in LIKE clause`, Detail: "This operation is not supported for indexes.", Position: "26"}},
			{"CREATE TABLE clone (LIKE src INCLUDING ALL,a TEXT)", fixture.Diagnostic{Code: "42701", Message: `column "a" specified more than once`}},
			{"CREATE TABLE clone (LIKE src INCLUDING ALL,LIKE src)", fixture.Diagnostic{Code: "42701", Message: `column "a" specified more than once`}},
		} {
			run(fixture.TableLikeError(tc.q, tc.d))
			fixture.TableLikeAbsent(run, "clone", prepared)
			run(fixture.Select("SELECT typname FROM pg_type WHERE typname='clone'", []string{"typname"}, []string{"NAME"}, nil))
			run(fixture.Select("SELECT relname FROM pg_class WHERE relname='clone_a_seq' OR relname='clone_a_key'", []string{"relname"}, []string{"NAME"}, nil))
		}
		for _, tc := range []struct{ q, token, pos string }{
			{"CREATE TABLE clone (LIKE src INCLUDING nonsense)", "nonsense", "40"},
			{`CREATE TABLE clone (LIKE src INCLUDING "comments")`, `"comments"`, "40"},
		} {
			s := fixture.ImplicitError(tc.q, fixture.Diagnostic{Code: "42601", Message: `syntax error at or near "` + tc.token + `"`, Position: tc.pos})
			if prepared {
				s.ErrorStage = "prepare"
			} else {
				s.ErrorStage = "execute"
			}
			run(s)
		}
		run(fixture.Exec("CREATE TABLE clone(LIKE src INCLUDING ALL)", 0))
		run(fixture.Exec("INSERT INTO clone DEFAULT VALUES", 1))
		run(fixture.Select("SELECT a,b FROM clone", []string{"a", "b"}, []string{"INT4", "TEXT"}, [][]any{{int64(1), nil}}))
	})
}

func TestReferenceTableLikeConstraintCollisions(t *testing.T) {
	fixture.TableLikeScenario(t, func(t *testing.T, p *fixture.Pair, b fixture.Backend, c *sql.Conn, prepared bool, run func(fixture.Step)) {
		run(fixture.Exec("CREATE TABLE src(a INT CONSTRAINT positive CHECK(a>0))", 0))
		run(fixture.Exec("CREATE TABLE other(b INT CONSTRAINT positive CHECK(b>0))", 0))
		for _, q := range []string{
			"CREATE TABLE clone(LIKE src INCLUDING CONSTRAINTS,CONSTRAINT positive CHECK(a>0))",
			"CREATE TABLE clone(CONSTRAINT positive CHECK(a>0),LIKE src INCLUDING CONSTRAINTS)",
			"CREATE TABLE clone(LIKE src INCLUDING CONSTRAINTS,LIKE other INCLUDING CONSTRAINTS)",
		} {
			run(fixture.TableLikeError(q, fixture.Diagnostic{Code: "42710", Message: `constraint "positive" for relation "clone" already exists`}))
			fixture.TableLikeAbsent(run, "clone", prepared)
		}
	})
}
