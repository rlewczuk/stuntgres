package reference_test

import (
	"context"
	"database/sql"
	"errors"
	"stuntgres/reference/fixture"
	"testing"
	"time"
)

func TestReferenceTableLikeAdmission(t *testing.T) {
	fixture.TableLikeScenario(t, func(t *testing.T, p *fixture.Pair, b fixture.Backend, c *sql.Conn, prepared bool, run func(fixture.Step)) {
		run(fixture.Exec("CREATE TABLE src(a INT DEFAULT 7)", 0))
		// lib/pq can send a fast utility even with a pre-canceled context. Native
		// cancellation is an adapter guarantee; PG cancellation uses the wait below.
		if !b.PG {
			canceled, cancel := context.WithCancel(p.Ctx)
			cancel()
			if _, err := c.ExecContext(canceled, "CREATE TABLE clone(LIKE src INCLUDING ALL)"); !errors.Is(err, context.Canceled) {
				t.Fatal(err)
			}
			fixture.TableLikeAbsent(run, "clone", prepared)
		}
		run(fixture.Exec("CREATE SCHEMA like_nested CREATE TABLE first(a INT DEFAULT 9) CREATE TABLE second(LIKE like_nested.first INCLUDING ALL)", 0))
		defer b.DB.ExecContext(context.Background(), "DROP SCHEMA IF EXISTS like_nested CASCADE")
		run(fixture.Exec("INSERT INTO like_nested.second DEFAULT VALUES", 1))
		run(fixture.Select("SELECT * FROM like_nested.second", []string{"a"}, []string{"INT4"}, [][]any{{int64(9)}}))
		run(fixture.TableLikeError("CREATE SCHEMA like_failed CREATE TABLE first(a INT GENERATED BY DEFAULT AS IDENTITY) CREATE TABLE second(LIKE like_failed.first INCLUDING ALL,a TEXT)", fixture.Diagnostic{Code: "42701", Message: `column "a" specified more than once`}))
		if b.PG {
			run(fixture.Select("SELECT nspname FROM pg_namespace WHERE nspname='like_failed'", []string{"nspname"}, []string{"NAME"}, nil))
		}
		run(fixture.Exec("DROP SCHEMA like_nested CASCADE", 0))
		// Native exact-incarnation queue mechanics are descriptor-only Round B tests.
		// This public PG barrier independently proves even an option-free LIKE waits.
		if !b.PG {
			return
		}
		holder, err := b.DB.Conn(p.Ctx)
		if err != nil {
			t.Fatal(err)
		}
		defer holder.Close()
		waiter, err := b.DB.Conn(p.Ctx)
		if err != nil {
			t.Fatal(err)
		}
		defer waiter.Close()
		hp, wp := fixture.LockPID(t, p.Ctx, holder), fixture.LockPID(t, p.Ctx, waiter)
		oid := fixture.LockOID(t, p.Ctx, "src")
		if _, err := holder.ExecContext(p.Ctx, "BEGIN; LOCK TABLE src IN ACCESS EXCLUSIVE MODE"); err != nil {
			t.Fatal(err)
		}
		defer holder.ExecContext(context.Background(), "ROLLBACK")
		ctx, stop := context.WithTimeout(p.Ctx, 5*time.Second)
		defer stop()
		done := make(chan error, 1)
		go func() { _, err := waiter.ExecContext(ctx, "CREATE TABLE clone(LIKE src)"); done <- err }()
		defer func() {
			stop()
			select {
			case <-done:
			case <-time.After(5 * time.Second):
				t.Error("LIKE worker did not join")
			}
		}()
		fixture.LockWaitBehind(t, ctx, wp, hp, oid, "AccessShareLock")
		if _, err := fixture.Admin.ExecContext(p.Ctx, "SELECT pg_cancel_backend($1)", wp); err != nil {
			t.Fatal(err)
		}
		select {
		case err := <-done:
			done <- err
			fixture.AssertDiagnostic(t, err, &fixture.Diagnostic{Severity: "ERROR", SeverityUnlocalized: "ERROR", Code: "57014", Message: "canceling statement due to user request"})
		case <-ctx.Done():
			t.Fatal(ctx.Err())
		}
		if _, err := holder.ExecContext(p.Ctx, "ROLLBACK"); err != nil {
			t.Fatal(err)
		}
		fixture.TableLikeAbsent(run, "clone", prepared)
		run(fixture.Exec("CREATE TABLE clone(LIKE src INCLUDING ALL)", 0))
		run(fixture.Exec("INSERT INTO clone DEFAULT VALUES", 1))
		run(fixture.Select("SELECT * FROM clone", []string{"a"}, []string{"INT4"}, [][]any{{int64(7)}}))
	})
}
