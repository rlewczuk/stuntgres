func TestReferenceAlterIdentityTransitions(t *testing.T) {
	fixture.AlterIdentityScenario(t, func(t *testing.T, p *fixture.Pair, b fixture.Backend, c *sql.Conn) {
		run := func(s fixture.Step) { fixture.RunStep(t, p.Ctx, c, b.Recorder, s) }
		run(fixture.Exec(`CREATE TABLE a(id INT NOT NULL)`, 0))
		run(fixture.Exec(`INSERT INTO a VALUES(40)`, 1))
		run(fixture.Prepared(fixture.Exec(`ALTER TABLE a ALTER id ADD GENERATED BY DEFAULT AS IDENTITY(START 7 INCREMENT 3 CACHE 1)`, 0)))
		omitted := fixture.IdentityHeld(t, p.Ctx, c, `INSERT INTO a DEFAULT VALUES`)
		explicit := fixture.IdentityHeld(t, p.Ctx, c, `INSERT INTO a VALUES($1)`)
		fixture.RunStep(t, p.Ctx, omitted, b.Recorder, fixture.Exec(omitted.SQL, 1))
		fixture.RunStep(t, p.Ctx, explicit, b.Recorder, fixture.Exec(explicit.SQL, 1, 99))
		run(fixture.Exec(`INSERT INTO a VALUES(DEFAULT)`, 1))
		run(fixture.Exec(`ALTER TABLE a ALTER id SET GENERATED ALWAYS`, 0))
		fixture.RunStep(t, p.Ctx, explicit, b.Recorder, fixture.ImplicitError(explicit.SQL, fixture.IdentityAlwaysDiagnostic(), 99))
		run(fixture.Exec(`INSERT INTO a OVERRIDING SYSTEM VALUE VALUES(101)`, 1))
		fixture.RunStep(t, p.Ctx, omitted, b.Recorder, fixture.Exec(omitted.SQL, 1))
		run(fixture.Prepared(fixture.Exec(`ALTER TABLE a ALTER id SET GENERATED BY DEFAULT`, 0)))
		fixture.RunStep(t, p.Ctx, explicit, b.Recorder, fixture.Exec(explicit.SQL, 1, 102))
		run(fixture.Exec(`ALTER TABLE a ALTER id RESTART WITH 20`, 0))
		for range 2 {
			fixture.RunStep(t, p.Ctx, omitted, b.Recorder, fixture.Exec(omitted.SQL, 1))
		}
		run(fixture.Select(`SELECT * FROM a ORDER BY id`, []string{"id"}, []string{"INT4"}, [][]any{{int64(7)}, {int64(10)}, {int64(13)}, {int64(20)}, {int64(23)}, {int64(40)}, {int64(99)}, {int64(101)}, {int64(102)}}))
		fixture.IdentityEmptyMetadata(t, p.Ctx, b, true, `SELECT * FROM a WHERE false`, []string{"id"}, []string{"INT4"}, []bool{false})
		rows, err := c.QueryContext(p.Ctx, `ALTER TABLE a ALTER id SET GENERATED ALWAYS`)
		if err != nil {
			t.Fatal(err)
		}
		defer rows.Close()
		cols, err := rows.Columns()
		if err != nil || len(cols) != 0 || rows.Next() || rows.Err() != nil {
			t.Fatal("DDL row metadata", cols, err, rows.Err())
		}
	})
}

func TestReferenceAlterIdentityDropLifecycle(t *testing.T) {
	fixture.AlterIdentityScenario(t, func(t *testing.T, p *fixture.Pair, b fixture.Backend, c *sql.Conn) {
		run := func(s fixture.Step) { fixture.RunStep(t, p.Ctx, c, b.Recorder, s) }
		for _, q := range []string{`CREATE SEQUENCE unrelated START 80`, `CREATE TABLE a(id INT NOT NULL)`, `ALTER TABLE a ALTER id ADD GENERATED BY DEFAULT AS IDENTITY`} {
			run(fixture.Exec(q, 0))
		}
		run(fixture.Exec(`INSERT INTO a VALUES(40)`, 1))
		held := fixture.IdentityHeld(t, p.Ctx, c, `INSERT INTO a DEFAULT VALUES`)
		fixture.RunStep(t, p.Ctx, held, b.Recorder, fixture.Exec(held.SQL, 1))
		run(fixture.Exec(`ALTER TABLE a ALTER id SET GENERATED ALWAYS SET INCREMENT 3 RESTART WITH 20`, 0))
		fixture.RunStep(t, p.Ctx, held, b.Recorder, fixture.Exec(held.SQL, 1))
		run(fixture.ImplicitError(`DROP SEQUENCE a_id_seq CASCADE`, fixture.Diagnostic{Code: "2BP01", Message: `cannot drop sequence a_id_seq because column id of table a requires it`, Hint: "You can drop column id of table a instead."}))
		run(fixture.ImplicitError(`ALTER SEQUENCE a_id_seq OWNED BY NONE`, fixture.Diagnostic{Code: "0A000", Message: `cannot change ownership of identity sequence`, Detail: `Sequence "a_id_seq" is linked to table "a".`}))
		for _, q := range []string{`BEGIN`, `SAVEPOINT s`, `ALTER TABLE a ALTER id RESTART WITH 100`, `ROLLBACK TO s`, `ALTER TABLE a ALTER id DROP IDENTITY`, `ROLLBACK`} {
			run(fixture.Exec(q, 0))
		}
		fixture.RunStep(t, p.Ctx, held, b.Recorder, fixture.Exec(held.SQL, 1))
		want := [][]any{{int64(1)}, {int64(20)}, {int64(23)}, {int64(40)}}
		run(fixture.Select(`SELECT * FROM a ORDER BY id`, []string{"id"}, []string{"INT4"}, want))
		run(fixture.Exec(`CREATE VIEW linked AS SELECT last_value FROM a_id_seq`, 0))
		run(fixture.ImplicitError(`ALTER TABLE a ALTER id DROP IDENTITY`, fixture.Diagnostic{Code: "2BP01", Message: "cannot drop sequence a_id_seq because other objects depend on it", Detail: "view linked depends on sequence a_id_seq", Hint: "Use DROP ... CASCADE to drop the dependent objects too."}))
		run(fixture.Exec(`DROP VIEW linked`, 0))
		run(fixture.Prepared(fixture.Exec(`ALTER TABLE a ALTER id DROP IDENTITY`, 0)))
		run(fixture.Select(`SELECT * FROM a ORDER BY id`, []string{"id"}, []string{"INT4"}, want))
		fixture.AlterIdentityMissing(t, p, b, c, "a_id_seq")
		fixture.IdentityEmptyMetadata(t, p.Ctx, b, true, `SELECT * FROM a WHERE false`, []string{"id"}, []string{"INT4"}, []bool{false})
		fixture.RunStep(t, p.Ctx, held, b.Recorder, fixture.ImplicitError(held.SQL, fixture.Diagnostic{Code: "23502", Message: `null value in column "id" of relation "a" violates not-null constraint`, Detail: "Failing row contains (null).", Schema: "public", Table: "a", Column: "id"}))
		run(fixture.Exec(`INSERT INTO a VALUES(55)`, 1))
		run(fixture.ImplicitError(`ALTER TABLE a ALTER id DROP IDENTITY`, fixture.Diagnostic{Code: "55000", Message: `column "id" of relation "a" is not an identity column`}))
		var notices []fixture.Diagnostic
		_, nc, nr := fixture.NoticeReferencePool(t, p, b.PG, &notices)
		fixture.RunStep(t, p.Ctx, nc, nr, fixture.Exec(`ALTER TABLE a ALTER id DROP IDENTITY IF EXISTS`, 0))
		n := fixture.Diagnostic{Severity: "NOTICE", SeverityUnlocalized: "NOTICE", Code: "00000", Message: `column "id" of relation "a" is not an identity column, skipping`}
		if !reflect.DeepEqual(notices, []fixture.Diagnostic{n}) {
			t.Fatal(notices)
		}
		run(fixture.ImplicitError(`ALTER TABLE a ALTER missing DROP IDENTITY IF EXISTS`, fixture.Diagnostic{Code: "42703", Message: `column "missing" of relation "a" does not exist`}))
		run(fixture.Exec(`ALTER TABLE a ALTER id ADD GENERATED BY DEFAULT AS IDENTITY`, 0))
		fixture.RunStep(t, p.Ctx, held, b.Recorder, fixture.Exec(held.SQL, 1))
		run(fixture.Select(`SELECT * FROM a ORDER BY id`, []string{"id"}, []string{"INT4"}, [][]any{{int64(1)}, {int64(1)}, {int64(20)}, {int64(23)}, {int64(40)}, {int64(55)}}))
		run(fixture.Select(`SELECT last_value,is_called FROM unrelated`, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(80), false}}))
		run(fixture.Exec(`DROP TABLE a`, 0))
		fixture.AlterIdentityMissing(t, p, b, c, "a_id_seq")
	})
}
