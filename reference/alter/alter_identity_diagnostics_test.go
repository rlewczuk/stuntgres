package reference_test

import (
	"stuntgres/reference/fixture"
	"testing"
)

func TestReferenceAlterIdentityDiagnosticsAndPrecedence(t *testing.T) {
	cases := []struct{ name, create, query, code, message string }{
		{"duplicate", `CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY)`, `ALTER TABLE i ALTER id SET GENERATED ALWAYS SET GENERATED BY DEFAULT`, "42601", "conflicting or redundant options"},
		{"duplicate_cache", `CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY)`, `ALTER TABLE i ALTER id SET CACHE 0 SET GENERATED ALWAYS SET GENERATED BY DEFAULT`, "22023", "CACHE (0) must be greater than zero"},
		{"duplicate_missing_relation", `CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY)`, `ALTER TABLE absent ALTER id SET GENERATED ALWAYS SET GENERATED BY DEFAULT`, "42P01", `relation "absent" does not exist`},
		{"add_precedence_nullable", `CREATE TABLE i(id INT)`, `ALTER TABLE i ALTER id ADD GENERATED ALWAYS AS IDENTITY(CACHE 0)`, "22023", "CACHE (0) must be greater than zero"},
		{"add_precedence_default", `CREATE TABLE i(id INT NOT NULL DEFAULT 7)`, `ALTER TABLE i ALTER id ADD GENERATED ALWAYS AS IDENTITY(CACHE 0)`, "22023", "CACHE (0) must be greater than zero"},
		{"add_precedence_existing", `CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY)`, `ALTER TABLE i ALTER id ADD GENERATED ALWAYS AS IDENTITY(CACHE 0)`, "22023", "CACHE (0) must be greater than zero"},
		{"unsupported_type_nullable", `CREATE TABLE i(id TEXT)`, `ALTER TABLE i ALTER id ADD GENERATED ALWAYS AS IDENTITY`, "22023", "identity column type must be smallint, integer, or bigint"},
		{"unsupported_type_not_null", `CREATE TABLE i(id TEXT NOT NULL)`, `ALTER TABLE i ALTER id ADD GENERATED ALWAYS AS IDENTITY`, "22023", "identity column type must be smallint, integer, or bigint"},
		{"nullable_guard", `CREATE TABLE i(id INT)`, `ALTER TABLE i ALTER id ADD GENERATED ALWAYS AS IDENTITY`, "55000", `column "id" of relation "i" must be declared NOT NULL before identity can be added`},
		{"default_guard", `CREATE TABLE i(id INT NOT NULL DEFAULT 7)`, `ALTER TABLE i ALTER id ADD GENERATED ALWAYS AS IDENTITY`, "55000", `column "id" of relation "i" already has a default value`},
		{"existing_guard", `CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY)`, `ALTER TABLE i ALTER id ADD GENERATED ALWAYS AS IDENTITY`, "55000", `column "id" of relation "i" is already an identity column`},
		{"add_name_collision", `CREATE TABLE i(id INT NOT NULL)`, `ALTER TABLE i ALTER id ADD GENERATED ALWAYS AS IDENTITY(SEQUENCE NAME sentinel)`, "42P07", `relation "sentinel" already exists`},
	}
	// Backend/case layout deliberately matches the living plan's focused RUN selectors.
	p := fixture.NewScenario(t)
	for _, b := range p.Backends() {
		t.Run(b.Name, func(t *testing.T) {
			for _, tc := range cases {
				for _, prepared := range []bool{false, true} {
					name := tc.name + "_direct"
					if prepared {
						name = tc.name + "_prepared"
					}
					t.Run(name, func(t *testing.T) {
						c := fixture.IdentityConnection(t, p.Ctx, b.DB)
						run := func(s fixture.Step) { fixture.RunStep(t, p.Ctx, c, b.Recorder, s) }
						run(fixture.Exec(tc.create, 0))
						t.Cleanup(func() {
							c.ExecContext(p.Ctx, `DROP TABLE IF EXISTS i CASCADE`)
							c.ExecContext(p.Ctx, `DROP SEQUENCE IF EXISTS sentinel CASCADE`)
						})
						run(fixture.Exec(`CREATE SEQUENCE sentinel START 80`, 0))
						before := ""
						if !b.PG {
							before = referenceDDLNativeDump(t, p)
						}
						s := fixture.ImplicitError(tc.query, fixture.Diagnostic{Code: tc.code, Message: tc.message})
						s.Prepared = prepared
						s.ErrorStage = "execute"
						run(s)
						if !b.PG && referenceDDLNativeDump(t, p) != before {
							t.Error("failed ALTER published state")
						}
						run(fixture.Select(`SELECT last_value,is_called FROM sentinel`, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(80), false}}))
						run(fixture.Select(`SELECT * FROM i`, []string{"id"}, []string{func() string {
							if tc.name == "unsupported_type_nullable" || tc.name == "unsupported_type_not_null" {
								return "TEXT"
							}
							return "INT4"
						}()}, nil))
						if tc.name == "duplicate" || tc.name == "duplicate_cache" || tc.name == "duplicate_missing_relation" || tc.name == "add_precedence_existing" || tc.name == "existing_guard" {
							run(fixture.ImplicitError(`INSERT INTO i VALUES(99)`, fixture.IdentityAlwaysDiagnostic()))
							run(fixture.Exec(`INSERT INTO i DEFAULT VALUES`, 1))
							run(fixture.Select(`SELECT * FROM i`, []string{"id"}, []string{"INT4"}, [][]any{{int64(1)}}))
						} else {
							fixture.AlterIdentityMissing(t, p, b, c, "i_id_seq")
						}
					})
				}
			}
		})
	}
}
