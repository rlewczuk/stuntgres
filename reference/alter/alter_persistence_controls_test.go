// Controls require unwrapped native pools. Consume their actual cursors through
// the fixture's raw native assertion helper, not middleware recording.
func persistenceControlRun(t *testing.T,p *fixture.Pair,x fixture.Executor,step fixture.Step) {
	t.Helper()
	rows,err:=x.QueryContext(p.Ctx,step.Query,step.Args...)
	fixture.StringCoreRetainedRows(t,rows,err,step.Columns,step.Types,step.Rows,step.Bag)
}

func persistenceControlFamily(t *testing.T,p *fixture.Pair,x fixture.Executor) {
	t.Helper()
	for _,name:=range []string{"persist_smoke","persist_smoke_pkey","persist_note","persist_smoke_id_seq","persist_smoke_n_seq"} {
		persistenceControlRun(t,p,x,persistencePropertyStep(name,"u"))
	}
}

func persistenceControlValue(t *testing.T,p *fixture.Pair,x fixture.Executor,expression string,want int64) {
	t.Helper()
	persistenceControlRun(t,p,x,fixture.Select("SELECT "+expression+" AS v",[]string{"v"},[]string{"INT8"},[][]any{{want}}))
}

func persistenceControlRoundtrip(t *testing.T,p *fixture.Pair) {
	t.Helper()
	var dump bytes.Buffer
	if err:=stuntgres.Dump(p.Ctx,p.Native,&dump);err!=nil {t.Fatal(err)}
	if !strings.Contains(dump.String(),"CREATE UNLOGGED TABLE") {t.Fatal("missing unlogged declaration",dump.String())}
	driver:=stuntgres.NewDriver()
	connector,err:=driver.OpenConnector("persistence-exact-opaque")
	if err!=nil {t.Fatal(err)}
	target:=sql.OpenDB(connector)
	defer func(){target.Close()}()
	for range 2 {
		if err=stuntgres.Restore(p.Ctx,target,bytes.NewReader(dump.Bytes()));err!=nil {t.Fatal(err)}
		var again bytes.Buffer
		if err=stuntgres.Dump(p.Ctx,target,&again);err!=nil || !bytes.Equal(again.Bytes(),dump.Bytes()) {t.Fatal("noncanonical persistence roundtrip",err,again.String(),dump.String())}
	}
	persistenceControlRun(t,p,target,persistenceRows())
	persistenceControlFamily(t,p,target)
	if err=target.Close();err!=nil {t.Fatal(err)}
	target=sql.OpenDB(connector)
	persistenceControlRun(t,p,target,persistenceRows())
	persistenceControlFamily(t,p,target)
	isolatedConnector,err:=stuntgres.NewDriver().OpenConnector("persistence-exact-opaque");if err!=nil {t.Fatal(err)}
	isolated:=sql.OpenDB(isolatedConnector);defer isolated.Close()
	persistenceControlRun(t,p,isolated,fixture.Select("SELECT count(*) FROM pg_class WHERE relname='persist_smoke'",[]string{"count"},[]string{"INT8"},[][]any{{int64(0)}}))
	ctx,cancel:=context.WithCancel(p.Ctx);cancel()
	if err=stuntgres.Restore(ctx,target,bytes.NewReader(dump.Bytes()));!errors.Is(err,context.Canceled) {t.Fatal(err)}
	if err=stuntgres.Restore(p.Ctx,target,strings.NewReader(dump.String()+"ALTER TABLE persist_smoke SET LOGGED, ADD CONSTRAINT bad CHECK(id<0);"));err==nil {t.Fatal("failed restore accepted")}
	persistenceControlRun(t,p,target,persistenceRows())
	persistenceControlFamily(t,p,target)
	persistenceControlValue(t,p,target,"nextval('persist_smoke_id_seq')",2)
	persistenceControlValue(t,p,target,"nextval('persist_smoke_n_seq')",2)
}

func TestReferenceAlterPersistenceControls(t *testing.T) {
	persistenceScenario(t,func(t *testing.T,p *fixture.Pair,b fixture.Backend,c *sql.Conn) {
		persistenceIdentityBody(t,p,b,c)
		if !b.PG {persistenceControlRoundtrip(t,p)}
		for _,q:=range []string{
			"CREATE UNLOGGED TABLE u(id int GENERATED BY DEFAULT AS IDENTITY)",
			"CREATE TABLE l(id int GENERATED BY DEFAULT AS IDENTITY)",
			"ALTER SEQUENCE u_id_seq SET LOGGED",
			"ALTER SEQUENCE l_id_seq SET UNLOGGED",
			"ALTER SEQUENCE u_id_seq INCREMENT 3 CACHE 5 START 10 RESTART 10",
			"CREATE UNLOGGED SEQUENCE manual START 20 CACHE 1 OWNED BY u.id",
		} {persistenceExec(t,p,b,c,q)}
		check:=func(run func(fixture.Step)) {
			for _,property:=range []struct{name,want string}{{"u","u"},{"u_id_seq","p"},{"l","p"},{"l_id_seq","u"},{"manual","u"}} {
				run(persistencePropertyStep(property.name,property.want))
			}
			run(fixture.Select("SELECT last_value,is_called FROM u_id_seq",[]string{"last_value","is_called"},[]string{"INT8","BOOL"},[][]any{{int64(10),false}}))
		}
		check(func(step fixture.Step){persistenceRun(t,p,b,c,step)})
		if !b.PG {
			var dump bytes.Buffer
			if err:=stuntgres.Dump(p.Ctx,p.Native,&dump);err!=nil {t.Fatal(err)}
			for _,fragment:=range []string{`ALTER SEQUENCE "public"."u_id_seq" SET LOGGED;`,`ALTER SEQUENCE "public"."l_id_seq" SET UNLOGGED;`} {if !strings.Contains(dump.String(),fragment) {t.Fatal("missing divergent identity",fragment)}}
			connector,err:=stuntgres.NewDriver().OpenConnector("divergent");if err!=nil {t.Fatal(err)}
			target:=sql.OpenDB(connector);defer target.Close()
			for range 2 {
				if err=stuntgres.Restore(p.Ctx,target,bytes.NewReader(dump.Bytes()));err!=nil {t.Fatal(err)}
				check(func(step fixture.Step){persistenceControlRun(t,p,target,step)})
				var again bytes.Buffer
				if err=stuntgres.Dump(p.Ctx,target,&again);err!=nil || !bytes.Equal(again.Bytes(),dump.Bytes()) {t.Fatal("divergent redump",err)}
			}
			persistenceControlValue(t,p,target,"nextval('u_id_seq')",10)
			persistenceControlValue(t,p,target,"nextval('u_id_seq')",13)
			persistenceControlValue(t,p,target,"nextval('manual')",20)
			if p.Postgres != nil {
				if _,err=p.Postgres.ExecContext(p.Ctx,dump.String());err!=nil {t.Fatal("PostgreSQL replay",err)}
				for _,oracle:=range p.Backends() {
					if !oracle.PG {continue}
					check(func(step fixture.Step){persistenceRun(t,p,oracle,p.Postgres,step)})
					persistenceRun(t,p,oracle,p.Postgres,persistenceRows())
					persistenceValue(t,p,oracle,p.Postgres,"nextval('u_id_seq')",10)
					persistenceValue(t,p,oracle,p.Postgres,"nextval('manual')",20)
				}
				if _,err=p.Postgres.ExecContext(p.Ctx,"DROP TABLE persist_smoke,u,l CASCADE");err!=nil {t.Fatal(err)}
			}
		}
		persistenceValue(t,p,b,c,"nextval('u_id_seq')",10)
		persistenceValue(t,p,b,c,"nextval('u_id_seq')",13)
		persistenceValue(t,p,b,c,"nextval('manual')",20)
	})
}
