package reference_test

import (
	"database/sql"
	"fmt"
	"testing"

	"stuntgres/reference/fixture"
)

// Keep each route bounded by its own scenario. In held cases each DROP is
// prepared once and actually executed again after rollback-to, not re-prepared.
func TestReferenceTransactionalSchemaDependencyDropRoutes(t *testing.T) {
	for _, goTx := range []bool{false, true} {
		for _, held := range []bool{false, true} {
			for _, commit := range []bool{false, true} {
				t.Run(fmt.Sprintf("go=%t/held=%t/commit=%t", goTx, held, commit), func(t *testing.T) {
					fixture.RoleReferenceCleanup(t, []string{"tx_route_reader"})
					p := fixture.NewScenario(t)
					for _, b := range p.Backends() {
						t.Run(b.Name, func(t *testing.T) {
							transactionalSchemaDependencyDropRoute(t, p, b, goTx, held, commit)
						})
					}
				})
			}
		}
	}
}

func transactionalSchemaDependencyDropRoute(t *testing.T, p *fixture.Pair, b fixture.Backend, goTx, held, commit bool) {
	t.Helper()
	c, peer := fixture.LockConnections(t, p.Ctx, b.DB)
	runOn := func(e fixture.Executor, s fixture.Step) { fixture.RunStep(t, p.Ctx, e, b.Recorder, s) }
	// Standalone view/index/GRANT owners stay outside explicit transaction
	// admission. The dependent view is deliberately created after the FK, as in
	// the independently specified table_external_boundaries oracle.
	for _, q := range []string{
		"CREATE ROLE tx_route_reader",
		"CREATE TABLE tx_route_parent(id SERIAL PRIMARY KEY, n INT CONSTRAINT tx_route_positive CHECK(n>0))",
		"CREATE TABLE tx_route_child(id INT GENERATED BY DEFAULT AS IDENTITY, parent INT CONSTRAINT tx_route_fk REFERENCES tx_route_parent(id))",
		"CREATE VIEW tx_route_view AS SELECT id FROM tx_route_parent",
		"CREATE INDEX tx_route_n_idx ON tx_route_parent(n)",
		"CREATE TABLE tx_route_a(v INT)",
		"CREATE TABLE tx_route_b(v INT)",
		"CREATE TABLE tx_route_mixed(v INT)",
		"CREATE TEMP TABLE tx_route_temp(v INT)",
		"GRANT SELECT ON tx_route_parent,tx_route_child,tx_route_a,tx_route_b,tx_route_mixed TO tx_route_reader",
	} {
		runOn(c, fixture.Exec(q, 0))
	}
	for _, q := range []string{
		"INSERT INTO tx_route_parent(n) VALUES(7)",
		"INSERT INTO tx_route_child(parent) VALUES(1)",
		"INSERT INTO tx_route_a VALUES(11)",
		"INSERT INTO tx_route_b VALUES(13)",
		"INSERT INTO tx_route_mixed VALUES(17)",
		"INSERT INTO tx_route_temp VALUES(19)",
	} {
		runOn(c, fixture.Exec(q, 1))
	}

	type relation struct {
		name                string
		oid, rowtype, array int64
		acl                 sql.NullString
		dropped             bool
	}
	objects := []relation{
		{name: "tx_route_parent", dropped: true},
		{name: "tx_route_parent_pkey", dropped: true},
		{name: "tx_route_parent_id_seq", dropped: true},
		{name: "tx_route_view", dropped: true},
		{name: "tx_route_n_idx", dropped: true},
		{name: "tx_route_child"},
		{name: "tx_route_child_id_seq"},
		{name: "tx_route_a", dropped: true},
		{name: "tx_route_b", dropped: true},
		{name: "tx_route_mixed", dropped: true},
	}
	for i := range objects {
		o := &objects[i]
		err := c.QueryRowContext(p.Ctx, `SELECT c.oid,c.reltype,COALESCE(t.typarray,0),c.relacl::text FROM pg_class c LEFT JOIN pg_type t ON t.oid=c.reltype WHERE c.oid=$1::regclass`, o.name).Scan(&o.oid, &o.rowtype, &o.array, &o.acl)
		if err != nil || o.oid <= 0 {
			t.Fatal(o.name, err)
		}
		if o.name == "tx_route_parent" || o.name == "tx_route_child" || o.name == "tx_route_a" || o.name == "tx_route_b" || o.name == "tx_route_mixed" {
			if !o.acl.Valid || o.rowtype <= 0 || o.array <= 0 || o.rowtype == o.array {
				t.Fatalf("missing ACL/rowtype companions: %+v", *o)
			}
		}
	}
	constraints := []struct {
		name  string
		kind  string
		table int64
		oid   int64
	}{
		{name: "tx_route_parent_pkey", kind: "p", table: objects[0].oid},
		{name: "tx_route_positive", kind: "c", table: objects[0].oid},
		{name: "tx_route_fk", kind: "f", table: objects[5].oid},
	}
	for i := range constraints {
		k := &constraints[i]
		if err := c.QueryRowContext(p.Ctx, "SELECT oid FROM pg_constraint WHERE conname=$1 AND conrelid=$2", k.name, k.table).Scan(&k.oid); err != nil || k.oid <= 0 {
			t.Fatal(k.name, err)
		}
	}
	var tempOID int64
	if err := c.QueryRowContext(p.Ctx, "SELECT 'tx_route_temp'::regclass::oid").Scan(&tempOID); err != nil {
		t.Fatal(err)
	}

	count := func(e fixture.Executor, q string, n int64, args ...any) {
		runOn(e, fixture.Select(q, []string{"count"}, []string{"INT8"}, [][]any{{n}}, args...))
	}
	// Identity/ACL values are captured from real predecessors, never equated
	// across backends. Presence, linkage and cardinality are independent contracts.
	graph := func(e fixture.Executor, dropped, includeData bool) {
		for _, o := range objects {
			n := int64(1)
			if dropped && o.dropped {
				n = 0
			}
			var acl any
			if o.acl.Valid {
				acl = o.acl.String
			}
			var rows [][]any
			if n == 1 {
				rows = [][]any{{o.oid, o.rowtype, acl}}
			}
			runOn(e, fixture.Select("SELECT oid::bigint AS oid,reltype::bigint AS reltype,relacl::text AS acl FROM pg_class WHERE relnamespace='public'::regnamespace AND relname=$1", []string{"oid", "reltype", "acl"}, []string{"INT8", "INT8", "TEXT"}, rows, o.name))
			if o.rowtype != 0 {
				count(e, "SELECT count(*) FROM pg_type WHERE oid=$1 AND typrelid=$2 AND typarray=$3", n, o.rowtype, o.oid, o.array)
				count(e, "SELECT count(*) FROM pg_type WHERE oid=$1 AND typelem=$2", n, o.array, o.rowtype)
			}
			if n == 0 {
				count(e, "SELECT count(*) FROM pg_depend WHERE (classid='pg_class'::regclass AND objid=$1) OR (refclassid='pg_class'::regclass AND refobjid=$1)", 0, o.oid)
				if o.rowtype != 0 {
					count(e, "SELECT count(*) FROM pg_depend WHERE (classid='pg_type'::regclass AND objid IN ($1,$2)) OR (refclassid='pg_type'::regclass AND refobjid IN ($1,$2))", 0, o.rowtype, o.array)
				}
			}
		}
		n := int64(1)
		if dropped {
			n = 0
		}
		count(e, "SELECT count(*) FROM pg_constraint WHERE conrelid=$1 AND contype IN ('p','c')", 2*n, objects[0].oid)
		count(e, "SELECT count(*) FROM pg_constraint WHERE conrelid=$1 AND confrelid=$2 AND conname='tx_route_fk' AND contype='f'", n, objects[5].oid, objects[0].oid)
		count(e, "SELECT count(*) FROM pg_index WHERE indrelid=$1 AND indexrelid IN ($2,$3)", 2*n, objects[0].oid, objects[1].oid, objects[4].oid)
		count(e, "SELECT count(*) FROM pg_depend WHERE classid='pg_class'::regclass AND objid=$1 AND refclassid='pg_class'::regclass AND refobjid=$2 AND refobjsubid=1 AND deptype='a'", n, objects[2].oid, objects[0].oid)
		count(e, "SELECT count(*) FROM pg_depend WHERE classid='pg_class'::regclass AND objid=$1 AND refclassid='pg_class'::regclass AND refobjid=$2 AND refobjsubid=1 AND deptype='i'", 1, objects[6].oid, objects[5].oid)
		count(e, "SELECT count(*) FROM pg_depend d JOIN pg_constraint k ON d.classid='pg_constraint'::regclass AND d.objid=k.oid WHERE k.conname='tx_route_fk' AND k.conrelid=$1 AND d.refclassid='pg_class'::regclass AND d.refobjid=$2", n, objects[5].oid, objects[0].oid)
		count(e, "SELECT count(*) FROM pg_attrdef WHERE adrelid=$1", n, objects[0].oid)
		for _, k := range constraints {
			var rows [][]any
			if !dropped {
				rows = [][]any{{k.oid, k.kind, k.table}}
			}
			runOn(e, fixture.Select("SELECT oid::bigint AS oid,contype::text AS kind,conrelid::bigint AS relation FROM pg_constraint WHERE conname=$1 AND conrelid=$2", []string{"oid", "kind", "relation"}, []string{"INT8", "TEXT", "INT8"}, rows, k.name, k.table))
			if dropped {
				count(e, "SELECT count(*) FROM pg_depend WHERE (classid='pg_constraint'::regclass AND objid=$1) OR (refclassid='pg_constraint'::regclass AND refobjid=$1)", 0, k.oid)
			}
		}
		// Peer data reads wait on AX holds; inspect only catalogs until the end.
		if !includeData {
			return
		}
		runOn(e, fixture.Select("SELECT id,parent FROM tx_route_child", []string{"id", "parent"}, []string{"INT4", "INT4"}, [][]any{{int64(1), int64(1)}}))
		if !dropped {
			runOn(e, fixture.Select("SELECT id,n FROM tx_route_parent", []string{"id", "n"}, []string{"INT4", "INT4"}, [][]any{{int64(1), int64(7)}}))
			runOn(e, fixture.Select("SELECT id FROM tx_route_view", []string{"id"}, []string{"INT4"}, [][]any{{int64(1)}}))
			for _, item := range []struct {
				name  string
				value int64
			}{{"tx_route_a", 11}, {"tx_route_b", 13}, {"tx_route_mixed", 17}} {
				runOn(e, fixture.Select("SELECT v FROM "+item.name, []string{"v"}, []string{"INT4"}, [][]any{{item.value}}))
			}
		}
	}
	graph(c, false, true)
	graph(peer, false, true)

	var e fixture.Executor = c
	var tx *sql.Tx
	if goTx {
		var err error
		tx, err = c.BeginTx(p.Ctx, nil)
		if err != nil {
			t.Fatal(err)
		}
		defer tx.Rollback()
		e = tx
	} else {
		runOn(c, fixture.Exec("BEGIN", 0))
		defer c.ExecContext(p.Ctx, "ROLLBACK")
	}
	run := func(s fixture.Step) { runOn(e, s) }
	queries := []string{
		"DROP TABLE tx_route_parent RESTRICT",
		"DROP TABLE tx_route_a,tx_route_missing",
		"DROP TABLE tx_route_temp,tx_route_mixed,tx_route_missing",
		"DROP TABLE tx_route_parent CASCADE",
		"DROP TABLE tx_route_a,tx_route_b",
		"DROP TABLE tx_route_temp,tx_route_mixed",
	}
	routes := make(map[string]fixture.Executor)
	for _, q := range queries {
		routes[q] = e
		if held {
			stmt, err := e.PrepareContext(p.Ctx, q)
			if err != nil {
				t.Fatal("quiet prepare", q, err)
			}
			defer stmt.Close()
			routes[q] = fixture.HeldStatement{Executor: e, Statement: stmt, SQL: q}
		}
	}
	// Preparing all routes, including missing/dependent targets, changes nothing.
	graph(e, false, true)
	count(e, "SELECT count(*) FROM pg_class WHERE oid=$1", 1, tempOID)
	for cycle := range 2 {
		run(fixture.Exec("SAVEPOINT route_cycle", 0))
		for i, q := range queries[:3] {
			run(fixture.Exec("SAVEPOINT route_failure", 0))
			d := fixture.ControlsReferenceDiagnostic("42P01", `table "tx_route_missing" does not exist`)
			if i == 0 {
				d = fixture.ControlsReferenceDiagnostic("2BP01", "cannot drop table tx_route_parent because other objects depend on it")
				d.Detail = "constraint tx_route_fk on table tx_route_child depends on table tx_route_parent\nview tx_route_view depends on table tx_route_parent"
				d.Hint = "Use DROP ... CASCADE to drop the dependent objects too."
			}
			s := fixture.ErrorDiagnostic(q, d)
			s.ErrorStage = "execute"
			runOn(routes[q], s)
			aborted := fixture.ErrorDiagnostic("SELECT 1", fixture.ControlsReferenceDiagnostic("25P02", "current transaction is aborted, commands ignored until end of transaction block"))
			aborted.SelectRows, aborted.ErrorStage = true, "execute"
			run(aborted)
			run(fixture.Exec("ROLLBACK TO route_failure", 0))
			run(fixture.Exec("RELEASE route_failure", 0))
			graph(e, false, true)
			run(fixture.Select("SELECT v FROM tx_route_temp", []string{"v"}, []string{"INT4"}, [][]any{{int64(19)}}))
			count(e, "SELECT count(*) FROM pg_class WHERE oid=$1", 1, tempOID)
			graph(peer, false, false)
		}
		for _, q := range queries[3:] {
			runOn(routes[q], fixture.Exec(q, 0))
		}
		graph(e, true, true)
		count(e, "SELECT count(*) FROM pg_class WHERE oid=$1", 0, tempOID)
		graph(peer, false, false)
		if cycle == 0 {
			run(fixture.Exec("ROLLBACK TO route_cycle", 0))
			run(fixture.Exec("RELEASE route_cycle", 0))
			graph(e, false, true)
			run(fixture.Select("SELECT v FROM tx_route_temp", []string{"v"}, []string{"INT4"}, [][]any{{int64(19)}}))
			count(e, "SELECT count(*) FROM pg_class WHERE oid=$1", 1, tempOID)
		}
	}
	if goTx {
		var err error
		if commit {
			err = tx.Commit()
		} else {
			err = tx.Rollback()
		}
		if err != nil {
			t.Fatal(err)
		}
	} else {
		end := "ROLLBACK"
		if commit {
			end = "COMMIT"
		}
		run(fixture.Exec(end, 0))
	}
	graph(peer, commit, true)
	tempCount := int64(1)
	if commit {
		tempCount = 0
	}
	count(c, "SELECT count(*) FROM pg_class WHERE oid=$1", tempCount, tempOID)
	if !commit {
		runOn(c, fixture.Select("SELECT v FROM tx_route_temp", []string{"v"}, []string{"INT4"}, [][]any{{int64(19)}}))
	}
}
