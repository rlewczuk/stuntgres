package reference_test

import (
	"database/sql"
	"stuntgres/reference/fixture"
	"testing"
)

func TestReferenceAlterIdentityTransactionalAtomicity(t *testing.T) {
	for _, prepared := range []bool{false, true} {
		fixture.AlterIdentityScenario(t, func(t *testing.T, p *fixture.Pair, b fixture.Backend, c *sql.Conn) {
			run := func(s fixture.Step) { fixture.RunStep(t, p.Ctx, c, b.Recorder, s) }
			defer c.ExecContext(p.Ctx, `ROLLBACK`)
			run(fixture.Exec(`CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY(CACHE 1),other INT NOT NULL)`, 0))
			run(fixture.Exec(`INSERT INTO i VALUES(DEFAULT,7)`, 1))
			held := fixture.IdentityHeld(t, p.Ctx, c, `INSERT INTO i VALUES(DEFAULT,7)`)
			for _, q := range []string{
				`ALTER TABLE i ALTER id SET GENERATED BY DEFAULT RESTART WITH 100, ALTER other SET GENERATED ALWAYS`,
				`ALTER TABLE i ALTER id DROP IDENTITY, ALTER other SET GENERATED ALWAYS`,
			} {
				before := ""
				if !b.PG {
					before = referenceDDLNativeDump(t, p)
				}
				s := fixture.ImplicitError(q, fixture.Diagnostic{Code: "55000", Message: `column "other" of relation "i" is not an identity column`})
				s.Prepared = prepared
				run(s)
				if !b.PG && before != referenceDDLNativeDump(t, p) {
					t.Fatal("late action published partial state")
				}
				run(fixture.Select(`SELECT * FROM i`, []string{"id", "other"}, []string{"INT4", "INT4"}, [][]any{{int64(1), int64(7)}}))
				run(fixture.Select(`SELECT last_value,is_called FROM i_id_seq`, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(1), true}}))
				run(fixture.ImplicitError(`INSERT INTO i VALUES(99,7)`, fixture.IdentityAlwaysDiagnostic()))
			}
			fixture.RunStep(t, p.Ctx, held, b.Recorder, fixture.Exec(held.SQL, 1))
			run(fixture.Select(`SELECT * FROM i ORDER BY id`, []string{"id", "other"}, []string{"INT4", "INT4"}, [][]any{{int64(1), int64(7)}, {int64(2), int64(7)}}))
			// First-action-alone controls establish that the failing action is genuinely later.
			for _, q := range []string{`BEGIN`, `ALTER TABLE i ALTER id SET GENERATED BY DEFAULT RESTART 100`, `ROLLBACK`, `BEGIN`, `ALTER TABLE i ALTER id DROP IDENTITY`, `ROLLBACK`} {
				run(fixture.Exec(q, 0))
			}
			run(fixture.Exec(`CREATE TABLE a(id INT NOT NULL)`, 0))
			run(fixture.Exec(`INSERT INTO a VALUES(40)`, 1))
			before := ""
			if !b.PG {
				before = referenceDDLNativeDump(t, p)
			}
			s := fixture.ImplicitError(`ALTER TABLE a ALTER id ADD GENERATED ALWAYS AS IDENTITY, ALTER id SET CACHE 0`, fixture.Diagnostic{Code: "22023", Message: "CACHE (0) must be greater than zero"})
			s.Prepared = prepared
			run(s)
			if !b.PG && before != referenceDDLNativeDump(t, p) {
				t.Fatal("failed ADD published sequence")
			}
			fixture.AlterIdentityMissing(t, p, b, c, "a_id_seq")
			for _, q := range []string{`BEGIN`, `ALTER TABLE a ALTER id ADD GENERATED ALWAYS AS IDENTITY`} {
				run(fixture.Exec(q, 0))
			}
			if !b.PG && before != referenceDDLNativeDump(t, p) {
				t.Fatal("Dump included private ADD")
			}
			run(fixture.Exec(`ROLLBACK`, 0))
			fixture.AlterIdentityMissing(t, p, b, c, "a_id_seq")
			run(fixture.ImplicitError(`INSERT INTO a DEFAULT VALUES`, fixture.Diagnostic{Code: "23502", Message: `null value in column "id" of relation "a" violates not-null constraint`, Detail: "Failing row contains (null).", Schema: "public", Table: "a", Column: "id"}))
			for _, q := range []string{`BEGIN`, `ALTER TABLE a ALTER id ADD GENERATED ALWAYS AS IDENTITY`, `COMMIT`} {
				run(fixture.Exec(q, 0))
			}
			peer := fixture.IdentityConnection(t, p.Ctx, b.DB)
			fixture.RunStep(t, p.Ctx, peer, b.Recorder, fixture.Exec(`INSERT INTO a DEFAULT VALUES`, 1))
			run(fixture.Select(`SELECT * FROM a ORDER BY id`, []string{"id"}, []string{"INT4"}, [][]any{{int64(1)}, {int64(40)}}))
			for _, q := range []string{`BEGIN`, `ALTER TABLE i ALTER id SET GENERATED BY DEFAULT`, `ROLLBACK`} {
				run(fixture.Exec(q, 0))
			}
			run(fixture.ImplicitError(`INSERT INTO i VALUES(99,7)`, fixture.IdentityAlwaysDiagnostic()))
			for _, q := range []string{`BEGIN`, `ALTER TABLE i ALTER id RESTART 100`} {
				run(fixture.Exec(q, 0))
			}
			privateBaseline := ""
			if !b.PG {
				privateBaseline = referenceDDLNativeDump(t, p)
			}
			fixture.RunStep(t, p.Ctx, held, b.Recorder, fixture.Exec(held.SQL, 1))
			if !b.PG && privateBaseline != referenceDDLNativeDump(t, p) {
				t.Fatal("Dump included private restart or row")
			}
			run(fixture.Exec(`ROLLBACK`, 0))
			// Private generator rollback does not erase physical-session sequence memories.
			run(fixture.Select(`SELECT currval('i_id_seq'),lastval()`, []string{"currval", "lastval"}, []string{"INT8", "INT8"}, [][]any{{int64(100), int64(100)}}))
			for _, q := range []string{`BEGIN`, `SAVEPOINT s`, `ALTER TABLE i ALTER id SET GENERATED BY DEFAULT SET INCREMENT 3 SET START 20 RESTART 20`} {
				run(fixture.Exec(q, 0))
			}
			fixture.RunStep(t, p.Ctx, held, b.Recorder, fixture.Exec(held.SQL, 1))
			for _, q := range []string{`ROLLBACK TO s`, `RELEASE s`, `COMMIT`} {
				run(fixture.Exec(q, 0))
			}
			run(fixture.ImplicitError(`INSERT INTO i VALUES(99,7)`, fixture.IdentityAlwaysDiagnostic()))
			run(fixture.Select(`SELECT last_value,is_called FROM i_id_seq`, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(2), true}}))
			fixture.RunStep(t, p.Ctx, held, b.Recorder, fixture.Exec(held.SQL, 1))
			run(fixture.Select(`SELECT * FROM i ORDER BY id`, []string{"id", "other"}, []string{"INT4", "INT4"}, [][]any{{int64(1), int64(7)}, {int64(2), int64(7)}, {int64(3), int64(7)}}))
			for _, q := range []string{`BEGIN`, `ALTER TABLE i ALTER id SET GENERATED BY DEFAULT`, `COMMIT`} {
				run(fixture.Exec(q, 0))
			}
			fixture.RunStep(t, p.Ctx, peer, b.Recorder, fixture.Exec(`INSERT INTO i VALUES(99,7)`, 1))
		})
	}
}
