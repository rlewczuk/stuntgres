func persistenceValue(t *testing.T,p *fixture.Pair,b fixture.Backend,x fixture.Executor,expression string,want int64) {
	t.Helper()
	persistenceRun(t,p,b,x,fixture.Select("SELECT "+expression+" AS v",[]string{"v"},[]string{"INT8"},[][]any{{want}}))
}

func TestReferenceAlterPersistenceSequences(t *testing.T) {
	t.Run("self-sequence",persistenceSelfCacheCases)
	t.Run("as-composition",func(t *testing.T) {
		persistenceScenario(t,func(t *testing.T,p *fixture.Pair,b fixture.Backend,c *sql.Conn) {
			persistenceExec(t,p,b,c,"CREATE TABLE t(id int GENERATED BY DEFAULT AS IDENTITY(CACHE 5))")
			persistenceRun(t,p,b,c,fixture.Exec("INSERT INTO t VALUES(7)",1))
			persistenceValue(t,p,b,c,"nextval('t_id_seq')",1)
			want:=persistenceDiagnostic("23514",`check constraint "bad" of relation "t" is violated by some row`)
			want.Schema,want.Table,want.Constraint="public","t","bad"
			persistenceFailure(t,p,b,c,"ALTER TABLE t SET UNLOGGED, ALTER id TYPE bigint, ADD CONSTRAINT bad CHECK(id<0)",true,want)
			persistenceProperty(t,p,b,c,"t","p")
			persistenceProperty(t,p,b,c,"t_id_seq","p")
			persistenceValue(t,p,b,c,"nextval('t_id_seq')",6)
		})
	})
	for _, route := range []string{"commit","rollback-no-demand","rollback-demand","noop","prealigned"} {
		for _, cache := range []string{"1","5"} {
			t.Run(route+cache,func(t *testing.T) {
				persistenceScenario(t,func(t *testing.T,p *fixture.Pair,b fixture.Backend,c *sql.Conn) {
					persistenceExec(t,p,b,c,"CREATE TABLE t(id int)")
					prefix:=""; if route=="prealigned" || route=="noop" {prefix="UNLOGGED "}
					persistenceExec(t,p,b,c,"CREATE "+prefix+"SEQUENCE owned CACHE "+cache+" OWNED BY t.id")
					persistenceExec(t,p,b,c,"CREATE SEQUENCE unrelated CACHE "+cache)
					persistenceExec(t,p,b,c,"ALTER TABLE t ALTER id SET DEFAULT nextval('unrelated')")
					persistenceValue(t,p,b,c,"nextval('owned')",1)
					persistenceValue(t,p,b,c,"nextval('unrelated')",1)
					if route=="noop" {
						persistenceExec(t,p,b,c,"ALTER TABLE t SET LOGGED")
						persistenceProperty(t,p,b,c,"owned","u")
						persistenceValue(t,p,b,c,"nextval('owned')",2)
					} else {
						tx,err:=c.BeginTx(p.Ctx,nil); if err!=nil {t.Fatal(err)}; defer tx.Rollback()
						persistenceExec(t,p,b,tx,"ALTER TABLE t SET UNLOGGED")
						persistenceProperty(t,p,b,tx,"t","u")
						persistenceProperty(t,p,b,tx,"owned","u")
						if route != "rollback-no-demand" { persistenceValue(t,p,b,tx,"currval('owned')",1) }
						adopted:=int64(2); if cache=="5" {adopted=6}
						if route=="rollback-demand" {persistenceValue(t,p,b,tx,"nextval('owned')",adopted)}
						if route=="rollback-no-demand" || route=="rollback-demand" {
							if err=tx.Rollback();err!=nil {t.Fatal(err)}
							persistenceProperty(t,p,b,c,"t","p")
							if route=="rollback-demand" {persistenceValue(t,p,b,c,"currval('owned')",adopted);persistenceValue(t,p,b,c,"lastval()",adopted);persistenceValue(t,p,b,c,"nextval('owned')",adopted)} else {persistenceValue(t,p,b,c,"nextval('owned')",2)}
						} else {
							if err=tx.Commit();err!=nil {t.Fatal(err)}
							persistenceValue(t,p,b,c,"currval('owned')",1)
							persistenceValue(t,p,b,c,"nextval('owned')",adopted)
							persistenceValue(t,p,b,c,"nextval('owned')",adopted+1)
						}
					}
					persistenceProperty(t,p,b,c,"unrelated","p")
					persistenceValue(t,p,b,c,"nextval('unrelated')",2)
				})
			})
		}
	}
	t.Run("surviving-final-ownership",func(t *testing.T) {
		persistenceScenario(t,func(t *testing.T,p *fixture.Pair,b fixture.Backend,c *sql.Conn) {
			persistenceExec(t,p,b,c,"CREATE TABLE t(id serial,retired int GENERATED BY DEFAULT AS IDENTITY,added int NOT NULL)")
			persistenceExec(t,p,b,c,"ALTER TABLE t SET UNLOGGED, ALTER retired DROP IDENTITY, ALTER added ADD GENERATED BY DEFAULT AS IDENTITY")
			for _, name:=range []string{"t","t_id_seq","t_added_seq"} {persistenceProperty(t,p,b,c,name,"u")}
			persistenceRun(t,p,b,c,fixture.Select("SELECT count(*) FROM pg_class WHERE relname='t_retired_seq'",[]string{"count"},[]string{"INT8"},[][]any{{int64(0)}}))
		})
	})
	t.Run("peer-cache",func(t *testing.T) {
		persistenceScenario(t,func(t *testing.T,p *fixture.Pair,b fixture.Backend,c *sql.Conn) {
			persistenceExec(t,p,b,c,"CREATE TABLE t(id int)")
			persistenceExec(t,p,b,c,"CREATE SEQUENCE owned CACHE 5 OWNED BY t.id")
			peer,err:=b.DB.Conn(p.Ctx);if err!=nil {t.Fatal(err)};defer peer.Close()
			persistenceValue(t,p,b,c,"nextval('owned')",1)
			persistenceValue(t,p,b,peer,"nextval('owned')",6)
			persistenceExec(t,p,b,c,"ALTER TABLE t SET UNLOGGED")
			persistenceValue(t,p,b,peer,"currval('owned')",6)
			persistenceValue(t,p,b,peer,"nextval('owned')",11)
			persistenceValue(t,p,b,c,"nextval('owned')",16)
		})
	})
}
