// Original public consumer routes run in fresh phases; the Context companions remain intact.
func TestReferenceAlterTypeIdentityPrivateDumpHasNoSequencePrefixSourceConsumerRoutes(t *testing.T) {
	p := fixture.NewScenario(t)
	for _, b := range p.Backends() {
		t.Run(b.Name, func(t *testing.T) {
			c, err := b.DB.Conn(p.Ctx)
			if err != nil {
				t.Fatal(err)
			}
			defer c.Close()
			defer c.ExecContext(p.Ctx, "ROLLBACK")
			run := func(s fixture.Step) { fixture.RunStep(t, p.Ctx, c, b.Recorder, s) }
			run(fixture.Exec("CREATE TABLE t(c INT GENERATED BY DEFAULT AS IDENTITY(CACHE 5))", 0))
			run(fixture.Exec("INSERT INTO t DEFAULT VALUES", 1))
			var before bytes.Buffer
			if !b.PG {
				if err := stuntgres.Dump(p.Ctx, p.Native, &before); err != nil {
					t.Fatal(err)
				}
			}
			for _, q := range []string{"BEGIN", "ALTER TABLE t ALTER c TYPE BIGINT"} {
				run(fixture.Exec(q, 0))
			}
			run(fixture.Exec("INSERT INTO t DEFAULT VALUES", 1))
			run(fixture.Select("SELECT c FROM t ORDER BY c", []string{"c"}, []string{"INT8"}, [][]any{{int64(1)}, {int64(6)}}))
			if !b.PG {
				var during bytes.Buffer
				if err := stuntgres.Dump(p.Ctx, p.Native, &during); err != nil || during.String() != before.String() {
					t.Fatal("private table/sequence prefix leaked", err, during.String(), before.String())
				}
			}
			run(fixture.Exec("ROLLBACK", 0))
			run(fixture.Select("SELECT c FROM t", []string{"c"}, []string{"INT4"}, [][]any{{int64(1)}}))
		})
	}
}

func TestReferenceAlterTypePreparedParameterGenerationSourceConsumerRoutes(t *testing.T) {
	p := fixture.NewScenario(t)
	for _, b := range p.Backends() {
		t.Run(b.Name, func(t *testing.T) {
			run := func(s fixture.Step) { s.NonContext = true; fixture.RunStep(t, p.Ctx, b.DB, b.Recorder, s) }
			run(fixture.Exec("CREATE TABLE t(c INT)", 0))
			held, err := b.DB.Prepare("INSERT INTO t VALUES($1)")
			if err != nil {
				t.Fatal(err)
			}
			defer held.Close()
			run(fixture.Exec("ALTER TABLE t ALTER c TYPE BIGINT", 0))
			if !b.PG {
				var dump bytes.Buffer
				if err := stuntgres.Dump(p.Ctx, p.Native, &dump); err != nil {
					t.Fatal(err)
				}
				if err := stuntgres.Reset(p.Ctx, p.Native); err != nil {
					t.Fatal(err)
				}
				if err := stuntgres.Restore(p.Ctx, p.Native, bytes.NewReader(dump.Bytes())); err != nil {
					t.Fatal(err)
				}
			}
			result, err := held.Exec(int64(7))
			if err != nil {
				t.Fatal(err)
			}
			if count, err := result.RowsAffected(); err != nil || count != 1 {
				t.Fatal(count, err)
			}
			if _, err := result.LastInsertId(); err == nil {
				t.Fatal("LastInsertId unexpectedly supported")
			}
			run(fixture.Select("SELECT c FROM t", []string{"c"}, []string{"INT8"}, [][]any{{int64(7)}}))
		})
	}
}
