package reference_test

import (
	"database/sql"
	"stuntgres/reference/fixture"
	"testing"
)

func TestReferenceAlterIdentityAuthorization(t *testing.T) {
	fixture.RoleReferenceCleanup(t, []string{"alter_identity_guest"})
	fixture.AlterIdentityScenario(t, func(t *testing.T, p *fixture.Pair, b fixture.Backend, c *sql.Conn) {
		run := func(s fixture.Step) { fixture.RunStep(t, p.Ctx, c, b.Recorder, s) }
		for _, q := range []string{`CREATE ROLE alter_identity_guest`, `CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY)`, `CREATE TABLE a(id INT NOT NULL)`} {
			run(fixture.Exec(q, 0))
		}
		// The PostgreSQL fixture restricts public-schema visibility. Native's
		// public namespace is already available and has no SQL GRANT capability.
		// This oracle setup grant is not part of the shared ALTER contract.
		if b.PG {
			run(fixture.Exec(`GRANT USAGE ON SCHEMA public TO alter_identity_guest`, 0))
		}
		run(fixture.Exec(`INSERT INTO i DEFAULT VALUES`, 1))
		run(fixture.Exec(`SET ROLE alter_identity_guest`, 0))
		defer c.ExecContext(p.Ctx, `RESET ROLE`)
		for _, q := range []string{`ALTER TABLE a ALTER id ADD GENERATED ALWAYS AS IDENTITY`, `ALTER TABLE i ALTER id DROP IDENTITY`, `ALTER TABLE i ALTER id SET GENERATED BY DEFAULT`, `ALTER TABLE i ALTER id SET CACHE 2`, `ALTER TABLE i ALTER id RESTART 100`} {
			table := "i"
			if q == `ALTER TABLE a ALTER id ADD GENERATED ALWAYS AS IDENTITY` {
				table = "a"
			}
			for _, prepared := range []bool{false, true} {
				s := fixture.ImplicitError(q, fixture.Diagnostic{Code: "42501", Message: `must be owner of table ` + table})
				s.Prepared = prepared
				s.ErrorStage = "execute"
				run(s)
			}
		}
		run(fixture.Exec(`RESET ROLE`, 0))
		for _, q := range []string{`ALTER TABLE a ALTER id ADD GENERATED ALWAYS AS IDENTITY`, `ALTER TABLE i ALTER id DROP IDENTITY`, `ALTER TABLE i ALTER id SET GENERATED BY DEFAULT`, `ALTER TABLE i ALTER id SET CACHE 2`, `ALTER TABLE i ALTER id RESTART 100`} {
			run(fixture.Exec(`BEGIN READ ONLY`, 0))
			s := fixture.ImplicitError(q, fixture.Diagnostic{Code: "25006", Message: "cannot execute ALTER TABLE in a read-only transaction"})
			s.ErrorStage = "execute"
			run(s)
			run(fixture.Exec(`ROLLBACK`, 0))
		}
		run(fixture.ImplicitError(`INSERT INTO i VALUES(99)`, fixture.IdentityAlwaysDiagnostic()))
		run(fixture.Select(`SELECT * FROM i`, []string{"id"}, []string{"INT4"}, [][]any{{int64(1)}}))
		run(fixture.Select(`SELECT last_value,is_called FROM i_id_seq`, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(1), true}}))
		fixture.AlterIdentityMissing(t, p, b, c, "a_id_seq")
		run(fixture.Exec(`ALTER TABLE i ALTER id RESTART 20`, 0))
		run(fixture.Exec(`INSERT INTO i DEFAULT VALUES`, 1))
	})
}
