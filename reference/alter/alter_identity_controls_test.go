package reference_test

import (
	"bytes"
	"context"
	"database/sql"
	"errors"
	"strings"
	"stuntgres"
	"stuntgres/reference/fixture"
	"testing"
)

func TestReferenceAlterIdentityControls(t *testing.T) {
	fixture.AlterIdentityScenario(t, func(t *testing.T, p *fixture.Pair, b fixture.Backend, c *sql.Conn) {
		run := func(s fixture.Step) { fixture.RunStep(t, p.Ctx, c, b.Recorder, s) }
		run(fixture.Exec(`CREATE TABLE a(id INT NOT NULL,dropped INT NOT NULL)`, 0))
		run(fixture.Exec(`INSERT INTO a VALUES(40,400)`, 1))
		for _, q := range []string{`ALTER TABLE a ALTER id ADD GENERATED BY DEFAULT AS IDENTITY(SEQUENCE NAME public.actual CACHE 1)`, `ALTER TABLE a ALTER dropped ADD GENERATED BY DEFAULT AS IDENTITY(SEQUENCE NAME public.removed)`} {
			run(fixture.Exec(q, 0))
		}
		explicit := fixture.IdentityHeld(t, p.Ctx, c, `INSERT INTO a VALUES($1,500)`)
		omitted := fixture.IdentityHeld(t, p.Ctx, c, `INSERT INTO a(dropped) VALUES($1)`)
		run(fixture.Exec(`ALTER TABLE a ALTER dropped DROP IDENTITY`, 0))
		run(fixture.Exec(`ALTER TABLE a ALTER id SET GENERATED ALWAYS SET START 20 SET INCREMENT 3 SET CACHE 1 RESTART 20`, 0))
		fixture.IdentityEmptyMetadata(t, p.Ctx, b, true, `SELECT * FROM a WHERE false`, []string{"id", "dropped"}, []string{"INT4", "INT4"}, []bool{false, false})
		var retained *sql.Rows
		if !b.PG {
			var err error
			retained, err = c.QueryContext(p.Ctx, `SELECT * FROM a ORDER BY id`)
			if err != nil {
				t.Fatal(err)
			}
			defer retained.Close()
			var dump bytes.Buffer
			if err := stuntgres.Dump(p.Ctx, p.Native, &dump); err != nil {
				t.Fatal(err)
			}
			if err := stuntgres.Reset(p.Ctx, p.Native); err != nil {
				t.Fatal(err)
			}
			if err := stuntgres.Restore(p.Ctx, p.Native, bytes.NewReader(dump.Bytes())); err != nil {
				t.Fatal(err)
			}
			var again bytes.Buffer
			if err := stuntgres.Dump(p.Ctx, p.Native, &again); err != nil {
				t.Fatal(err)
			}
			if !bytes.Equal(dump.Bytes(), again.Bytes()) {
				t.Fatal("altered state roundtrip changed canonical bytes")
			}
			for _, script := range []string{`CREATE TABLE replacement(x INT); ALTER TABLE replacement ALTER x ADD GENERATED ALWAYS AS IDENTITY;`, `CREATE TABLE replacement(id INT GENERATED ALWAYS AS IDENTITY); ALTER SEQUENCE replacement_id_seq CACHE 0;`} {
				if err := stuntgres.Restore(p.Ctx, p.Native, strings.NewReader(script)); err == nil {
					t.Fatal("invalid restore accepted")
				}
			}
			failure := errors.New("altered identity reader failure")
			if err := stuntgres.Restore(p.Ctx, p.Native, fixture.IdentityFailingReader{failure}); !errors.Is(err, failure) {
				t.Fatal(err)
			}
			canceled, cancel := context.WithCancel(p.Ctx)
			cancel()
			if err := stuntgres.Restore(canceled, p.Native, bytes.NewReader(dump.Bytes())); !errors.Is(err, context.Canceled) {
				t.Fatal(err)
			}
			if referenceDDLNativeDump(t, p) != dump.String() {
				t.Fatal("failed Restore changed post-ALTER baseline")
			}
			if !retained.Next() {
				t.Fatal(retained.Err())
			}
			var id, dropped int64
			if err := retained.Scan(&id, &dropped); err != nil || id != 40 || dropped != 400 {
				t.Fatal(id, dropped, err)
			}
			if retained.Next() || retained.Err() != nil {
				t.Fatal("retained snapshot changed", retained.Err())
			}
			if err := retained.Close(); err != nil {
				t.Fatal(err)
			}
		}
		// PostgreSQL runs the same ALTER history; no fictional PostgreSQL control API.
		run(fixture.Select(`SELECT * FROM a`, []string{"id", "dropped"}, []string{"INT4", "INT4"}, [][]any{{int64(40), int64(400)}}))
		run(fixture.Select(`SELECT last_value,is_called FROM actual`, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(20), false}}))
		fixture.AlterIdentityMissing(t, p, b, c, "removed")
		fixture.RunStep(t, p.Ctx, explicit, b.Recorder, fixture.ImplicitError(explicit.SQL, fixture.IdentityAlwaysDiagnostic(), 99))
		fixture.RunStep(t, p.Ctx, omitted, b.Recorder, fixture.Exec(omitted.SQL, 1, 500))
		fixture.RunStep(t, p.Ctx, omitted, b.Recorder, fixture.Exec(omitted.SQL, 1, 501))
		run(fixture.Select(`SELECT * FROM a ORDER BY id`, []string{"id", "dropped"}, []string{"INT4", "INT4"}, [][]any{{int64(20), int64(500)}, {int64(23), int64(501)}, {int64(40), int64(400)}}))
		run(fixture.ImplicitError(`INSERT INTO a DEFAULT VALUES`, fixture.Diagnostic{Code: "23502", Message: `null value in column "dropped" of relation "a" violates not-null constraint`, Detail: "Failing row contains (26, null).", Schema: "public", Table: "a", Column: "dropped"}))
	})
}
