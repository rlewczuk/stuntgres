func TestReferenceAlterTypeIdentityTargets(t *testing.T) {
	for _, prepared := range []bool{false, true} {
		for _, tc := range []struct {
			name, decl, target, typ string
			seed, next, min, max    int64
			mode                    string
		}{
			{"widen", "INT GENERATED BY DEFAULT AS IDENTITY", "BIGINT", "INT8", 1, 2, 1, 9223372036854775807, "d"},
			{"always", "INT GENERATED ALWAYS AS IDENTITY", "INT8", "INT8", 1, 2, 1, 9223372036854775807, "a"},
			{"narrow", "BIGINT GENERATED BY DEFAULT AS IDENTITY", "SMALLINT", "INT2", 1, 2, 1, 32767, "d"},
			{"custom", "BIGINT GENERATED BY DEFAULT AS IDENTITY(MINVALUE 1 MAXVALUE 100 START 1)", "INT2", "INT2", 1, 2, 1, 100, "d"},
			{"options", "INT GENERATED BY DEFAULT AS IDENTITY(MINVALUE -100 MAXVALUE 100 START 7 INCREMENT 3 CACHE 1 CYCLE)", "BIGINT", "INT8", 7, 10, -100, 100, "d"},
			{"descending", "INT GENERATED BY DEFAULT AS IDENTITY(INCREMENT -1)", "BIGINT", "INT8", -1, -2, -9223372036854775808, -1, "d"},
		} {
			t.Run(tc.name+fmt.Sprint(prepared), func(t *testing.T) {
				p := fixture.NewScenario(t)
				for _, b := range p.Backends() {
					t.Run(b.Name, func(t *testing.T) {
						c, err := b.DB.Conn(p.Ctx)
						if err != nil {
							t.Fatal(err)
						}
						defer c.Close()
						run := func(s fixture.Step) { fixture.RunStep(t, p.Ctx, c, b.Recorder, s) }
						run(fixture.Exec("CREATE TABLE t(c "+tc.decl+")", 0))
						run(fixture.Exec("INSERT INTO t DEFAULT VALUES", 1))
						held, err := c.PrepareContext(p.Ctx, "INSERT INTO t DEFAULT VALUES")
						if err != nil {
							t.Fatal(err)
						}
						defer held.Close()
						heldSelect, err := c.PrepareContext(p.Ctx, "SELECT c FROM t")
						if err != nil {
							t.Fatal(err)
						}
						defer heldSelect.Close()
						var old *sql.Rows
						if !b.PG {
							old, err = c.QueryContext(p.Ctx, "SELECT c FROM t")
							if err != nil {
								t.Fatal(err)
							}
							defer old.Close()
						}
						var table, sequence, attribute int64
						if b.Name == "postgres" {
							if err = c.QueryRowContext(p.Ctx, "SELECT 't'::regclass::oid::bigint,'t_c_seq'::regclass::oid::bigint,attnum::bigint FROM pg_attribute WHERE attrelid='t'::regclass AND attname='c'").Scan(&table, &sequence, &attribute); err != nil || table <= 0 || sequence <= 0 || table == sequence || attribute != 1 {
								t.Fatal(table, sequence, attribute, err)
							}
						}
						action := fixture.Exec("ALTER TABLE t ALTER c TYPE "+tc.target, 0)
						action.Prepared = prepared
						run(action)
						changed, err := heldSelect.QueryContext(p.Ctx)
						if changed != nil {
							changed.Close()
							t.Fatal("failed held SELECT returned cursor")
						}
						fixture.AssertDiagnostic(t, err, &fixture.Diagnostic{Severity: "ERROR", SeverityUnlocalized: "ERROR", Code: "0A000", Message: "cached plan must not change result type"})
						if old != nil {
							alterTypeIdentityOldRows(t, old, tc.decl, tc.seed)
						}
						rows := [][]any{{tc.seed}, {tc.next}}
						if tc.seed > tc.next {
							rows = [][]any{{tc.next}, {tc.seed}}
						}
						x := fixture.HeldStatement{Executor: c, Statement: held, SQL: "INSERT INTO t DEFAULT VALUES"}
						fixture.RunStep(t, p.Ctx, x, b.Recorder, fixture.Exec(x.SQL, 1))
						run(fixture.Select("SELECT c FROM t ORDER BY c", []string{"c"}, []string{tc.typ}, rows))
						if b.Name == "postgres" {
							var oid, linkedTable, linkedAttribute int64
							var mode, dependency string
							var notnull bool
							if err = c.QueryRowContext(p.Ctx, "SELECT s.oid::bigint,d.refobjid::bigint,d.refobjsubid::bigint,d.deptype::text,a.attidentity::text,a.attnotnull FROM pg_class s JOIN pg_depend d ON d.objid=s.oid AND d.deptype='i' JOIN pg_attribute a ON a.attrelid=d.refobjid AND a.attnum=d.refobjsubid WHERE s.oid='t_c_seq'::regclass").Scan(&oid, &linkedTable, &linkedAttribute, &dependency, &mode, &notnull); err != nil || oid != sequence || linkedTable != table || linkedAttribute != attribute || dependency != "i" || mode != tc.mode || !notnull {
								t.Fatal("identity reciprocal catalog", oid, linkedTable, linkedAttribute, dependency, mode, notnull, err)
							}
						}
						{
							var typ, min, max, start, increment, cache, sequenceOID int64
							var cycle bool
							if err = c.QueryRowContext(p.Ctx, "SELECT oid FROM pg_class WHERE relname='t_c_seq'").Scan(&sequenceOID); err != nil || sequenceOID <= 0 {
								t.Fatal("identity sequence OID", sequenceOID, err)
							}
							if err = c.QueryRowContext(p.Ctx, "SELECT seqtypid::bigint,seqmin,seqmax,seqstart,seqincrement,seqcache,seqcycle FROM pg_sequence WHERE seqrelid=$1::oid", sequenceOID).Scan(&typ, &min, &max, &start, &increment, &cache, &cycle); err != nil {
								t.Fatal(err)
							}
							wantType := int64(20)
							if tc.typ == "INT2" {
								wantType = 21
							}
							wantIncrement := int64(1)
							if tc.seed < 0 {
								wantIncrement = -1
							}
							if tc.name == "options" {
								wantIncrement = 3
							}
							if typ != wantType || min != tc.min || max != tc.max || start != tc.seed || increment != wantIncrement || cache != 1 || cycle != (tc.name == "options") {
								t.Fatal("identity AS metadata", typ, min, max, start, increment, cache, cycle, tc)
							}
						}
						if tc.name == "descending" {
							run(fixture.Select("SELECT setval('t_c_seq',-2147483648,true)", []string{"setval"}, []string{"INT8"}, [][]any{{int64(-2147483648)}}))
							run(fixture.Exec("INSERT INTO t DEFAULT VALUES", 1))
							run(fixture.Select("SELECT c FROM t WHERE c=-2147483649", []string{"c"}, []string{"INT8"}, [][]any{{int64(-2147483649)}}))
						}
						if tc.name == "widen" || tc.name == "always" {
							run(fixture.Select("SELECT setval('t_c_seq',2147483647,true)", []string{"setval"}, []string{"INT8"}, [][]any{{int64(2147483647)}}))
							run(fixture.Exec("INSERT INTO t DEFAULT VALUES", 1))
							run(fixture.Select("SELECT c FROM t WHERE c=2147483648", []string{"c"}, []string{"INT8"}, [][]any{{int64(2147483648)}}))
						}
						if tc.name == "always" {
							run(fixture.ImplicitError("INSERT INTO t VALUES(99)", fixture.Diagnostic{Code: "428C9", Message: `cannot insert a non-DEFAULT value into column "c"`, Detail: `Column "c" is an identity column defined as GENERATED ALWAYS.`, Hint: "Use OVERRIDING SYSTEM VALUE to override."}))
							run(fixture.Exec("INSERT INTO t OVERRIDING SYSTEM VALUE VALUES(99)", 1))
							run(fixture.Exec("INSERT INTO t OVERRIDING USER VALUE VALUES(9999)", 1))
							run(fixture.Select("SELECT c FROM t WHERE c=2147483649", []string{"c"}, []string{"INT8"}, [][]any{{int64(2147483649)}}))
						}
					})
				}
			})
		}
	}
}

