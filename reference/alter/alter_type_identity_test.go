func TestReferenceAlterTypeIdentityControls(t *testing.T) {
	p := fixture.NewScenario(t)
	for _, s := range []fixture.Step{
		fixture.Exec("CREATE TABLE t(c INT CONSTRAINT nn GENERATED ALWAYS AS IDENTITY(START 7 INCREMENT 3 CACHE 2) CONSTRAINT ck CHECK(c>0),p INT DEFAULT 4)", 0),
		fixture.Exec("COMMENT ON COLUMN t.c IS 'identity column'", 0), fixture.Exec("COMMENT ON SEQUENCE t_c_seq IS 'identity sequence'", 0),
		fixture.Exec("INSERT INTO t DEFAULT VALUES", 1), fixture.Exec("ALTER TABLE t ALTER c TYPE BIGINT", 0),
	} {
		p.Step(t, s)
	}
	var dump bytes.Buffer
	if err := stuntgres.Dump(p.Ctx, p.Native, &dump); err != nil {
		t.Fatal(err)
	}
	for _, text := range []string{"BIGINT", "GENERATED ALWAYS AS IDENTITY", "CACHE 2", "nn", "ck", "identity column", "identity sequence"} {
		if !strings.Contains(dump.String(), text) {
			t.Fatal(text, dump.String())
		}
	}
	if strings.Contains(dump.String(), "ALTER TABLE") || strings.Contains(dump.String(), "CREATE SEQUENCE") {
		t.Fatal("identity history or duplicate", dump.String())
	}
	if err := stuntgres.Reset(p.Ctx, p.Native); err != nil {
		t.Fatal(err)
	}
	if err := stuntgres.Restore(p.Ctx, p.Native, bytes.NewReader(dump.Bytes())); err != nil {
		t.Fatal(err)
	}
	var again bytes.Buffer
	if err := stuntgres.Dump(p.Ctx, p.Native, &again); err != nil || again.String() != dump.String() {
		t.Fatal(err, again.String(), dump.String())
	}
	p.Step(t, fixture.Exec("INSERT INTO t DEFAULT VALUES", 1))
	p.Step(t, fixture.Select("SELECT * FROM t ORDER BY c", []string{"c", "p"}, []string{"INT8", "INT4"}, [][]any{{int64(7), int64(4)}, {int64(13), int64(4)}}))
	p.Step(t, fixture.ImplicitError("INSERT INTO t VALUES(99,4)", fixture.Diagnostic{Code: "428C9", Message: `cannot insert a non-DEFAULT value into column "c"`, Detail: `Column "c" is an identity column defined as GENERATED ALWAYS.`, Hint: "Use OVERRIDING SYSTEM VALUE to override."}))
	p.Step(t, fixture.ImplicitError("INSERT INTO t OVERRIDING SYSTEM VALUE VALUES(-1,4)", fixture.Diagnostic{Code: "23514", Message: `new row for relation "t" violates check constraint "ck"`, Detail: "Failing row contains (-1, 4).", Schema: "public", Table: "t", Constraint: "ck"}))
	p.Step(t, fixture.Select("SELECT setval('t_c_seq',2147483647,true)", []string{"setval"}, []string{"INT8"}, [][]any{{int64(2147483647)}}))
	p.Step(t, fixture.Exec("INSERT INTO t DEFAULT VALUES", 1))
	p.Step(t, fixture.Select("SELECT c FROM t WHERE c=2147483650", []string{"c"}, []string{"INT8"}, [][]any{{int64(2147483650)}}))
}

