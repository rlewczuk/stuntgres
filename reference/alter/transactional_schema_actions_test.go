package reference_test

import (
	"fmt"
	"testing"

	"stuntgres/reference/fixture"
)

// Each row exercises its actual action, not an ADD COLUMN stand-in. The target
// is either newly private or renamed privately after legitimate standalone setup.
func TestReferenceTransactionalSchemaActions(t *testing.T) {
	attribute := func(column, expression string) string {
		return "SELECT " + expression + " AS ok FROM pg_attribute WHERE attrelid='tx_action'::regclass AND attname='" + column + "' AND NOT attisdropped"
	}
	constraint := func(name string) string {
		return "SELECT EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid='tx_action'::regclass AND conname='" + name + "') AS ok"
	}
	type actionCase struct {
		name, definition, action, probe string
		before, after                   bool
		standalone, setup               []string
		failure                         string
		diagnostic                      fixture.Diagnostic
	}
	cases := []actionCase{
		{name: "SetNotNull", definition: "a INT", action: "ALTER a SET NOT NULL", probe: attribute("a", "attnotnull"), after: true,
			failure: "INSERT INTO tx_action VALUES(NULL)", diagnostic: fixture.Diagnostic{Code: "23502", Message: `null value in column "a" of relation "tx_action" violates not-null constraint`, Detail: "Failing row contains (null).", Schema: "public", Table: "tx_action", Column: "a"}},
		{name: "DropNotNull", definition: "a INT NOT NULL", action: "ALTER a DROP NOT NULL", probe: attribute("a", "attnotnull"), before: true},
		{name: "AddNotNull", definition: "a INT", action: "ADD CONSTRAINT tx_nn NOT NULL a", probe: constraint("tx_nn"), after: true,
			failure: "INSERT INTO tx_action VALUES(NULL)", diagnostic: fixture.Diagnostic{Code: "23502", Message: `null value in column "a" of relation "tx_action" violates not-null constraint`, Detail: "Failing row contains (null).", Schema: "public", Table: "tx_action", Column: "a"}},
		{name: "DropConstraint", definition: "a INT CONSTRAINT tx_ck CHECK(a>0)", action: "DROP CONSTRAINT tx_ck", probe: constraint("tx_ck"), before: true},
		{name: "DropColumn", definition: "a INT,b TEXT", action: "DROP COLUMN b", probe: "SELECT EXISTS(SELECT 1 FROM pg_attribute WHERE attrelid='tx_action'::regclass AND attname='b' AND NOT attisdropped) AS ok", before: true},
		{name: "AddIdentity", definition: "a INT,b INT NOT NULL DEFAULT 40", action: "ALTER b ADD GENERATED BY DEFAULT AS IDENTITY", setup: []string{"ALTER TABLE tx_action ALTER b DROP DEFAULT"}, probe: attribute("b", "attidentity='d'"), after: true},
		{name: "DropIdentity", definition: "a INT,b INT GENERATED BY DEFAULT AS IDENTITY", action: "ALTER b DROP IDENTITY", probe: attribute("b", "attidentity='d'"), before: true,
			failure: "INSERT INTO tx_action(a) VALUES(8)", diagnostic: fixture.Diagnostic{Code: "23502", Message: `null value in column "b" of relation "tx_action" violates not-null constraint`, Detail: "Failing row contains (8, null).", Schema: "public", Table: "tx_action", Column: "b"}},
		{name: "SetIdentity", definition: "a INT,b INT GENERATED BY DEFAULT AS IDENTITY", action: "ALTER b SET GENERATED ALWAYS", probe: attribute("b", "attidentity='a'"), after: true,
			failure: "INSERT INTO tx_action VALUES(8,99)", diagnostic: fixture.Diagnostic{Code: "428C9", Message: `cannot insert a non-DEFAULT value into column "b"`, Detail: `Column "b" is an identity column defined as GENERATED ALWAYS.`, Hint: "Use OVERRIDING SYSTEM VALUE to override."}},
		{name: "AlterColumnType", definition: "a INT", action: "ALTER a TYPE BIGINT USING a+1", probe: attribute("a", "atttypid='int8'::regtype"), after: true},
		{name: "AddColumn", definition: "a INT", action: "ADD COLUMN b INT DEFAULT 11", probe: "SELECT EXISTS(SELECT 1 FROM pg_attribute WHERE attrelid='tx_action'::regclass AND attname='b' AND NOT attisdropped) AS ok", after: true},
		{name: "AddExclusion", definition: "a INT", action: "ADD CONSTRAINT tx_ex EXCLUDE(a WITH =)", probe: constraint("tx_ex"), after: true,
			failure: "INSERT INTO tx_action VALUES(7)", diagnostic: fixture.ExclusionReferenceConflict("tx_action", "tx_ex", "a", "7", "7")},
		{name: "EnableRowSecurity", definition: "a INT", action: "ENABLE ROW LEVEL SECURITY", probe: "SELECT relrowsecurity AS ok FROM pg_class WHERE oid='tx_action'::regclass", after: true},
		{name: "DisableRowSecurity", definition: "a INT", setup: []string{"ALTER TABLE tx_action ENABLE ROW LEVEL SECURITY"}, action: "DISABLE ROW LEVEL SECURITY", probe: "SELECT relrowsecurity AS ok FROM pg_class WHERE oid='tx_action'::regclass", before: true},
		{name: "ForceRowSecurity", definition: "a INT", action: "FORCE ROW LEVEL SECURITY", probe: "SELECT relforcerowsecurity AS ok FROM pg_class WHERE oid='tx_action'::regclass", after: true},
		{name: "NoForceRowSecurity", definition: "a INT", setup: []string{"ALTER TABLE tx_action FORCE ROW LEVEL SECURITY"}, action: "NO FORCE ROW LEVEL SECURITY", probe: "SELECT relforcerowsecurity AS ok FROM pg_class WHERE oid='tx_action'::regclass", before: true},
		// CREATE INDEX is deliberately outside BEGIN. Its table becomes private
		// through RENAME before the attachment consumes the index provider.
		{name: "AddUsingIndex", standalone: []string{"CREATE TABLE tx_action_old(a INT)", "INSERT INTO tx_action_old VALUES(7)", "CREATE UNIQUE INDEX tx_using ON tx_action_old(a)"}, action: "ADD CONSTRAINT tx_using UNIQUE USING INDEX tx_using", probe: constraint("tx_using"), after: true},
		{name: "SetExpression", definition: "a INT,b INT GENERATED ALWAYS AS(a+1) STORED", action: "ALTER b SET EXPRESSION AS(a+2)", probe: "SELECT b=9 AS ok FROM tx_action", after: true},
		{name: "DropExpression", definition: "a INT,b INT GENERATED ALWAYS AS(a+1) STORED", action: "ALTER b DROP EXPRESSION", probe: attribute("b", "attgenerated='s'"), before: true},
		{name: "AddCheck", definition: "a INT", action: "ADD CONSTRAINT tx_ck CHECK(a>0)", probe: constraint("tx_ck"), after: true,
			failure: "INSERT INTO tx_action VALUES(-1)", diagnostic: fixture.Diagnostic{Code: "23514", Message: `new row for relation "tx_action" violates check constraint "tx_ck"`, Detail: "Failing row contains (-1).", Schema: "public", Table: "tx_action", Constraint: "tx_ck"}},
		{name: "AddUnique", definition: "a INT", action: "ADD CONSTRAINT tx_unique UNIQUE(a)", probe: constraint("tx_unique"), after: true,
			failure: "INSERT INTO tx_action VALUES(7)", diagnostic: fixture.Diagnostic{Code: "23505", Message: `duplicate key value violates unique constraint "tx_unique"`, Detail: "Key (a)=(7) already exists.", Schema: "public", Table: "tx_action", Constraint: "tx_unique"}},
		{name: "AddForeignKey", definition: "a INT", setup: []string{"CREATE TABLE tx_parent(a INT PRIMARY KEY)", "INSERT INTO tx_parent VALUES(7)"}, action: "ADD CONSTRAINT tx_fk FOREIGN KEY(a) REFERENCES tx_parent(a)", probe: constraint("tx_fk"), after: true,
			failure: "INSERT INTO tx_action VALUES(8)", diagnostic: fixture.Diagnostic{Code: "23503", Message: `insert or update on table "tx_action" violates foreign key constraint "tx_fk"`, Detail: `Key (a)=(8) is not present in table "tx_parent".`, Schema: "public", Table: "tx_action", Constraint: "tx_fk"}},
		{name: "SetTablespace", definition: "a INT", action: "SET TABLESPACE pg_default", probe: "SELECT reltablespace=0::oid AS ok FROM pg_class WHERE oid='tx_action'::regclass", before: true, after: true,
			failure: "ALTER TABLE tx_action SET TABLESPACE pg_global", diagnostic: fixture.Diagnostic{Code: "22023", Message: "only shared relations can be placed in pg_global tablespace"}},
		{name: "InheritTable", definition: "a INT", setup: []string{"CREATE TABLE tx_parent(a INT)"}, action: "INHERIT tx_parent", probe: "SELECT EXISTS(SELECT 1 FROM pg_inherits WHERE inhrelid='tx_action'::regclass AND inhparent='tx_parent'::regclass) AS ok", after: true},
		{name: "NoInheritTable", definition: "a INT", setup: []string{"CREATE TABLE tx_parent(a INT)", "ALTER TABLE tx_action INHERIT tx_parent"}, action: "NO INHERIT tx_parent", probe: "SELECT EXISTS(SELECT 1 FROM pg_inherits WHERE inhrelid='tx_action'::regclass AND inhparent='tx_parent'::regclass) AS ok", before: true},
		{name: "SetRelationOptions", definition: "a INT", action: "SET (fillfactor=70)", probe: "SELECT reloptions IS NOT NULL AS ok FROM pg_class WHERE oid='tx_action'::regclass", after: true},
		{name: "ResetRelationOptions", definition: "a INT", setup: []string{"ALTER TABLE tx_action SET (fillfactor=70)"}, action: "RESET (fillfactor)", probe: "SELECT reloptions IS NOT NULL AS ok FROM pg_class WHERE oid='tx_action'::regclass", before: true},
		{name: "Of", standalone: []string{"CREATE TYPE tx_pair AS(a INT)"}, definition: "a INT", action: "OF tx_pair", probe: "SELECT reloftype='tx_pair'::regtype AS ok FROM pg_class WHERE oid='tx_action'::regclass", after: true},
		{name: "NotOf", standalone: []string{"CREATE TYPE tx_pair AS(a INT)"}, definition: "OF tx_pair", action: "NOT OF", probe: "SELECT reloftype='tx_pair'::regtype AS ok FROM pg_class WHERE oid='tx_action'::regclass", before: true},
		{name: "Owner", standalone: []string{"CREATE ROLE tx_action_owner", "GRANT USAGE,CREATE ON SCHEMA public TO tx_action_owner"}, definition: "a INT", action: "OWNER TO tx_action_owner", probe: "SELECT relowner=(SELECT oid FROM pg_roles WHERE rolname='tx_action_owner') AS ok FROM pg_class WHERE oid='tx_action'::regclass", after: true},
		{name: "AllInTablespace", definition: "a INT", action: "ALTER TABLE ALL IN TABLESPACE pg_default OWNED BY CURRENT_USER SET TABLESPACE pg_default NOWAIT", probe: "SELECT reltablespace=0::oid AS ok FROM pg_class WHERE oid='tx_action'::regclass", before: true, after: true,
			failure: "ALTER TABLE ALL IN TABLESPACE pg_default SET TABLESPACE pg_global", diagnostic: fixture.Diagnostic{Code: "22023", Message: "cannot move relations in to or out of pg_global tablespace"}},
		{name: "AttachPartition", definition: "a INT", setup: []string{"CREATE TABLE tx_parent(a INT) PARTITION BY RANGE(a)"}, action: "ALTER TABLE tx_parent ATTACH PARTITION tx_action FOR VALUES FROM(0) TO(10)", probe: "SELECT relispartition AS ok FROM pg_class WHERE oid='tx_action'::regclass", after: true},
		{name: "DetachPartition", definition: "a INT", setup: []string{"CREATE TABLE tx_parent(a INT) PARTITION BY RANGE(a)", "ALTER TABLE tx_parent ATTACH PARTITION tx_action FOR VALUES FROM(0) TO(10)"}, action: "ALTER TABLE tx_parent DETACH PARTITION tx_action", probe: "SELECT relispartition AS ok FROM pg_class WHERE oid='tx_action'::regclass", before: true},
		{name: "PrivateRowtypeColumn", definition: "a INT", setup: []string{"CREATE TABLE tx_provider(v INT)"}, action: "ADD COLUMN b tx_provider DEFAULT '(11)'::tx_provider", probe: "SELECT b::text='(11)' AS ok FROM tx_action", before: true, after: true},
	}
	for _, tc := range cases {
		for _, held := range []bool{false, true} {
			for _, goTx := range []bool{false, true} {
				t.Run(fmt.Sprintf("%s/held=%v/goTx=%v", tc.name, held, goTx), func(t *testing.T) {
					fixture.RoleReferenceCleanup(t, []string{"tx_action_owner"})
					p := fixture.NewScenario(t)
					for _, b := range p.Backends() {
						t.Run(b.Name, func(t *testing.T) {
							c, peer := fixture.LockConnections(t, p.Ctx, b.DB)
							for _, q := range tc.standalone {
								count := int64(0)
								if q == "INSERT INTO tx_action_old VALUES(7)" {
									count = 1
								}
								fixture.RunStep(t, p.Ctx, c, b.Recorder, fixture.Exec(q, count))
							}
							var e fixture.Executor = c
							rollback := func() { fixture.LockExec(t, p.Ctx, c, "ROLLBACK", 0) }
							if goTx {
								tx, err := c.BeginTx(p.Ctx, nil)
								if err != nil {
									t.Fatal(err)
								}
								defer tx.Rollback()
								e = tx
								rollback = func() {
									if err := tx.Rollback(); err != nil {
										t.Fatal(err)
									}
								}
							} else {
								fixture.LockExec(t, p.Ctx, c, "BEGIN", 0)
								defer c.ExecContext(p.Ctx, "ROLLBACK")
							}
							run := func(s fixture.Step) { fixture.RunStep(t, p.Ctx, e, b.Recorder, s) }
							if tc.definition != "" {
								definition := "(" + tc.definition + ")"
								if tc.name == "NotOf" {
									definition = tc.definition
								}
								run(fixture.Exec("CREATE TABLE tx_action_old"+" "+definition, 0))
								run(fixture.Exec("INSERT INTO tx_action_old(a) VALUES(7)", 1))
							}
							run(fixture.Exec("ALTER TABLE tx_action_old RENAME TO tx_action", 0))
							for _, q := range tc.setup {
								count := int64(0)
								if q == "INSERT INTO tx_parent VALUES(7)" {
									count = 1
								}
								run(fixture.Exec(q, count))
							}
							rows := fixture.Select("SELECT a::int AS a FROM tx_action", []string{"a"}, []string{"INT4"}, [][]any{{int64(7)}})
							run(rows)
							probe := func(want bool) { run(fixture.Select(tc.probe, []string{"ok"}, []string{"BOOL"}, [][]any{{want}})) }
							before := func() {
								if tc.name == "PrivateRowtypeColumn" {
									run(fixture.Select("SELECT count(*) FROM pg_attribute WHERE attrelid='tx_action'::regclass AND attname='b' AND NOT attisdropped", []string{"count"}, []string{"INT8"}, [][]any{{int64(0)}}))
								} else {
									probe(tc.before)
								}
							}
							before()
							run(fixture.Exec("SAVEPOINT action", 0))
							q := tc.action
							if tc.name != "AllInTablespace" && tc.name != "AttachPartition" && tc.name != "DetachPartition" {
								q = "ALTER TABLE tx_action " + q
							}
							if held {
								stmt, err := e.PrepareContext(p.Ctx, q)
								if err != nil {
									t.Fatal(err)
								}
								defer stmt.Close()
								before()
								fixture.RunStep(t, p.Ctx, fixture.HeldStatement{Executor: e, Statement: stmt, SQL: q}, b.Recorder, fixture.Exec(q, 0))
							} else {
								run(fixture.Exec(q, 0))
							}
							probe(tc.after)
							fixture.RunStep(t, p.Ctx, peer, b.Recorder, fixture.Select("SELECT count(*) FROM pg_class WHERE relnamespace='public'::regnamespace AND relname IN ('tx_action','tx_provider','tx_parent')", []string{"count"}, []string{"INT8"}, [][]any{{int64(0)}}))
							if tc.name == "AlterColumnType" {
								run(fixture.Select("SELECT a FROM tx_action", []string{"a"}, []string{"INT8"}, [][]any{{int64(8)}}))
							} else {
								run(rows)
							}
							if tc.name == "AddColumn" {
								run(fixture.Select("SELECT a,b FROM tx_action", []string{"a", "b"}, []string{"INT4", "INT4"}, [][]any{{int64(7), int64(11)}}))
							}
							if tc.name == "AddIdentity" || tc.name == "DropNotNull" || tc.name == "DropExpression" {
								run(fixture.Exec("SAVEPOINT write_effect", 0))
								switch tc.name {
								case "AddIdentity":
									run(fixture.Exec("INSERT INTO tx_action(a) VALUES(8)", 1))
									run(fixture.Select("SELECT b FROM tx_action WHERE a=8", []string{"b"}, []string{"INT4"}, [][]any{{int64(1)}}))
								case "DropNotNull":
									run(fixture.Exec("INSERT INTO tx_action VALUES(NULL)", 1))
									run(fixture.Select("SELECT a FROM tx_action WHERE a IS NULL", []string{"a"}, []string{"INT4"}, [][]any{{nil}}))
								case "DropExpression":
									run(fixture.Exec("UPDATE tx_action SET a=10", 1))
									run(fixture.Select("SELECT a,b FROM tx_action", []string{"a", "b"}, []string{"INT4", "INT4"}, [][]any{{int64(10), int64(8)}}))
								}
								run(fixture.Exec("ROLLBACK TO write_effect", 0))
							}
							if tc.name == "SetRelationOptions" {
								run(fixture.Select("SELECT reloptions::text AS options FROM pg_class WHERE oid='tx_action'::regclass", []string{"options"}, []string{"TEXT"}, [][]any{{"{fillfactor=70}"}}))
							}
							if tc.name == "PrivateRowtypeColumn" {
								run(fixture.Select("SELECT deptype FROM pg_depend WHERE classid='pg_class'::regclass AND objid='tx_action'::regclass AND objsubid=2 AND refclassid='pg_type'::regclass AND refobjid='tx_provider'::regtype AND refobjsubid=0", []string{"deptype"}, []string{"CHAR"}, [][]any{{"n"}}))
								run(fixture.Select("SELECT t.typrelid=c.oid AND c.reltype=t.oid AS ok FROM pg_class c JOIN pg_type t ON t.oid=c.reltype WHERE c.oid='tx_provider'::regclass", []string{"ok"}, []string{"BOOL"}, [][]any{{true}}))
								run(fixture.Exec("SAVEPOINT provider_write", 0))
								run(fixture.Exec("INSERT INTO tx_action(a) VALUES(8)", 1))
								run(fixture.Select("SELECT b::text AS value FROM tx_action WHERE a=8", []string{"value"}, []string{"TEXT"}, [][]any{{"(11)"}}))
								run(fixture.Exec("ROLLBACK TO provider_write", 0))
								reject := "ALTER TABLE tx_action OF tx_provider"
								want := fixture.ImplicitError(reject, fixture.Diagnostic{Code: "42809", Message: "type tx_provider is the row type of another table", Detail: "A typed table must use a stand-alone composite type created with CREATE TYPE."})
								want.ErrorStage = "execute"
								if held {
									stmt, err := e.PrepareContext(p.Ctx, reject)
									if err != nil {
										t.Fatal(err)
									}
									defer stmt.Close()
									fixture.RunStep(t, p.Ctx, fixture.HeldStatement{Executor: e, Statement: stmt, SQL: reject}, b.Recorder, want)
								} else {
									run(want)
								}
								run(fixture.ImplicitError("SELECT 1", fixture.Diagnostic{Code: "25P02", Message: "current transaction is aborted, commands ignored until end of transaction block"}))
								run(fixture.Exec("ROLLBACK TO provider_write", 0))
								probe(true)
							}
							if tc.failure != "" {
								run(fixture.Exec("SAVEPOINT enforcement", 0))
								s := fixture.ImplicitError(tc.failure, tc.diagnostic)
								s.ErrorStage = "execute"
								run(s)
								run(fixture.ImplicitError("SELECT 1", fixture.Diagnostic{Code: "25P02", Message: "current transaction is aborted, commands ignored until end of transaction block"}))
								run(fixture.Exec("ROLLBACK TO enforcement", 0))
								probe(tc.after)
							}
							run(fixture.Exec("ROLLBACK TO action", 0))
							if tc.name == "PrivateRowtypeColumn" {
								run(fixture.Select("SELECT count(*) FROM pg_attribute WHERE attrelid='tx_action'::regclass AND attname='b' AND NOT attisdropped", []string{"count"}, []string{"INT8"}, [][]any{{int64(0)}}))
								run(fixture.Select("SELECT count(*) FROM pg_depend WHERE classid='pg_class'::regclass AND objid='tx_action'::regclass AND refclassid='pg_type'::regclass AND refobjid='tx_provider'::regtype", []string{"count"}, []string{"INT8"}, [][]any{{int64(0)}}))
							} else {
								probe(tc.before)
							}
							run(rows)
							rollback()
							fixture.RunStep(t, p.Ctx, peer, b.Recorder, fixture.Select("SELECT count(*) FROM pg_class WHERE relnamespace='public'::regnamespace AND relname IN ('tx_action','tx_provider','tx_parent')", []string{"count"}, []string{"INT8"}, [][]any{{int64(0)}}))
							fixture.RunStep(t, p.Ctx, peer, b.Recorder, fixture.Select("SELECT count(*) FROM pg_type WHERE typnamespace='public'::regnamespace AND typname IN ('tx_action','_tx_action','tx_provider','_tx_provider','tx_parent','_tx_parent')", []string{"count"}, []string{"INT8"}, [][]any{{int64(0)}}))
							if tc.name == "AddUsingIndex" {
								fixture.RunStep(t, p.Ctx, peer, b.Recorder, fixture.Select("SELECT a FROM tx_action_old", []string{"a"}, []string{"INT4"}, [][]any{{int64(7)}}))
								fixture.RunStep(t, p.Ctx, peer, b.Recorder, fixture.Select("SELECT count(*) FROM pg_constraint WHERE conname='tx_using'", []string{"count"}, []string{"INT8"}, [][]any{{int64(0)}}))
							}
						})
					}
				})
			}
		}
	}
}
