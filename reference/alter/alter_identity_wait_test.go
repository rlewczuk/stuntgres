package reference_test

import (
	"context"
	"database/sql"
	"errors"
	"stuntgres/reference/fixture"
	"testing"
	"time"
)

func TestReferenceAlterIdentityWaitCancellation(t *testing.T) {
	cases := []struct {
		name, query      string
		ordinary, linked bool
	}{
		{"table_add", `ALTER TABLE i ALTER id ADD GENERATED ALWAYS AS IDENTITY`, true, false},
		{"table_mode", `ALTER TABLE i ALTER id SET GENERATED BY DEFAULT`, false, false},
		{"table_options", `ALTER TABLE i ALTER id SET CACHE 2`, false, false},
		{"table_restart", `ALTER TABLE i ALTER id RESTART 100`, false, false},
		{"table_drop", `ALTER TABLE i ALTER id DROP IDENTITY`, false, false},
		{"sequence_options", `ALTER TABLE i ALTER id SET CACHE 2`, false, true},
		{"sequence_restart", `ALTER TABLE i ALTER id RESTART 100`, false, true},
		{"sequence_drop", `ALTER TABLE i ALTER id DROP IDENTITY`, false, true},
		{"sequence_staged_mode", `ALTER TABLE i ALTER id SET GENERATED BY DEFAULT, ALTER id RESTART 100`, false, true},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			fixture.AlterIdentityScenario(t, func(t *testing.T, p *fixture.Pair, b fixture.Backend, c *sql.Conn) {
				ctx, stop := context.WithTimeout(p.Ctx, 10*time.Second)
				defer stop()
				run := func(s fixture.Step) { fixture.RunStep(t, ctx, c, b.Recorder, s) }
				create := `CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY(CACHE 1))`
				if tc.ordinary {
					create = `CREATE TABLE i(id INT NOT NULL)`
				}
				run(fixture.Exec(create, 0))
				if tc.ordinary {
					run(fixture.Exec(`INSERT INTO i VALUES(40)`, 1))
				} else {
					run(fixture.Exec(`INSERT INTO i DEFAULT VALUES`, 1))
				}
				holder := fixture.IdentityConnection(t, ctx, b.DB)
				observer := fixture.IdentityConnection(t, ctx, b.DB)
				workerPID, holderPID := 0, 0
				var oid int64
				if b.PG {
					workerPID = fixture.LockPID(t, ctx, c)
					holderPID = fixture.LockPID(t, ctx, holder)
					name := "i"
					if tc.linked {
						name = "i_id_seq"
					}
					oid = fixture.LockOID(t, ctx, name)
				}
				tx, err := holder.BeginTx(ctx, nil)
				if err != nil {
					t.Fatal(err)
				}
				defer tx.Rollback()
				if tc.linked {
					fixture.RunStep(t, ctx, tx, b.Recorder, fixture.Exec(`ALTER SEQUENCE i_id_seq CACHE 1`, 0))
				} else {
					fixture.RunStep(t, ctx, tx, b.Recorder, fixture.Exec(`INSERT INTO i OVERRIDING SYSTEM VALUE VALUES(50)`, 1))
				}
				// Prepare before the wait so reuse is genuinely held, not prepare-per-execution.
				held := fixture.IdentityHeld(t, ctx, c, tc.query)
				waitCtx, cancel := context.WithCancel(ctx)
				done := make(chan error, 1)
				go func() {
					r, e := held.Statement.ExecContext(waitCtx)
					if e == nil {
						n, x := r.RowsAffected()
						if x != nil {
							e = x
						} else if n != 0 {
							e = errors.New("nonzero ALTER count")
						}
					}
					done <- e
				}()
				joined := false
				defer func() {
					cancel()
					tx.Rollback()
					if !joined {
						select {
						case <-done:
						case <-ctx.Done():
							t.Error("worker did not join", ctx.Err())
						}
					}
				}()
				if b.PG {
					mode := "AccessExclusiveLock"
					if tc.linked && tc.name != "sequence_drop" {
						mode = "ShareRowExclusiveLock"
					}
					fixture.LockWaitBehind(t, ctx, workerPID, holderPID, oid, mode)
				} else {
					fixture.AlterIdentityObserveAX(t, ctx, observer, done)
				}
				if b.PG {
					var ok bool
					if err := fixture.Admin.QueryRowContext(ctx, `SELECT pg_cancel_backend($1)`, workerPID).Scan(&ok); err != nil || !ok {
						t.Fatal(ok, err)
					}
				} else {
					cancel()
				}
				select {
				case err := <-done:
					joined = true
					if b.PG {
						want := fixture.ControlsReferenceDiagnostic("57014", "canceling statement due to user request")
						fixture.AssertDiagnostic(t, err, &want)
					} else if !errors.Is(err, context.Canceled) {
						t.Fatal(err)
					}
				case <-ctx.Done():
					t.Fatal("cancel did not join", ctx.Err())
				}
				if err := tx.Rollback(); err != nil {
					t.Fatal(err)
				}
				want := int64(1)
				if tc.ordinary {
					want = 40
				}
				run(fixture.Select(`SELECT * FROM i`, []string{"id"}, []string{"INT4"}, [][]any{{want}}))
				if tc.ordinary {
					fixture.AlterIdentityMissing(t, p, b, c, "i_id_seq")
				} else {
					run(fixture.ImplicitError(`INSERT INTO i VALUES(99)`, fixture.IdentityAlwaysDiagnostic()))
					run(fixture.Select(`SELECT last_value,is_called FROM i_id_seq`, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(1), true}}))
				}
				// An observer can now acquire AX: no canceled table ticket remains.
				probe, err := observer.BeginTx(ctx, nil)
				if err != nil {
					t.Fatal(err)
				}
				fixture.RunStep(t, ctx, probe, b.Recorder, fixture.Exec(`LOCK TABLE i IN ACCESS EXCLUSIVE MODE NOWAIT`, 0))
				if err := probe.Rollback(); err != nil {
					t.Fatal(err)
				}
				fixture.RunStep(t, ctx, held, b.Recorder, fixture.Exec(tc.query, 0))
			})
		})
	}
}
