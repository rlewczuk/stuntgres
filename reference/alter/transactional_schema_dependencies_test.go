package reference_test

import (
	"stuntgres/reference/fixture"
	"testing"
)

func TestReferenceTransactionalSchemaDependencies(t *testing.T) {
	transactionalSchemaRollbackRoutes(t, false)
	p := fixture.NewScenario(t)
	for _, b := range p.Backends() {
		t.Run(b.Name, func(t *testing.T) {
			c, peer := fixture.LockConnections(t, p.Ctx, b.DB)
			run := func(s fixture.Step) { fixture.RunStep(t, p.Ctx, c, b.Recorder, s) }
			for _, q := range []string{"CREATE TABLE tx_dep_parent(id SERIAL PRIMARY KEY, n INT CHECK(n>0))", "CREATE TABLE tx_dep_child(id INT GENERATED BY DEFAULT AS IDENTITY, parent INT REFERENCES tx_dep_parent(id))", "CREATE VIEW tx_dep_view AS SELECT id FROM tx_dep_parent"} {
				run(fixture.Exec(q, 0))
			}
			run(fixture.Exec("INSERT INTO tx_dep_parent(n) VALUES(7)", 1))
			run(fixture.Exec("INSERT INTO tx_dep_child(parent) VALUES(1)", 1))
			var original int64
			if err := c.QueryRowContext(p.Ctx, "SELECT 'tx_dep_parent'::regclass::oid").Scan(&original); err != nil {
				t.Fatal(err)
			}
			run(fixture.Exec("BEGIN", 0))
			defer c.ExecContext(p.Ctx, "ROLLBACK")
			run(fixture.Exec("SAVEPOINT before_drop", 0))
			run(fixture.Error("DROP TABLE tx_dep_parent", "2BP01"))
			run(fixture.Error("SELECT 1", "25P02"))
			run(fixture.Exec("ROLLBACK TO before_drop", 0))
			run(fixture.Exec("DROP TABLE tx_dep_parent CASCADE", 0))
			run(fixture.Select("SELECT id,parent FROM tx_dep_child", []string{"id", "parent"}, []string{"INT4", "INT4"}, [][]any{{int64(1), int64(1)}}))
			run(fixture.Select("SELECT count(*) FROM pg_constraint WHERE conrelid='tx_dep_child'::regclass AND contype='f'", []string{"count"}, []string{"INT8"}, [][]any{{int64(0)}}))
			fixture.RunStep(t, p.Ctx, peer, b.Recorder, fixture.Select("SELECT count(*) FROM pg_class WHERE relname IN ('tx_dep_parent','tx_dep_view') AND relnamespace='public'::regnamespace", []string{"count"}, []string{"INT8"}, [][]any{{int64(2)}}))
			run(fixture.Exec("ROLLBACK", 0))
			var restored int64
			if err := c.QueryRowContext(p.Ctx, "SELECT 'tx_dep_parent'::regclass::oid").Scan(&restored); err != nil || restored != original {
				t.Fatal(original, restored, err)
			}
			run(fixture.Select("SELECT id,n FROM tx_dep_parent", []string{"id", "n"}, []string{"INT4", "INT4"}, [][]any{{int64(1), int64(7)}}))
			run(fixture.Exec("BEGIN", 0))
			run(fixture.Exec("CREATE TABLE tx_dep_private(id SERIAL PRIMARY KEY)", 0))
			var first, second int64
			if err := c.QueryRowContext(p.Ctx, "SELECT 'tx_dep_private'::regclass::oid").Scan(&first); err != nil {
				t.Fatal(err)
			}
			run(fixture.Exec("INSERT INTO tx_dep_private DEFAULT VALUES", 1))
			run(fixture.Exec("DROP TABLE tx_dep_private", 0))
			run(fixture.Exec("CREATE TABLE tx_dep_private(id SERIAL PRIMARY KEY)", 0))
			if err := c.QueryRowContext(p.Ctx, "SELECT 'tx_dep_private'::regclass::oid").Scan(&second); err != nil || first == second {
				t.Fatal(first, second, err)
			}
			run(fixture.Select("SELECT id FROM tx_dep_private", []string{"id"}, []string{"INT4"}, nil))
			run(fixture.Exec("CREATE TEMP TABLE tx_dep_temp(v INT)", 0))
			run(fixture.Exec("SAVEPOINT drop_group", 0))
			run(fixture.Error("DROP TABLE tx_dep_private,tx_dep_missing", "42P01"))
			run(fixture.Exec("ROLLBACK TO drop_group", 0))
			run(fixture.Select("SELECT id FROM tx_dep_private", []string{"id"}, []string{"INT4"}, nil))
			run(fixture.Exec("DROP TABLE tx_dep_temp,tx_dep_private", 0))
			run(fixture.Exec("COMMIT", 0))
			run(fixture.Exec("BEGIN", 0))
			run(fixture.Exec("DROP TABLE tx_dep_parent CASCADE", 0))
			fixture.RunStep(t, p.Ctx, peer, b.Recorder, fixture.Select("SELECT count(*) FROM pg_constraint WHERE conrelid='tx_dep_child'::regclass AND contype='f'", []string{"count"}, []string{"INT8"}, [][]any{{int64(1)}}))
			fixture.RunStep(t, p.Ctx, peer, b.Recorder, fixture.Select("SELECT count(*) FROM pg_class WHERE relnamespace='public'::regnamespace AND relname IN ('tx_dep_parent','tx_dep_parent_pkey','tx_dep_parent_id_seq','tx_dep_view')", []string{"count"}, []string{"INT8"}, [][]any{{int64(4)}}))
			run(fixture.Exec("COMMIT", 0))
			fixture.RunStep(t, p.Ctx, peer, b.Recorder, fixture.Select("SELECT count(*) FROM pg_class WHERE relnamespace='public'::regnamespace AND relname IN ('tx_dep_parent','tx_dep_parent_pkey','tx_dep_parent_id_seq','tx_dep_view')", []string{"count"}, []string{"INT8"}, [][]any{{int64(0)}}))
			fixture.RunStep(t, p.Ctx, peer, b.Recorder, fixture.Select("SELECT count(*) FROM pg_type WHERE typnamespace='public'::regnamespace AND typname IN ('tx_dep_parent','_tx_dep_parent','tx_dep_view','_tx_dep_view')", []string{"count"}, []string{"INT8"}, [][]any{{int64(0)}}))
			fixture.RunStep(t, p.Ctx, peer, b.Recorder, fixture.Select("SELECT count(*) FROM pg_constraint WHERE conrelid='tx_dep_child'::regclass AND contype='f'", []string{"count"}, []string{"INT8"}, [][]any{{int64(0)}}))
			fixture.RunStep(t, p.Ctx, peer, b.Recorder, fixture.Select("SELECT id,parent FROM tx_dep_child", []string{"id", "parent"}, []string{"INT4", "INT4"}, [][]any{{int64(1), int64(1)}}))
		})
	}
}
