package reference_test

import (
	"database/sql"
	"testing"

	"stuntgres/reference/fixture"
)

func persistenceScenario(t *testing.T, body func(*testing.T, *fixture.Pair, fixture.Backend, *sql.Conn)) {
	t.Helper()
	p := fixture.NewScenario(t)
	for _, b := range p.Backends() {
		t.Run(b.Name, func(t *testing.T) {
			c, err := b.DB.Conn(p.Ctx)
			if err != nil { t.Fatal(err) }
			t.Cleanup(func() { c.Close() })
			body(t, p, b, c)
		})
	}
}

func persistenceRun(t *testing.T, p *fixture.Pair, b fixture.Backend, x fixture.Executor, step fixture.Step) {
	t.Helper()
	fixture.RunStep(t, p.Ctx, x, b.Recorder, step)
}

func persistenceExec(t *testing.T, p *fixture.Pair, b fixture.Backend, x fixture.Executor, query string) {
	t.Helper()
	persistenceRun(t, p, b, x, fixture.Exec(query, 0))
}

func persistenceProperty(t *testing.T, p *fixture.Pair, b fixture.Backend, x fixture.Executor, name, want string) {
	t.Helper()
	persistenceRun(t, p, b, x, persistencePropertyStep(name,want))
}

func persistencePropertyStep(name,want string) fixture.Step {
	return fixture.Select("SELECT relpersistence FROM pg_class WHERE oid=$1::regclass", []string{"relpersistence"}, []string{"CHAR"}, [][]any{{want}}, name)
}

func persistenceDiagnostic(code, message string) fixture.Diagnostic {
	return fixture.Diagnostic{Severity:"ERROR", SeverityUnlocalized:"ERROR", Code:code, Message:message}
}

func persistenceFailure(t *testing.T, p *fixture.Pair, b fixture.Backend, x fixture.Executor, query string, prepared bool, want fixture.Diagnostic) {
	t.Helper()
	step := fixture.ErrorDiagnostic(query, want)
	step.ErrorStage = "execute"
	if prepared { step = fixture.Prepared(step) }
	persistenceRun(t, p, b, x, step)
}

func persistenceFamily(t *testing.T, p *fixture.Pair, b fixture.Backend, x fixture.Executor, want string) {
	t.Helper()
	for _, name := range []string{"persist_smoke", "persist_smoke_pkey", "persist_note", "persist_smoke_id_seq", "persist_smoke_n_seq"} {
		persistenceProperty(t, p, b, x, name, want)
	}
}

func persistenceRows() fixture.Step {
	return fixture.Select("SELECT id,n,note FROM persist_smoke ORDER BY id", []string{"id","n","note"}, []string{"INT4","INT4","TEXT"}, [][]any{{int64(1),int64(1),"keep"}})
}

func persistenceIdentityBody(t *testing.T, p *fixture.Pair, b fixture.Backend, c *sql.Conn) {
	persistenceExec(t,p,b,c,"CREATE UNLOGGED TABLE persist_smoke(id serial PRIMARY KEY,n int GENERATED BY DEFAULT AS IDENTITY,note text DEFAULT 'keep')")
	persistenceExec(t,p,b,c,"CREATE INDEX persist_note ON persist_smoke(note)")
	persistenceRun(t,p,b,c,fixture.Exec("INSERT INTO persist_smoke DEFAULT VALUES",1))
	persistenceFamily(t,p,b,c,"u")
	persistenceRun(t,p,b,c,persistenceRows())
	var oid, rowtype int64
	if err := c.QueryRowContext(p.Ctx,"SELECT oid::bigint,reltype::bigint FROM pg_class WHERE oid='persist_smoke'::regclass").Scan(&oid,&rowtype); err != nil || oid <= 0 || rowtype <= 0 { t.Fatal(oid,rowtype,err) }
	selected, err := c.PrepareContext(p.Ctx,"SELECT note FROM persist_smoke WHERE id=$1")
	if err != nil { t.Fatal(err) }; defer selected.Close()
	inserted, err := c.PrepareContext(p.Ctx,"INSERT INTO persist_smoke VALUES($1,$2,$3)")
	if err != nil { t.Fatal(err) }; defer inserted.Close()
	for _, mode := range []string{"LOGGED","UNLOGGED"} {
		persistenceRun(t,p,b,c,fixture.Prepared(fixture.Exec("ALTER TABLE ONLY persist_smoke SET "+mode,0)))
		want := "p"; if mode=="UNLOGGED" { want="u" }
		if mode=="LOGGED" { persistenceExec(t,p,b,c,"CREATE INDEX persist_late ON persist_smoke(n)") }
		persistenceProperty(t,p,b,c,"persist_late",want)
		persistenceFamily(t,p,b,c,want)
		persistenceRun(t,p,b,c,persistenceRows())
		var current, typ int64
		if err := c.QueryRowContext(p.Ctx,"SELECT oid::bigint,reltype::bigint FROM pg_class WHERE oid='persist_smoke'::regclass").Scan(&current,&typ); err != nil || current!=oid || typ!=rowtype { t.Fatal(current,typ,err) }
		var note string
		if err := selected.QueryRowContext(p.Ctx,1).Scan(&note); err != nil || note!="keep" { t.Fatal(note,err) }
	}
	persistenceRun(t,p,b,fixture.HeldStatement{Executor:c,Statement:inserted,SQL:"INSERT INTO persist_smoke VALUES($1,$2,$3)"},fixture.Exec("INSERT INTO persist_smoke VALUES($1,$2,$3)",1,9,9,"explicit"))
	persistenceRun(t,p,b,c,fixture.Exec("DELETE FROM persist_smoke WHERE id=9",1))
	want := persistenceDiagnostic("23514",`check constraint "bad" of relation "persist_smoke" is violated by some row`)
	want.Schema,want.Table,want.Constraint="public","persist_smoke","bad"
	persistenceFailure(t,p,b,c,"ALTER TABLE persist_smoke SET LOGGED, ADD CONSTRAINT bad CHECK(id<0)",false,want)
	persistenceFamily(t,p,b,c,"u")
	persistenceRun(t,p,b,c,persistenceRows())
}

func TestReferenceAlterPersistenceIdentity(t *testing.T) {
	t.Run("identity-options",persistenceIdentityOptionCases)
	t.Run("metadata",persistenceMetadataCase)
	t.Run("notices",persistenceNoticeCases)
	persistenceScenario(t,persistenceIdentityBody)
	for _, query := range []string{
		"CREATE UNLOGGED TABLE t(id int)",
		"CREATE UNLOGGED TABLE IF NOT EXISTS t(id int)",
		"CREATE UNLOGGED TABLE t(LIKE source INCLUDING IDENTITY)",
		"CREATE UNLOGGED TABLE t(id int) INHERITS(source)",
		"CREATE UNLOGGED TABLE t OF pair",
		"CREATE UNLOGGED TABLE IF NOT EXISTS t OF pair",
		"CREATE UNLOGGED TABLE t PARTITION OF parts FOR VALUES FROM(0) TO(10)",
		"CREATE UNLOGGED TABLE IF NOT EXISTS t PARTITION OF parts FOR VALUES FROM(0) TO(10)",
	} {
		t.Run(query,func(t *testing.T) {
			persistenceScenario(t,func(t *testing.T,p *fixture.Pair,b fixture.Backend,c *sql.Conn) {
				for _, setup := range []string{"CREATE TABLE source(x int GENERATED BY DEFAULT AS IDENTITY)","CREATE TYPE pair AS(id int)","CREATE TABLE parts(id int) PARTITION BY RANGE(id)"} { persistenceExec(t,p,b,c,setup) }
				persistenceExec(t,p,b,c,query)
				persistenceProperty(t,p,b,c,"t","u")
				persistenceExec(t,p,b,c,"ALTER TABLE IF EXISTS t SET LOGGED")
				persistenceProperty(t,p,b,c,"t","p")
			})
		})
	}
}

