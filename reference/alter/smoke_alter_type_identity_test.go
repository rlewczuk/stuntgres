func alterTypeIdentitySmokeCommand(t *testing.T, ctx context.Context, c *sql.Conn, q string, prepared bool) error {
	t.Helper()
	var result sql.Result
	var err error
	if prepared {
		s, e := c.PrepareContext(ctx, q)
		if e != nil {
			t.Fatal("effect-free native utility Prepare", e)
		}
		defer s.Close()
		result, err = s.ExecContext(ctx)
	} else {
		result, err = c.ExecContext(ctx, q)
	}
	if err == nil {
		count, e := result.RowsAffected()
		if e != nil || count != 0 {
			t.Fatal(count, e)
		}
	}
	if err != nil && result != nil {
		t.Fatal("failed ALTER published result", result, err)
	}
	return err
}
func alterTypeIdentitySmokeDiagnostic(t *testing.T, err error, want stuntgres.Error) {
	t.Helper()
	want.Severity, want.SeverityUnlocalized = "ERROR", "ERROR"
	d := fixture.MigrationDiagnostic(want)
	fixture.AssertDiagnostic(t, err, &d)
}

func TestReferenceSmokeAlterTypeIdentitySmoke(t *testing.T) {
	for _, prepared := range []bool{false, true} {
		t.Run("targets"+fmt.Sprint(prepared), func(t *testing.T) {
			p := fixture.NewScenario(t)
			for _, backend := range p.Backends() {
				t.Run(backend.Name, func(t *testing.T) {
					m, db, ctx, notices := fixture.MigrationAlterFixture(t, p, backend)
					c, err := db.Conn(ctx)
					if err != nil {
						t.Fatal(err)
					}
					defer c.Close()
					for _, q := range []string{"CREATE TABLE t(c INT GENERATED ALWAYS AS IDENTITY)", "INSERT INTO t DEFAULT VALUES"} {
						if _, err = c.ExecContext(ctx, q); err != nil {
							t.Fatal(q, err)
						}
					}
					if err = alterTypeIdentitySmokeCommand(t, ctx, c, "ALTER TABLE t ALTER c TYPE BIGINT", prepared); err != nil {
						t.Fatal(err)
					}
					if _, err = c.ExecContext(ctx, "INSERT INTO t DEFAULT VALUES"); err != nil {
						t.Fatal(err)
					}
					rows, err := c.QueryContext(ctx, "SELECT c FROM t ORDER BY c")
					if err != nil {
						t.Fatal(err)
					}
					m.DropRows(rows, []string{"c"}, []string{"INT8"}, [][]any{{int64(1)}, {int64(2)}})
					err = alterTypeIdentitySmokeCommand(t, ctx, c, "ALTER TABLE t ALTER c TYPE TEXT USING (1/(c-c))::text", prepared)
					alterTypeIdentitySmokeDiagnostic(t, err, stuntgres.Error{Code: "22023", Message: "identity column type must be smallint, integer, or bigint"})
					_, err = c.ExecContext(ctx, "INSERT INTO t VALUES(99)")
					alterTypeIdentitySmokeDiagnostic(t, err, stuntgres.Error{Code: "428C9", Message: `cannot insert a non-DEFAULT value into column "c"`, Detail: `Column "c" is an identity column defined as GENERATED ALWAYS.`, Hint: "Use OVERRIDING SYSTEM VALUE to override."})
					for _, action := range []string{"ALTER c DROP IDENTITY, ALTER c TYPE TEXT USING c::text", "ALTER c TYPE TEXT USING c::text, ALTER c DROP IDENTITY"} {
						err = alterTypeIdentitySmokeCommand(t, ctx, c, "ALTER TABLE t "+action, prepared)
						alterTypeIdentitySmokeDiagnostic(t, err, stuntgres.Error{Code: "22023", Message: "identity column type must be smallint, integer, or bigint"})
					}
					if _, err = c.ExecContext(ctx, "CREATE TABLE bounded(c BIGINT GENERATED BY DEFAULT AS IDENTITY(MINVALUE -40000 MAXVALUE 40000 START 1))"); err != nil {
						t.Fatal(err)
					}
					err = alterTypeIdentitySmokeCommand(t, ctx, c, "ALTER TABLE bounded ALTER c TYPE SMALLINT", prepared)
					alterTypeIdentitySmokeDiagnostic(t, err, stuntgres.Error{Code: "22023", Message: "MAXVALUE (40000) is out of range for sequence data type smallint"})
					rows, err = c.QueryContext(ctx, "SELECT c FROM bounded")
					if err != nil {
						t.Fatal(err)
					}
					m.DropRows(rows, []string{"c"}, []string{"INT8"}, [][]any{})
					if len(*notices) != 0 {
						t.Fatal(notices)
					}
				})
			}
		})
		t.Run("cache-gates"+fmt.Sprint(prepared), func(t *testing.T) {
			p := fixture.NewScenario(t)
			for _, backend := range p.Backends() {
				t.Run(backend.Name, func(t *testing.T) {
					m, db, ctx, notices := fixture.MigrationAlterFixture(t, p, backend)
					c, err := db.Conn(ctx)
					if err != nil {
						t.Fatal(err)
					}
					defer c.Close()
					for _, q := range []string{"CREATE TABLE t(c INT GENERATED BY DEFAULT AS IDENTITY(CACHE 5))", "INSERT INTO t DEFAULT VALUES"} {
						if _, err = c.ExecContext(ctx, q); err != nil {
							t.Fatal(q, err)
						}
					}
					err = alterTypeIdentitySmokeCommand(t, ctx, c, "ALTER TABLE t ALTER c TYPE TEXT USING missing_col", prepared)
					alterTypeIdentitySmokeDiagnostic(t, err, stuntgres.Error{Code: "42703", Message: `column "missing_col" does not exist`, Position: "39"})
					if _, err = c.ExecContext(ctx, "INSERT INTO t DEFAULT VALUES"); err != nil {
						t.Fatal(err)
					}
					err = alterTypeIdentitySmokeCommand(t, ctx, c, "ALTER TABLE t ALTER c TYPE BIGINT USING c::text", prepared)
					alterTypeIdentitySmokeDiagnostic(t, err, stuntgres.Error{Code: "42804", Message: `result of USING clause for column "c" cannot be cast automatically to type bigint`, Hint: "You might need to add an explicit cast."})
					if _, err = c.ExecContext(ctx, "INSERT INTO t DEFAULT VALUES"); err != nil {
						t.Fatal(err)
					}
					rows, err := c.QueryContext(ctx, "SELECT c FROM t ORDER BY c")
					if err != nil {
						t.Fatal(err)
					}
					m.DropRows(rows, []string{"c"}, []string{"INT4"}, [][]any{{int64(1)}, {int64(2)}, {int64(6)}})
					if err = alterTypeIdentitySmokeCommand(t, ctx, c, "ALTER TABLE t ALTER c TYPE INT USING c+1", prepared); err != nil {
						t.Fatal(err)
					}
					if _, err = c.ExecContext(ctx, "INSERT INTO t DEFAULT VALUES"); err != nil {
						t.Fatal(err)
					}
					rows, err = c.QueryContext(ctx, "SELECT c FROM t ORDER BY c")
					if err != nil {
						t.Fatal(err)
					}
					m.DropRows(rows, []string{"c"}, []string{"INT4"}, [][]any{{int64(2)}, {int64(3)}, {int64(7)}, {int64(11)}})
					if len(*notices) != 0 {
						t.Fatal(*notices)
					}
				})
			}
		})
		t.Run("sessions"+fmt.Sprint(prepared), func(t *testing.T) {
			p := fixture.NewScenario(t)
			for _, backend := range p.Backends() {
				t.Run(backend.Name, func(t *testing.T) {
					m, db, ctx, notices := fixture.MigrationAlterFixture(t, p, backend)
					a, err := db.Conn(ctx)
					if err != nil {
						t.Fatal(err)
					}
					defer a.Close()
					b, err := db.Conn(ctx)
					if err != nil {
						t.Fatal(err)
					}
					defer b.Close()
					for _, q := range []string{"CREATE TABLE t(c INT GENERATED BY DEFAULT AS IDENTITY(CACHE 5))", "INSERT INTO t DEFAULT VALUES"} {
						if _, err = a.ExecContext(ctx, q); err != nil {
							t.Fatal(q, err)
						}
					}
					if _, err = b.ExecContext(ctx, "INSERT INTO t DEFAULT VALUES"); err != nil {
						t.Fatal(err)
					}
					if err = alterTypeIdentitySmokeCommand(t, ctx, a, "ALTER TABLE t ALTER c TYPE BIGINT", prepared); err != nil {
						t.Fatal(err)
					}
					for _, c := range []*sql.Conn{a, b} {
						if _, err = c.ExecContext(ctx, "INSERT INTO t DEFAULT VALUES"); err != nil {
							t.Fatal(err)
						}
					}
					rows, err := a.QueryContext(ctx, "SELECT c FROM t ORDER BY c")
					if err != nil {
						t.Fatal(err)
					}
					m.DropRows(rows, []string{"c"}, []string{"INT8"}, [][]any{{int64(1)}, {int64(6)}, {int64(11)}, {int64(16)}})
					for _, q := range []string{"BEGIN", "ALTER TABLE t ALTER c TYPE SMALLINT", "ROLLBACK", "INSERT INTO t DEFAULT VALUES"} {
						if _, err = a.ExecContext(ctx, q); err != nil {
							t.Fatal(q, err)
						}
					}
					if _, err = b.ExecContext(ctx, "INSERT INTO t DEFAULT VALUES"); err != nil {
						t.Fatal(err)
					}
					rows, err = a.QueryContext(ctx, "SELECT c FROM t ORDER BY c")
					if err != nil {
						t.Fatal(err)
					}
					m.DropRows(rows, []string{"c"}, []string{"INT8"}, [][]any{{int64(1)}, {int64(6)}, {int64(11)}, {int64(16)}, {int64(17)}, {int64(21)}})
					if len(*notices) != 0 {
						t.Fatal(*notices)
					}
				})
			}
		})
	}
	t.Run("staged-demand", alterTypeIdentityStagedDemandSmoke)
	t.Run("cache-tail-and-removal", alterTypeIdentityCacheTailAndRemovalSmoke)
}

func TestReferenceSmokeAlterTypeIdentityControlsSmoke(t *testing.T) {
	p := fixture.NewScenario(t)
	for _, backend := range p.Backends() {
		t.Run(backend.Name, func(t *testing.T) {
			m, db, ctx, notices := fixture.MigrationAlterFixture(t, p, backend)
			db.SetMaxOpenConns(1)
			for _, q := range []string{"CREATE TABLE t(c INT CONSTRAINT nn GENERATED ALWAYS AS IDENTITY(START 7 INCREMENT 3 CACHE 2) CONSTRAINT ck CHECK(c>0),p INT DEFAULT 4)", "COMMENT ON COLUMN t.c IS 'identity column'", "COMMENT ON SEQUENCE t_c_seq IS 'identity sequence'", "INSERT INTO t DEFAULT VALUES", "ALTER TABLE t ALTER c TYPE BIGINT"} {
				m.NullExec(db, false, q, alterTypeIdentitySmokeAffected(q))
			}
			rows, err := db.Query("SELECT * FROM t ORDER BY c")
			if err != nil {
				t.Fatal(err)
			}
			m.DropRows(rows, []string{"c", "p"}, []string{"INT8", "INT4"}, [][]any{{int64(7), int64(4)}})
			if !backend.PG {
				var dump bytes.Buffer
				if err := stuntgres.Dump(ctx, p.Native, &dump); err != nil {
					t.Fatal(err)
				}
				for _, text := range []string{"BIGINT", "GENERATED ALWAYS AS IDENTITY", "CACHE 2", "nn", "ck", "identity column", "identity sequence"} {
					if !strings.Contains(dump.String(), text) {
						t.Fatal(text, dump.String())
					}
				}
				if strings.Contains(dump.String(), "ALTER TABLE") || strings.Contains(dump.String(), "CREATE SEQUENCE") {
					t.Fatal("identity history or duplicate", dump.String())
				}
				if err := stuntgres.Reset(ctx, p.Native); err != nil {
					t.Fatal(err)
				}
				if err := stuntgres.Restore(ctx, p.Native, bytes.NewReader(dump.Bytes())); err != nil {
					t.Fatal(err)
				}
				var again bytes.Buffer
				if err := stuntgres.Dump(ctx, p.Native, &again); err != nil || again.String() != dump.String() {
					t.Fatal(err, again.String(), dump.String())
				}
			}
			m.NullExec(db, false, "INSERT INTO t DEFAULT VALUES", 1)
			rows, err = db.Query("SELECT * FROM t ORDER BY c")
			if err != nil {
				t.Fatal(err)
			}
			m.DropRows(rows, []string{"c", "p"}, []string{"INT8", "INT4"}, [][]any{{int64(7), int64(4)}, {int64(13), int64(4)}})
			_, err = db.Exec("INSERT INTO t VALUES(99,4)")
			alterTypeIdentitySmokeDiagnostic(t, err, stuntgres.Error{Code: "428C9", Message: `cannot insert a non-DEFAULT value into column "c"`, Detail: `Column "c" is an identity column defined as GENERATED ALWAYS.`, Hint: "Use OVERRIDING SYSTEM VALUE to override."})
			_, err = db.Exec("INSERT INTO t OVERRIDING SYSTEM VALUE VALUES(-1,4)")
			alterTypeIdentitySmokeDiagnostic(t, err, stuntgres.Error{Code: "23514", Message: `new row for relation "t" violates check constraint "ck"`, Detail: "Failing row contains (-1, 4).", Schema: "public", Table: "t", Constraint: "ck"})
			rows, err = db.Query("SELECT setval('t_c_seq',2147483647,true)")
			if err != nil {
				t.Fatal(err)
			}
			m.DropRows(rows, []string{"setval"}, []string{"INT8"}, [][]any{{int64(2147483647)}})
			m.NullExec(db, false, "INSERT INTO t DEFAULT VALUES", 1)
			rows, err = db.Query("SELECT c FROM t WHERE c=2147483650")
			if err != nil {
				t.Fatal(err)
			}
			m.DropRows(rows, []string{"c"}, []string{"INT8"}, [][]any{{int64(2147483650)}})
			if len(*notices) != 0 {
				t.Fatal(notices)
			}
		})
	}
}

func alterTypeIdentityStagedDemandSmoke(t *testing.T) {
	for _, failure := range []bool{false, true} {
		t.Run(fmt.Sprint(failure), func(t *testing.T) {
			p := fixture.NewScenario(t)
			for _, backend := range p.Backends() {
				t.Run(backend.Name, func(t *testing.T) {
					m, db, ctx, notices := fixture.MigrationAlterFixture(t, p, backend)
					db.SetMaxOpenConns(1)
					decl := "c INT GENERATED BY DEFAULT AS IDENTITY"
					if failure {
						decl += " CONSTRAINT ck CHECK(c<5)"
					}
					m.NullExec(db, false, "CREATE TABLE t("+decl+")", 0)
					m.NullExec(db, false, "INSERT INTO t DEFAULT VALUES", 1)
					if failure {
						m.NullExec(db, false, "INSERT INTO t DEFAULT VALUES", 1)
					}
					_, err := db.Exec("ALTER TABLE t ALTER c TYPE BIGINT USING c+nextval('t_c_seq')")
					currval := int64(2)
					if failure {
						currval = 4
						alterTypeIdentitySmokeDiagnostic(t, err, stuntgres.Error{Code: "23514", Message: `check constraint "ck" of relation "t" is violated by some row`, Schema: "public", Table: "t", Constraint: "ck"})
					} else if err != nil {
						t.Fatal(err)
					}
					rows, err := db.Query("SELECT last_value,is_called FROM t_c_seq")
					if err != nil {
						t.Fatal(err)
					}
					m.DropRows(rows, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(2), true}})
					rows, err = db.Query("SELECT currval('t_c_seq')")
					if err != nil {
						t.Fatal(err)
					}
					m.DropRows(rows, []string{"currval"}, []string{"INT8"}, [][]any{{currval}})
					if !failure && !backend.PG {
						var dump bytes.Buffer
						if err = stuntgres.Dump(ctx, p.Native, &dump); err != nil {
							t.Fatal(err)
						}
						if err = stuntgres.Reset(ctx, p.Native); err != nil {
							t.Fatal(err)
						}
						if err = stuntgres.Restore(ctx, p.Native, bytes.NewReader(dump.Bytes())); err != nil {
							t.Fatal(err)
						}
					}
					m.NullExec(db, false, "INSERT INTO t DEFAULT VALUES", 1)
					rows, err = db.Query("SELECT c FROM t ORDER BY c")
					if err != nil {
						t.Fatal(err)
					}
					if failure {
						m.DropRows(rows, []string{"c"}, []string{"INT4"}, [][]any{{int64(1)}, {int64(2)}, {int64(3)}})
					} else {
						m.DropRows(rows, []string{"c"}, []string{"INT8"}, [][]any{{int64(3)}, {int64(3)}})
					}
					if len(*notices) != 0 {
						t.Fatal(*notices)
					}
				})
			}
		})
	}
}

func alterTypeIdentityCacheTailAndRemovalSmoke(t *testing.T) {
	for _, prepared := range []bool{false, true} {
		for _, clause := range []string{"ALTER c TYPE BIGINT USING c+nextval('t_c_seq')", "ALTER c DROP IDENTITY, ALTER c TYPE BIGINT", "ALTER c TYPE BIGINT, ALTER c DROP IDENTITY"} {
			t.Run(fmt.Sprint(prepared, clause), func(t *testing.T) {
				p := fixture.NewScenario(t)
				for _, backend := range p.Backends() {
					t.Run(backend.Name, func(t *testing.T) {
						m, db, ctx, notices := fixture.MigrationAlterFixture(t, p, backend)
						c, err := db.Conn(ctx)
						if err != nil {
							t.Fatal(err)
						}
						defer c.Close()
						for _, q := range []string{"CREATE TABLE t(c INT GENERATED BY DEFAULT AS IDENTITY(CACHE 5))", "INSERT INTO t DEFAULT VALUES"} {
							if _, err = c.ExecContext(ctx, q); err != nil {
								t.Fatal(q, err)
							}
						}
						if err = alterTypeIdentitySmokeCommand(t, ctx, c, "ALTER TABLE t "+clause, prepared); err != nil {
							t.Fatal(err)
						}
						if strings.Contains(clause, "DROP IDENTITY") {
							var last int64
							alterTypeIdentitySmokeDiagnostic(t, c.QueryRowContext(ctx, "SELECT last_value FROM t_c_seq").Scan(&last), stuntgres.Error{Code: "42P01", Message: `relation "t_c_seq" does not exist`, Position: "24"})
							alterTypeIdentitySmokeDiagnostic(t, c.QueryRowContext(ctx, "SELECT lastval()").Scan(&last), stuntgres.Error{Code: "55000", Message: "lastval is not yet defined in this session"})
							_, err = c.ExecContext(ctx, "INSERT INTO t DEFAULT VALUES")
							alterTypeIdentitySmokeDiagnostic(t, err, stuntgres.Error{Code: "23502", Message: `null value in column "c" of relation "t" violates not-null constraint`, Detail: "Failing row contains (null).", Schema: "public", Table: "t", Column: "c"})
							rows, err := c.QueryContext(ctx, "SELECT c FROM t")
							if err != nil {
								t.Fatal(err)
							}
							m.DropRows(rows, []string{"c"}, []string{"INT8"}, [][]any{{int64(1)}})
						} else {
							rows, err := c.QueryContext(ctx, "SELECT last_value,is_called FROM t_c_seq")
							if err != nil {
								t.Fatal(err)
							}
							m.DropRows(rows, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(10), true}})
							rows, err = c.QueryContext(ctx, "SELECT currval('t_c_seq')")
							if err != nil {
								t.Fatal(err)
							}
							m.DropRows(rows, []string{"currval"}, []string{"INT8"}, [][]any{{int64(6)}})
							if _, err = c.ExecContext(ctx, "INSERT INTO t DEFAULT VALUES"); err != nil {
								t.Fatal(err)
							}
							rows, err = c.QueryContext(ctx, "SELECT c FROM t ORDER BY c")
							if err != nil {
								t.Fatal(err)
							}
							m.DropRows(rows, []string{"c"}, []string{"INT8"}, [][]any{{int64(7)}, {int64(7)}})
						}
						if len(*notices) != 0 {
							t.Fatal(notices)
						}
					})
				}
			})
		}
	}
}

func alterTypeIdentitySmokeAffected(q string) int64 {
	if strings.HasPrefix(q, "INSERT") {
		return 1
	}
	return 0
}
