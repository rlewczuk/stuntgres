package reference_test

import (
	"testing"

	"stuntgres/reference/fixture"
)

func TestReferenceCreateroleSelfGrantTransactions(t *testing.T) {
	selfGrantCases(t, "sg_tx", []string{"pre", "discarded", "replacement", "committed", "local", "local_abort", "set", "setlocal", "nested", "recovered", "denied"}, func(s *selfGrantCase) {
		defer s.actor.ExecContext(s.p.Ctx, "ROLLBACK")
		s.reads(s.actor, "", "default")
		s.reads(s.peer, "", "default")
		s.exec(s.actor, "BEGIN")
		s.set(s.actor, "set")
		s.create("pre")
		s.edges(s.actor, "sg_tx_pre", false, true, true)
		s.exec(s.actor, "SAVEPOINT s")
		s.set(s.actor, "inherit")
		s.create("discarded")
		s.edges(s.actor, "sg_tx_discarded", true, false, true)
		s.absent(s.peer, "sg_tx_pre")
		s.absent(s.peer, "sg_tx_discarded")
		s.reads(s.peer, "", "default")
		s.exec(s.actor, "ROLLBACK TO s")
		s.reads(s.actor, "set", "session")
		s.absent(s.actor, "sg_tx_discarded")
		s.create("replacement")
		s.edges(s.actor, "sg_tx_replacement", false, true, true)
		s.exec(s.actor, "ROLLBACK")
		s.reads(s.actor, "", "default")
		for _, name := range []string{"sg_tx_pre", "sg_tx_discarded", "sg_tx_replacement"} {
			s.absent(s.actor, name)
			s.absent(s.peer, name)
		}
		s.exec(s.actor, "BEGIN")
		s.set(s.actor, "inherit")
		s.create("committed")
		s.edges(s.actor, "sg_tx_committed", true, false, true)
		s.absent(s.peer, "sg_tx_committed")
		s.exec(s.actor, "COMMIT")
		s.reads(s.actor, "inherit", "session")
		s.edges(s.peer, "sg_tx_committed", true, false, true)
		s.reads(s.peer, "", "default")
		s.set(s.actor, "set")
		for _, commit := range []bool{true, false} {
			name := "local"
			if !commit { name = "local_abort" }
			s.exec(s.actor, "BEGIN")
			s.exec(s.actor, "SET LOCAL createrole_self_grant='inherit'")
			s.reads(s.actor, "inherit", "session")
			s.create(name)
			s.edges(s.actor, "sg_tx_" + name, true, false, true)
			s.absent(s.peer, "sg_tx_" + name)
			if commit { s.exec(s.actor, "COMMIT") } else { s.exec(s.actor, "ROLLBACK") }
			s.reads(s.actor, "set", "session")
			if commit { s.edges(s.peer, "sg_tx_" + name, true, false, true) } else { s.absent(s.peer, "sg_tx_" + name); s.absent(s.actor, "sg_tx_" + name) }
		}
		// SET followed by LOCAL commits the SET value, not the LOCAL override.
		s.exec(s.actor, "BEGIN")
		s.set(s.actor, "inherit")
		s.create("set")
		s.exec(s.actor, "SAVEPOINT outer_s")
		s.exec(s.actor, "SET LOCAL createrole_self_grant='set'")
		s.create("setlocal")
		s.exec(s.actor, "SAVEPOINT inner_s")
		s.set(s.actor, "set,inherit")
		s.create("nested")
		s.exec(s.actor, "RELEASE SAVEPOINT inner_s")
		s.exec(s.actor, "ROLLBACK TO outer_s")
		s.reads(s.actor, "inherit", "session")
		s.absent(s.actor, "sg_tx_setlocal")
		s.absent(s.actor, "sg_tx_nested")
		s.exec(s.actor, "SET LOCAL createrole_self_grant='set'")
		s.create("setlocal")
		s.edges(s.actor, "sg_tx_setlocal", false, true, true)
		s.exec(s.actor, "COMMIT")
		s.reads(s.actor, "inherit", "session")
		s.edges(s.peer, "sg_tx_set", true, false, true)
		s.edges(s.peer, "sg_tx_setlocal", false, true, true)
		s.absent(s.peer, "sg_tx_nested")
		s.exec(s.actor, "BEGIN")
		s.exec(s.actor, "SAVEPOINT invalid_s")
		s.run(s.actor, selfGrantInvalid("bogus,SET,", "List syntax is invalid."))
		aborted := fixture.RoleReferenceError("SHOW createrole_self_grant", "25P02", "current transaction is aborted, commands ignored until end of transaction block", "", s.prepared, "prepare")
		s.run(s.actor, aborted)
		s.exec(s.actor, "ROLLBACK TO invalid_s")
		s.reads(s.actor, "inherit", "session")
		s.create("recovered")
		s.edges(s.actor, "sg_tx_recovered", true, false, true)
		s.exec(s.actor, "COMMIT")
		s.edges(s.peer, "sg_tx_recovered", true, false, true)
		s.exec(s.admin, "ALTER ROLE " + s.creator + " NOCREATEROLE")
		s.exec(s.actor, "BEGIN")
		s.exec(s.actor, "SAVEPOINT denied_s")
		s.run(s.actor, selfGrantDenied("CREATE ROLE sg_tx_denied", "Only roles with the CREATEROLE attribute may create roles."))
		s.exec(s.actor, "ROLLBACK TO denied_s")
		s.absent(s.actor, "sg_tx_denied")
		s.reads(s.actor, "inherit", "session")
		s.exec(s.actor, "ROLLBACK")
		s.absent(s.peer, "sg_tx_denied")
		s.reads(s.peer, "", "default")
	})
}
