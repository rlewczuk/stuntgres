package reference_test

import "stuntgres/reference/fixture"

import "testing"

func TestReferenceRoleMembershipRevokeDependencies(t *testing.T) {
	fixture.RoleMembershipCases(t, []string{"mr_role", "mr_a", "mr_b", "mr_c", "mr_x"}, func(s *fixture.RoleMembershipScenario) {
		s.Owned("mr_role")
		s.Exec("GRANT mr_role TO mr_a,mr_x WITH ADMIN TRUE")
		s.Actor("mr_a")
		s.Exec("GRANT mr_role TO mr_b WITH ADMIN TRUE")
		s.Actor("mr_b")
		s.Exec("GRANT mr_role TO mr_c")
		s.Actor("")
		s.Restrict("REVOKE mr_role FROM mr_a")
		s.Restrict("REVOKE ADMIN OPTION FOR mr_role FROM mr_a RESTRICT")
		s.Actor("mr_c")
		s.Read(true)
		s.Actor("")
		s.Exec("REVOKE INHERIT OPTION FOR mr_role FROM mr_a")
		s.Exec("REVOKE SET OPTION FOR mr_role FROM mr_a")
		s.Flags("mr_role", "mr_b", "mr_a", 1, true, true, true)
		s.Actor("mr_x")
		s.Exec("GRANT mr_role TO mr_a WITH ADMIN TRUE")
		s.Actor("")
		s.Exec("REVOKE ADMIN OPTION FOR mr_role FROM mr_a")
		s.Flags("mr_role", "mr_a", s.Bootstrap, 1, false, false, false)
		s.Flags("mr_role", "mr_b", "mr_a", 1, true, true, true)
		s.Exec("GRANT mr_role TO mr_c WITH INHERIT TRUE, SET FALSE")
		s.Restrict("REVOKE mr_role FROM mr_a GRANTED BY mr_x")
		s.Exec("REVOKE mr_role FROM mr_a GRANTED BY mr_x CASCADE")
		s.Flags("mr_role", "mr_a", "mr_x", 0, false, false, false)
		s.Flags("mr_role", "mr_b", "mr_a", 0, false, false, false)
		s.Flags("mr_role", "mr_c", "mr_b", 0, false, false, false)
		s.Flags("mr_role", "mr_c", s.Bootstrap, 1, false, true, false)
		s.Actor("mr_c")
		s.Read(true)
		s.Actor("")
		s.Exec("REVOKE mr_role FROM mr_c")
		s.Actor("mr_c")
		s.Read(false)
		s.Actor("")
		s.Exec("GRANT mr_role TO mr_a WITH ADMIN TRUE")
		s.Actor("mr_a")
		s.Exec("GRANT mr_role TO mr_b WITH ADMIN TRUE")
		s.Actor("mr_b")
		s.Exec("GRANT mr_role TO mr_c")
		s.Actor("")
		s.Exec("REVOKE ADMIN OPTION FOR mr_role FROM mr_a CASCADE")
		s.Flags("mr_role", "mr_a", s.Bootstrap, 1, false, false, false)
		s.Actor("mr_c")
		s.Read(false)
		s.Actor("")
	})
}

func TestReferenceRoleMembershipCycles(t *testing.T) {
	fixture.RoleMembershipCases(t, []string{"my_r", "my_a", "my_b", "my_c", "my_x"}, func(s *fixture.RoleMembershipScenario) {
		s.Fail("GRANT my_a TO my_a WITH ADMIN FALSE, INHERIT FALSE, SET FALSE", "0LP01", `role "my_a" is a member of role "my_a"`, "")
		s.Exec("GRANT my_a TO my_b WITH INHERIT FALSE, SET FALSE")
		s.Exec("GRANT my_b TO my_c WITH INHERIT FALSE, SET FALSE")
		s.Fail("GRANT my_c TO my_a WITH INHERIT FALSE, SET FALSE", "0LP01", `role "my_c" is a member of role "my_a"`, "")
		s.Exec("GRANT my_r TO my_a WITH ADMIN TRUE")
		s.Actor("my_a")
		s.Exec("GRANT my_r TO my_b WITH ADMIN TRUE")
		s.Actor("my_b")
		s.Fail("GRANT my_r TO my_a WITH ADMIN TRUE", "0LP01", "ADMIN option cannot be granted back to your own grantor", "")
		s.Actor("")
		s.Exec("GRANT my_r TO my_b WITH ADMIN TRUE")
		s.Actor("my_b")
		s.Exec("GRANT my_r TO my_a WITH ADMIN TRUE")
		s.Actor("")
		s.Flags("my_r", "my_a", "my_b", 1, true, true, true)
		s.Fail("GRANT my_r TO my_a,my_b WITH ADMIN TRUE GRANTED BY my_b", "0LP01", "ADMIN option cannot be granted back to your own grantor", "")
		s.Flags("my_r", "my_b", "my_b", 0, false, false, false)
	})
}
