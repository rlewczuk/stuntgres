func TestReferenceIdentityDiagnosticRecords(t *testing.T){identityReferenceCase(t,func(t *testing.T,db *sql.DB){
	identityRefExec(t,db,`CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY)`,0)
	always:=referenceDiagnostic{Severity:"ERROR",SeverityUnlocalized:"ERROR",Code:"428C9",Message:`cannot insert a non-DEFAULT value into column "id"`,Detail:`Column "id" is an identity column defined as GENERATED ALWAYS.`,Hint:"Use OVERRIDING SYSTEM VALUE to override."}
	for _,tc:=range []struct{query string;want referenceDiagnostic}{
		{`INSERT INTO i VALUES(99)`,always},
		{`INSERT INTO i SELECT 99 FROM i WHERE false`,always},
		{`UPDATE i SET id=99 WHERE false`,referenceDiagnostic{Severity:"ERROR",SeverityUnlocalized:"ERROR",Code:"428C9",Message:`column "id" can only be updated to DEFAULT`,Detail:`Column "id" is an identity column defined as GENERATED ALWAYS.`}},
		{`ALTER TABLE i ALTER id DROP NOT NULL`,controlsReferenceDiagnostic("42601",`column "id" of relation "i" is an identity column`)},
		{`ALTER TABLE i ALTER id SET DEFAULT 4`,controlsReferenceDiagnostic("42601",`column "id" of relation "i" is an identity column`)},
		{`ALTER TABLE i ALTER id DROP DEFAULT`,referenceDiagnostic{Severity:"ERROR",SeverityUnlocalized:"ERROR",Code:"42601",Message:`column "id" of relation "i" is an identity column`,Hint:"Use ALTER TABLE ... ALTER COLUMN ... DROP IDENTITY instead."}},
		{`DROP SEQUENCE i_id_seq CASCADE`,referenceDiagnostic{Severity:"ERROR",SeverityUnlocalized:"ERROR",Code:"2BP01",Message:"cannot drop sequence i_id_seq because column id of table i requires it",Hint:"You can drop column id of table i instead."}},
		{`ALTER SEQUENCE i_id_seq OWNED BY NONE`,referenceDiagnostic{Severity:"ERROR",SeverityUnlocalized:"ERROR",Code:"0A000",Message:"cannot change ownership of identity sequence",Detail:`Sequence "i_id_seq" is linked to table "i".`}},
		{`ALTER TABLE i ALTER id SET OWNED BY NONE`,referenceDiagnostic{Severity:"ERROR",SeverityUnlocalized:"ERROR",Code:"42601",Message:`sequence option "owned_by" not supported here`,Position:"28"}},
		{`ALTER TABLE i ALTER id SET RESTART WITH 4`,referenceDiagnostic{Severity:"ERROR",SeverityUnlocalized:"ERROR",Code:"42601",Message:`sequence option "restart" not supported here`,Position:"28"}},
		{`ALTER TABLE i ALTER id SET AS bigint`,referenceDiagnostic{Severity:"ERROR",SeverityUnlocalized:"ERROR",Code:"42601",Message:`sequence option "as" not supported here`,Position:"28"}},
	}{_,err:=db.Exec(tc.query);referenceAssertDiagnostic(t,err,&tc.want)}
	identityRefExec(t,db,`CREATE TABLE a(id INT)`,0)
	_,err:=db.Exec(`ALTER TABLE a ALTER id ADD GENERATED ALWAYS AS IDENTITY`)
	want:=controlsReferenceDiagnostic("55000",`column "id" of relation "a" must be declared NOT NULL before identity can be added`);referenceAssertDiagnostic(t,err,&want)
	identityRefExec(t,db,`CREATE TABLE bd(id INT GENERATED BY DEFAULT AS IDENTITY)`,0)
	_,err=db.Exec(`INSERT INTO bd VALUES(NULL)`)
	want=referenceDiagnostic{Severity:"ERROR",SeverityUnlocalized:"ERROR",Code:"23502",Message:`null value in column "id" of relation "bd" violates not-null constraint`,Detail:"Failing row contains (null).",Schema:"public",Table:"bd",Column:"id"};referenceAssertDiagnostic(t,err,&want)
})}

func TestReferenceIdentityOverrideSourceShape(t *testing.T){identityReferenceCase(t,func(t *testing.T,db *sql.DB){
	for _,tc:=range []struct{query string;last int64;called bool;rows [][]int64}{
		{`INSERT INTO i OVERRIDING USER VALUE VALUES(nextval('side'),10)`,50,false,[][]int64{{1,10}}},
		{`INSERT INTO i OVERRIDING USER VALUE VALUES(nextval('side'),16),(nextval('side'),17)`,51,true,[][]int64{{1,16},{2,17}}},
		{`INSERT INTO i OVERRIDING USER VALUE SELECT nextval('side'),14`,50,true,[][]int64{{1,14}}},
	}{
		identityRefExec(t,db,`CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY,p INT)`,0);identityRefExec(t,db,`CREATE SEQUENCE side START 50 CACHE 1`,0)
		identityRefExec(t,db,tc.query,int64(len(tc.rows)));identityRefRows(t,db,`SELECT * FROM i ORDER BY id`,tc.rows)
		var last int64;var called bool;if err:=db.QueryRow(`SELECT last_value,is_called FROM side`).Scan(&last,&called);err!=nil||last!=tc.last||called!=tc.called{t.Fatal(last,called,err)}
		identityRefExec(t,db,`DROP TABLE i`,0);identityRefExec(t,db,`DROP SEQUENCE side`,0)
	}
})}
