func TestReferenceInheritanceNonpropagation(t *testing.T) {
	inheritanceScenario(t, func(s *inheritanceCase) {
		s.exec("CREATE TABLE p(a INT UNIQUE)", 0)
		s.exec("CREATE TABLE c() INHERITS(p)", 0)
		s.exec("CREATE TABLE own_unique(UNIQUE(a)) INHERITS(p)", 0)
		s.exec("INSERT INTO p VALUES(1)", 1)
		s.exec("INSERT INTO c VALUES(1),(1)", 2)
		s.fail("INSERT INTO p VALUES(1)", fixture.Diagnostic{Code: "23505", Message: `duplicate key value violates unique constraint "p_a_key"`, Detail: "Key (a)=(1) already exists.", Schema: "public", Table: "p", Constraint: "p_a_key"})
		s.exec("INSERT INTO own_unique VALUES(1)", 1)
		s.fail("INSERT INTO own_unique VALUES(1)", fixture.Diagnostic{Code: "23505", Message: `duplicate key value violates unique constraint "own_unique_a_key"`, Detail: "Key (a)=(1) already exists.", Schema: "public", Table: "own_unique", Constraint: "own_unique_a_key"})
		s.constraints("c", nil)
		s.values("SELECT * FROM c", []string{"a"}, []string{"INT4"}, [][]any{{int64(1)}, {int64(1)}})
		s.values("SELECT * FROM own_unique", []string{"a"}, []string{"INT4"}, [][]any{{int64(1)}})
	})
}

func TestReferenceInheritanceKeyBoundaries(t *testing.T) {
	inheritanceScenario(t, func(s *inheritanceCase) {
		s.exec("CREATE TABLE pk(a INT PRIMARY KEY)", 0)
		s.exec("CREATE TABLE pk_child() INHERITS(pk)", 0)
		s.exec("INSERT INTO pk VALUES(1)", 1)
		s.exec("INSERT INTO pk_child VALUES(1),(1),(2)", 3)
		s.fail("INSERT INTO pk_child VALUES(NULL)", inheritanceNullDiagnostic("pk_child", "a", "null"))
		s.constraints("pk_child", [][]any{{"pk_a_not_null", "n"}})
		if !s.b.PG {
			q := "CREATE TABLE fk(a INT REFERENCES pk)"
			s.fail(q, fixture.Diagnostic{Code: "0A000", Message: "column constraints are unsupported", Position: fixture.Position(strings.Index(q, "REFERENCES") + 1)})
			s.absent("fk")
			s.values("SELECT * FROM pk_child ORDER BY a", []string{"a"}, []string{"INT4"}, [][]any{{int64(1)}, {int64(1)}, {int64(2)}})
			return
		}
		s.exec("CREATE TABLE fk(a INT REFERENCES pk)", 0)
		s.exec("CREATE TABLE fk_child() INHERITS(fk)", 0)
		s.exec("INSERT INTO fk VALUES(1)", 1)
		s.exec("INSERT INTO fk_child VALUES(999)", 1)
		s.constraints("fk_child", nil)
		for _, value := range []string{"999", "2"} {
			s.fail("INSERT INTO fk VALUES("+value+")", fixture.Diagnostic{Code: "23503", Message: `insert or update on table "fk" violates foreign key constraint "fk_a_fkey"`, Detail: "Key (a)=(" + value + ") is not present in table \"pk\".", Schema: "public", Table: "fk", Constraint: "fk_a_fkey"})
		}
		s.values("SELECT * FROM pk_child ORDER BY a", []string{"a"}, []string{"INT4"}, [][]any{{int64(1)}, {int64(1)}, {int64(2)}})
		s.values("SELECT * FROM fk_child", []string{"a"}, []string{"INT4"}, [][]any{{int64(999)}})
	})
}

func TestReferenceInheritanceForeignBoundary(t *testing.T) {
	inheritanceScenario(t, func(s *inheritanceCase) {
		if !s.b.PG {
			s.fail("CREATE FOREIGN TABLE p(a INT) SERVER inheritance_server", fixture.Diagnostic{Code: "42601", Message: `syntax error at or near "FOREIGN"`, Position: "8"})
			s.absent("p")
			return
		}
		s.exec("CREATE EXTENSION file_fdw", 0)
		defer func() {
			if _, err := s.c.ExecContext(s.p.Ctx, "DROP SERVER IF EXISTS inheritance_server CASCADE; DROP EXTENSION file_fdw CASCADE"); err != nil {
				s.t.Error(err)
			}
		}()
		s.exec("CREATE SERVER inheritance_server FOREIGN DATA WRAPPER file_fdw", 0)
		// Real FDW metadata, no external file access or foreign scan is exercised.
		s.exec("CREATE FOREIGN TABLE p(a INT DEFAULT 7 NOT NULL,CONSTRAINT ck CHECK(a>0)) SERVER inheritance_server OPTIONS(filename '/dev/null',format 'csv')", 0)
		s.exec("CREATE TABLE c() INHERITS(p)", 0)
		s.exec("INSERT INTO c DEFAULT VALUES", 1)
		s.values("SELECT * FROM c", []string{"a"}, []string{"INT4"}, [][]any{{int64(7)}})
		s.constraints("c", [][]any{{"ck", "c"}, {"p_a_not_null", "n"}})
		s.edges("c", "p")
		s.fail("INSERT INTO c VALUES(-1)", inheritanceCheckDiagnostic("c", "ck", "-1"))
	})
}

func TestReferenceInheritanceExpressions(t *testing.T) {
	inheritanceScenario(t, func(s *inheritanceCase) {
		s.exec("CREATE TABLE identity_parent(id BIGINT GENERATED BY DEFAULT AS IDENTITY(START 7 INCREMENT 3))", 0)
		s.exec("CREATE TABLE identity_child() INHERITS(identity_parent)", 0)
		s.values("SELECT pg_get_serial_sequence('identity_child','id') AS owned", []string{"owned"}, []string{"TEXT"}, [][]any{{nil}})
		s.fail("INSERT INTO identity_child DEFAULT VALUES", inheritanceNullDiagnostic("identity_child", "id", "null"))
		s.exec("INSERT INTO identity_child VALUES(99)", 1)
		s.values("SELECT * FROM identity_child", []string{"id"}, []string{"INT8"}, [][]any{{int64(99)}})
		s.values("SELECT last_value,is_called FROM identity_parent_id_seq", []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(7), false}})
		s.exec("CREATE TABLE serial_parent(id SERIAL)", 0)
		s.exec("CREATE TABLE serial_child() INHERITS(serial_parent)", 0)
		s.values("SELECT pg_get_serial_sequence('serial_child','id') AS owned", []string{"owned"}, []string{"TEXT"}, [][]any{{nil}})
		s.exec("INSERT INTO serial_child DEFAULT VALUES", 1)
		s.exec("INSERT INTO serial_parent DEFAULT VALUES", 1)
		s.exec("INSERT INTO serial_child DEFAULT VALUES", 1)
		s.values("SELECT * FROM serial_child ORDER BY id", []string{"id"}, []string{"INT4"}, [][]any{{int64(1)}, {int64(3)}})
		s.values("SELECT last_value,is_called FROM serial_parent_id_seq", []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(3), true}})
		s.exec("CREATE TABLE generated_parent(dead TEXT,b INT DEFAULT 42,g INT GENERATED ALWAYS AS(a*2) STORED,a INT CHECK(a>0))", 0)
		s.exec("ALTER TABLE generated_parent DROP COLUMN dead", 0)
		s.exec("CREATE TABLE generated_child(lead TEXT) INHERITS(generated_parent)", 0)
		s.exec("INSERT INTO generated_child(a,lead) VALUES(11,'x')", 1)
		s.values("SELECT * FROM generated_child", []string{"b", "g", "a", "lead"}, []string{"INT4", "INT4", "INT4", "TEXT"}, [][]any{{int64(42), int64(22), int64(11), "x"}})
		s.fail("INSERT INTO generated_child(a,g) VALUES(1,3)", fixture.Diagnostic{Code: "428C9", Message: `cannot insert a non-DEFAULT value into column "g"`, Detail: `Column "g" is a generated column.`})
		s.exec("UPDATE generated_child SET a=12", 1)
		s.values("SELECT g FROM generated_child", []string{"g"}, []string{"INT4"}, [][]any{{int64(24)}})
	})
}
