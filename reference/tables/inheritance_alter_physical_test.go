func TestReferenceInheritanceAlterPhysicalConstraints(t *testing.T) {
	for _, kind := range []string{"unique", "primary", "exclude", "foreign", "using_index"} {
		t.Run(kind, func(t *testing.T) {
			inheritanceScenario(t, func(s *inheritanceCase) {
				s.exec("CREATE TABLE p(a INT NOT NULL)", 0)
				s.exec("CREATE TABLE c() INHERITS(p)", 0)
				s.exec("INSERT INTO p VALUES(1)", 1)
				s.exec("INSERT INTO c VALUES(1),(1)", 2)
				action := "ADD CONSTRAINT physical UNIQUE(a)"
				switch kind {
				case "primary":
					action = "ADD CONSTRAINT physical PRIMARY KEY(a)"
				case "exclude":
					action = "ADD CONSTRAINT physical EXCLUDE USING btree(a WITH =)"
				case "foreign":
					s.exec("CREATE TABLE referenced(a INT PRIMARY KEY)", 0)
					s.exec("INSERT INTO referenced VALUES(1)", 1)
					action = "ADD CONSTRAINT physical FOREIGN KEY(a) REFERENCES referenced(a)"
				case "using_index":
					s.exec("CREATE UNIQUE INDEX physical ON p(a)", 0)
					action = "ADD CONSTRAINT physical UNIQUE USING INDEX physical"
				}
				s.exec("ALTER TABLE p "+action, 0)
				s.values("SELECT count(*) AS n FROM pg_constraint WHERE conrelid='c'::regclass::oid AND conname='physical'", []string{"n"}, []string{"INT8"}, [][]any{{int64(0)}})
				s.values("SELECT count(*) AS n FROM pg_index WHERE indrelid='c'::regclass::oid", []string{"n"}, []string{"INT8"}, [][]any{{int64(0)}})
				s.exec("INSERT INTO c VALUES(99)", 1)
				if kind == "foreign" {
					s.fail("INSERT INTO p VALUES(99)", fixture.Diagnostic{Code: "23503", Message: `insert or update on table "p" violates foreign key constraint "physical"`, Detail: `Key (a)=(99) is not present in table "referenced".`, Schema: "public", Table: "p", Constraint: "physical"})
				} else if kind == "exclude" {
					s.run(fixture.ErrorDiagnostic("INSERT INTO p VALUES(1)", fixture.ExclusionReferenceConflict("p", "physical", "a", "1", "1")))
				} else {
					s.run(fixture.ErrorDiagnostic("INSERT INTO p VALUES(1)", fixture.UniqueReferenceDuplicate("p", "physical", "Key (a)=(1) already exists.")))
				}
				id := inheritanceAlterConstraintOID(s, "p", "physical")
				s.exec("ALTER TABLE ONLY p RENAME CONSTRAINT physical TO renamed", 0)
				if inheritanceAlterConstraintOID(s, "p", "renamed") != id {
					s.t.Fatal("local rename changed identity")
				}
				s.exec("ALTER TABLE p DROP CONSTRAINT renamed", 0)
				s.values("SELECT count(*) AS n FROM pg_constraint WHERE conrelid='p'::regclass::oid AND conname='renamed'", []string{"n"}, []string{"INT8"}, [][]any{{int64(0)}})
				s.exec("INSERT INTO p VALUES(1)", 1)
			})
		})
	}
	for _, only := range []bool{false, true} {
		t.Run(map[bool]string{false: "primary_implied_nn", true: "primary_only_nn"}[only], func(t *testing.T) {
			inheritanceScenario(t, func(s *inheritanceCase) {
				s.exec("CREATE TABLE p(a INT)", 0)
				s.exec("CREATE TABLE c() INHERITS(p)", 0)
				s.exec("INSERT INTO p VALUES(1)", 1)
				s.exec("INSERT INTO c VALUES(NULL)", 1)
				q := "ALTER TABLE p ADD PRIMARY KEY(a)"
				if only {
					q = "ALTER TABLE ONLY p ADD PRIMARY KEY(a)"
					s.fail(q, fixture.Diagnostic{Code: "XX000", Message: `column "a" of table "c" is not marked NOT NULL`})
				} else {
					s.fail(q, fixture.Diagnostic{Code: "23502", Message: `column "a" of relation "c" contains null values`, Schema: "public", Table: "c", Column: "a"})
				}
				inheritanceAlterFacts(s, "p", nil)
				inheritanceAlterFacts(s, "c", nil)
				s.exec("UPDATE c SET a=1", 1)
				if !only {
					s.exec(q, 0)
					inheritanceAlterFacts(s, "c", [][]any{{"p_a_not_null", false, int64(1), false}})
					s.values("SELECT count(*) AS n FROM pg_index WHERE indrelid='c'::regclass::oid", []string{"n"}, []string{"INT8"}, [][]any{{int64(0)}})
				}
			})
		})
	}
}

func TestReferenceInheritanceAlterPhysicalIdentity(t *testing.T) {
	inheritanceScenario(t, func(s *inheritanceCase) {
		s.exec("CREATE TABLE p(a INT)", 0)
		s.exec("CREATE TABLE c() INHERITS(p)", 0)
		s.fail("ALTER TABLE p ALTER a ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 10)", fixture.Diagnostic{Code: "55000", Message: `column "a" of relation "p" must be declared NOT NULL before identity can be added`})
		s.exec("ALTER TABLE p ALTER a SET NOT NULL", 0)
		s.exec("ALTER TABLE p ALTER a ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 10)", 0)
		s.exec("ALTER TABLE c ALTER a ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 100)", 0)
		s.exec("INSERT INTO p DEFAULT VALUES", 1)
		s.exec("INSERT INTO c DEFAULT VALUES", 1)
		s.exec("ALTER TABLE p ALTER a SET GENERATED ALWAYS", 0)
		s.values("SELECT attidentity FROM pg_attribute WHERE attrelid='p'::regclass::oid AND attname='a'", []string{"attidentity"}, []string{"CHAR"}, [][]any{{"a"}})
		s.values("SELECT attidentity FROM pg_attribute WHERE attrelid='c'::regclass::oid AND attname='a'", []string{"attidentity"}, []string{"CHAR"}, [][]any{{"d"}})
		s.exec("INSERT INTO p DEFAULT VALUES", 1)
		s.exec("INSERT INTO c DEFAULT VALUES", 1)
		s.exec("ALTER TABLE p ALTER a DROP IDENTITY", 0)
		s.exec("INSERT INTO p VALUES(20)", 1)
		s.exec("INSERT INTO c DEFAULT VALUES", 1)
		s.values("SELECT a FROM ONLY p ORDER BY a", []string{"a"}, []string{"INT4"}, [][]any{{int64(10)}, {int64(11)}, {int64(20)}})
		s.values("SELECT a FROM ONLY c ORDER BY a", []string{"a"}, []string{"INT4"}, [][]any{{int64(100)}, {int64(101)}, {int64(102)}})
		s.values("SELECT attidentity FROM pg_attribute WHERE attrelid='c'::regclass::oid AND attname='a'", []string{"attidentity"}, []string{"CHAR"}, [][]any{{"d"}})
	})
}

func TestReferenceInheritanceAlterPhysicalSecurity(t *testing.T) {
	inheritanceScenario(t, func(s *inheritanceCase) {
		s.exec("CREATE TABLE p(a INT)", 0)
		s.exec("CREATE TABLE c() INHERITS(p)", 0)
		flags := func(pEnabled, pForced bool) {
			s.values("SELECT relname,relrowsecurity,relforcerowsecurity FROM pg_class WHERE oid='p'::regclass::oid OR oid='c'::regclass::oid ORDER BY relname", []string{"relname", "relrowsecurity", "relforcerowsecurity"}, []string{"NAME", "BOOL", "BOOL"}, [][]any{{"c", false, false}, {"p", pEnabled, pForced}})
		}
		s.exec("ALTER TABLE p ENABLE ROW LEVEL SECURITY", 0)
		flags(true, false)
		s.exec("ALTER TABLE p FORCE ROW LEVEL SECURITY", 0)
		flags(true, true)
		s.exec("ALTER TABLE p NO FORCE ROW LEVEL SECURITY", 0)
		flags(true, false)
		s.exec("ALTER TABLE p DISABLE ROW LEVEL SECURITY", 0)
		flags(false, false)
	})
}

func TestReferenceInheritanceAlterPhysicalNames(t *testing.T) {
	fixture.SchemaReferenceCleanup(t, "inherit_dml_move")
	inheritanceScenario(t, func(s *inheritanceCase) {
		s.exec("CREATE SCHEMA inherit_dml_move", 0)
		s.exec("CREATE TABLE p(a INT)", 0)
		s.exec("CREATE TABLE c() INHERITS(p)", 0)
		s.exec("INSERT INTO p VALUES(1)", 1)
		s.exec("INSERT INTO c VALUES(2)", 1)
		const q = "SELECT a FROM c ORDER BY a"
		held, err := s.c.PrepareContext(s.p.Ctx, q)
		if err != nil {
			s.t.Fatal(err)
		}
		defer held.Close()
		var parent, child int64
		if err = s.c.QueryRowContext(s.p.Ctx, "SELECT 'p'::regclass::bigint,'c'::regclass::bigint").Scan(&parent, &child); err != nil {
			s.t.Fatal(err)
		}
		s.exec("ALTER TABLE p RENAME TO renamed_p", 0)
		s.exec("ALTER TABLE renamed_p SET SCHEMA inherit_dml_move", 0)
		s.values("SELECT a FROM inherit_dml_move.renamed_p ORDER BY a", []string{"a"}, []string{"INT4"}, [][]any{{int64(1)}, {int64(2)}})
		fixture.RunStep(s.t, s.p.Ctx, fixture.HeldStatement{Executor: s.c, Statement: held, SQL: q}, s.record, fixture.Select(q, []string{"a"}, []string{"INT4"}, [][]any{{int64(2)}}))
		s.values("SELECT inhparent::bigint AS parent,inhrelid::bigint AS child FROM pg_inherits WHERE inhrelid='c'::regclass::oid", []string{"parent", "child"}, []string{"INT8", "INT8"}, [][]any{{parent, child}})
		s.values("SELECT 'inherit_dml_move.renamed_p'::regclass::bigint AS parent,'c'::regclass::bigint AS child", []string{"parent", "child"}, []string{"INT8", "INT8"}, [][]any{{parent, child}})
		inheritanceAlterAttributes(s, "c", [][]any{{"a", int64(1), false, int64(1)}})
		s.exec("UPDATE inherit_dml_move.renamed_p SET a=a", 2)
		s.values("SELECT n.nspname FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE c.oid='c'::regclass::oid", []string{"nspname"}, []string{"NAME"}, [][]any{{"public"}})
		inheritanceQueryRole(s, "inherit_physical_owner", "NOBYPASSRLS")
		s.exec("ALTER TABLE inherit_dml_move.renamed_p OWNER TO inherit_physical_owner", 0)
		s.values("SELECT p.relowner=c.relowner AS same FROM pg_class p JOIN pg_class c ON c.oid='c'::regclass::oid WHERE p.oid='inherit_dml_move.renamed_p'::regclass::oid", []string{"same"}, []string{"BOOL"}, [][]any{{false}})
		s.exec("DROP TABLE c", 0)
		s.exec("DROP TABLE inherit_dml_move.renamed_p", 0)
		s.exec("DROP SCHEMA inherit_dml_move", 0)
	})
}
