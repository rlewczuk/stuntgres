package reference_test

import (
	"context"
	"database/sql"
	"errors"
	"reflect"
	"testing"

	"stuntgres/reference/fixture"
)

func fdwWriteTruncateGroups(t *testing.T, p *fixture.Pair, b fixture.Backend, c *sql.Conn, r *fdwSQLReader, run func(fixture.Step)) {
	t.Helper()
	fdwSourceExec(t, p, b, r, run, "CREATE TABLE fdw_source.third(id integer GENERATED BY DEFAULT AS IDENTITY,label text,flag boolean)", 0)
	fdwSourceExec(t, p, b, r, run, "INSERT INTO fdw_source.third(label,flag) VALUES('before',true)", 1)
	if b.PG {
		run(fixture.Exec("CREATE SERVER fdw_truncate_second FOREIGN DATA WRAPPER postgres_fdw OPTIONS(host '127.0.0.1',port '5432',dbname 'stuntgres_reference')", 0))
		run(fixture.Exec("CREATE USER MAPPING FOR CURRENT_USER SERVER fdw_truncate_second OPTIONS(user 'stuntgres',password 'stuntgres')", 0))
	} else {
		run(fixture.Exec("CREATE SERVER fdw_truncate_second FOREIGN DATA WRAPPER fdw_native", 0))
		run(fixture.Exec("CREATE USER MAPPING FOR CURRENT_USER SERVER fdw_truncate_second", 0))
	}
	run(fixture.Exec("CREATE FOREIGN TABLE fdw_third_data(id integer,label text,flag boolean) SERVER fdw_truncate_second OPTIONS(schema_name 'fdw_source',table_name 'third')", 0))
	fdwSourceExec(t, p, b, r, run, "INSERT INTO fdw_source.data VALUES(80,'data',true)", 1)
	fdwSourceExec(t, p, b, r, run, "INSERT INTO fdw_source.other VALUES(81,'other',false)", 1)
	run(fixture.Exec("TRUNCATE fdw_data,fdw_other_data,fdw_third_data,fdw_data RESTART IDENTITY CASCADE", 0))
	for _, table := range []string{"data", "other", "third"} {
		fdwWriteSourceRows(t, p, b, r, fdwRows("SELECT id,label,flag FROM fdw_source."+table, nil))
	}
	fdwSourceExec(t, p, b, r, run, "INSERT INTO fdw_source.third(label,flag) VALUES('restarted',false)", 1)
	fdwWriteSourceRows(t, p, b, r, fdwRows("SELECT id,label,flag FROM fdw_source.third", [][]any{{int64(1), "restarted", false}}))
	if !b.PG {
		if !reflect.DeepEqual(r.writer.truncateGroups, []int{2, 2, 1}) {
			t.Fatal("per-server grouping/dedup", r.writer.truncateGroups)
		}
		fdwSourceExec(t, p, b, r, run, "INSERT INTO fdw_source.data VALUES(82,'preserved',true)", 1)
		calls := 0
		failure := errors.New("second truncate group failed")
		r.writer.writeHook = func(ctx context.Context, name string) error {
			if name == "ExecForeignTruncate" {
				calls++
				if calls == 2 {
					return failure
				}
			}
			return nil
		}
		fdwWriteFailedExec(t, p.Ctx, c, "TRUNCATE fdw_data,fdw_third_data", failure)
		r.writer.writeHook = nil
		fdwWriteSourceRows(t, p, b, r, fdwRows("SELECT id,label,flag FROM fdw_source.data", [][]any{{int64(82), "preserved", true}}))
		fdwWriteSourceRows(t, p, b, r, fdwRows("SELECT id,label,flag FROM fdw_source.third", [][]any{{int64(1), "restarted", false}}))
	}
	fdwSourceExec(t, p, b, r, run, "CREATE TABLE fdw_source.restrict_parent(id integer PRIMARY KEY,label text,flag boolean)", 0)
	fdwSourceExec(t, p, b, r, run, "CREATE TABLE fdw_source.restrict_child(id integer REFERENCES fdw_source.restrict_parent(id))", 0)
	fdwSourceExec(t, p, b, r, run, "INSERT INTO fdw_source.restrict_parent VALUES(1,'parent',true)", 1)
	fdwSourceExec(t, p, b, r, run, "INSERT INTO fdw_source.restrict_child VALUES(1)", 1)
	run(fixture.Exec("CREATE FOREIGN TABLE fdw_restrict(id integer,label text,flag boolean) SERVER fdw_live OPTIONS(schema_name 'fdw_source',table_name 'restrict_parent')", 0))
	fdwWriteFailedExec(t, p.Ctx, c, "TRUNCATE fdw_restrict RESTRICT", nil)
	fdwWriteSourceRows(t, p, b, r, fdwRows("SELECT id,label,flag FROM fdw_source.restrict_parent", [][]any{{int64(1), "parent", true}}))
	run(fixture.Exec("TRUNCATE fdw_restrict CASCADE", 0))
	fdwWriteSourceRows(t, p, b, r, fdwRows("SELECT id,label,flag FROM fdw_source.restrict_parent", nil))
	fdwWriteSourceRows(t, p, b, r, fixture.Select("SELECT id FROM fdw_source.restrict_child", []string{"id"}, []string{"INT4"}, nil))
}
