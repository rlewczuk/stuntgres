func uniqueReferenceProducerFrontier(t *testing.T, standalone bool) {
	p := fixture.NewScenario(t)
	for _, b := range p.Backends() {
		t.Run(b.Name, func(t *testing.T) {
			a, _ := fixture.LockConnections(t, p.Ctx, b.DB)
			run := func(s fixture.Step) { fixture.RunStep(t, p.Ctx, a, b.Recorder, s) }
			run(fixture.Exec("CREATE SEQUENCE draws", 0))
			uniqueIndexReferenceCreate(run, standalone, "CREATE TABLE t(k INT CONSTRAINT u UNIQUE,draw BIGINT DEFAULT nextval('draws'))", "CREATE TABLE t(k INT,draw BIGINT DEFAULT nextval('draws'))", "CREATE UNIQUE INDEX u ON t(k)")
			run(fixture.Exec("INSERT INTO t VALUES(2,0)", 1))
			duplicate := fixture.UniqueReferenceDuplicate("t", "u", "Key (k)=(2) already exists.")
			run(fixture.Prepared(fixture.ErrorDiagnostic("INSERT INTO t(k) VALUES(1),(2),(3)", duplicate)))
			run(fixture.Select("SELECT last_value FROM draws", []string{"last_value"}, []string{"INT8"}, [][]any{{int64(2)}}))
			run(fixture.Select("SELECT k,draw FROM t", []string{"k", "draw"}, []string{"INT4", "INT8"}, [][]any{{int64(2), int64(0)}}))
			run(fixture.Exec("ALTER SEQUENCE draws RESTART WITH 1", 0))
			run(fixture.Exec("CREATE TABLE source(k INT)", 0))
			run(fixture.Exec("INSERT INTO source VALUES(3),(1),(2)", 3))
			run(fixture.ErrorDiagnostic("INSERT INTO t(k) SELECT k FROM source ORDER BY k", duplicate))
			run(fixture.Select("SELECT last_value FROM draws", []string{"last_value"}, []string{"INT8"}, [][]any{{int64(2)}}))
			run(fixture.Exec("INSERT INTO t VALUES(1,0),(3,0)", 2))
			run(fixture.Exec("ALTER SEQUENCE draws RESTART WITH 1", 0))
			run(fixture.Prepared(fixture.ErrorDiagnostic("UPDATE t SET k=2,draw=nextval('draws') WHERE k<>2", duplicate)))
			run(fixture.Select("SELECT last_value,is_called FROM draws", []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(1), true}}))
			run(fixture.Select("SELECT k,draw FROM t ORDER BY k", []string{"k", "draw"}, []string{"INT4", "INT8"}, [][]any{{int64(1), int64(0)}, {int64(2), int64(0)}, {int64(3), int64(0)}}))
		})
	}
}
