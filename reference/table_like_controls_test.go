func TestReferenceTableLikeFeatureSmoke(t *testing.T) {
	tableLikeLifecycle(t)
	tableLikePartialLifecycle(t)
	tableLikeTemporaryDefaultsLifecycle(t)
	tableLikeTemporaryIdentity(t)
}
func TestReferenceTableLikeControls(t *testing.T) { tableLikeLifecycle(t) }

func tableLikeLifecycle(t *testing.T) {
	tableLikeScenario(t, func(t *testing.T, p *referencePair, b referenceBackend, c *sql.Conn, prepared bool, run func(referenceStep)) {
		run(referenceExec("CREATE TABLE src(id BIGINT GENERATED BY DEFAULT AS IDENTITY(START 7 INCREMENT 3),a INT DEFAULT 7,g INT GENERATED ALWAYS AS(a*2) STORED,CONSTRAINT positive CHECK(a>0) NO INHERIT,UNIQUE(a))", 0))
		run(referenceExec("COMMENT ON COLUMN src.a IS 'O''Brien é'", 0))
		run(referenceExec("COMMENT ON TABLE src IS 'source only'", 0))
		run(referenceExec("CREATE INDEX src_hash ON src USING hash(a)", 0))
		run(referenceExec("INSERT INTO src(a) VALUES(11)", 1))
		run(referenceExec("CREATE TABLE clone(lead TEXT,LIKE src INCLUDING ALL EXCLUDING INDEXES,tail BOOL)", 0))
		names, types := []string{"lead", "id", "a", "g", "tail"}, []string{"TEXT", "INT8", "INT4", "INT4", "BOOL"}
		run(referenceSelect("SELECT * FROM clone", names, types, nil))
		referenceTableDDLMetadata(t, p.ctx, c, b.pg, prepared, "SELECT * FROM clone", names, types, []bool{true, false, true, true, true}, 0)
		run(referenceExec("INSERT INTO clone(lead,tail) VALUES('x',true)", 1))
		first := referenceSelect("SELECT * FROM clone ORDER BY id", names, types, [][]any{{"x", int64(7), int64(7), int64(14), true}})
		run(first)
		run(referenceSelect("SELECT pg_get_serial_sequence('src','id')<>pg_get_serial_sequence('clone','id') AS independent", []string{"independent"}, []string{"BOOL"}, [][]any{{true}}))
		comment := referenceSelect("SELECT obj_description('clone'::regclass,'pg_class') AS table_comment,col_description('clone'::regclass,3) AS comment", []string{"table_comment", "comment"}, []string{"TEXT", "TEXT"}, [][]any{{nil, "O'Brien é"}})
		run(comment)
		run(referenceExec("INSERT INTO src(a) VALUES(12)", 1))
		run(referenceSelect("SELECT id FROM src ORDER BY id", []string{"id"}, []string{"INT8"}, [][]any{{int64(7)}, {int64(10)}}))
		run(referenceExec("INSERT INTO clone(lead,tail) VALUES('y',false)", 1))
		run(tableLikeError("INSERT INTO clone(a) VALUES(-1)", referenceDiagnostic{Code: "23514", Message: `new row for relation "clone" violates check constraint "positive"`, Detail: "Failing row contains (null, 13, -1, -2, null).", Schema: "public", Table: "clone", Constraint: "positive"}))
		run(tableLikeError("INSERT INTO clone(g) VALUES(2)", referenceDiagnostic{Code: "428C9", Message: `cannot insert a non-DEFAULT value into column "g"`, Detail: `Column "g" is a generated column.`}))
		want := referenceSelect("SELECT * FROM clone ORDER BY id", names, types, [][]any{{"x", int64(7), int64(7), int64(14), true}, {"y", int64(10), int64(7), int64(14), false}})
		run(want)
		run(referenceExec("CREATE TABLE indexed(LIKE src INCLUDING INDEXES INCLUDING DEFAULTS)", 0))
		run(referenceExec("INSERT INTO indexed(id,g) VALUES(1,99)", 1))
		run(tableLikeError("INSERT INTO indexed(id,g) VALUES(2,99)", referenceDiagnostic{Code: "23505", Message: `duplicate key value violates unique constraint "indexed_a_key"`, Detail: "Key (a)=(7) already exists.", Schema: "public", Table: "indexed", Constraint: "indexed_a_key"}))
		run(referenceExec("CREATE TABLE mask(LIKE src INCLUDING ALL EXCLUDING ALL INCLUDING DEFAULTS)", 0))
		run(referenceExec("INSERT INTO mask(id) VALUES(1)", 1))
		run(referenceSelect("SELECT * FROM mask", []string{"id", "a", "g"}, []string{"INT8", "INT4", "INT4"}, [][]any{{int64(1), int64(7), nil}}))
		run(referenceExec("INSERT INTO mask VALUES(2,-1,5),(2,-1,5)", 2))
		run(referenceSelect("SELECT col_description('mask'::regclass,2) AS comment", []string{"comment"}, []string{"TEXT"}, [][]any{{nil}}))
		run(referenceExec("CREATE VIEW v AS SELECT a,g FROM src", 0))
		run(referenceExec("CREATE TABLE view_copy(LIKE v INCLUDING ALL)", 0))
		run(referenceExec("INSERT INTO view_copy DEFAULT VALUES", 1))
		run(referenceSelect("SELECT * FROM view_copy", []string{"a", "g"}, []string{"INT4", "INT4"}, [][]any{{nil, nil}}))
		run(tableLikeError("CREATE TABLE bad(LIKE src INCLUDING ALL,a TEXT)", referenceDiagnostic{Code: "42701", Message: `column "a" specified more than once`}))
		tableLikeAbsent(run, "bad", prepared)
		run(referenceExec("CREATE TABLE bad(a TEXT)", 0))
		// Explicit native-only controls; actual emitted SQL is replayed on PG below.
		if b.pg {
			return
		}
		heldConn, err := p.native.Conn(p.ctx)
		if err != nil {
			t.Fatal(err)
		}
		defer heldConn.Close()
		var held driver.Rows
		if err := heldConn.Raw(func(raw any) error {
			var e error
			held, e = raw.(driver.QueryerContext).QueryContext(p.ctx, "SELECT * FROM clone ORDER BY id", nil)
			return e
		}); err != nil {
			t.Fatal(err)
		}
		defer held.Close()
		state := referenceSelect("SELECT last_value,is_called FROM clone_id_seq", []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(13), true}})
		run(state)
		var dump bytes.Buffer
		if err := stuntgres.Dump(p.ctx, p.native, &dump); err != nil {
			t.Fatal(err)
		}
		run(state)
		if err := stuntgres.Reset(p.ctx, p.native); err != nil {
			t.Fatal(err)
		}
		tableLikeAbsent(run, "clone", prepared)
		if err := stuntgres.Restore(p.ctx, p.native, bytes.NewReader(dump.Bytes())); err != nil {
			t.Fatal(err)
		}
		run(want)
		run(comment)
		run(state)
		for _, script := range []string{dump.String() + "; CREATE TABLE late(LIKE missing)", dump.String() + "; CREATE TABLE late(a INT,a TEXT)"} {
			if err := stuntgres.Restore(p.ctx, p.native, strings.NewReader(script)); err == nil {
				t.Fatal("late invalid restore accepted")
			}
			run(want)
			run(comment)
			run(state)
		}
		canceled, cancel := context.WithCancel(p.ctx)
		cancel()
		if err := stuntgres.Restore(canceled, p.native, bytes.NewReader(dump.Bytes())); !errors.Is(err, context.Canceled) {
			t.Fatal(err)
		}
		if _, err := c.ExecContext(canceled, "CREATE TABLE canceled(LIKE src INCLUDING ALL)"); !errors.Is(err, context.Canceled) {
			t.Fatal(err)
		}
		tableLikeAbsent(run, "canceled", prepared)
		run(want)
		cells := make([]driver.Value, len(names))
		for _, row := range want.rows {
			if err := held.Next(cells); err != nil || !reflect.DeepEqual([]any{cells[0], cells[1], cells[2], cells[3], cells[4]}, row) {
				t.Fatal(cells, err, row)
			}
		}
		if err := held.Next(cells); err != io.EOF {
			t.Fatal(err)
		}
		if !reflect.DeepEqual(held.Columns(), names) {
			t.Fatal(held.Columns())
		}
		if p.postgres != nil {
			if _, err := p.postgres.ExecContext(p.ctx, "DROP SCHEMA public CASCADE; CREATE SCHEMA public"); err != nil {
				t.Fatal(err)
			}
			if _, err := p.postgres.ExecContext(p.ctx, dump.String()); err != nil {
				t.Fatal("actual native dump replay", err)
			}
			for _, s := range []referenceStep{want, comment, state} {
				s.prepared = prepared
				referenceRunStep(t, p.ctx, p.postgres, p.postgresRecord, s)
			}
			referenceRunStep(t, p.ctx, p.postgres, p.postgresRecord, referenceExec("INSERT INTO clone(lead) VALUES('restored')", 1))
			referenceRunStep(t, p.ctx, p.postgres, p.postgresRecord, referenceSelect("SELECT id,a,g FROM clone WHERE lead='restored'", []string{"id", "a", "g"}, []string{"INT8", "INT4", "INT4"}, [][]any{{int64(16), int64(7), int64(14)}}))
			if _, err := p.postgres.ExecContext(p.ctx, "DROP SCHEMA public CASCADE; CREATE SCHEMA public"); err != nil {
				t.Fatal(err)
			}
		}
		run(referenceExec("INSERT INTO clone(lead) VALUES('restored')", 1))
		run(referenceSelect("SELECT id,a,g FROM clone WHERE lead='restored'", []string{"id", "a", "g"}, []string{"INT8", "INT4", "INT4"}, [][]any{{int64(16), int64(7), int64(14)}}))
	})
}
