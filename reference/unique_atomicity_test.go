func uniqueReferenceTransactions(t *testing.T, standalone bool) {
	p := newReferenceScenario(t)
	for _, backend := range p.backends() {
		t.Run(backend.name, func(t *testing.T) {
			a, b := referenceLockConnections(t, p.ctx, backend.db)
			run := func(s referenceStep) { referenceRunStep(t, p.ctx, a, backend.recorder, s) }
			uniqueIndexReferenceCreate(run, standalone, "CREATE TABLE t(k INT CONSTRAINT u UNIQUE)", "CREATE TABLE t(k INT)", "CREATE UNIQUE INDEX u ON t(k)")
			run(referenceExec("BEGIN", 0))
			run(referenceExec("INSERT INTO t VALUES(1)", 1))
			run(referenceExec("SAVEPOINT before_duplicate", 0))
			s := referencePrepared(referenceErrorDiagnostic("INSERT INTO t VALUES($1)", uniqueReferenceDuplicate("t", "u", "Key (k)=(1) already exists."), int64(1)))
			s.errorStage = "execute"
			run(s)
			run(referenceExec("ROLLBACK TO before_duplicate", 0))
			run(referenceSelect("SELECT k FROM t", []string{"k"}, []string{"INT4"}, [][]any{{int64(1)}}))
			run(referenceExec("SAVEPOINT release_key", 0))
			run(referenceExec("INSERT INTO t VALUES(2)", 1))
			run(referenceExec("ROLLBACK TO release_key", 0))
			referenceRunStep(t, p.ctx, b, backend.recorder, referencePrepared(referenceExec("INSERT INTO t VALUES($1)", 1, int64(2))))
			run(referenceExec("DELETE FROM t WHERE k=1", 1))
			run(referenceExec("INSERT INTO t VALUES(1)", 1))
			run(referenceExec("UPDATE t SET k=3 WHERE k=1", 1))
			run(referenceExec("INSERT INTO t VALUES(1)", 1))
			run(referenceExec("COMMIT", 0))
			run(referenceSelect("SELECT k FROM t ORDER BY k", []string{"k"}, []string{"INT4"}, [][]any{{int64(1)}, {int64(2)}, {int64(3)}}))
		})
	}
}

