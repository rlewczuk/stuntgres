func uniqueReferenceProducerFrontier(t *testing.T, standalone bool) {
	p := newReferenceScenario(t)
	for _, b := range p.backends() {
		t.Run(b.name, func(t *testing.T) {
			a, _ := referenceLockConnections(t, p.ctx, b.db)
			run := func(s referenceStep) { referenceRunStep(t, p.ctx, a, b.recorder, s) }
			run(referenceExec("CREATE SEQUENCE draws", 0))
			uniqueIndexReferenceCreate(run, standalone, "CREATE TABLE t(k INT CONSTRAINT u UNIQUE,draw BIGINT DEFAULT nextval('draws'))", "CREATE TABLE t(k INT,draw BIGINT DEFAULT nextval('draws'))", "CREATE UNIQUE INDEX u ON t(k)")
			run(referenceExec("INSERT INTO t VALUES(2,0)", 1))
			duplicate := uniqueReferenceDuplicate("t", "u", "Key (k)=(2) already exists.")
			run(referencePrepared(referenceErrorDiagnostic("INSERT INTO t(k) VALUES(1),(2),(3)", duplicate)))
			run(referenceSelect("SELECT last_value FROM draws", []string{"last_value"}, []string{"INT8"}, [][]any{{int64(2)}}))
			run(referenceSelect("SELECT k,draw FROM t", []string{"k", "draw"}, []string{"INT4", "INT8"}, [][]any{{int64(2), int64(0)}}))
			run(referenceExec("ALTER SEQUENCE draws RESTART WITH 1", 0))
			run(referenceExec("CREATE TABLE source(k INT)", 0))
			run(referenceExec("INSERT INTO source VALUES(3),(1),(2)", 3))
			run(referenceErrorDiagnostic("INSERT INTO t(k) SELECT k FROM source ORDER BY k", duplicate))
			run(referenceSelect("SELECT last_value FROM draws", []string{"last_value"}, []string{"INT8"}, [][]any{{int64(2)}}))
			run(referenceExec("INSERT INTO t VALUES(1,0),(3,0)", 2))
			run(referenceExec("ALTER SEQUENCE draws RESTART WITH 1", 0))
			run(referencePrepared(referenceErrorDiagnostic("UPDATE t SET k=2,draw=nextval('draws') WHERE k<>2", duplicate)))
			run(referenceSelect("SELECT last_value,is_called FROM draws", []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(1), true}}))
			run(referenceSelect("SELECT k,draw FROM t ORDER BY k", []string{"k", "draw"}, []string{"INT4", "INT8"}, [][]any{{int64(1), int64(0)}, {int64(2), int64(0)}, {int64(3), int64(0)}}))
		})
	}
}
