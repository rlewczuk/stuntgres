package reference_test

import (
	"context"
	"database/sql"
	"errors"
	"testing"
	"time"
)

func TestReferenceTableLikeAdmission(t *testing.T) {
	tableLikeScenario(t, func(t *testing.T, p *referencePair, b referenceBackend, c *sql.Conn, prepared bool, run func(referenceStep)) {
		run(referenceExec("CREATE TABLE src(a INT DEFAULT 7)", 0))
		// lib/pq can send a fast utility even with a pre-canceled context. Native
		// cancellation is an adapter guarantee; PG cancellation uses the wait below.
		if !b.pg {
			canceled, cancel := context.WithCancel(p.ctx)
			cancel()
			if _, err := c.ExecContext(canceled, "CREATE TABLE clone(LIKE src INCLUDING ALL)"); !errors.Is(err, context.Canceled) {
				t.Fatal(err)
			}
			tableLikeAbsent(run, "clone", prepared)
		}
		run(referenceExec("CREATE SCHEMA like_nested CREATE TABLE first(a INT DEFAULT 9) CREATE TABLE second(LIKE like_nested.first INCLUDING ALL)", 0))
		defer b.db.ExecContext(context.Background(), "DROP SCHEMA IF EXISTS like_nested CASCADE")
		run(referenceExec("INSERT INTO like_nested.second DEFAULT VALUES", 1))
		run(referenceSelect("SELECT * FROM like_nested.second", []string{"a"}, []string{"INT4"}, [][]any{{int64(9)}}))
		run(tableLikeError("CREATE SCHEMA like_failed CREATE TABLE first(a INT GENERATED BY DEFAULT AS IDENTITY) CREATE TABLE second(LIKE like_failed.first INCLUDING ALL,a TEXT)", referenceDiagnostic{Code: "42701", Message: `column "a" specified more than once`}))
		if b.pg {
			run(referenceSelect("SELECT nspname FROM pg_namespace WHERE nspname='like_failed'", []string{"nspname"}, []string{"NAME"}, nil))
		}
		run(referenceExec("DROP SCHEMA like_nested CASCADE", 0))
		// Native exact-incarnation queue mechanics are descriptor-only Round B tests.
		// This public PG barrier independently proves even an option-free LIKE waits.
		if !b.pg {
			return
		}
		holder, err := b.db.Conn(p.ctx)
		if err != nil {
			t.Fatal(err)
		}
		defer holder.Close()
		waiter, err := b.db.Conn(p.ctx)
		if err != nil {
			t.Fatal(err)
		}
		defer waiter.Close()
		hp, wp := referenceLockPID(t, p.ctx, holder), referenceLockPID(t, p.ctx, waiter)
		oid := referenceLockOID(t, p.ctx, "src")
		if _, err := holder.ExecContext(p.ctx, "BEGIN; LOCK TABLE src IN ACCESS EXCLUSIVE MODE"); err != nil {
			t.Fatal(err)
		}
		defer holder.ExecContext(context.Background(), "ROLLBACK")
		ctx, stop := context.WithTimeout(p.ctx, 5*time.Second)
		defer stop()
		done := make(chan error, 1)
		go func() { _, err := waiter.ExecContext(ctx, "CREATE TABLE clone(LIKE src)"); done <- err }()
		defer func() {
			stop()
			select {
			case <-done:
			case <-time.After(5 * time.Second):
				t.Error("LIKE worker did not join")
			}
		}()
		referenceLockWaitBehind(t, ctx, wp, hp, oid, "AccessShareLock")
		if _, err := referenceAdmin.ExecContext(p.ctx, "SELECT pg_cancel_backend($1)", wp); err != nil {
			t.Fatal(err)
		}
		select {
		case err := <-done:
			done <- err
			referenceAssertDiagnostic(t, err, &referenceDiagnostic{Severity: "ERROR", SeverityUnlocalized: "ERROR", Code: "57014", Message: "canceling statement due to user request"})
		case <-ctx.Done():
			t.Fatal(ctx.Err())
		}
		if _, err := holder.ExecContext(p.ctx, "ROLLBACK"); err != nil {
			t.Fatal(err)
		}
		tableLikeAbsent(run, "clone", prepared)
		run(referenceExec("CREATE TABLE clone(LIKE src INCLUDING ALL)", 0))
		run(referenceExec("INSERT INTO clone DEFAULT VALUES", 1))
		run(referenceSelect("SELECT * FROM clone", []string{"a"}, []string{"INT4"}, [][]any{{int64(7)}}))
	})
}
