func TestReferenceBitwiseValuesSignsShiftsAndResolution(t *testing.T) {
	p := newReferenceScenario(t)
	p.step(t, referenceExec("CREATE TABLE one(v INTEGER)", 0))
	p.step(t, referenceExec("INSERT INTO one VALUES(1)", 1))
	for _, tc := range referenceBitwiseValueCases {
		step := referenceSelect("SELECT "+tc.expr+" FROM one", []string{"?column?"}, []string{tc.typ}, [][]any{{tc.want}})
		p.step(t, step)
		p.step(t, referencePrepared(step))
	}
}
