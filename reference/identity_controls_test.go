//go:build reference

package reference_test

import (
	"bytes"
	"database/sql"
	"stuntgres"
	"testing"
)

func TestReferenceIdentityControls(t *testing.T) {
	p := newReferencePair(t)
	for _, q := range []string{`CREATE TABLE narrow(id SMALLINT GENERATED ALWAYS AS IDENTITY)`, `ALTER SEQUENCE narrow_id_seq AS bigint MAXVALUE 100000 RESTART WITH 32768`, `CREATE TABLE uncalled(id INT GENERATED BY DEFAULT AS IDENTITY(START 7 CACHE 2))`, `COMMENT ON SEQUENCE narrow_id_seq IS 'divergent generator'`} {
		identityRefExec(t, p.memory, q, 0)
	}
	identityRefExec(t, p.memory, `INSERT INTO narrow DEFAULT VALUES`, 1)
	identityRefExec(t, p.memory, `INSERT INTO uncalled VALUES(99)`, 1)
	var dump bytes.Buffer
	if err := stuntgres.Dump(p.ctx, p.native, &dump); err != nil {
		t.Fatal(err)
	}
	if _, err := p.postgres.ExecContext(p.ctx, dump.String()); err != nil {
		t.Fatal(err)
	}
	if err := stuntgres.Reset(p.ctx, p.native); err != nil {
		t.Fatal(err)
	}
	if err := stuntgres.Restore(p.ctx, p.native, bytes.NewReader(dump.Bytes())); err != nil {
		t.Fatal(err)
	}
	var again bytes.Buffer
	if err := stuntgres.Dump(p.ctx, p.native, &again); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(dump.Bytes(), again.Bytes()) {
		t.Fatalf("redump mismatch\n%s\n%s", dump.Bytes(), again.Bytes())
	}
	for _, db := range []*sql.DB{p.memory, p.postgres} {
		identityRefExec(t, db, `INSERT INTO narrow DEFAULT VALUES`, 1)
		identityRefExec(t, db, `INSERT INTO uncalled DEFAULT VALUES`, 1)
		identityRefRows(t, db, `SELECT * FROM narrow ORDER BY id`, [][]int64{{-32768}, {-32767}})
		identityRefRows(t, db, `SELECT * FROM uncalled ORDER BY id`, [][]int64{{7}, {99}})
	}
}
