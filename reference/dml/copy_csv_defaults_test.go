func TestReferenceCopyCSVDefaultsDemand(t *testing.T) {
	copyTextScenario(t, func(t *testing.T, p *fixture.Pair, b fixture.Backend, c copyTextConnection) {
		c.exec(t, "CREATE TABLE copy_csv_defaults(id int GENERATED BY DEFAULT AS IDENTITY,a text DEFAULT 'fallback',omitted int DEFAULT 7,g int GENERATED ALWAYS AS(omitted+1) STORED)")
		result, err := c.from("COPY copy_csv_defaults(a) FROM STDIN WITH(FORMAT csv,DEFAULT 'DEF',FORCE_NULL(a),FORCE_NOT_NULL(a))", strings.NewReader("DEF\n\"DEF\"\n\n\"\"\n"))
		copyTextSuccess(t, result, err, 4)
		c.selectRows(t, "SELECT * FROM copy_csv_defaults ORDER BY id", []string{"id", "a", "omitted", "g"}, []string{"INT4", "TEXT", "INT4", "INT4"}, [][]any{{int64(1), "fallback", int64(7), int64(8)}, {int64(2), "DEF", int64(7), int64(8)}, {int64(3), "", int64(7), int64(8)}, {int64(4), nil, int64(7), int64(8)}})
		result, err = c.from("COPY copy_csv_defaults(a) FROM STDIN WITH(FORMAT csv)", strings.NewReader(""))
		copyTextSuccess(t, result, err, 0)
		result, err = c.from("COPY copy_csv_defaults(a) FROM STDIN WITH(FORMAT csv)", strings.NewReader("\n"))
		copyTextSuccess(t, result, err, 1)
		c.selectRows(t, "SELECT id,a FROM copy_csv_defaults WHERE id=5", []string{"id", "a"}, []string{"INT4", "TEXT"}, [][]any{{int64(5), nil}})
		c.exec(t, "CREATE SEQUENCE copy_csv_demand")
		c.exec(t, "CREATE TABLE copy_csv_sequence(id int DEFAULT nextval('copy_csv_demand'),v text DEFAULT 'fallback')")
		result, err = c.from("COPY copy_csv_sequence(id,v) FROM STDIN WITH(FORMAT csv,DEFAULT 'DEF')", strings.NewReader("DEF,DEF\n42,\"DEF\"\n"))
		copyTextSuccess(t, result, err, 2)
		c.selectRows(t, "SELECT * FROM copy_csv_sequence ORDER BY id", []string{"id", "v"}, []string{"INT4", "TEXT"}, [][]any{{int64(1), "fallback"}, {int64(42), "DEF"}})
		c.selectRows(t, "SELECT last_value,is_called FROM copy_csv_demand", []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(1), true}})
		result, err = c.from("COPY copy_csv_sequence(v) FROM STDIN WITH(FORMAT csv)", strings.NewReader(""))
		copyTextSuccess(t, result, err, 0)
		result, err = c.from("COPY copy_csv_sequence(id,v) FROM STDIN WITH(FORMAT csv,DEFAULT 'DEF')", strings.NewReader("DEF,ok\nbad,no\n"))
		copyTextDiagnostic(t, result, err, fixture.Diagnostic{Code: "22P02", Message: "invalid input syntax for type integer: \"bad\"", Context: "COPY copy_csv_sequence, line 2, column id: \"bad\""})
		c.selectRows(t, "SELECT last_value,is_called FROM copy_csv_demand", []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(2), true}})
		c.selectRows(t, "SELECT * FROM copy_csv_sequence ORDER BY id", []string{"id", "v"}, []string{"INT4", "TEXT"}, [][]any{{int64(1), "fallback"}, {int64(42), "DEF"}})
		for _, def := range []string{"", " DEFAULT NULL"} {
			c.exec(t, "CREATE TABLE copy_csv_no_default(v text"+def+")")
			result, err = c.from("COPY copy_csv_no_default FROM STDIN WITH(FORMAT csv,DEFAULT 'DEF')", strings.NewReader("DEF\n"))
			copyTextDiagnostic(t, result, err, fixture.Diagnostic{Code: "22P04", Message: "unexpected default marker in COPY data", Detail: "Column \"v\" has no default value.", Context: "COPY copy_csv_no_default, line 1: \"DEF\""})
			c.exec(t, "DROP TABLE copy_csv_no_default")
		}
		c.exec(t, "CREATE TABLE copy_csv_bad_default(v int DEFAULT 1/0)")
		never := &copyTextNoRead{}
		result, err = c.from("COPY copy_csv_bad_default FROM STDIN WITH(FORMAT csv,DEFAULT 'DEF')", never)
		copyTextDiagnostic(t, result, err, fixture.Diagnostic{Code: "22012", Message: "division by zero"})
		if !b.PG && never.calls != 0 {
			t.Fatal("default preflight read caller")
		}
	})
}

func TestReferenceCopyCSVFeatureSmoke(t *testing.T) {
	copyTextScenario(t, func(t *testing.T, p *fixture.Pair, b fixture.Backend, c copyTextConnection) {
		c.exec(t, "CREATE TABLE copy_csv_smoke(id int,a text,b text)")
		result, err := c.from("COPY copy_csv_smoke FROM STDIN WITH(FORMAT csv,HEADER MATCH)", strings.NewReader("id,a,b\n"+copyCSVGolden))
		copyTextSuccess(t, result, err, 3)
		c.selectRows(t, "SELECT * FROM copy_csv_smoke ORDER BY id", []string{"id", "a", "b"}, []string{"INT4", "TEXT", "TEXT"}, [][]any{{int64(1), nil, ""}, {int64(2), "x,y", "a\"b"}, {int64(3), "line\nbreak", "cr\r\nlf"}})
		c.output(t, "COPY (SELECT * FROM copy_csv_smoke ORDER BY id) TO STDOUT WITH(FORMAT csv,HEADER true,FORCE_QUOTE(a))", "id,a,b\n"+copyCSVGolden, 3)
		c.exec(t, "CREATE TABLE copy_csv_smoke_force(a text,b text)")
		result, err = c.from("COPY copy_csv_smoke_force FROM STDIN WITH(FORMAT csv,NULL 'NIL',FORCE_NOT_NULL(a),FORCE_NULL(b))", strings.NewReader("NIL,\"NIL\"\n"))
		copyTextSuccess(t, result, err, 1)
		c.selectRows(t, "SELECT * FROM copy_csv_smoke_force", []string{"a", "b"}, []string{"TEXT", "TEXT"}, [][]any{{"NIL", nil}})
		c.output(t, "COPY copy_csv_smoke_force TO STDOUT WITH(FORMAT csv,NULL 'NIL')", "\"NIL\",NIL\n", 1)
		c.exec(t, "CREATE TABLE copy_csv_smoke_custom(v text)")
		result, err = c.from("COPY copy_csv_smoke_custom FROM STDIN WITH(FORMAT csv,QUOTE '''',ESCAPE '!')", strings.NewReader("'a!'b!!c'\n"))
		copyTextSuccess(t, result, err, 1)
		c.output(t, "COPY copy_csv_smoke_custom TO STDOUT WITH(FORMAT csv,QUOTE '''',ESCAPE '!')", "'a!'b!!c'\n", 1)
		result, err = c.from("COPY copy_csv_smoke FROM STDIN WITH(FORMAT csv)", strings.NewReader("4,ok,good\n5,\"unterminated"))
		copyTextDiagnostic(t, result, err, fixture.Diagnostic{Code: "22P04", Message: "unterminated CSV quoted field", Context: "COPY copy_csv_smoke, line 2: \"5,\"unterminated\""})
		c.output(t, "COPY (SELECT * FROM copy_csv_smoke ORDER BY id) TO STDOUT WITH(FORMAT csv)", copyCSVGolden, 3)
	})
}
