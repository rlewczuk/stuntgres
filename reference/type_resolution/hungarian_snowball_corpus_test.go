func TestReferenceHungarianSnowballMorphology(t *testing.T) {
	for start := 0; start < len(hungarianMorphology); start += 24 {
		end := min(start+24, len(hungarianMorphology))
		group := hungarianMorphology[start:end]
		t.Run(group[0][0], func(t *testing.T) {
			dictionaryScenario(t, func(t *testing.T, p *fixture.Pair, b fixture.Backend, c *sql.Conn) {
				regtsExec(t, p, b, c, "CREATE TEXT SEARCH DICTIONARY hungarian_rules (TEMPLATE=snowball,Language='HuNgArIaN')", 0)
				q := "SELECT ts_lexize('hungarian_rules',$1::text) AS lexemes"
				stmt, err := c.PrepareContext(p.Ctx, q)
				if err != nil {
					t.Fatal(err)
				}
				defer stmt.Close()
				for _, tc := range group {
					t.Run(tc[0], func(t *testing.T) {
						for _, route := range []struct {
							name     string
							executor fixture.Executor
						}{{"direct", c}, {"held-prepared", fixture.HeldStatement{Executor: c, Statement: stmt, SQL: q}}} {
							t.Run(route.name, func(t *testing.T) {
								dictionaryResult(t, p, b, route.executor, q, "{"+tc[1]+"}", tc[0])
							})
						}
					})
				}
			})
		})
	}
}
