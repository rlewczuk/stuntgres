package reference_test

import (
	"database/sql"
	"fmt"
	"strings"
	"testing"
)

func TestReferenceTableLikeProviderPrecedence(t *testing.T) {
	tableLikeScenario(t, func(t *testing.T, p *referencePair, b referenceBackend, c *sql.Conn, prepared bool, run func(referenceStep)) {
		run(referenceExec("CREATE TABLE src(id INT GENERATED BY DEFAULT AS IDENTITY,a INT DEFAULT 7,g INT GENERATED ALWAYS AS(a*2) STORED,CONSTRAINT positive CHECK(a>0),UNIQUE(a))", 0))
		run(referenceExec("COMMENT ON COLUMN src.a IS 'exact'", 0))
		for _, option := range []string{"DEFAULTS", "GENERATED", "IDENTITY", "CONSTRAINTS", "INDEXES", "COMMENTS"} {
			for i, tc := range []struct {
				options  string
				included bool
			}{
				{"INCLUDING " + option + " EXCLUDING " + option, false},
				{"EXCLUDING " + option + " INCLUDING " + option, true},
				{"INCLUDING ALL EXCLUDING " + option, false},
				{"EXCLUDING " + option + " INCLUDING ALL", true},
			} {
				name := fmt.Sprintf("copy_%s_%d", strings.ToLower(option), i)
				all := i >= 2
				selected := func(property string) bool {
					if property == option {
						return tc.included
					}
					return all
				}
				run(referenceExec("CREATE TABLE "+name+"(LIKE src "+tc.options+")", 0))
				run(referenceExec("INSERT INTO "+name+"(id) VALUES(99)", 1))
				var def, gen any
				if selected("DEFAULTS") {
					def = int64(7)
					if selected("GENERATED") {
						gen = int64(14)
					}
				}
				run(referenceSelect("SELECT a,g FROM "+name, []string{"a", "g"}, []string{"INT4", "INT4"}, [][]any{{def, gen}}))
				var comment any
				if selected("COMMENTS") {
					comment = "exact"
				}
				run(referenceSelect("SELECT col_description('"+name+"'::regclass,2) AS comment", []string{"comment"}, []string{"TEXT"}, [][]any{{comment}}))
				if selected("IDENTITY") {
					run(referenceExec("INSERT INTO "+name+"(a) VALUES(8)", 1))
					run(referenceSelect("SELECT id FROM "+name+" WHERE a=8", []string{"id"}, []string{"INT4"}, [][]any{{int64(1)}}))
				} else {
					run(tableLikeError("INSERT INTO "+name+"(a) VALUES(8)", referenceDiagnostic{Code: "23502", Message: `null value in column "id" of relation "` + name + `" violates not-null constraint`, Detail: func() string {
						if selected("GENERATED") {
							return "Failing row contains (null, 8, 16)."
						}
						return "Failing row contains (null, 8, null)."
					}(), Schema: "public", Table: name, Column: "id"}))
				}
				run(referenceExec("INSERT INTO "+name+"(id,a) VALUES(100,5)", 1))
				if selected("INDEXES") {
					run(tableLikeError("INSERT INTO "+name+"(id,a) VALUES(101,5)", referenceDiagnostic{Code: "23505", Message: `duplicate key value violates unique constraint "` + name + `_a_key"`, Detail: "Key (a)=(5) already exists.", Schema: "public", Table: name, Constraint: name + "_a_key"}))
				} else {
					run(referenceExec("INSERT INTO "+name+"(id,a) VALUES(101,5)", 1))
				}
				if selected("CONSTRAINTS") {
					detail := "Failing row contains (102, -1, null)."
					if selected("GENERATED") {
						detail = "Failing row contains (102, -1, -2)."
					}
					run(tableLikeError("INSERT INTO "+name+"(id,a) VALUES(102,-1)", referenceDiagnostic{Code: "23514", Message: `new row for relation "` + name + `" violates check constraint "positive"`, Detail: detail, Schema: "public", Table: name, Constraint: "positive"}))
				} else {
					run(referenceExec("INSERT INTO "+name+"(id,a) VALUES(102,-1)", 1))
				}
			}
		}
	})
}
