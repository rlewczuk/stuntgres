func pgNamespaceNoLeak(t *testing.T, dump []byte) {
	t.Helper()
	for _, line := range strings.Split(string(dump), "\n") {
		if strings.HasPrefix(line, "INSERT INTO pg_catalog.pg_namespace") || strings.HasPrefix(line, "CREATE SCHEMA pg_toast") || strings.Contains(line, "pg_temp_") || strings.Contains(line, "pg_toast_temp_") {
			t.Fatal("catalog/TEMP dump leakage", line)
		}
	}
}

func pgNamespaceNativeControls(t *testing.T, p *fixture.Pair, b fixture.Backend, schema string) {
	t.Helper()
	id := pgNamespaceID(t, p, b.DB, schema)
	_, owner := pgNamespaceCurrentRole(t, p, b, b.DB)
	// A held eager result owns its original namespace/type generation.
	rows, err := b.DB.QueryContext(p.Ctx, "SELECT * FROM pg_namespace WHERE oid=$1", id)
	if err != nil {
		t.Fatal(err)
	}
	defer rows.Close()
	pgNamespaceMetadata(t, rows, false)
	target := fixture.SequenceCoreConn(t, p.Ctx, b.DB)
	pgNamespaceExec(t, p, b, target, "CREATE TEMP TABLE ns18_control_temp(i INT)", "CREATE TEMP SEQUENCE ns18_control_seq START 41 CACHE 3")
	fixture.RunStep(t, p.Ctx, target, b.Recorder, fixture.Exec("INSERT INTO ns18_control_temp VALUES(18)", 1))
	name, tid, toast, toid := pgNamespaceTempPair(t, p, b, target, "ns18_control_temp", owner)
	var next int64
	if err := target.QueryRowContext(p.Ctx, "SELECT nextval('ns18_control_seq')").Scan(&next); err != nil || next != 41 {
		t.Fatal(next, err)
	}
	dump := fixture.ViewDump(t, p)
	pgNamespaceNoLeak(t, dump)
	late := append(append([]byte(nil), dump...), []byte("CREATE SEQUENCE ns18_control_bad CACHE 0;")...)
	if err := stuntgres.Restore(p.Ctx, p.Native, bytes.NewReader(late)); err == nil {
		t.Fatal("late invalid restore succeeded")
	} else {
		want := fixture.ControlsReferenceDiagnostic("22023", "CACHE (0) must be greater than zero")
		fixture.AssertDiagnostic(t, err, &want)
	}
	pgNamespaceRow(t, p, b, b.DB, schema, id, owner, nil)
	canceled, cancel := context.WithCancel(p.Ctx)
	cancel()
	if err := stuntgres.Restore(canceled, p.Native, bytes.NewReader(dump)); !errors.Is(err, context.Canceled) {
		t.Fatal(err)
	}
	if err := stuntgres.Reset(p.Ctx, p.Native); err != nil {
		t.Fatal(err)
	}
	pgNamespaceCheck(t, p, b, b.DB, fixture.Select("SELECT nspname FROM pg_namespace WHERE nspname=$1", []string{"nspname"}, []string{"NAME"}, nil, schema))
	fixture.ViewRestore(t, p, dump)
	fresh := pgNamespaceID(t, p, b.DB, schema)
	pgNamespaceRow(t, p, b, b.DB, schema, fresh, owner, nil)
	pgNamespaceRow(t, p, b, target, name, tid, 10, nil)
	pgNamespaceRow(t, p, b, target, toast, toid, 10, nil)
	pgNamespaceCheck(t, p, b, target, fixture.Select("SELECT i FROM pg_temp.ns18_control_temp", []string{"i"}, []string{"INT4"}, [][]any{{int64(18)}}))
	if err := target.QueryRowContext(p.Ctx, "SELECT nextval('ns18_control_seq')").Scan(&next); err != nil || next != 42 {
		t.Fatal("preserved generator/cache", next, err)
	}
	if !rows.Next() {
		t.Fatal("held namespace lost", rows.Err())
	}
	var oldID, oldOwner int64
	var oldName string
	var oldACL sql.NullString
	if err := rows.Scan(&oldID, &oldName, &oldOwner, &oldACL); err != nil || oldID != id || oldName != schema || oldOwner != owner || oldACL.Valid {
		t.Fatal(oldID, oldName, oldOwner, oldACL, err)
	}
	if rows.Next() || rows.Err() != nil {
		t.Fatal("held namespace multiplicity/error", rows.Err())
	}
	rows.Close()
	if redump := fixture.ViewDump(t, p); !bytes.Equal(dump, redump) {
		t.Fatal("nondeterministic logical redump", string(dump), string(redump))
	}
	targetPair := fixture.NewFixture(t, false, false)
	destination := targetPair.Memory
	targetBackend := fixture.Backend{Name: "memory", DB: destination, Recorder: targetPair.MemoryRecord}
	if err := stuntgres.Restore(p.Ctx, targetPair.Native, bytes.NewReader(dump)); err != nil {
		t.Fatal(err)
	}
	pgNamespaceRow(t, targetPair, targetBackend, destination, "pg_toast", 99, 10, nil)
	pgNamespaceCheck(t, targetPair, targetBackend, destination, fixture.Select("SELECT nspname FROM pg_namespace WHERE nspname=$1 OR nspname=$2", []string{"nspname"}, []string{"NAME"}, nil, name, toast))
	pgNamespaceRow(t, targetPair, targetBackend, destination, schema, pgNamespaceID(t, targetPair, destination, schema), 10, nil)
	// Ordinary dropped/recreated public is serialized, not regenerated by projection.
	pgNamespaceExec(t, p, b, b.DB, "DROP SCHEMA public CASCADE", "CREATE SCHEMA public")
	public := pgNamespaceID(t, p, b.DB, "public")
	if public == 2200 {
		t.Fatal("recreated public has bootstrap identity")
	}
	dump = fixture.ViewDump(t, p)
	fixture.ViewRestore(t, p, dump)
	pgNamespaceRow(t, p, b, b.DB, "public", pgNamespaceID(t, p, b.DB, "public"), 10, nil)
}

func TestReferencePGNamespaceControls(t *testing.T) {
	t.Run("nominal_replay", pgNamespaceNominalReplay)
	pgNamespaceScenario(t, []string{"ns18_controls", "ns18_control_acl"}, []string{"ns18_control_reader"}, func(t *testing.T, p *fixture.Pair, b fixture.Backend) {
		pgNamespaceExec(t, p, b, b.DB, "CREATE SCHEMA ns18_controls", "CREATE TABLE ns18_controls.ns18_control_table(i INT)")
		id := pgNamespaceID(t, p, b.DB, "ns18_controls")
		_, owner := pgNamespaceCurrentRole(t, p, b, b.DB)
		pgNamespaceRow(t, p, b, b.DB, "ns18_controls", id, owner, nil)
		if b.PG {
			return
		}
		pgNamespaceNativeControls(t, p, b, "ns18_controls")
		pgNamespaceExec(t, p, b, b.DB, "CREATE ROLE ns18_control_reader")
		defer pgNamespaceExec(t, p, b, b.DB, "ALTER DEFAULT PRIVILEGES REVOKE USAGE ON SCHEMAS FROM ns18_control_reader")
		pgNamespaceExec(t, p, b, b.DB, "ALTER DEFAULT PRIVILEGES GRANT USAGE ON SCHEMAS TO ns18_control_reader", "CREATE SCHEMA ns18_control_acl")
		// Existing schemas keep materialized ACLs after creator defaults are revoked.
		pgNamespaceExec(t, p, b, b.DB, "ALTER DEFAULT PRIVILEGES REVOKE USAGE ON SCHEMAS FROM ns18_control_reader")
		var out bytes.Buffer
		if err := stuntgres.Dump(p.Ctx, p.Native, &out); err == nil || err.Error() != "stuntgres: dump cannot serialize explicit namespace ACL" || out.Len() != 0 {
			t.Fatal("honest ACL preflight", err, out.String())
		}
	})
}

func TestReferencePGNamespaceFeatureSmoke(t *testing.T) {
	t.Run("nominal_replay", pgNamespaceNominalReplay)
	t.Run("TemporarySuperuserAuthority", TestReferencePGNamespaceTemporarySuperuserAuthority)
	pgNamespaceScenario(t, []string{"ns18_smoke", "ns18_smoke_new", "ns18_smoke_denied"}, []string{"ns18_smoke_actor"}, func(t *testing.T, p *fixture.Pair, b fixture.Backend) {
		pgNamespaceRow(t, p, b, b.DB, "pg_toast", 99, 10, nil)
		bootstrap := "postgres"
		if b.PG {
			bootstrap = "stuntgres"
		}
		pgNamespaceRow(t, p, b, b.DB, "pg_catalog", 11, 10, "{"+bootstrap+"=UC/"+bootstrap+",=U/"+bootstrap+"}")
		pgNamespaceExec(t, p, b, b.DB, "CREATE ROLE ns18_smoke_actor", "CREATE SCHEMA ns18_smoke", "CREATE TABLE ns18_smoke.ns18_smoke_table(i INT)", "CREATE SCHEMA ns18_smoke_denied", "CREATE TABLE ns18_smoke_denied.ns18_hidden(i INT)")
		id := pgNamespaceID(t, p, b.DB, "ns18_smoke")
		_, owner := pgNamespaceCurrentRole(t, p, b, b.DB)
		pgNamespaceRow(t, p, b, b.DB, "ns18_smoke", id, owner, nil)
		pgNamespaceCheck(t, p, b, b.DB, fixture.Select("SELECT relnamespace FROM pg_class WHERE relname='ns18_smoke_table'", []string{"relnamespace"}, []string{"OID"}, [][]any{{id}}))
		pgNamespaceExec(t, p, b, b.DB, "ALTER SCHEMA ns18_smoke RENAME TO ns18_smoke_new")
		pgNamespaceRow(t, p, b, b.DB, "ns18_smoke_new", id, owner, nil)
		c := fixture.SequenceCoreConn(t, p.Ctx, b.DB)
		pgNamespaceExec(t, p, b, c, "SET ROLE ns18_smoke_actor")
		denied := pgNamespaceID(t, p, c, "ns18_smoke_denied")
		pgNamespaceRow(t, p, b, c, "ns18_smoke_denied", denied, owner, nil)
		s := fixture.SchemaReferenceError("SELECT i FROM ns18_smoke_denied.ns18_hidden", "42501", "permission denied for schema ns18_smoke_denied", "", false, "execute", "15")
		s.SelectRows = true
		fixture.RunStep(t, p.Ctx, c, b.Recorder, s)
		pgNamespaceExec(t, p, b, c, "CREATE TEMP TABLE ns18_smoke_temp(i INT)")
		pgNamespaceTempPair(t, p, b, c, "ns18_smoke_temp", pgNamespaceRoleID(t, p, c, "ns18_smoke_actor"))
		pgNamespaceExec(t, p, b, c, "RESET ROLE")
		if !b.PG {
			pgNamespaceNativeControls(t, p, b, "ns18_smoke_new")
		}
	})
}
