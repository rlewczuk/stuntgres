package reference_test

import (
	"bytes"
	"context"
	"database/sql"
	"errors"
	"strings"
	"stuntgres"
	"testing"
)

func TestReferenceAlterIdentityControls(t *testing.T) {
	alterIdentityScenario(t, func(t *testing.T, p *referencePair, b referenceBackend, c *sql.Conn) {
		run := func(s referenceStep) { referenceRunStep(t, p.ctx, c, b.recorder, s) }
		run(referenceExec(`CREATE TABLE a(id INT NOT NULL,dropped INT NOT NULL)`, 0))
		run(referenceExec(`INSERT INTO a VALUES(40,400)`, 1))
		for _, q := range []string{`ALTER TABLE a ALTER id ADD GENERATED BY DEFAULT AS IDENTITY(SEQUENCE NAME public.actual CACHE 1)`, `ALTER TABLE a ALTER dropped ADD GENERATED BY DEFAULT AS IDENTITY(SEQUENCE NAME public.removed)`} {
			run(referenceExec(q, 0))
		}
		explicit := identityHeld(t, p.ctx, c, `INSERT INTO a VALUES($1,500)`)
		omitted := identityHeld(t, p.ctx, c, `INSERT INTO a(dropped) VALUES($1)`)
		run(referenceExec(`ALTER TABLE a ALTER dropped DROP IDENTITY`, 0))
		run(referenceExec(`ALTER TABLE a ALTER id SET GENERATED ALWAYS SET START 20 SET INCREMENT 3 SET CACHE 1 RESTART 20`, 0))
		identityEmptyMetadata(t, p.ctx, b, true, `SELECT * FROM a WHERE false`, []string{"id", "dropped"}, []string{"INT4", "INT4"}, []bool{false, false})
		var retained *sql.Rows
		if !b.pg {
			var err error
			retained, err = c.QueryContext(p.ctx, `SELECT * FROM a ORDER BY id`)
			if err != nil {
				t.Fatal(err)
			}
			defer retained.Close()
			var dump bytes.Buffer
			if err := stuntgres.Dump(p.ctx, p.native, &dump); err != nil {
				t.Fatal(err)
			}
			if err := stuntgres.Reset(p.ctx, p.native); err != nil {
				t.Fatal(err)
			}
			if err := stuntgres.Restore(p.ctx, p.native, bytes.NewReader(dump.Bytes())); err != nil {
				t.Fatal(err)
			}
			var again bytes.Buffer
			if err := stuntgres.Dump(p.ctx, p.native, &again); err != nil {
				t.Fatal(err)
			}
			if !bytes.Equal(dump.Bytes(), again.Bytes()) {
				t.Fatal("altered state roundtrip changed canonical bytes")
			}
			for _, script := range []string{`CREATE TABLE replacement(x INT); ALTER TABLE replacement ALTER x ADD GENERATED ALWAYS AS IDENTITY;`, `CREATE TABLE replacement(id INT GENERATED ALWAYS AS IDENTITY); ALTER SEQUENCE replacement_id_seq CACHE 0;`} {
				if err := stuntgres.Restore(p.ctx, p.native, strings.NewReader(script)); err == nil {
					t.Fatal("invalid restore accepted")
				}
			}
			failure := errors.New("altered identity reader failure")
			if err := stuntgres.Restore(p.ctx, p.native, identityFailingReader{failure}); !errors.Is(err, failure) {
				t.Fatal(err)
			}
			canceled, cancel := context.WithCancel(p.ctx)
			cancel()
			if err := stuntgres.Restore(canceled, p.native, bytes.NewReader(dump.Bytes())); !errors.Is(err, context.Canceled) {
				t.Fatal(err)
			}
			if referenceDDLNativeDump(t, p) != dump.String() {
				t.Fatal("failed Restore changed post-ALTER baseline")
			}
			if !retained.Next() {
				t.Fatal(retained.Err())
			}
			var id, dropped int64
			if err := retained.Scan(&id, &dropped); err != nil || id != 40 || dropped != 400 {
				t.Fatal(id, dropped, err)
			}
			if retained.Next() || retained.Err() != nil {
				t.Fatal("retained snapshot changed", retained.Err())
			}
			if err := retained.Close(); err != nil {
				t.Fatal(err)
			}
		}
		// PostgreSQL runs the same ALTER history; no fictional PostgreSQL control API.
		run(referenceSelect(`SELECT * FROM a`, []string{"id", "dropped"}, []string{"INT4", "INT4"}, [][]any{{int64(40), int64(400)}}))
		run(referenceSelect(`SELECT last_value,is_called FROM actual`, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(20), false}}))
		alterIdentityMissing(t, p, b, c, "removed")
		referenceRunStep(t, p.ctx, explicit, b.recorder, referenceImplicitError(explicit.query, identityAlwaysDiagnostic(), 99))
		referenceRunStep(t, p.ctx, omitted, b.recorder, referenceExec(omitted.query, 1, 500))
		referenceRunStep(t, p.ctx, omitted, b.recorder, referenceExec(omitted.query, 1, 501))
		run(referenceSelect(`SELECT * FROM a ORDER BY id`, []string{"id", "dropped"}, []string{"INT4", "INT4"}, [][]any{{int64(20), int64(500)}, {int64(23), int64(501)}, {int64(40), int64(400)}}))
		run(referenceImplicitError(`INSERT INTO a DEFAULT VALUES`, referenceDiagnostic{Code: "23502", Message: `null value in column "dropped" of relation "a" violates not-null constraint`, Detail: "Failing row contains (26, null).", Schema: "public", Table: "a", Column: "dropped"}))
	})
}
