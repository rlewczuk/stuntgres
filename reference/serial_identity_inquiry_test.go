const serialIdentityQuery = `SELECT pg_get_serial_sequence($1,$2)`

// All SQL assertions below are shared; native controls live in the controls file.
func serialIdentityScenario(t *testing.T, body func(*testing.T, *referencePair, referenceBackend, *sql.Conn)) {
	t.Helper()
	p := newReferenceScenario(t)
	for _, b := range p.backends() {
		t.Run(b.name, func(t *testing.T) {
			c, err := b.db.Conn(p.ctx)
			if err != nil { t.Fatal(err) }
			defer c.Close()
			body(t, p, b, c)
		})
	}
}

func serialIdentityText(q string, value any, pg bool, args ...any) referenceStep {
	s := referenceSelect(q, []string{"pg_get_serial_sequence"}, []string{"TEXT"}, [][]any{{value}}, args...)
	s.checkMetadata = func(t *testing.T, rows *sql.Rows) {
		types, err := rows.ColumnTypes()
		if err != nil { t.Fatal(err) }
		if len(types) != 1 { t.Fatal(types) }
		typ := types[0]
		n, known := typ.Nullable()
		if typ.Name() != "pg_get_serial_sequence" || typ.DatabaseTypeName() != "TEXT" || typ.ScanType() != reflect.TypeFor[string]() {
			t.Fatal("TEXT descriptor", typ.Name(), typ.DatabaseTypeName(), typ.ScanType())
		}
		if pg {
			if n || known { t.Fatal("pq nullable availability", n, known) }
		} else if !n || !known { t.Fatal("native nullable descriptor", n, known) }
	}
	return s
}

func serialIdentityHeld(t *testing.T, p *referencePair, b referenceBackend, c *sql.Conn) referenceHeldStatement {
	t.Helper()
	stmt, err := c.PrepareContext(p.ctx, serialIdentityQuery)
	if err != nil { t.Fatal(err) }
	t.Cleanup(func() { if err := stmt.Close(); err != nil { t.Error(err) } })
	return referenceHeldStatement{referenceExecutor: c, statement: stmt, query: serialIdentityQuery}
}

func serialIdentityCheck(t *testing.T, p *referencePair, b referenceBackend, c *sql.Conn, held referenceHeldStatement, table, column string, want any) {
	t.Helper()
	q := `SELECT pg_get_serial_sequence(` + pq.QuoteLiteral(table) + `,` + pq.QuoteLiteral(column) + `)`
	referenceRunStep(t, p.ctx, c, b.recorder, serialIdentityText(q, want, b.pg))
	referenceRunStep(t, p.ctx, held, b.recorder, serialIdentityText(serialIdentityQuery, want, b.pg, table, column))
}

func serialIdentityRun(t *testing.T, p *referencePair, b referenceBackend, c referenceExecutor, steps ...referenceStep) {
	t.Helper()
	for _, s := range steps { referenceRunStep(t, p.ctx, c, b.recorder, s) }
}

func TestReferenceSerialIdentityOwnership(t *testing.T) {
	serialIdentityScenario(t, func(t *testing.T, p *referencePair, b referenceBackend, c *sql.Conn) {
		serialIdentityRun(t, p, b, c,
			referenceExec(`CREATE TABLE owned(gone INT,s SMALLSERIAL,i SERIAL,b BIGSERIAL,plain INT)`, 0),
			referenceExec(`CREATE TABLE si_identity(sa SMALLINT GENERATED ALWAYS AS IDENTITY,sd SMALLINT GENERATED BY DEFAULT AS IDENTITY,ia INTEGER GENERATED ALWAYS AS IDENTITY,id INTEGER GENERATED BY DEFAULT AS IDENTITY,ba BIGINT GENERATED ALWAYS AS IDENTITY,bd BIGINT GENERATED BY DEFAULT AS IDENTITY,custom INTEGER GENERATED ALWAYS AS IDENTITY (SEQUENCE NAME "Owned.Seq"))`, 0))
		held := serialIdentityHeld(t, p, b, c)
		for _, col := range []string{"s", "i", "b"} { serialIdentityCheck(t, p, b, c, held, "owned", col, "public.owned_"+col+"_seq") }
		serialIdentityCheck(t, p, b, c, held, "owned", "plain", nil)
		for _, col := range []string{"sa", "sd", "ia", "id", "ba", "bd"} { serialIdentityCheck(t, p, b, c, held, "si_identity", col, "public.si_identity_"+col+"_seq") }
		serialIdentityCheck(t, p, b, c, held, "si_identity", "custom", `public."Owned.Seq"`)
		for _, q := range []string{`SELECT pg_get_serial_sequence('owned','s') WHERE FALSE`, `SELECT pg_get_serial_sequence(NULL,NULL) WHERE FALSE`} {
			s := serialIdentityText(q, nil, b.pg)
			s.rows = [][]any{}
			serialIdentityRun(t, p, b, c, s, referencePrepared(s))
		}
		serialIdentityRun(t, p, b, c,
			referenceSelect(`SELECT count(*) FROM pg_catalog.pg_attrdef WHERE adrelid='si_identity'::regclass::oid`, []string{"count"}, []string{"INT8"}, [][]any{{int64(0)}}),
			referenceSelect(`SELECT last_value,is_called FROM owned_s_seq`, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(1), false}}))
		for _, name := range []string{"owned_s_seq", "owned_i_seq", "owned_b_seq", "si_identity_sa_seq", "si_identity_sd_seq", "si_identity_ia_seq", "si_identity_id_seq", "si_identity_ba_seq", "si_identity_bd_seq", `"Owned.Seq"`} {
			serialIdentityRun(t, p, b, c, referenceSelect(`SELECT nextval(`+pq.QuoteLiteral(name)+`)`, []string{"nextval"}, []string{"INT8"}, [][]any{{int64(1)}}))
		}
	})
}

func TestReferenceSerialIdentityLifecycle(t *testing.T) {
	serialIdentityScenario(t, func(t *testing.T, p *referencePair, b referenceBackend, c *sql.Conn) {
		serialIdentityRun(t, p, b, c, referenceExec(`CREATE TABLE owned(gone INT,s SERIAL,plain INT,other INT)`, 0), referenceExec(`CREATE SEQUENCE provider`, 0))
		held := serialIdentityHeld(t, p, b, c)
		rows, err := held.statement.QueryContext(p.ctx, "owned", "s")
		if err != nil { t.Fatal(err) }
		types, err := rows.ColumnTypes()
		if err != nil { t.Fatal(err) }
		if !rows.Next() { t.Fatal("missing retained row", rows.Err()) }
		var retained string
		if err := rows.Scan(&retained); err != nil { t.Fatal(err) }
		if rows.Next() || rows.Err() != nil { t.Fatal("retained scalar cardinality", rows.Err()) }
		if err := rows.Close(); err != nil { t.Fatal(err) }
		serialIdentityRun(t, p, b, c, referenceExec(`ALTER TABLE owned ALTER s DROP DEFAULT`, 0))
		serialIdentityCheck(t, p, b, c, held, "owned", "s", "public.owned_s_seq")
		serialIdentityRun(t, p, b, c, referenceExec(`ALTER TABLE owned ALTER s SET DEFAULT nextval('provider')`, 0), referenceExec(`ALTER TABLE owned ALTER other SET DEFAULT nextval('provider')`, 0))
		serialIdentityCheck(t, p, b, c, held, "owned", "s", "public.owned_s_seq")
		serialIdentityCheck(t, p, b, c, held, "owned", "other", nil)
		serialIdentityRun(t, p, b, c, referenceExec(`CREATE SEQUENCE manual OWNED BY owned.plain`, 0))
		serialIdentityCheck(t, p, b, c, held, "owned", "plain", "public.manual")
		serialIdentityRun(t, p, b, c, referenceExec(`ALTER SEQUENCE owned_s_seq OWNED BY NONE`, 0))
		serialIdentityCheck(t, p, b, c, held, "owned", "s", nil)
		serialIdentityRun(t, p, b, c, referenceExec(`ALTER SEQUENCE owned_s_seq OWNED BY owned.s`, 0), referenceExec(`ALTER SEQUENCE manual OWNED BY owned.other`, 0))
		serialIdentityCheck(t, p, b, c, held, "owned", "plain", nil)
		serialIdentityCheck(t, p, b, c, held, "owned", "other", "public.manual")
		tx, err := c.BeginTx(p.ctx, nil)
		if err != nil { t.Fatal(err) }
		defer tx.Rollback()
		serialIdentityRun(t, p, b, tx, referenceExec(`ALTER SEQUENCE owned_s_seq OWNED BY NONE`, 0), serialIdentityText(serialIdentityQuery, nil, b.pg, "owned", "s"))
		txHeld := referenceHeldStatement{referenceExecutor: tx, statement: tx.StmtContext(p.ctx, held.statement), query: serialIdentityQuery}
		serialIdentityRun(t, p, b, txHeld, serialIdentityText(serialIdentityQuery, nil, b.pg, "owned", "s"))
		if err := txHeld.statement.Close(); err != nil { t.Fatal(err) }
		if err := tx.Rollback(); err != nil { t.Fatal(err) }
		serialIdentityCheck(t, p, b, c, held, "owned", "s", "public.owned_s_seq")
		serialIdentityRun(t, p, b, c, referenceExec(`ALTER TABLE owned DROP COLUMN gone`, 0), referenceExec(`ALTER TABLE owned RENAME COLUMN s TO renamed`, 0), referenceExec(`ALTER TABLE owned RENAME TO renamed_owned`, 0), referenceExec(`ALTER SEQUENCE owned_s_seq RENAME TO "Actual.Seq"`, 0), referenceExec(`CREATE SCHEMA si_lifecycle`, 0), referenceExec(`ALTER TABLE renamed_owned SET SCHEMA si_lifecycle`, 0))
		defer func() { if _, err := c.ExecContext(p.ctx, `DROP SCHEMA si_lifecycle CASCADE`); err != nil { t.Error(err) } }()
		serialIdentityCheck(t, p, b, c, held, "si_lifecycle.renamed_owned", "renamed", `si_lifecycle."Actual.Seq"`)
		if retained != "public.owned_s_seq" || len(types) != 1 || types[0].DatabaseTypeName() != "TEXT" || types[0].Name() != "pg_get_serial_sequence" { t.Fatal("retained row/descriptor changed", retained, types) }
		serialIdentityRun(t, p, b, c, referenceSelect(`SELECT nextval('si_lifecycle."Actual.Seq"'),nextval('provider'),nextval('si_lifecycle.manual')`, []string{"nextval", "nextval", "nextval"}, []string{"INT8", "INT8", "INT8"}, [][]any{{int64(1), int64(1), int64(1)}}))
	})
}

func TestReferenceSerialIdentityNames(t *testing.T) {
	serialIdentityScenario(t, func(t *testing.T, p *referencePair, b referenceBackend, c *sql.Conn) {
		serialIdentityRun(t, p, b, c, referenceExec(`CREATE TABLE "Mixed"("ID" SERIAL)`, 0), referenceExec(`CREATE TABLE mixed(id SERIAL)`, 0), referenceExec(`CREATE TABLE "123"(id SERIAL)`, 0), referenceExec(`CREATE TABLE "si--literal"(id SERIAL)`, 0), referenceExec(`CREATE SCHEMA "si.Dot"`, 0), referenceExec(`CREATE SCHEMA si_shadow`, 0), referenceExec(`CREATE TABLE "si.Dot"."Ta""ble"("C.Dot" INT)`, 0), referenceExec(`CREATE SEQUENCE "si.Dot"."select" OWNED BY "si.Dot"."Ta""ble"."C.Dot"`, 0), referenceExec(`CREATE TABLE si_shadow.mixed(id SERIAL)`, 0))
		defer func() { for _, q := range []string{`SET search_path TO public`, `DROP SCHEMA "si.Dot" CASCADE`, `DROP SCHEMA si_shadow CASCADE`} { if _, err := c.ExecContext(p.ctx, q); err != nil { t.Error(err) } } }()
		held := serialIdentityHeld(t, p, b, c)
		for _, tc := range []struct{ table, col, want string }{
			{`public."Mixed"`, "ID", `public."Mixed_ID_seq"`}, {"PUBLIC.Mixed", "id", "public.mixed_id_seq"}, {" \t public . \"Mixed\" \n", "ID", `public."Mixed_ID_seq"`}, {"123", "id", `public."123_id_seq"`}, {"si--literal", "id", `public."si--literal_id_seq"`}, {`"si.Dot"."Ta""ble"`, "C.Dot", `"si.Dot"."select"`},
		} { serialIdentityCheck(t, p, b, c, held, tc.table, tc.col, tc.want) }
		serialIdentityRun(t, p, b, c, referenceExec(`ALTER SEQUENCE "si.Dot"."select" RENAME TO "Se""q.Dot"`, 0))
		serialIdentityCheck(t, p, b, c, held, `"si.Dot"."Ta""ble"`, "C.Dot", `"si.Dot"."Se""q.Dot"`)
		// Consume the actual returned name through the existing REGCLASS
		// parameter route, without widening legacy sequence-call composition.
		var returned string
		if err := held.statement.QueryRowContext(p.ctx, `"si.Dot"."Ta""ble"`, "C.Dot").Scan(&returned); err != nil { t.Fatal(err) }
		if returned != `"si.Dot"."Se""q.Dot"` { t.Fatal("returned sequence name", returned) }
		const consumeQuery = `SELECT nextval($1::regclass),currval($1::regclass)`
		consume, err := c.PrepareContext(p.ctx, consumeQuery)
		if err != nil { t.Fatal(err) }
		defer consume.Close()
		consumer := referenceHeldStatement{referenceExecutor: c, statement: consume, query: consumeQuery}
		serialIdentityRun(t, p, b, consumer, referenceSelect(consumeQuery, []string{"nextval", "currval"}, []string{"INT8", "INT8"}, [][]any{{int64(1), int64(1)}}, returned))
		serialIdentityCheck(t, p, b, c, held, "mixed", "id", "public.mixed_id_seq")
		serialIdentityRun(t, p, b, c, referenceExec(`SET search_path TO si_shadow,public`, 0))
		serialIdentityCheck(t, p, b, c, held, "mixed", "id", "si_shadow.mixed_id_seq")
		var database string
		if err := c.QueryRowContext(p.ctx, `SELECT current_database()`).Scan(&database); err != nil { t.Fatal(err) }
		serialIdentityCheck(t, p, b, c, held, pq.QuoteIdentifier(database)+`.public.mixed`, "id", "public.mixed_id_seq")
		// The first argument truncates identifiers at a complete UTF8 boundary;
		// the column argument remains literal and is not truncated.
		for _, quoted := range []bool{false, true} {
			name := strings.Repeat("x", 60) + "é"
			if quoted { name = strings.Repeat("Y", 60) + "é" }
			seq := "si_long_unquoted"
			if quoted { seq = "si_long_quoted" }
			serialIdentityRun(t, p, b, c, referenceExec(`CREATE TABLE public.`+pq.QuoteIdentifier(name)+`(id INT)`, 0), referenceExec(`CREATE SEQUENCE public.`+seq+` OWNED BY public.`+pq.QuoteIdentifier(name)+`.id`, 0))
			input := name + "éextra"
			if quoted { input = pq.QuoteIdentifier(input) }
			serialIdentityCheck(t, p, b, c, held, "public."+input, "id", "public."+seq)
		}
	})
}

func TestReferenceSerialIdentityNulls(t *testing.T) {
	serialIdentityScenario(t, func(t *testing.T, p *referencePair, b referenceBackend, c *sql.Conn) {
		held := serialIdentityHeld(t, p, b, c)
		for _, q := range []string{`SELECT pg_get_serial_sequence(NULL,'missing')`, `SELECT pg_get_serial_sequence('missing',NULL)`, `SELECT pg_get_serial_sequence('malformed.',NULL)`, `SELECT pg_get_serial_sequence(NULL,NULL)`, `SELECT pg_catalog.pg_get_serial_sequence(NULL::text,NULL::text)`} {
			serialIdentityRun(t, p, b, c, serialIdentityText(q, nil, b.pg), referencePrepared(serialIdentityText(q, nil, b.pg)))
		}
		for _, args := range [][]any{{nil, "missing"}, {"missing", nil}, {"malformed.", nil}, {nil, nil}} { serialIdentityRun(t, p, b, held, serialIdentityText(serialIdentityQuery, nil, b.pg, args...)) }
		serialIdentityRun(t, p, b, c, referenceExec(`CREATE TABLE si_cast(id SERIAL)`, 0), referenceExec(`CREATE DOMAIN si_text_domain AS TEXT`, 0))
		for _, q := range []string{`SELECT pg_get_serial_sequence('si_cast'::varchar,'id'::varchar)`, `SELECT pg_get_serial_sequence('si_cast   '::char(10),'id '::char(3))`, `SELECT pg_get_serial_sequence('si_cast'::si_text_domain,'id'::si_text_domain)`} {
			serialIdentityRun(t, p, b, c, serialIdentityText(q, "public.si_cast_id_seq", b.pg), referencePrepared(serialIdentityText(q, "public.si_cast_id_seq", b.pg)))
		}
		// Both children are demanded: a NULL peer cannot suppress TEXT input
		// conversion. Use a parameter so conversion is execution-owned.
		stmt, err := c.PrepareContext(p.ctx, `SELECT pg_get_serial_sequence(NULL,$1::integer::text)`)
		if err != nil { t.Fatal(err) }
		defer stmt.Close()
		rows, err := stmt.QueryContext(p.ctx, "bad")
		if rows != nil { rows.Close(); t.Fatal("conversion failure exposed rows") }
		want := controlsReferenceDiagnostic("22P02", `invalid input syntax for type integer: "bad"`)
		want.Context = "unnamed portal parameter $1 = '...'"
		referenceAssertDiagnostic(t, err, &want)
	})
}
