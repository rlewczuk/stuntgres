func alterIdentityObserveAX(t *testing.T, ctx context.Context, c *sql.Conn, done <-chan error) {
	t.Helper()
	for {
		select {
		case err := <-done:
			t.Fatal("ALTER ended before wait observation", err)
		case <-ctx.Done():
			t.Fatal("AX not observed", ctx.Err())
		default:
		}
		tx, err := c.BeginTx(ctx, nil)
		if err != nil {
			t.Fatal(err)
		}
		_, err = tx.ExecContext(ctx, `LOCK TABLE i IN ACCESS SHARE MODE NOWAIT`)
		if e := tx.Rollback(); e != nil {
			t.Fatal(e)
		}
		if err != nil {
			want := controlsReferenceDiagnostic("55P03", `could not obtain lock on relation "i"`)
			referenceAssertDiagnostic(t, err, &want)
			return
		}
		runtime.Gosched()
	}
}

func TestReferenceAlterIdentityWaitCancellation(t *testing.T) {
	cases := []struct {
		name, query      string
		ordinary, linked bool
	}{
		{"table_add", `ALTER TABLE i ALTER id ADD GENERATED ALWAYS AS IDENTITY`, true, false},
		{"table_mode", `ALTER TABLE i ALTER id SET GENERATED BY DEFAULT`, false, false},
		{"table_options", `ALTER TABLE i ALTER id SET CACHE 2`, false, false},
		{"table_restart", `ALTER TABLE i ALTER id RESTART 100`, false, false},
		{"table_drop", `ALTER TABLE i ALTER id DROP IDENTITY`, false, false},
		{"sequence_options", `ALTER TABLE i ALTER id SET CACHE 2`, false, true},
		{"sequence_restart", `ALTER TABLE i ALTER id RESTART 100`, false, true},
		{"sequence_drop", `ALTER TABLE i ALTER id DROP IDENTITY`, false, true},
		{"sequence_staged_mode", `ALTER TABLE i ALTER id SET GENERATED BY DEFAULT, ALTER id RESTART 100`, false, true},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			alterIdentityScenario(t, func(t *testing.T, p *referencePair, b referenceBackend, c *sql.Conn) {
				ctx, stop := context.WithTimeout(p.ctx, 10*time.Second)
				defer stop()
				run := func(s referenceStep) { referenceRunStep(t, ctx, c, b.recorder, s) }
				create := `CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY(CACHE 1))`
				if tc.ordinary {
					create = `CREATE TABLE i(id INT NOT NULL)`
				}
				run(referenceExec(create, 0))
				if tc.ordinary {
					run(referenceExec(`INSERT INTO i VALUES(40)`, 1))
				} else {
					run(referenceExec(`INSERT INTO i DEFAULT VALUES`, 1))
				}
				holder := identityConnection(t, ctx, b.db)
				observer := identityConnection(t, ctx, b.db)
				workerPID, holderPID := 0, 0
				var oid int64
				if b.pg {
					workerPID = referenceLockPID(t, ctx, c)
					holderPID = referenceLockPID(t, ctx, holder)
					name := "i"
					if tc.linked {
						name = "i_id_seq"
					}
					oid = referenceLockOID(t, ctx, name)
				}
				tx, err := holder.BeginTx(ctx, nil)
				if err != nil {
					t.Fatal(err)
				}
				defer tx.Rollback()
				if tc.linked {
					referenceRunStep(t, ctx, tx, b.recorder, referenceExec(`ALTER SEQUENCE i_id_seq CACHE 1`, 0))
				} else {
					referenceRunStep(t, ctx, tx, b.recorder, referenceExec(`INSERT INTO i OVERRIDING SYSTEM VALUE VALUES(50)`, 1))
				}
				// Prepare before the wait so reuse is genuinely held, not prepare-per-execution.
				held := identityHeld(t, ctx, c, tc.query)
				waitCtx, cancel := context.WithCancel(ctx)
				done := make(chan error, 1)
				go func() {
					r, e := held.statement.ExecContext(waitCtx)
					if e == nil {
						n, x := r.RowsAffected()
						if x != nil {
							e = x
						} else if n != 0 {
							e = errors.New("nonzero ALTER count")
						}
					}
					done <- e
				}()
				joined := false
				defer func() {
					cancel()
					tx.Rollback()
					if !joined {
						select {
						case <-done:
						case <-ctx.Done():
							t.Error("worker did not join", ctx.Err())
						}
					}
				}()
				if b.pg {
					mode := "AccessExclusiveLock"
					if tc.linked && tc.name != "sequence_drop" {
						mode = "ShareRowExclusiveLock"
					}
					referenceLockWaitBehind(t, ctx, workerPID, holderPID, oid, mode)
				} else {
					alterIdentityObserveAX(t, ctx, observer, done)
				}
				if b.pg {
					var ok bool
					if err := referenceAdmin.QueryRowContext(ctx, `SELECT pg_cancel_backend($1)`, workerPID).Scan(&ok); err != nil || !ok {
						t.Fatal(ok, err)
					}
				} else {
					cancel()
				}
				select {
				case err := <-done:
					joined = true
					if b.pg {
						want := controlsReferenceDiagnostic("57014", "canceling statement due to user request")
						referenceAssertDiagnostic(t, err, &want)
					} else if !errors.Is(err, context.Canceled) {
						t.Fatal(err)
					}
				case <-ctx.Done():
					t.Fatal("cancel did not join", ctx.Err())
				}
				if err := tx.Rollback(); err != nil {
					t.Fatal(err)
				}
				want := int64(1)
				if tc.ordinary {
					want = 40
				}
				run(referenceSelect(`SELECT * FROM i`, []string{"id"}, []string{"INT4"}, [][]any{{want}}))
				if tc.ordinary {
					alterIdentityMissing(t, p, b, c, "i_id_seq")
				} else {
					run(referenceImplicitError(`INSERT INTO i VALUES(99)`, identityAlwaysDiagnostic()))
					run(referenceSelect(`SELECT last_value,is_called FROM i_id_seq`, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(1), true}}))
				}
				// An observer can now acquire AX: no canceled table ticket remains.
				probe, err := observer.BeginTx(ctx, nil)
				if err != nil {
					t.Fatal(err)
				}
				referenceRunStep(t, ctx, probe, b.recorder, referenceExec(`LOCK TABLE i IN ACCESS EXCLUSIVE MODE NOWAIT`, 0))
				if err := probe.Rollback(); err != nil {
					t.Fatal(err)
				}
				referenceRunStep(t, ctx, held, b.recorder, referenceExec(tc.query, 0))
			})
		})
	}
}
