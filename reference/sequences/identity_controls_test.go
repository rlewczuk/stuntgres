package reference_test

import (
	"bytes"
	"stuntgres"
	"stuntgres/reference/fixture"
	"testing"
)

func TestReferenceIdentityControls(t *testing.T) {
	p := fixture.NewScenario(t)
	for _, q := range []string{`CREATE TABLE narrow(id SMALLINT GENERATED ALWAYS AS IDENTITY)`, `ALTER SEQUENCE narrow_id_seq AS bigint MAXVALUE 100000 RESTART WITH 32768`, `CREATE TABLE uncalled(id INT GENERATED BY DEFAULT AS IDENTITY(START 7 CACHE 2))`, `COMMENT ON SEQUENCE narrow_id_seq IS 'divergent generator'`} {
		fixture.RunStep(t, p.Ctx, p.Memory, p.MemoryRecord, fixture.Exec(q, 0))
	}
	fixture.RunStep(t, p.Ctx, p.Memory, p.MemoryRecord, fixture.Exec(`INSERT INTO narrow DEFAULT VALUES`, 1))
	fixture.RunStep(t, p.Ctx, p.Memory, p.MemoryRecord, fixture.Exec(`INSERT INTO uncalled VALUES(99)`, 1))
	fixture.RunStep(t, p.Ctx, p.Memory, p.MemoryRecord, identitySequenceState("uncalled_id_seq", 7, false))
	var dump bytes.Buffer
	if err := stuntgres.Dump(p.Ctx, p.Native, &dump); err != nil {
		t.Fatal(err)
	}
	if p.Postgres != nil {
		if _, err := p.Postgres.ExecContext(p.Ctx, dump.String()); err != nil {
			t.Fatal("unchanged native replay", err)
		}
	}
	if err := stuntgres.Reset(p.Ctx, p.Native); err != nil {
		t.Fatal(err)
	}
	if err := stuntgres.Restore(p.Ctx, p.Native, bytes.NewReader(dump.Bytes())); err != nil {
		t.Fatal(err)
	}
	var again bytes.Buffer
	if err := stuntgres.Dump(p.Ctx, p.Native, &again); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(dump.Bytes(), again.Bytes()) {
		t.Fatalf("redump mismatch\n%s\n%s", dump.Bytes(), again.Bytes())
	}
	for _, b := range p.Backends() {
		run := func(s fixture.Step) { fixture.RunStep(t, p.Ctx, b.DB, b.Recorder, s) }
		run(fixture.Exec(`INSERT INTO narrow DEFAULT VALUES`, 1))
		run(fixture.Exec(`INSERT INTO uncalled DEFAULT VALUES`, 1))
		run(fixture.Select(`SELECT * FROM narrow ORDER BY id`, []string{"id"}, []string{"INT2"}, [][]any{{int64(-32768)}, {int64(-32767)}}))
		run(fixture.Select(`SELECT * FROM uncalled ORDER BY id`, []string{"id"}, []string{"INT4"}, [][]any{{int64(7)}, {int64(99)}}))
	}
	if err := stuntgres.Restore(p.Ctx, p.Native, bytes.NewBufferString(`CREATE TABLE replacement(id INT GENERATED ALWAYS AS IDENTITY); INSERT INTO replacement VALUES(9);`)); err == nil {
		t.Fatal("malformed restore accepted")
	}
	fixture.RunStep(t, p.Ctx, p.Memory, p.MemoryRecord, fixture.Select(`SELECT * FROM narrow ORDER BY id`, []string{"id"}, []string{"INT2"}, [][]any{{int64(-32768)}, {int64(-32767)}}))
}
