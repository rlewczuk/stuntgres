package reference_test

import (
	"stuntgres/reference/fixture"
	"testing"
)

func TestReferenceAlterAddColumnGeneratedDiagnostics(t *testing.T) {
	for _, kind := range []string{"STORED", "VIRTUAL", ""} {
		for _, tc := range []struct{ name, expr, typ, code, message, detail, hint string }{
			{"self", "b+1", "integer", "42P17", `cannot use generated column "b" in column generation expression`, "A generated column cannot reference another generated column.", ""},
			{"dead-self", "CASE WHEN false THEN b ELSE a END", "integer", "42P17", `cannot use generated column "b" in column generation expression`, "A generated column cannot reference another generated column.", ""},
			{"whole-row", "g", "integer", "42P17", "cannot use whole-row variable in column generation expression", "This would cause the generated column to depend on its own value.", ""},
			{"missing", "missing+1", "integer", "42703", `column "missing" does not exist`, "", ""},
			{"xmin", "xmin", "bigint", "42P10", `cannot use system column "xmin" in column generation expression`, "", ""},
			{"ctid", "ctid", "text", "42P10", `cannot use system column "ctid" in column generation expression`, "", ""},
			{"cmin", "cmin", "integer", "42P10", `cannot use system column "cmin" in column generation expression`, "", ""},
			{"xmax", "xmax", "bigint", "42P10", `cannot use system column "xmax" in column generation expression`, "", ""},
			{"cmax", "cmax", "integer", "42P10", `cannot use system column "cmax" in column generation expression`, "", ""},
			{"volatile", "random()", "double precision", "42P17", "generation expression is not immutable", "", ""},
			{"stable", "current_user", "text", "42P17", "generation expression is not immutable", "", ""},
			{"subquery", "(SELECT a)", "integer", "0A000", "cannot use subquery in column generation expression", "", ""},
			{"aggregate", "sum(a)", "bigint", "42803", "aggregate functions are not allowed in column generation expressions", "", ""},
			{"window", "row_number() OVER ()", "bigint", "42P20", "window functions are not allowed in column generation expressions", "", ""},
			{"set-returning", "generate_series(1,a)", "integer", "0A000", "set-returning functions are not allowed in column generation expressions", "", ""},
			{"parameter", "$1", "integer", "42P02", "there is no parameter $1", "", ""},
			{"assignment", "true", "integer", "42804", `column "b" is of type integer but default expression is of type boolean`, "", "You will need to rewrite or cast the expression."},
		} {
			t.Run(kind+"/"+tc.name, func(t *testing.T) {
				addGeneratedRoutes(t, func(g *addGeneratedCase) {
					g.exec("CREATE TABLE g(a integer)", 0)
					g.exec("INSERT INTO g VALUES(2)", 1)
					d := addGeneratedDiagnostic(tc.code, tc.message)
					d.Detail, d.Hint = tc.detail, tc.hint
					g.fail("/* éλ */ ALTER TABLE g ADD COLUMN b "+tc.typ+" GENERATED ALWAYS AS("+tc.expr+") "+kind, d, false, "execute")
					g.unchanged([][]any{{int64(2)}})
				})
			})
		}
	}
	for _, kind := range []string{"STORED", "VIRTUAL"} {
		for _, tc := range []struct{ clauses, message, token string }{
			{"DEFAULT 1 GENERATED ALWAYS AS(a+1) " + kind, `both default and generation expression specified for column "b" of table "g"`, "GENERATED"},
			{"GENERATED ALWAYS AS(a+1) " + kind + " DEFAULT 1", `both default and generation expression specified for column "b" of table "g"`, "DEFAULT"},
			{"GENERATED ALWAYS AS IDENTITY GENERATED ALWAYS AS(a+1) " + kind, `both identity and generation expression specified for column "b" of table "g"`, "GENERATED ALWAYS AS(a+1)"},
			{"GENERATED ALWAYS AS(a+1) " + kind + " GENERATED ALWAYS AS IDENTITY", `both identity and generation expression specified for column "b" of table "g"`, "GENERATED ALWAYS AS IDENTITY"},
			{"GENERATED ALWAYS AS(a+1) " + kind + " GENERATED ALWAYS AS(a+2) " + kind, `multiple generation clauses specified for column "b" of table "g"`, "GENERATED ALWAYS AS(a+2)"},
			{"GENERATED BY DEFAULT AS(a+1) " + kind, "for a generated column, GENERATED ALWAYS must be specified", "BY DEFAULT"},
		} {
			t.Run(tc.clauses, func(t *testing.T) {
				addGeneratedRoutes(t, func(g *addGeneratedCase) {
					g.exec("CREATE TABLE g(a integer)", 0)
					g.exec("INSERT INTO g VALUES(2)", 1)
					q := "/* éλ */ ALTER TABLE g ADD b integer " + tc.clauses
					d := addGeneratedDiagnostic("42601", tc.message)
					d.Position = addGeneratedPosition(q, tc.token)
					stage := "execute"
					if g.prepared && tc.token == "BY DEFAULT" {
						stage = "prepare"
					}
					g.fail(q, d, false, stage)
					g.unchanged([][]any{{int64(2)}})
				})
			})
		}
		for _, existing := range []string{"STORED", "VIRTUAL"} {
			t.Run(kind+"/other-"+existing, func(t *testing.T) {
				addGeneratedRoutes(t, func(g *addGeneratedCase) {
					g.exec("CREATE TABLE g(a integer,c integer GENERATED ALWAYS AS(a+1) "+existing+")", 0)
					g.exec("INSERT INTO g(a) VALUES(2)", 1)
					d := addGeneratedDiagnostic("42P17", `cannot use generated column "c" in column generation expression`)
					d.Detail = "A generated column cannot reference another generated column."
					g.fail("ALTER TABLE g ADD b integer GENERATED ALWAYS AS(c+1) "+kind, d, false, "execute")
					g.run(fixture.Select("SELECT * FROM g", []string{"a", "c"}, []string{"INT4", "INT4"}, [][]any{{int64(2), int64(3)}}))
					g.kinds("g", []any{"c", map[string]string{"STORED": "s", "VIRTUAL": "v"}[existing]})
				})
			})
		}
		for _, tc := range []struct {
			q      string
			args   []any
			update bool
		}{
			{"INSERT INTO g VALUES(3,4)", nil, false}, {"INSERT INTO g VALUES(3,NULL)", nil, false}, {"INSERT INTO g VALUES(3,$1)", []any{4}, false},
			{"INSERT INTO g SELECT 3,4 WHERE false", nil, false}, {"UPDATE g SET b=4 WHERE false", nil, true}, {"UPDATE g SET b=NULL", nil, true}, {"UPDATE g SET b=$1", []any{4}, true},
		} {
			t.Run(kind+"/"+tc.q, func(t *testing.T) {
				addGeneratedRoutes(t, func(g *addGeneratedCase) {
					g.exec("CREATE TABLE g(a integer)", 0)
					g.exec("INSERT INTO g VALUES(2)", 1)
					g.exec("ALTER TABLE g ADD b integer GENERATED ALWAYS AS(a+1) "+kind, 0)
					message := `cannot insert a non-DEFAULT value into column "b"`
					if tc.update {
						message = `column "b" can only be updated to DEFAULT`
					}
					d := addGeneratedDiagnostic("428C9", message)
					d.Detail = `Column "b" is a generated column.`
					stage := "execute"
					if g.prepared {
						stage = "prepare"
					}
					g.fail(tc.q, d, false, stage, tc.args...)
					g.run(fixture.Select("SELECT * FROM g", []string{"a", "b"}, []string{"INT4", "INT4"}, [][]any{{int64(2), int64(3)}}))
				})
			})
		}
	}
	t.Run("syntax-full-input", func(t *testing.T) {
		addGeneratedRoutes(t, func(g *addGeneratedCase) {
			g.exec("CREATE TABLE g(a integer)", 0)
			g.exec("INSERT INTO g VALUES(2)", 1)
			q := "/* éλ */ ALTER TABLE g ADD b integer GENERATED ALWAYS AS(a+1) STORED trailing"
			d := addGeneratedDiagnostic("42601", `syntax error at or near "trailing"`)
			d.Position = addGeneratedPosition(q, "trailing")
			stage := "execute"
			if g.prepared {
				stage = "prepare"
			}
			g.fail(q, d, false, stage)
			g.unchanged([][]any{{int64(2)}})
		})
	})
	t.Run("tableoid-exception", func(t *testing.T) {
		addGeneratedRoutes(t, func(g *addGeneratedCase) {
			g.exec("CREATE TABLE g(a integer)", 0)
			g.exec("INSERT INTO g VALUES(2)", 1)
			g.exec("ALTER TABLE g ADD b oid GENERATED ALWAYS AS(tableoid) STORED", 0)
			g.exec("ALTER TABLE g ADD v oid GENERATED ALWAYS AS(tableoid) VIRTUAL", 0)
			g.run(fixture.Select("SELECT a,b='g'::regclass AS owner,v='g'::regclass AS virtual_owner FROM g", []string{"a", "owner", "virtual_owner"}, []string{"INT4", "BOOL", "BOOL"}, [][]any{{int64(2), true, true}}))
		})
	})
}
