func TestReferenceIdentityLifecycle(t *testing.T) {
	p := fixture.NewScenario(t)
	for _, backend := range p.Backends() {
		t.Run(backend.Name, func(t *testing.T) {
			run := func(s fixture.Step) { fixture.RunStep(t, p.Ctx, backend.DB, backend.Recorder, s) }
			for _, multi := range []bool{false, true} {
				name, column := "i", "id"
				q := `CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY)`
				if multi {
					name, column, q = "life", "a", `CREATE TABLE life(a INT GENERATED ALWAYS AS IDENTITY,b INT,c INT GENERATED BY DEFAULT AS IDENTITY)`
				}
				run(fixture.Exec(q, 0))
				seq := name + "_" + column + "_seq"
				run(fixture.ImplicitError(`DROP SEQUENCE `+seq+` CASCADE`, fixture.Diagnostic{Code: "2BP01", Message: "cannot drop sequence " + seq + " because column " + column + " of table " + name + " requires it", Hint: "You can drop column " + column + " of table " + name + " instead."}))
				run(fixture.ImplicitError(`ALTER SEQUENCE `+seq+` OWNED BY NONE`, fixture.Diagnostic{Code: "0A000", Message: "cannot change ownership of identity sequence", Detail: `Sequence "` + seq + `" is linked to table "` + name + `".`}))
				if multi {
					run(fixture.Exec(`ALTER TABLE life DROP COLUMN b`, 0))
					column = "c"
				}
				run(fixture.Exec(`ALTER TABLE `+name+` RENAME COLUMN `+column+` TO other`, 0))
				run(fixture.Exec(`INSERT INTO `+name+` DEFAULT VALUES`, 1))
				cols, types, want := []string{"other"}, []string{"INT4"}, [][]any{{int64(1)}}
				if multi {
					cols, types, want = []string{"a", "other"}, []string{"INT4", "INT4"}, [][]any{{int64(1), int64(1)}}
				}
				run(fixture.Select(`SELECT * FROM `+name, cols, types, want))
				if multi {
					run(fixture.Exec(`ALTER TABLE life DROP COLUMN a`, 0))
				}
				run(fixture.Exec(`DROP TABLE `+name, 0))
				missing := name + "_" + column + "_seq"
				run(fixture.ImplicitError(`SELECT nextval('`+missing+`')`, fixture.Diagnostic{Code: "42P01", Message: `relation "` + missing + `" does not exist`, Position: "16"}))
			}
		})
	}
}
