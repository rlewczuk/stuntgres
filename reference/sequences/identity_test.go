func TestReferenceIdentityOptions(t *testing.T) {
	p := fixture.NewScenario(t)
	for _, backend := range p.Backends() {
		t.Run(backend.Name, func(t *testing.T) {
			c := fixture.IdentityConnection(t, p.Ctx, backend.DB)
			run := func(s fixture.Step) { fixture.RunStep(t, p.Ctx, c, backend.Recorder, s) }
			run(fixture.Exec(`CREATE TABLE opt(id INT GENERATED BY DEFAULT AS IDENTITY(START 7 INCREMENT 3 CACHE 1))`, 0))
			for range 2 {
				run(fixture.Exec(`INSERT INTO opt DEFAULT VALUES`, 1))
			}
			run(fixture.Exec(`ALTER TABLE opt ALTER id SET START 20`, 0))
			run(fixture.Exec(`INSERT INTO opt DEFAULT VALUES`, 1))
			run(fixture.Exec(`ALTER TABLE opt ALTER id RESTART`, 0))
			run(fixture.Exec(`INSERT INTO opt DEFAULT VALUES`, 1))
			run(fixture.Select(`SELECT * FROM opt ORDER BY id`, []string{"id"}, []string{"INT4"}, [][]any{{int64(7)}, {int64(10)}, {int64(13)}, {int64(20)}}))
			for _, prior := range []bool{false, true} {
				opts := ""
				if prior {
					opts = "(START 7 INCREMENT 3)"
				}
				run(fixture.Exec(`CREATE TABLE narrow(id SMALLINT GENERATED ALWAYS AS IDENTITY`+opts+`)`, 0))
				if prior {
					for range 2 {
						run(fixture.Exec(`INSERT INTO narrow DEFAULT VALUES`, 1))
					}
					run(fixture.Select(`SELECT * FROM narrow ORDER BY id`, []string{"id"}, []string{"INT2"}, [][]any{{int64(7)}, {int64(10)}}))
				}
				run(fixture.Exec(`ALTER SEQUENCE narrow_id_seq AS bigint MAXVALUE 100000 RESTART WITH 32768`, 0))
				run(fixture.Exec(`INSERT INTO narrow DEFAULT VALUES`, 1))
				want := [][]any{{int64(-32768)}}
				if prior {
					want = append(want, []any{int64(7)}, []any{int64(10)})
				}
				run(fixture.Select(`SELECT * FROM narrow ORDER BY id`, []string{"id"}, []string{"INT2"}, want))
				run(fixture.Select(`SELECT currval('narrow_id_seq')`, []string{"currval"}, []string{"INT8"}, [][]any{{int64(32768)}}))
				run(fixture.Exec(`DROP TABLE narrow`, 0))
			}
		})
	}
}
func TestReferenceIdentityAlter(t *testing.T) {
	for _, heldRoute := range []bool{false, true} {
		p := fixture.NewScenario(t)
		for _, backend := range p.Backends() {
			t.Run(backend.Name, func(t *testing.T) {
				c := fixture.IdentityConnection(t, p.Ctx, backend.DB)
				var executor fixture.Executor = c
				run := func(s fixture.Step) { fixture.RunStep(t, p.Ctx, executor, backend.Recorder, s) }
				run(fixture.Exec(`CREATE TABLE a(id INT NOT NULL)`, 0))
				run(fixture.Exec(`INSERT INTO a VALUES(40)`, 1))
				run(fixture.Exec(`ALTER TABLE a ALTER id ADD GENERATED BY DEFAULT AS IDENTITY`, 0))
				if heldRoute {
					executor = fixture.IdentityHeld(t, p.Ctx, c, `INSERT INTO a DEFAULT VALUES`)
				}
				run(fixture.Exec(`INSERT INTO a DEFAULT VALUES`, 1))
				run(fixture.Exec(`ALTER TABLE a ALTER id SET GENERATED ALWAYS SET INCREMENT 3 RESTART WITH 20`, 0))
				run(fixture.Exec(`INSERT INTO a DEFAULT VALUES`, 1))
				run(fixture.Select(`SELECT * FROM a ORDER BY id`, []string{"id"}, []string{"INT4"}, [][]any{{int64(1)}, {int64(20)}, {int64(40)}}))
				run(fixture.Exec(`ALTER TABLE a ALTER id DROP IDENTITY`, 0))
				run(fixture.ImplicitError(`INSERT INTO a DEFAULT VALUES`, fixture.Diagnostic{Code: "23502", Message: `null value in column "id" of relation "a" violates not-null constraint`, Detail: "Failing row contains (null).", Schema: "public", Table: "a", Column: "id"}))
				run(fixture.Exec(`INSERT INTO a VALUES(55)`, 1))
			})
		}
	}
}
