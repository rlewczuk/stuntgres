func TestReferenceIdentityDiagnostics(t *testing.T) {
	p := fixture.NewScenario(t)
	p.Step(t, fixture.Exec(`CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY)`, 0))
	for _, q := range []string{`INSERT INTO i VALUES(NULL)`, `INSERT INTO i SELECT 99 FROM i WHERE false`} {
		p.Step(t, fixture.ImplicitError(q, fixture.IdentityAlwaysDiagnostic()))
	}
	s := fixture.Prepared(fixture.ImplicitError(`INSERT INTO i VALUES($1)`, fixture.IdentityAlwaysDiagnostic()))
	s.ErrorStage = "prepare"
	p.Step(t, s)
	for _, q := range []string{`ALTER TABLE i ALTER id DROP NOT NULL`, `ALTER TABLE i ALTER id SET DEFAULT 4`, `ALTER TABLE i ALTER id DROP DEFAULT`} {
		want := fixture.Diagnostic{Code: "42601", Message: `column "id" of relation "i" is an identity column`}
		if q == `ALTER TABLE i ALTER id DROP DEFAULT` {
			want.Hint = "Use ALTER TABLE ... ALTER COLUMN ... DROP IDENTITY instead."
		}
		p.Step(t, fixture.ImplicitError(q, want))
	}
}
