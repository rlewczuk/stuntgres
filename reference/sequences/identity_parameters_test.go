func TestReferenceIdentityDiscardedRuntimeConversionDemand(t *testing.T) {
	p := fixture.NewScenario(t)
	for _, b := range p.Backends() {
		t.Run(b.Name, func(t *testing.T) {
			for _, tc := range []struct {
				name, source        string
				fails, side, column bool
				payloads            []int64
			}{
				{"single_values_pruned", `VALUES(CAST($1::text AS integer),7)`, false, false, false, []int64{7}},
				{"multi_values_demanded", `VALUES(CAST($1::text AS integer),7),(0,8)`, true, false, false, []int64{7, 8}},
				{"select_pruned", `SELECT CAST($1::text AS integer),7`, false, false, false, []int64{7}},
				{"select_column_pruned", `SELECT CAST(v AS integer),p FROM inputs`, false, false, true, []int64{7, 8}},
				{"decorated_values_pruned", `VALUES(CAST($1::text AS integer),7) LIMIT 1`, false, false, false, []int64{7}},
				{"ordered_select_demanded", `SELECT CAST($1::text AS integer),p FROM inputs ORDER BY 1,2`, true, false, false, []int64{7, 8}},
				{"ordered_values_demanded", `VALUES(CAST($1::text AS integer),7),(0,8) ORDER BY 1`, true, false, false, []int64{8, 7}},
				{"other_order_values_demanded", `VALUES(CAST($1::text AS integer),7),(0,8) ORDER BY 2`, true, false, false, []int64{7, 8}},
				{"expression_order_values_demanded", `VALUES(CAST($1::text AS integer),7),(0,8) ORDER BY column2+1`, true, false, false, []int64{7, 8}},
				{"limited_multi_values_demanded", `VALUES(CAST($1::text AS integer),7),(0,8) LIMIT 1`, true, false, false, []int64{7}},
				{"volatile_select_demanded", `SELECT CAST(CASE WHEN nextval('side')>0 THEN $1::text ELSE '' END AS integer),7`, true, true, false, []int64{7}},
			} {
				for _, prepared := range []bool{false, true} {
					t.Run(fmt.Sprintf("%s/prepared=%t", tc.name, prepared), func(t *testing.T) {
						c := fixture.IdentityConnection(t, p.Ctx, b.DB)
						var executor fixture.Executor = c
						run := func(s fixture.Step) { fixture.RunStep(t, p.Ctx, executor, b.Recorder, s) }
						for _, q := range []string{`CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY(CACHE 1),p INT)`, `CREATE SEQUENCE side START 50 CACHE 1`, `CREATE TABLE inputs(v TEXT,p INT)`} {
							run(fixture.Exec(q, 0))
						}
						defer func() {
							for _, q := range []string{`DROP TABLE i`, `DROP TABLE inputs`, `DROP SEQUENCE side`} {
								fixture.RunStep(t, p.Ctx, c, b.Recorder, fixture.Exec(q, 0))
							}
						}()
						run(fixture.Exec(`INSERT INTO inputs VALUES('bad',7),('8',8)`, 2))
						q := `INSERT INTO i OVERRIDING USER VALUE ` + tc.source
						if prepared {
							executor = fixture.IdentityHeld(t, p.Ctx, c, q)
						}
						run(identitySequenceState("i_id_seq", 1, false))
						execute := func(value string) (sql.Result, error) {
							args := []any{value}
							if tc.column {
								args = nil
							}
							return executor.ExecContext(p.Ctx, q, args...)
						}
						rowsFor := func(start int64) [][]any {
							rows := make([][]any, len(tc.payloads))
							for i, payload := range tc.payloads {
								rows[i] = []any{start + int64(i), payload}
							}
							return rows
						}
						assertRows := func(want [][]any) {
							if b.PG && tc.column {
								identityUncoupledRows(t, p.Ctx, c, b.Recorder, `SELECT * FROM i ORDER BY id`, want, len(tc.payloads))
								return
							}
							run(fixture.Select(`SELECT * FROM i ORDER BY id`, []string{"id", "p"}, []string{"INT4", "INT4"}, want))
						}
						result, err := execute("bad")
						if tc.fails {
							if result != nil {
								t.Fatal("failed INSERT returned result")
							}
							want := fixture.ControlsReferenceDiagnostic("22P02", `invalid input syntax for type integer: "bad"`)
							fixture.AssertDiagnostic(t, err, &want)
							run(fixture.Select(`SELECT * FROM i`, []string{"id", "p"}, []string{"INT4", "INT4"}, nil))
							run(identitySequenceState("i_id_seq", 1, false))
							run(fixture.ImplicitError(`SELECT currval('i_id_seq')`, fixture.Diagnostic{Code: "55000", Message: `currval of sequence "i_id_seq" is not yet defined in this session`}))
							if !tc.side {
								run(fixture.ImplicitError(`SELECT lastval()`, fixture.Diagnostic{Code: "55000", Message: "lastval is not yet defined in this session"}))
							}
						} else {
							identityResult(t, result, err, int64(len(tc.payloads)))
							assertRows(rowsFor(1))
						}
						run(identitySequenceState("side", 50, tc.side))
						if tc.side {
							run(identityScalar(`SELECT currval('side')`, "currval", 50))
							run(identityScalar(`SELECT lastval()`, "lastval", 50))
						}
						run(fixture.Exec(`UPDATE inputs SET v='8'`, 2))
						result, err = execute("8")
						identityResult(t, result, err, int64(len(tc.payloads)))
						var want [][]any
						if !tc.fails {
							want = rowsFor(1)
						}
						want = append(want, rowsFor(int64(len(want)+1))...)
						assertRows(want)
						run(identityScalar(`SELECT currval('i_id_seq')`, "currval", int64(len(want))))
						run(identityScalar(`SELECT lastval()`, "lastval", int64(len(want))))
						last := int64(50)
						if tc.side {
							last = 51
						}
						run(identitySequenceState("side", last, tc.side))
					})
				}
			}
		})
	}
}

func identitySequenceState(sequence string, last int64, called bool) fixture.Step {
	return fixture.Select(`SELECT last_value,is_called FROM `+sequence, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{last, called}})
}
func identityScalar(q, label string, value int64) fixture.Step {
	return fixture.Select(q, []string{label}, []string{"INT8"}, [][]any{{value}})
}
func identityResult(t *testing.T, result sql.Result, err error, count int64) {
	t.Helper()
	if err != nil {
		t.Fatal(err)
	}
	if result == nil {
		t.Fatal("successful execution has no result")
	}
	if n, err := result.RowsAffected(); err != nil || n != count {
		t.Fatal(n, err, count)
	}
}
