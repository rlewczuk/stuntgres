func TestReferenceIdentityDiscardedParameterIndex(t *testing.T) {
	p := fixture.NewScenario(t)
	for _, b := range p.Backends() {
		t.Run(b.Name, func(t *testing.T) {
			c := fixture.IdentityConnection(t, p.Ctx, b.DB)
			var executor fixture.Executor = c
			run := func(s fixture.Step) { fixture.RunStep(t, p.Ctx, executor, b.Recorder, s) }
			run(fixture.Exec(`CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY,p INT)`, 0))
			q := `INSERT INTO i(p,id) OVERRIDING USER VALUE VALUES($1,$2)`
			executor = fixture.IdentityHeld(t, p.Ctx, c, q)
			want := fixture.ControlsReferenceDiagnostic("22P02", `invalid input syntax for type integer: "bad"`)
			want.Context = "unnamed portal parameter $2 = '...'"
			run(fixture.ErrorDiagnostic(q, want, 7, "bad"))
			run(identitySequenceState(`i_id_seq`, 1, false))
			run(fixture.Exec(q, 1, 7, 99))
			run(fixture.Select(`SELECT * FROM i`, []string{"id", "p"}, []string{"INT4", "INT4"}, [][]any{{int64(1), int64(7)}}))
			run(fixture.ErrorDiagnostic(`INSERT INTO i(p,id) OVERRIDING SYSTEM VALUE VALUES($1,$2)`, want, 8, "bad"))
			run(fixture.Exec(`INSERT INTO i OVERRIDING USER VALUE VALUES(CAST($1::text AS integer),8)`, 1, "bad"))
			run(fixture.Select(`SELECT * FROM i ORDER BY id`, []string{"id", "p"}, []string{"INT4", "INT4"}, [][]any{{int64(1), int64(7)}, {int64(2), int64(8)}}))
			want.Context = ""
			run(fixture.ErrorDiagnostic(`INSERT INTO i(p) VALUES(CAST($1::text AS integer))`, want, "bad"))
			run(fixture.Exec(`CREATE TABLE ordinary(a INT,b INT)`, 0))
			want.Context = "unnamed portal parameter $2 = '...'"
			run(fixture.ErrorDiagnostic(`INSERT INTO ordinary VALUES($1,$2)`, want, 8, "bad"))
		})
	}
}
