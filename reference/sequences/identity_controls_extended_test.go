func TestReferenceIdentityControlsCurrentDefinitions(t *testing.T) {
	var p *fixture.Pair
	// Run after fixture pool closure/reset, with startup failure guarded.
	t.Cleanup(func() {
		if p == nil || p.Postgres == nil {
			return
		}
		ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
		defer cancel()
		for _, q := range []string{`DROP SCHEMA IF EXISTS owned CASCADE`, `DROP ROLE IF EXISTS identity_owner`} {
			if _, err := fixture.Admin.ExecContext(ctx, q); err != nil {
				t.Error(err)
			}
		}
	})
	p = fixture.NewScenario(t)
	p.Step(t, fixture.Exec(`CREATE ROLE identity_owner`, 0))
	for _, q := range []string{`CREATE SCHEMA owned AUTHORIZATION identity_owner CREATE TABLE i(id INT CONSTRAINT id_nn GENERATED ALWAYS AS IDENTITY(START 7 INCREMENT 3 CACHE 2),p INT DEFAULT 4) CREATE TABLE u(id INT GENERATED BY DEFAULT AS IDENTITY(UNLOGGED START 9))`, `COMMENT ON TABLE owned.i IS 'identity table'`, `COMMENT ON COLUMN owned.i.id IS 'identity attribute'`, `COMMENT ON SEQUENCE owned.i_id_seq IS 'identity sequence'`, `INSERT INTO owned.i DEFAULT VALUES`, `INSERT INTO owned.i OVERRIDING SYSTEM VALUE VALUES(99,8)`, `INSERT INTO owned.u VALUES(88)`} {
		count := int64(0)
		if strings.HasPrefix(q, "INSERT") {
			count = 1
		}
		fixture.RunStep(t, p.Ctx, p.Memory, p.MemoryRecord, fixture.Exec(q, count))
	}
	ctx := context.WithValue(p.Ctx, fixture.RecorderKey{}, p.MemoryRecord)
	old, err := p.Memory.QueryContext(ctx, `SELECT * FROM owned.i ORDER BY id`)
	if err != nil {
		t.Fatal(err)
	}
	defer old.Close()
	held := fixture.IdentityHeld(t, p.Ctx, p.Memory, `INSERT INTO owned.i DEFAULT VALUES`)
	var dump bytes.Buffer
	if err := stuntgres.Dump(p.Ctx, p.Native, &dump); err != nil {
		t.Fatal(err)
	}
	if p.Postgres != nil {
		if _, err := p.Postgres.ExecContext(p.Ctx, dump.String()); err != nil {
			t.Fatal("unchanged owner-bearing replay", err)
		}
	}
	if err := stuntgres.Reset(p.Ctx, p.Native); err != nil {
		t.Fatal(err)
	}
	if err := stuntgres.Restore(p.Ctx, p.Native, bytes.NewReader(dump.Bytes())); err != nil {
		t.Fatal(err)
	}
	var redump bytes.Buffer
	if err := stuntgres.Dump(p.Ctx, p.Native, &redump); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(dump.Bytes(), redump.Bytes()) {
		t.Fatalf("definitions/state changed\n%s\n%s", dump.Bytes(), redump.Bytes())
	}
	for _, want := range [][]any{{int64(7), int64(4)}, {int64(99), int64(8)}} {
		if !old.Next() {
			t.Fatal(old.Err())
		}
		var id, payload any
		if err := old.Scan(&id, &payload); err != nil || id != want[0] || payload != want[1] {
			t.Fatal(id, payload, err, want)
		}
	}
	if old.Next() || old.Err() != nil {
		t.Fatal("retained rows changed", old.Err())
	}
	if err := old.Close(); err != nil {
		t.Fatal(err)
	}
	// This is the original snapshot's owned recording, before later same-SQL queries.
	p.MemoryRecord.Mu.Lock()
	var snapshot *fixture.Operation
	for _, op := range p.MemoryRecord.Operations {
		if op.SQL == `SELECT * FROM owned.i ORDER BY id` && op.Columns != nil {
			snapshot = op
		}
	}
	ok := snapshot != nil && snapshot.Closed && snapshot.CloseErr == nil
	var captured [][]any
	if snapshot != nil {
		captured = make([][]any, len(snapshot.Rows))
		for i, row := range snapshot.Rows {
			captured[i] = make([]any, len(row))
			for j, value := range row {
				captured[i][j] = value
			}
		}
	}
	p.MemoryRecord.Mu.Unlock()
	for _, row := range captured {
		for _, value := range row {
			fixture.AssertRawValue(t, false, "INT4", value)
		}
	}
	ok = ok && fixture.RecordedRowsMatch(captured, fixture.Select("", nil, nil, [][]any{{int64(7), int64(4)}, {int64(99), int64(8)}}))
	if !ok {
		t.Fatal("retained snapshot recording/closure")
	}
	for _, b := range p.Backends() {
		var executor fixture.Executor = b.DB
		if !b.PG {
			executor = held
		}
		run := func(s fixture.Step) { fixture.RunStep(t, p.Ctx, executor, b.Recorder, s) }
		run(fixture.Select(`SELECT * FROM owned.i ORDER BY id`, []string{"id", "p"}, []string{"INT4", "INT4"}, [][]any{{int64(7), int64(4)}, {int64(99), int64(8)}}))
		run(fixture.Exec(`INSERT INTO owned.i DEFAULT VALUES`, 1))
		run(fixture.Exec(`INSERT INTO owned.u DEFAULT VALUES`, 1))
		run(fixture.Select(`SELECT * FROM owned.i ORDER BY id`, []string{"id", "p"}, []string{"INT4", "INT4"}, [][]any{{int64(7), int64(4)}, {int64(13), int64(4)}, {int64(99), int64(8)}}))
		run(fixture.Select(`SELECT * FROM owned.u ORDER BY id`, []string{"id"}, []string{"INT4"}, [][]any{{int64(9)}, {int64(88)}}))
	}
	if p.Postgres != nil {
		var tableOwner, sequenceOwner, persistence, comment string
		if err := p.Postgres.QueryRowContext(p.Ctx, `SELECT pg_get_userbyid(relowner) FROM pg_class WHERE oid='owned.i'::regclass`).Scan(&tableOwner); err != nil {
			t.Fatal(err)
		}
		if err := p.Postgres.QueryRowContext(p.Ctx, `SELECT pg_get_userbyid(relowner),obj_description(oid) FROM pg_class WHERE oid='owned.i_id_seq'::regclass`).Scan(&sequenceOwner, &comment); err != nil {
			t.Fatal(err)
		}
		if tableOwner != "identity_owner" || sequenceOwner != tableOwner || comment != "identity sequence" {
			t.Fatal(tableOwner, sequenceOwner, comment)
		}
		if err := p.Postgres.QueryRowContext(p.Ctx, `SELECT relpersistence FROM pg_class WHERE oid='owned.u_id_seq'::regclass`).Scan(&persistence); err != nil || persistence != "u" {
			t.Fatal(persistence, err)
		}
	}
}
func TestReferenceIdentityControlsImportFailures(t *testing.T) {
	p := fixture.NewScenario(t)
	for _, q := range []string{`CREATE SCHEMA owned`, `CREATE TABLE owned.i(id INT CONSTRAINT id_nn GENERATED ALWAYS AS IDENTITY(START 7 INCREMENT 3 CACHE 2),p INT DEFAULT 4)`, `CREATE TABLE owned.u(id INT GENERATED BY DEFAULT AS IDENTITY(UNLOGGED START 9))`, `COMMENT ON TABLE owned.i IS 'identity table'`, `COMMENT ON COLUMN owned.i.id IS 'identity attribute'`, `COMMENT ON SEQUENCE owned.i_id_seq IS 'identity sequence'`, `INSERT INTO owned.i DEFAULT VALUES`, `INSERT INTO owned.i OVERRIDING SYSTEM VALUE VALUES(99,8)`, `INSERT INTO owned.u VALUES(88)`} {
		count := int64(0)
		if strings.HasPrefix(q, "INSERT") {
			count = 1
		}
		fixture.RunStep(t, p.Ctx, p.Memory, p.MemoryRecord, fixture.Exec(q, count))
	}
	held := fixture.IdentityHeld(t, p.Ctx, p.Memory, `INSERT INTO owned.i DEFAULT VALUES`)
	var dump bytes.Buffer
	if err := stuntgres.Dump(p.Ctx, p.Native, &dump); err != nil {
		t.Fatal(err)
	}
	if err := stuntgres.Reset(p.Ctx, p.Native); err != nil {
		t.Fatal(err)
	}
	if err := stuntgres.Restore(p.Ctx, p.Native, bytes.NewReader(dump.Bytes())); err != nil {
		t.Fatal(err)
	}
	fixture.RunStep(t, p.Ctx, held, p.MemoryRecord, fixture.Exec(`INSERT INTO owned.i DEFAULT VALUES`, 1))
	fixture.RunStep(t, p.Ctx, p.Memory, p.MemoryRecord, fixture.Exec(`INSERT INTO owned.u DEFAULT VALUES`, 1))
	for _, script := range []string{
		`CREATE TABLE replacement(id INT GENERATED BY DEFAULT AS IDENTITY); INSERT INTO replacement VALUES(9);`,
		`CREATE TABLE replacement(id INT GENERATED ALWAYS AS IDENTITY); INSERT INTO replacement OVERRIDING USER VALUE VALUES(9);`,
		`CREATE TABLE replacement(id INT GENERATED ALWAYS AS IDENTITY); ALTER SEQUENCE replacement_id_seq CACHE 0;`,
		`CREATE TABLE replacement(id INT GENERATED ALWAYS AS IDENTITY); SELECT setval('replacement_id_seq',0,true);`,
		`CREATE TABLE replacement(id INT GENERATED ALWAYS AS IDENTITY); INSERT INTO replacement OVERRIDING SYSTEM VALUE VALUES(CAST($1 AS integer));`,
	} {
		if err := stuntgres.Restore(p.Ctx, p.Native, strings.NewReader(script)); err == nil {
			t.Fatal("invalid reconstruction accepted", script)
		}
	}
	failure := errors.New("identity reader failure")
	if err := stuntgres.Restore(p.Ctx, p.Native, fixture.IdentityFailingReader{failure}); !errors.Is(err, failure) {
		t.Fatal(err)
	}
	canceled, cancel := context.WithCancel(p.Ctx)
	cancel()
	if err := stuntgres.Restore(canceled, p.Native, bytes.NewReader(dump.Bytes())); !errors.Is(err, context.Canceled) {
		t.Fatal(err)
	}
	fixture.RunStep(t, p.Ctx, p.Memory, p.MemoryRecord, fixture.Select(`SELECT * FROM owned.i ORDER BY id`, []string{"id", "p"}, []string{"INT4", "INT4"}, [][]any{{int64(7), int64(4)}, {int64(13), int64(4)}, {int64(99), int64(8)}}))
	fixture.RunStep(t, p.Ctx, p.Memory, p.MemoryRecord, fixture.Select(`SELECT * FROM owned.u ORDER BY id`, []string{"id"}, []string{"INT4"}, [][]any{{int64(9)}, {int64(88)}}))
	fixture.RunStep(t, p.Ctx, held, p.MemoryRecord, fixture.Exec(`INSERT INTO owned.i DEFAULT VALUES`, 1))
	fixture.RunStep(t, p.Ctx, p.Memory, p.MemoryRecord, fixture.Select(`SELECT id FROM owned.i ORDER BY id`, []string{"id"}, []string{"INT4"}, [][]any{{int64(7)}, {int64(13)}, {int64(16)}, {int64(99)}}))
}
