func TestReferenceSerialDeclarations(t *testing.T) {
	for _, tc := range []struct{ query, message, token string }{
		{`CREATE TABLE bad(id SERIAL NULL)`, `conflicting NULL/NOT NULL declarations for column "id" of table "bad"`, "NULL"},
		{`CREATE TABLE bad(id SERIAL DEFAULT 7)`, `multiple default values specified for column "id" of table "bad"`, ""},
		{`CREATE TABLE bad(id SERIAL GENERATED BY DEFAULT AS IDENTITY)`, `both default and identity specified for column "id" of table "bad"`, ""},
		{`CREATE TABLE bad(id SERIAL(2))`, `type modifier is not allowed for type "integer"`, "SERIAL"},
	} {
		t.Run(tc.query, func(t *testing.T) {
			serialReferenceStreams(t, false, func(bool) []fixture.Step {
				position := ""
				if tc.token != "" {
					position = fmt.Sprint(strings.Index(tc.query, tc.token) + 1)
				}
				failure := fixture.ImplicitError(tc.query, fixture.Diagnostic{Code: "42601", Message: tc.message, Position: position})
				failure.ErrorStage = "execute"
				return []fixture.Step{failure, fixture.Exec(`CREATE TABLE bad(id SERIAL)`, 0), fixture.Exec(`INSERT INTO bad DEFAULT VALUES`, 1), fixture.Select(`SELECT * FROM bad`, []string{"id"}, []string{"INT4"}, [][]any{{int64(1)}}), fixture.Exec(`DROP TABLE bad RESTRICT`, 0), fixture.Exec(`CREATE SEQUENCE bad_id_seq`, 0)}
			})
		})
	}
}

func TestReferenceSerialCascadeNotice(t *testing.T) {
	p := fixture.NewScenario(t)
	for _, backend := range p.Backends() {
		postgres := backend.PG
		t.Run(backend.Name, func(t *testing.T) {
			var notices []fixture.Diagnostic
			_, conn, record := fixture.NoticeReferencePool(t, p, postgres, &notices)
			for _, step := range []fixture.Step{fixture.Exec(`CREATE TABLE dep(id SERIAL)`, 0), fixture.Exec(`DROP SEQUENCE dep_id_seq CASCADE`, 0)} {
				fixture.RunStep(t, p.Ctx, conn, record, step)
			}
			want := []fixture.Diagnostic{{Severity: "NOTICE", SeverityUnlocalized: "NOTICE", Code: "00000", Message: `drop cascades to default value for column id of table dep`}}
			if !reflect.DeepEqual(notices, want) {
				t.Fatalf("notice got %#v want %#v", notices, want)
			}
		})
	}
}
