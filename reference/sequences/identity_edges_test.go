func TestReferenceIdentitySessionsConcurrentAllocation(t *testing.T) {
	p := fixture.NewScenario(t)
	for _, backend := range p.Backends() {
		t.Run(backend.Name, func(t *testing.T) {
			fixture.RunStep(t, p.Ctx, backend.DB, backend.Recorder, fixture.Exec(`CREATE TABLE concurrent(id INT GENERATED ALWAYS AS IDENTITY(CACHE 1))`, 0))
			connections := []*sql.Conn{fixture.IdentityConnection(t, p.Ctx, backend.DB), fixture.IdentityConnection(t, p.Ctx, backend.DB)}
			const n = 32
			var wg sync.WaitGroup
			failures := make(chan error, 2)
			start := make(chan struct{})
			for _, c := range connections {
				wg.Add(1)
				go func(c *sql.Conn) {
					defer wg.Done()
					<-start
					for range n {
						r, err := c.ExecContext(p.Ctx, `INSERT INTO concurrent DEFAULT VALUES`)
						if err == nil {
							var count int64
							count, err = r.RowsAffected()
							if err == nil && count != 1 {
								err = fmt.Errorf("RowsAffected=%d want 1", count)
							}
						}
						if err != nil {
							failures <- err
							return
						}
					}
				}(c)
			}
			close(start)
			wg.Wait()
			close(failures)
			for err := range failures {
				t.Error(err)
			}
			if t.Failed() {
				t.FailNow()
			}
			want := make([][]any, 2*n)
			for i := range want {
				want[i] = []any{int64(i + 1)}
			}
			fixture.RunStep(t, p.Ctx, backend.DB, backend.Recorder, fixture.Select(`SELECT * FROM concurrent ORDER BY id`, []string{"id"}, []string{"INT4"}, want))
		})
	}
}
