func TestReferenceIdentityDeclarationAtomicNamesAndLike(t *testing.T) {
	p := fixture.NewScenario(t)
	p.Step(t, fixture.Exec(`CREATE SEQUENCE i_id_seq`, 0))
	p.Step(t, fixture.Exec(`CREATE TABLE i(id pg_catalog.int4 GENERATED ALWAYS AS IDENTITY,other BIGINT GENERATED BY DEFAULT AS IDENTITY(SEQUENCE NAME public."Quoted Seq" OWNED BY NONE))`, 0))
	p.Step(t, fixture.Exec(`INSERT INTO i DEFAULT VALUES`, 1))
	p.Step(t, fixture.Select(`SELECT * FROM i`, []string{"id", "other"}, []string{"INT4", "INT8"}, [][]any{{int64(1), int64(1)}}))
	p.Step(t, fixture.Select(`SELECT last_value,is_called FROM i_id_seq1`, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(1), true}}))
	p.Step(t, fixture.Exec(`CREATE TABLE clone(LIKE i)`, 0))
	p.Step(t, fixture.ImplicitError(`INSERT INTO clone DEFAULT VALUES`, fixture.Diagnostic{Code: "23502", Message: `null value in column "id" of relation "clone" violates not-null constraint`, Detail: "Failing row contains (null, null).", Schema: "public", Table: "clone", Column: "id"}))
	for _, tc := range []struct{ query, message, position, code string }{
		{`CREATE TABLE bad(id INT GENERATED ALWAYS AS IDENTITY DEFAULT 4)`, `both default and identity specified for column "id" of table "bad"`, "54", "42601"},
		{`CREATE TABLE bad(id INT DEFAULT 4 GENERATED ALWAYS AS IDENTITY)`, `both default and identity specified for column "id" of table "bad"`, "35", "42601"},
		{`CREATE TABLE bad(id INT NULL GENERATED ALWAYS AS IDENTITY)`, `conflicting NULL/NOT NULL declarations for column "id" of table "bad"`, "30", "42601"},
		{`CREATE TABLE bad(id INT GENERATED ALWAYS AS IDENTITY GENERATED BY DEFAULT AS IDENTITY)`, `multiple identity specifications for column "id" of table "bad"`, "54", "42601"},
		{`CREATE TABLE bad(id INT GENERATED ALWAYS AS IDENTITY(CACHE 0))`, `CACHE (0) must be greater than zero`, "", "22023"},
	} {
		p.Step(t, fixture.ImplicitError(tc.query, fixture.Diagnostic{Code: tc.code, Message: tc.message, Position: tc.position}))
		for _, name := range []string{"bad", "bad_id_seq"} {
			s := fixture.ImplicitError(`SELECT * FROM `+name, fixture.Diagnostic{Code: "42P01", Message: `relation "` + name + `" does not exist`, Position: "15"})
			s.SelectRows = true
			p.Step(t, s)
		}
	}
	p.Step(t, fixture.Exec(`CREATE SCHEMA nested CREATE TABLE n(id INT GENERATED ALWAYS AS IDENTITY)`, 0))
	p.Step(t, fixture.Exec(`INSERT INTO nested.n DEFAULT VALUES`, 1))
	p.Step(t, fixture.Select(`SELECT * FROM nested.n`, []string{"id"}, []string{"INT4"}, [][]any{{int64(1)}}))
	for _, backend := range p.Backends() {
		fixture.RunStep(t, p.Ctx, backend.DB, backend.Recorder, fixture.Exec(`DROP SCHEMA nested CASCADE`, 0))
	}
}
func TestReferenceIdentityAlterPassesAndFailureAtomicity(t *testing.T) {
	p := fixture.NewScenario(t)
	p.Step(t, fixture.Exec(`CREATE TABLE a(id INT)`, 0))
	p.Step(t, fixture.Exec(`INSERT INTO a VALUES(40)`, 1))
	p.Step(t, fixture.Exec(`ALTER TABLE a ALTER id ADD GENERATED ALWAYS AS IDENTITY, ALTER id SET NOT NULL`, 0))
	p.Step(t, fixture.Exec(`INSERT INTO a DEFAULT VALUES`, 1))
	p.Step(t, fixture.ImplicitError(`ALTER TABLE a ALTER id SET GENERATED BY DEFAULT, ALTER missing SET NOT NULL`, fixture.Diagnostic{Code: "42703", Message: `column "missing" of relation "a" does not exist`}))
	p.Step(t, fixture.ImplicitError(`INSERT INTO a VALUES(99)`, fixture.IdentityAlwaysDiagnostic()))
	p.Step(t, fixture.ImplicitError(`ALTER TABLE a ALTER id RESTART WITH 100, ALTER id SET CACHE 0`, fixture.Diagnostic{Code: "22023", Message: "CACHE (0) must be greater than zero"}))
	p.Step(t, fixture.Exec(`INSERT INTO a DEFAULT VALUES`, 1))
	p.Step(t, fixture.Select(`SELECT * FROM a ORDER BY id`, []string{"id"}, []string{"INT4"}, [][]any{{int64(1)}, {int64(2)}, {int64(40)}}))
	p.Step(t, fixture.Exec(`ALTER TABLE a ALTER id DROP IDENTITY`, 0))
	p.Step(t, fixture.Exec(`ALTER TABLE a ALTER id ADD GENERATED BY DEFAULT AS IDENTITY`, 0))
	p.Step(t, fixture.Exec(`INSERT INTO a DEFAULT VALUES`, 1))
	p.Step(t, fixture.Select(`SELECT * FROM a ORDER BY id`, []string{"id"}, []string{"INT4"}, [][]any{{int64(1)}, {int64(1)}, {int64(2)}, {int64(40)}}))
}
func TestReferenceIdentityLifecycleDependenciesAndMoves(t *testing.T) {
	p := fixture.NewScenario(t)
	for _, q := range []string{`CREATE SCHEMA moved`, `CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY)`, `CREATE VIEW linked AS SELECT last_value FROM i_id_seq`} {
		p.Step(t, fixture.Exec(q, 0))
	}
	p.Step(t, fixture.ImplicitError(`ALTER TABLE i ALTER id DROP IDENTITY`, fixture.Diagnostic{Code: "2BP01", Message: "cannot drop sequence i_id_seq because other objects depend on it", Detail: "view linked depends on sequence i_id_seq", Hint: "Use DROP ... CASCADE to drop the dependent objects too."}))
	p.Step(t, fixture.Exec(`INSERT INTO i DEFAULT VALUES`, 1))
	p.Step(t, fixture.Select(`SELECT * FROM i`, []string{"id"}, []string{"INT4"}, [][]any{{int64(1)}}))
	p.Step(t, fixture.Exec(`ALTER TABLE i SET SCHEMA moved`, 0))
	p.Step(t, fixture.Exec(`ALTER SEQUENCE moved.i_id_seq RENAME TO actual`, 0))
	p.Step(t, fixture.Exec(`INSERT INTO moved.i DEFAULT VALUES`, 1))
	p.Step(t, fixture.Select(`SELECT * FROM moved.i ORDER BY id`, []string{"id"}, []string{"INT4"}, [][]any{{int64(1)}, {int64(2)}}))
	p.Step(t, fixture.Exec(`DROP TABLE moved.i CASCADE`, 0))
	s := fixture.ImplicitError(`SELECT * FROM moved.actual`, fixture.Diagnostic{Code: "42P01", Message: `relation "moved.actual" does not exist`, Position: "15"})
	s.SelectRows = true
	p.Step(t, s)
	p.Step(t, fixture.Exec(`DROP SCHEMA moved CASCADE`, 0))
}
