func smokeIdentityNonContext(s fixture.Step) fixture.Step { s.NonContext = true; return s }
func smokeIdentityState(t *testing.T, err error, code string) {
	t.Helper()
	var state interface{ SQLState() string }
	if !errors.As(err, &state) || state.SQLState() != code {
		t.Fatalf("error=%v want=%s", err, code)
	}
}
func smokeIdentityDiagnostic(t *testing.T, err error, want stuntgres.Error) {
	t.Helper()
	diagnostic := fixture.MigrationDiagnostic(want)
	diagnostic.Severity, diagnostic.SeverityUnlocalized = "ERROR", "ERROR"
	fixture.AssertDiagnostic(t, err, &diagnostic)
}

func TestReferenceSmokeIdentitySmoke(t *testing.T) {
	p := fixture.NewScenario(t)
	for _, b := range p.Backends() {
		func() {
			db := b.DB
			stepRun := func(step fixture.Step) { fixture.RunStep(t, p.Ctx, db, b.Recorder, step) }
			stepRun(smokeIdentityNonContext(fixture.Exec(`CREATE TABLE a(id INT GENERATED ALWAYS AS IDENTITY,p INT DEFAULT 7)`, 0)))
			held, err := db.Prepare(`INSERT INTO a DEFAULT VALUES`)
			if err != nil {
				t.Fatal(err)
			}
			defer held.Close()
			fixture.RunStep(t, p.Ctx, fixture.HeldStatement{Executor: db, Statement: held, SQL: `INSERT INTO a DEFAULT VALUES`}, b.Recorder, smokeIdentityNonContext(fixture.Exec(`INSERT INTO a DEFAULT VALUES`, 1)))
			stepRun(smokeIdentityNonContext(fixture.Exec(`INSERT INTO a VALUES(DEFAULT,DEFAULT)`, 1)))
			_, err = db.Exec(`INSERT INTO a VALUES(99,9)`)
			smokeIdentityState(t, err, "428C9")
			stepRun(smokeIdentityNonContext(fixture.Exec(`INSERT INTO a OVERRIDING SYSTEM VALUE VALUES(99,9)`, 1)))
			stepRun(smokeIdentityNonContext(fixture.Exec(`INSERT INTO a DEFAULT VALUES`, 1)))
			stepRun(smokeIdentityNonContext(fixture.Exec(`INSERT INTO a OVERRIDING USER VALUE VALUES(99,8)`, 1)))
			stepRun(smokeIdentityNonContext(fixture.Select(`SELECT * FROM a ORDER BY id`, []string{"id", "p"}, []string{"INT4", "INT4"}, [][]any{{int64(1), int64(7)}, {int64(2), int64(7)}, {int64(3), int64(7)}, {int64(4), int64(8)}, {int64(99), int64(9)}})))
			empty := fixture.Select(`SELECT id FROM a WHERE false`, []string{"id"}, []string{"INT4"}, nil)
			empty.CheckMetadata = func(t *testing.T, rows *sql.Rows) {
				types, err := rows.ColumnTypes()
				if err != nil {
					t.Fatal(err)
				}
				nullable, known := types[0].Nullable()
				scan := reflect.TypeFor[int64]()
				if b.PG {
					scan = reflect.TypeFor[int32]()
				}
				if nullable || known == b.PG || types[0].ScanType() != scan {
					t.Fatal(types[0], nullable, known)
				}
			}
			stepRun(smokeIdentityNonContext(empty))
			stepRun(smokeIdentityNonContext(fixture.Exec(`CREATE TABLE b(id INT GENERATED BY DEFAULT AS IDENTITY)`, 0)))
			for _, q := range []string{`INSERT INTO b DEFAULT VALUES`, `INSERT INTO b VALUES(99)`, `INSERT INTO b VALUES(DEFAULT)`} {
				stepRun(smokeIdentityNonContext(fixture.Exec(q, 1)))
			}
			stepRun(smokeIdentityNonContext(fixture.Select(`SELECT * FROM b ORDER BY id`, []string{"id"}, []string{"INT4"}, [][]any{{int64(1)}, {int64(2)}, {int64(99)}})))
			stepRun(smokeIdentityNonContext(fixture.Exec(`CREATE TABLE opt(id INT GENERATED ALWAYS AS IDENTITY(START 7 INCREMENT 3))`, 0)))
			for range 2 {
				stepRun(smokeIdentityNonContext(fixture.Exec(`INSERT INTO opt DEFAULT VALUES`, 1)))
			}
			stepRun(smokeIdentityNonContext(fixture.Select(`SELECT * FROM opt ORDER BY id`, []string{"id"}, []string{"INT4"}, [][]any{{int64(7)}, {int64(10)}})))
			for _, tc := range []struct {
				query  string
				last   int64
				called bool
				n      int64
			}{
				{`INSERT INTO shape OVERRIDING USER VALUE VALUES(nextval('side'),10)`, 50, false, 1},
				{`INSERT INTO shape OVERRIDING USER VALUE VALUES(nextval('side'),16),(nextval('side'),17)`, 51, true, 2},
				{`INSERT INTO shape OVERRIDING USER VALUE SELECT nextval('side'),14`, 50, true, 1},
			} {
				stepRun(smokeIdentityNonContext(fixture.Exec(`CREATE TABLE shape(id INT GENERATED ALWAYS AS IDENTITY,p INT)`, 0)))
				stepRun(smokeIdentityNonContext(fixture.Exec(`CREATE SEQUENCE side START 50 CACHE 1`, 0)))
				stepRun(smokeIdentityNonContext(fixture.Exec(tc.query, tc.n)))
				stepRun(smokeIdentityNonContext(fixture.Select(`SELECT last_value,is_called FROM side`, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{tc.last, tc.called}})))
				stepRun(smokeIdentityNonContext(fixture.Exec(`DROP TABLE shape`, 0)))
				stepRun(smokeIdentityNonContext(fixture.Exec(`DROP SEQUENCE side`, 0)))
			}
			parameter, err := db.Prepare(`INSERT INTO b OVERRIDING USER VALUE VALUES($1)`)
			if err != nil {
				t.Fatal(err)
			}
			defer parameter.Close()
			want := fixture.ControlsReferenceDiagnostic("22P02", `invalid input syntax for type integer: "bad"`)
			want.Context = "unnamed portal parameter $1 = '...'"
			fixture.RunStep(t, p.Ctx, fixture.HeldStatement{Executor: db, Statement: parameter, SQL: `INSERT INTO b OVERRIDING USER VALUE VALUES($1)`}, b.Recorder, smokeIdentityNonContext(fixture.ErrorDiagnostic(`INSERT INTO b OVERRIDING USER VALUE VALUES($1)`, want, "bad")))
		}()
	}
}

func TestReferenceSmokeIdentityControlsSmoke(t *testing.T) {
	p := fixture.NewScenario(t)
	for _, b := range p.Backends() {
		func() {
			db := b.DB
			stepRun := func(step fixture.Step) { fixture.RunStep(t, p.Ctx, db, b.Recorder, step) }
			ctx := p.Ctx
			for _, q := range []string{`CREATE TABLE narrow(id SMALLINT GENERATED ALWAYS AS IDENTITY)`, `ALTER SEQUENCE narrow_id_seq AS bigint MAXVALUE 100000 RESTART WITH 32768`, `COMMENT ON SEQUENCE narrow_id_seq IS 'divergent generator'`, `CREATE TABLE uncalled(id INT GENERATED BY DEFAULT AS IDENTITY(START 7 CACHE 2))`} {
				stepRun(smokeIdentityNonContext(fixture.Exec(q, 0)))
			}
			stepRun(smokeIdentityNonContext(fixture.Exec(`INSERT INTO narrow DEFAULT VALUES`, 1)))
			stepRun(smokeIdentityNonContext(fixture.Exec(`INSERT INTO uncalled VALUES(99)`, 1)))
			if !b.PG {
				var dump bytes.Buffer
				if err := stuntgres.Dump(ctx, p.Native, &dump); err != nil {
					t.Fatal(err)
				}
				if err := stuntgres.Reset(ctx, p.Native); err != nil {
					t.Fatal(err)
				}
				if err := stuntgres.Restore(ctx, p.Native, bytes.NewReader(dump.Bytes())); err != nil {
					t.Fatal(err)
				}
				var again bytes.Buffer
				if err := stuntgres.Dump(ctx, p.Native, &again); err != nil {
					t.Fatal(err)
				}
				if !bytes.Equal(dump.Bytes(), again.Bytes()) {
					t.Fatalf("redump mismatch\n%s\n%s", dump.Bytes(), again.Bytes())
				}
			}
			stepRun(smokeIdentityNonContext(fixture.Exec(`INSERT INTO narrow DEFAULT VALUES`, 1)))
			stepRun(smokeIdentityNonContext(fixture.Exec(`INSERT INTO uncalled DEFAULT VALUES`, 1)))
			stepRun(smokeIdentityNonContext(fixture.Select(`SELECT * FROM narrow ORDER BY id`, []string{"id"}, []string{"INT2"}, [][]any{{int64(-32768)}, {int64(-32767)}})))
			stepRun(smokeIdentityNonContext(fixture.Select(`SELECT * FROM uncalled ORDER BY id`, []string{"id"}, []string{"INT4"}, [][]any{{int64(7)}, {int64(99)}})))
			if !b.PG {
				if err := stuntgres.Restore(ctx, p.Native, bytes.NewBufferString(`CREATE TABLE bad(id INT GENERATED ALWAYS AS IDENTITY); INSERT INTO bad VALUES(4);`)); err == nil {
					t.Fatal("invalid import accepted")
				}
				stepRun(smokeIdentityNonContext(fixture.Select(`SELECT * FROM narrow ORDER BY id`, []string{"id"}, []string{"INT2"}, [][]any{{int64(-32768)}, {int64(-32767)}})))
			}
		}()
	}
}

func TestReferenceSmokeIdentityFailureDemandSmoke(t *testing.T) {
	for _, side := range []bool{false, true} {
		for _, prepared := range []bool{false, true} {
			t.Run(fmt.Sprintf("early/side=%t/prepared=%t", side, prepared), func(t *testing.T) {
				p := fixture.NewScenario(t)
				for _, b := range p.Backends() {
					func() {
						db := b.DB
						stepRun := func(step fixture.Step) { fixture.RunStep(t, p.Ctx, db, b.Recorder, step) }
						ctx := p.Ctx
						c, err := db.Conn(ctx)
						if err != nil {
							t.Fatal(err)
						}
						defer c.Close()
						stepRun = func(step fixture.Step) { step.NonContext = false; fixture.RunStep(t, p.Ctx, c, b.Recorder, step) }
						options := "MINVALUE 0 MAXVALUE 1 START 1 CACHE 1"
						later := "$2"
						args := []any{nil, 8}
						if side {
							options = "MINVALUE 0 MAXVALUE 10 START 1 CACHE 1"
							later = "nextval('side')"
							args = args[:1]
						}
						for _, q := range []string{`CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY(` + options + `),p INT NOT NULL)`, `CREATE SEQUENCE side START 50 CACHE 1`} {
							if _, err = c.ExecContext(ctx, q); err != nil {
								t.Fatal(q, err)
							}
						}
						query := `INSERT INTO i VALUES(DEFAULT,$1),(DEFAULT,` + later + `)`
						var held *sql.Stmt
						if prepared {
							held, err = c.PrepareContext(ctx, query)
							if err != nil {
								t.Fatal(err)
							}
							defer held.Close()
						}
						run := func() (sql.Result, error) {
							if prepared {
								return (fixture.HeldStatement{Executor: c, Statement: held, SQL: query}).ExecContext(ctx, query, args...)
							}
							return c.ExecContext(ctx, query, args...)
						}
						stepRun(smokeIdentityNonContext(fixture.Select(`SELECT last_value,is_called FROM i_id_seq`, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(1), false}})))
						result, err := run()
						if result != nil {
							t.Fatal("failed batch returned a result")
						}
						smokeIdentityDiagnostic(t, err, stuntgres.Error{Code: "23502", Message: `null value in column "p" of relation "i" violates not-null constraint`, Detail: "Failing row contains (1, null).", Schema: "public", Table: "i", Column: "p"})
						stepRun(smokeIdentityNonContext(fixture.Select(`SELECT * FROM i`, []string{"id", "p"}, []string{"INT4", "INT4"}, nil)))
						stepRun(smokeIdentityNonContext(fixture.Select(`SELECT last_value,is_called FROM i_id_seq`, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(1), true}})))
						stepRun(smokeIdentityNonContext(fixture.Select(`SELECT last_value,is_called FROM side`, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(50), false}})))
						var memory int64
						for _, q := range []string{`SELECT currval('i_id_seq')`, `SELECT lastval()`} {
							if err = c.QueryRowContext(ctx, q).Scan(&memory); err != nil || memory != 1 {
								t.Fatal(q, memory, err)
							}
						}
						smokeIdentityDiagnostic(t, c.QueryRowContext(ctx, `SELECT currval('side')`).Scan(&memory), stuntgres.Error{Code: "55000", Message: `currval of sequence "side" is not yet defined in this session`})
						first := int64(2)
						payload := int64(50)
						if !side {
							if _, err = c.ExecContext(ctx, `ALTER TABLE i ALTER id RESTART WITH 0`); err != nil {
								t.Fatal(err)
							}
							first = 0
							payload = 8
						}
						args[0] = 7
						result, err = run()
						if err != nil {
							t.Fatal("healthy reuse", err)
						}
						if n, err := result.RowsAffected(); err != nil || n != 2 {
							t.Fatal(n, err)
						}
						stepRun(smokeIdentityNonContext(fixture.Select(`SELECT * FROM i ORDER BY id`, []string{"id", "p"}, []string{"INT4", "INT4"}, [][]any{{first, int64(7)}, {first + 1, payload}})))
						for _, q := range []string{`SELECT currval('i_id_seq')`, `SELECT lastval()`} {
							if err = c.QueryRowContext(ctx, q).Scan(&memory); err != nil || memory != first+1 {
								t.Fatal(q, memory, err)
							}
						}
					}()
				}
			})
		}
	}
	for _, tc := range []struct {
		name, source string
		fails, side  bool
		payloads     []int64
	}{
		{"multi_values", `VALUES(CAST($1::text AS integer),7),(0,8)`, true, false, []int64{7, 8}},
		{"ordered_select", `SELECT CAST($1::text AS integer),p FROM inputs ORDER BY 1`, true, false, []int64{7}},
		{"single_values", `VALUES(CAST($1::text AS integer),7)`, false, false, []int64{7}},
		{"select", `SELECT CAST($1::text AS integer),7`, false, false, []int64{7}},
		{"volatile_select", `SELECT CAST(CASE WHEN nextval('side')>0 THEN $1::text ELSE '' END AS integer),7`, true, true, []int64{7}},
	} {
		for _, prepared := range []bool{false, true} {
			t.Run(fmt.Sprintf("conversion/%s/prepared=%t", tc.name, prepared), func(t *testing.T) {
				p := fixture.NewScenario(t)
				for _, b := range p.Backends() {
					func() {
						db := b.DB
						stepRun := func(step fixture.Step) { fixture.RunStep(t, p.Ctx, db, b.Recorder, step) }
						ctx := p.Ctx
						c, err := db.Conn(ctx)
						if err != nil {
							t.Fatal(err)
						}
						defer c.Close()
						stepRun = func(step fixture.Step) { step.NonContext = false; fixture.RunStep(t, p.Ctx, c, b.Recorder, step) }
						for _, q := range []string{`CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY(CACHE 1),p INT)`, `CREATE SEQUENCE side START 50 CACHE 1`, `CREATE TABLE inputs(p INT)`, `INSERT INTO inputs VALUES(7)`} {
							if _, err = c.ExecContext(ctx, q); err != nil {
								t.Fatal(q, err)
							}
						}
						query := `INSERT INTO i OVERRIDING USER VALUE ` + tc.source
						var held *sql.Stmt
						if prepared {
							held, err = c.PrepareContext(ctx, query)
							if err != nil {
								t.Fatal("Prepare demanded conversion", err)
							}
							defer held.Close()
						}
						run := func(value string) (sql.Result, error) {
							if prepared {
								return (fixture.HeldStatement{Executor: c, Statement: held, SQL: query}).ExecContext(ctx, query, value)
							}
							return c.ExecContext(ctx, query, value)
						}
						stepRun(smokeIdentityNonContext(fixture.Select(`SELECT last_value,is_called FROM i_id_seq`, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(1), false}})))
						result, err := run("bad")
						var want [][]any
						if tc.fails {
							if result != nil {
								t.Fatal("failed conversion returned result")
							}
							smokeIdentityDiagnostic(t, err, stuntgres.Error{Code: "22P02", Message: `invalid input syntax for type integer: "bad"`})
							stepRun(smokeIdentityNonContext(fixture.Select(`SELECT * FROM i`, []string{"id", "p"}, []string{"INT4", "INT4"}, nil)))
							stepRun(smokeIdentityNonContext(fixture.Select(`SELECT last_value,is_called FROM i_id_seq`, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(1), false}})))
							var memory int64
							smokeIdentityDiagnostic(t, c.QueryRowContext(ctx, `SELECT currval('i_id_seq')`).Scan(&memory), stuntgres.Error{Code: "55000", Message: `currval of sequence "i_id_seq" is not yet defined in this session`})
							if tc.side {
								if err = c.QueryRowContext(ctx, `SELECT lastval()`).Scan(&memory); err != nil || memory != 50 {
									t.Fatal(memory, err)
								}
							} else {
								smokeIdentityDiagnostic(t, c.QueryRowContext(ctx, `SELECT lastval()`).Scan(&memory), stuntgres.Error{Code: "55000", Message: "lastval is not yet defined in this session"})
							}
						} else {
							if err != nil {
								t.Fatal("pruned conversion ran", err)
							}
							if n, err := result.RowsAffected(); err != nil || n != int64(len(tc.payloads)) {
								t.Fatal(n, err)
							}
							want = [][]any{{int64(1), int64(7)}}
							stepRun(smokeIdentityNonContext(fixture.Select(`SELECT * FROM i`, []string{"id", "p"}, []string{"INT4", "INT4"}, want)))
						}
						stepRun(smokeIdentityNonContext(fixture.Select(`SELECT last_value,is_called FROM side`, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(50), tc.side}})))
						result, err = run("8")
						if err != nil {
							t.Fatal("healthy reuse", err)
						}
						if n, err := result.RowsAffected(); err != nil || n != int64(len(tc.payloads)) {
							t.Fatal(n, err)
						}
						for _, p := range tc.payloads {
							want = append(want, []any{int64(len(want) + 1), p})
						}
						stepRun(smokeIdentityNonContext(fixture.Select(`SELECT * FROM i ORDER BY id`, []string{"id", "p"}, []string{"INT4", "INT4"}, want)))
						var memory int64
						for _, q := range []string{`SELECT currval('i_id_seq')`, `SELECT lastval()`} {
							if err = c.QueryRowContext(ctx, q).Scan(&memory); err != nil || memory != int64(len(want)) {
								t.Fatal(q, memory, err)
							}
						}
						last := int64(50)
						if tc.side {
							last = 51
						}
						stepRun(smokeIdentityNonContext(fixture.Select(`SELECT last_value,is_called FROM side`, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{last, tc.side}})))
					}()
				}
			})
		}
	}
}
