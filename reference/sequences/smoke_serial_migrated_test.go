package reference_test

import (
	"bytes"
	"fmt"
	"reflect"
	"stuntgres"
	"stuntgres/reference/fixture"
	"testing"
)

func TestReferenceSmokeSerialSmoke(t *testing.T) {
	p := fixture.NewScenario(t)
	for _, b := range p.Backends() {
		func() {
			db := b.DB
			run := func(s fixture.Step) { s.NonContext = true; fixture.RunStep(t, p.Ctx, db, b.Recorder, s) }
			exec := func(q string, n int64) { run(fixture.Exec(q, n)) }
			exec(`CREATE TABLE widths(a SMALLSERIAL,b SERIAL,c BIGSERIAL)`, 0)
			rows, err := db.Query(`SELECT * FROM widths`)
			if err != nil {
				t.Fatal(err)
			}
			metadata, err := rows.ColumnTypes()
			if err != nil || len(metadata) != 3 {
				t.Fatal(metadata, err)
			}
			for i, typ := range []string{"INT2", "INT4", "INT8"} {
				scan := reflect.TypeFor[int64]()
				if b.PG && i == 0 {
					scan = reflect.TypeFor[int16]()
				}
				if b.PG && i == 1 {
					scan = reflect.TypeFor[int32]()
				}
				nullable, known := metadata[i].Nullable()
				if metadata[i].DatabaseTypeName() != typ || (!b.PG && !known) || (b.PG && known) || nullable || metadata[i].ScanType() != scan {
					t.Fatal(metadata[i], nullable, known)
				}
			}
			rows.Close()
			held, err := db.Prepare(`INSERT INTO widths DEFAULT VALUES`)
			if err != nil {
				t.Fatal(err)
			}
			defer held.Close()
			for range 2 {
				fixture.RunStep(t, p.Ctx, fixture.HeldStatement{Executor: db, Statement: held, SQL: `INSERT INTO widths DEFAULT VALUES`}, b.Recorder, smokeIdentityNonContext(fixture.Exec(`INSERT INTO widths DEFAULT VALUES`, 1)))
			}
			exec(`INSERT INTO widths VALUES(100,100,100),(100,100,100)`, 2)
			exec(`INSERT INTO widths DEFAULT VALUES`, 1)
			run(fixture.Select(`SELECT * FROM widths ORDER BY a`, []string{"a", "b", "c"}, []string{"INT2", "INT4", "INT8"}, [][]any{{int64(1), int64(1), int64(1)}, {int64(2), int64(2), int64(2)}, {int64(3), int64(3), int64(3)}, {int64(100), int64(100), int64(100)}, {int64(100), int64(100), int64(100)}}))
			_, err = db.Exec(`INSERT INTO widths VALUES(NULL,100,100)`)
			smokeIdentityState(t, err, "23502")
			run(fixture.Select(`SELECT last_value FROM widths_a_seq`, []string{"last_value"}, []string{"INT8"}, [][]any{{int64(3)}}))
			exec(`CREATE TABLE queried(id SERIAL,v TEXT)`, 0)
			exec(`CREATE TABLE source(v TEXT)`, 0)
			exec(`INSERT INTO queried(v) SELECT v FROM source`, 0)
			exec(`INSERT INTO source VALUES('a'),('b')`, 2)
			exec(`INSERT INTO queried(v) SELECT v FROM source ORDER BY v`, 2)
			run(fixture.Select(`SELECT * FROM queried ORDER BY id`, []string{"id", "v"}, []string{"INT4", "TEXT"}, [][]any{{int64(1), "a"}, {int64(2), "b"}}))
			for i, width := range []struct {
				alias, typ string
				max        int64
			}{{"SMALLSERIAL", "INT2", 32767}, {"SERIAL", "INT4", 2147483647}, {"BIGSERIAL", "INT8", 9223372036854775807}} {
				name := fmt.Sprintf("endpoint%d", i)
				exec(`CREATE TABLE `+name+`(id `+width.alias+`)`, 0)
				run(fixture.Select(fmt.Sprintf(`SELECT setval('%s_id_seq',%d,false)`, name, width.max), []string{"setval"}, []string{"INT8"}, [][]any{{width.max}}))
				exec(`INSERT INTO `+name+` DEFAULT VALUES`, 1)
				_, err := db.Exec(`INSERT INTO ` + name + ` DEFAULT VALUES`)
				smokeIdentityState(t, err, "2200H")
				_, err = db.Exec(fmt.Sprintf(`SELECT setval('%s_id_seq',0)`, name))
				smokeIdentityState(t, err, "22003")
				run(fixture.Select(`SELECT * FROM `+name, []string{"id"}, []string{width.typ}, [][]any{{width.max}}))
			}
			exec(`CREATE TABLE owned(gone INT,id SERIAL,v TEXT)`, 0)
			exec(`ALTER TABLE owned DROP COLUMN gone`, 0)
			exec(`ALTER TABLE owned DROP COLUMN id RESTRICT`, 0)
			exec(`CREATE SEQUENCE owned_id_seq`, 0)
			exec(`CREATE TABLE dropped(id SERIAL)`, 0)
			exec(`DROP TABLE dropped RESTRICT`, 0)
			exec(`CREATE SEQUENCE dropped_id_seq`, 0)
			exec(`CREATE TABLE dep(id SERIAL)`, 0)
			_, err = db.Exec(`DROP SEQUENCE dep_id_seq RESTRICT`)
			smokeIdentityState(t, err, "2BP01")
			exec(`DROP SEQUENCE dep_id_seq CASCADE`, 0)
			_, err = db.Exec(`INSERT INTO dep DEFAULT VALUES`)
			smokeIdentityState(t, err, "23502")
			exec(`CREATE TABLE called(id SERIAL)`, 0)
			exec(`CREATE TABLE untouched(id SMALLSERIAL)`, 0)
			exec(`INSERT INTO called VALUES(100),(100),(0),(-1)`, 4)
			run(fixture.Select(`SELECT setval('called_id_seq',7,true)`, []string{"setval"}, []string{"INT8"}, [][]any{{int64(7)}}))
			exec(`ALTER SEQUENCE called_id_seq RENAME TO renamed`, 0)
			// The consumer was created first, but its current default needs an inline
			// identity provider belonging to the later producer table during replay.
			exec(`CREATE TABLE consumer(id SERIAL)`, 0)
			exec(`CREATE TABLE producer(id BIGINT GENERATED BY DEFAULT AS IDENTITY)`, 0)
			exec(`ALTER TABLE consumer ALTER id SET DEFAULT nextval('producer_id_seq')`, 0)
			exec(`INSERT INTO consumer DEFAULT VALUES`, 1)
			exec(`INSERT INTO producer DEFAULT VALUES`, 1)
			var dump bytes.Buffer
			ctx := p.Ctx
			if !b.PG {
				if err := stuntgres.Dump(ctx, p.Native, &dump); err != nil {
					t.Fatal(err)
				}
				run(fixture.Select(`SELECT last_value FROM renamed`, []string{"last_value"}, []string{"INT8"}, [][]any{{int64(7)}}))
				if err := stuntgres.Reset(ctx, p.Native); err != nil {
					t.Fatal(err)
				}
				if err := stuntgres.Restore(ctx, p.Native, bytes.NewReader(dump.Bytes())); err != nil {
					t.Fatal(err)
				}
			}
			exec(`INSERT INTO consumer DEFAULT VALUES`, 1)
			exec(`INSERT INTO producer DEFAULT VALUES`, 1)
			run(fixture.Select(`SELECT id FROM consumer ORDER BY id`, []string{"id"}, []string{"INT4"}, [][]any{{int64(1)}, {int64(3)}}))
			run(fixture.Select(`SELECT id FROM producer ORDER BY id`, []string{"id"}, []string{"INT8"}, [][]any{{int64(2)}, {int64(4)}}))
			exec(`INSERT INTO called DEFAULT VALUES`, 1)
			exec(`INSERT INTO untouched DEFAULT VALUES`, 1)
			run(fixture.Select(`SELECT * FROM called ORDER BY id`, []string{"id"}, []string{"INT4"}, [][]any{{int64(-1)}, {int64(0)}, {int64(8)}, {int64(100)}, {int64(100)}}))
			run(fixture.Select(`SELECT * FROM untouched`, []string{"id"}, []string{"INT2"}, [][]any{{int64(1)}}))
		}()
	}
}
