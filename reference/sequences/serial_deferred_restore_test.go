package reference_test

import (
	"database/sql"
	"fmt"
	"strings"
	"stuntgres"
	"stuntgres/reference/fixture"
	"testing"
)

func TestReferenceSerialDeferredDefaultRestoreAtomicity(t *testing.T) {
	for _, definition := range []string{`nextval('missing')`, `nextval('consumer')`, `nextval('producer_id_seq')+1`, `7`, `NULL`, `nextval($1)`} {
		for _, source := range []bool{false, true} {
			t.Run(fmt.Sprintf("%s/source=%t", definition, source), func(t *testing.T) {
				p := fixture.NewScenario(t)
				for _, backend := range p.Backends() {
					t.Run(backend.Name, func(t *testing.T) {
						run := func(s fixture.Step) {
							s.NonContext = source
							fixture.RunStep(t, p.Ctx, backend.DB, backend.Recorder, s)
						}
						run(fixture.Exec(`CREATE TABLE sentinel(id SERIAL)`, 0))
						run(fixture.Exec(`INSERT INTO sentinel DEFAULT VALUES`, 1))
						var rows *sql.Rows
						var err error
						if source {
							rows, err = backend.DB.Query(`SELECT id FROM sentinel`)
						} else {
							rows, err = backend.DB.QueryContext(p.Ctx, `SELECT id FROM sentinel`)
						}
						if err != nil {
							t.Fatal(err)
						}
						defer rows.Close()
						script := `CREATE TABLE producer(id BIGINT GENERATED BY DEFAULT AS IDENTITY); CREATE TABLE consumer(id INT); ALTER TABLE consumer ALTER id SET DEFAULT ` + definition + `;`
						if !backend.PG {
							if err := stuntgres.Restore(p.Ctx, p.Native, strings.NewReader(script)); err == nil {
								t.Fatal("accepted invalid deferred default", definition)
							}
						} else {
							// PostgreSQL supports general defaults, unlike native deferred
							// reconstruction. Roll back real staged DDL on the server.
							tx, err := backend.DB.BeginTx(p.Ctx, nil)
							if err != nil {
								t.Fatal(err)
							}
							defer tx.Rollback()
							_, err = tx.ExecContext(p.Ctx, script)
							state := ""
							switch definition {
							case `nextval('missing')`:
								state = "42P01"
							case `nextval($1)`:
								state = "42P02"
							}
							fixture.State(t, err, state)
							if definition == `nextval('consumer')` {
								_, err := tx.ExecContext(p.Ctx, `INSERT INTO consumer DEFAULT VALUES`)
								fixture.State(t, err, "42809")
							}
							if err := tx.Rollback(); err != nil {
								t.Fatal(err)
							}
						}
						if !rows.Next() {
							t.Fatal("replacement invalidated retained row", rows.Err())
						}
						var old int64
						if err := rows.Scan(&old); err != nil || old != 1 {
							t.Fatal(old, err)
						}
						if rows.Next() || rows.Err() != nil {
							t.Fatal(rows.Err())
						}
						if err := rows.Close(); err != nil {
							t.Fatal(err)
						}
						run(fixture.Prepared(fixture.Exec(`INSERT INTO sentinel DEFAULT VALUES`, 1)))
						run(fixture.Select(`SELECT id FROM sentinel ORDER BY id`, []string{"id"}, []string{"INT4"}, [][]any{{int64(1)}, {int64(2)}}))
						run(fixture.Exec(`CREATE TABLE producer(id SERIAL)`, 0))
					})
				}
			})
		}
	}
}
