// A separate destination and actual emitted-SQL replay use the same independent
// steps as the primary driver. No equality-only or dump-substring oracle.
func serialIdentityConsumeSteps(t *testing.T, p *fixture.Pair, x fixture.Executor, pg bool, steps []fixture.Step) {
	t.Helper()
	stmt, err := x.PrepareContext(p.Ctx, serialIdentityQuery)
	if err != nil {
		t.Fatal(err)
	}
	defer stmt.Close()
	held := fixture.HeldStatement{Executor: x, Statement: stmt, SQL: serialIdentityQuery}
	for _, s := range steps {
		if s.SelectRows {
			rows, err := x.QueryContext(p.Ctx, s.Query, s.Args...)
			if rows != nil && s.CheckMetadata != nil {
				s.CheckMetadata(t, rows)
			}
			fixture.DeleteReferenceConsume(t, pg, rows, err, s)
			if s.Query == serialIdentityQuery {
				rows, err := held.QueryContext(p.Ctx, s.Query, s.Args...)
				if rows != nil && s.CheckMetadata != nil {
					s.CheckMetadata(t, rows)
				}
				fixture.DeleteReferenceConsume(t, pg, rows, err, s)
			}
		} else {
			result, err := x.ExecContext(p.Ctx, s.Query, s.Args...)
			if s.Diagnostic != nil {
				if result != nil {
					t.Fatal("failed replay write exposed result")
				}
				fixture.CheckDiagnostic(t, err, s, "execute")
				continue
			}
			if err != nil {
				t.Fatal(err)
			}
			if n, err := result.RowsAffected(); err != nil || n != s.Affected {
				t.Fatal("affected", n, err, s.Affected)
			}
		}
	}
}

func serialIdentityControlPhase(t *testing.T, p *fixture.Pair, b fixture.Backend, c *sql.Conn, held fixture.HeldStatement) {
	t.Helper()
	if b.PG {
		return
	} // Native API phase, not a discovery bypass.
	var before, after bytes.Buffer
	if err := stuntgres.Dump(p.Ctx, p.Native, &before); err != nil {
		t.Fatal(err)
	}
	for _, s := range serialIdentityControlSteps(false) {
		serialIdentityRun(t, p, b, held, s)
	}
	if err := stuntgres.Dump(p.Ctx, p.Native, &after); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(before.Bytes(), after.Bytes()) {
		t.Fatal("inquiry changed dump/state")
	}
	// Retain actual driver-owned values and descriptors across replacement.
	rows, err := held.Statement.QueryContext(p.Ctx, `"si.Control"`, "ID")
	if err != nil {
		t.Fatal(err)
	}
	types, err := rows.ColumnTypes()
	if err != nil {
		rows.Close()
		t.Fatal(err)
	}
	if !rows.Next() {
		rows.Close()
		t.Fatal("retained row missing")
	}
	var value string
	if err := rows.Scan(&value); err != nil {
		rows.Close()
		t.Fatal(err)
	}
	if rows.Next() || rows.Err() != nil {
		rows.Close()
		t.Fatal("retained cardinality", rows.Err())
	}
	if err := rows.Close(); err != nil {
		t.Fatal(err)
	}
	if err := stuntgres.Reset(p.Ctx, p.Native); err != nil {
		t.Fatal(err)
	}
	if err := stuntgres.Restore(p.Ctx, p.Native, bytes.NewReader(before.Bytes())); err != nil {
		t.Fatal(err)
	}
	for _, s := range serialIdentityControlSteps(false) {
		serialIdentityRun(t, p, b, c, s)
		if s.Query == serialIdentityQuery {
			serialIdentityRun(t, p, b, held, s)
		}
	}
	if value != `public."si.Serial"` || len(types) != 1 || types[0].DatabaseTypeName() != "TEXT" || types[0].Name() != "pg_get_serial_sequence" {
		t.Fatal("retained inquiry changed", value, types)
	}
	other := fixture.UpdateReturningNativeDestination(t)
	if _, err := other.ExecContext(p.Ctx, `CREATE TEMP SEQUENCE si_control_address_shift`); err != nil {
		t.Fatal(err)
	}
	if err := stuntgres.Restore(p.Ctx, other, bytes.NewReader(before.Bytes())); err != nil {
		t.Fatal(err)
	}
	serialIdentityConsumeSteps(t, p, other, false, append(serialIdentityControlSteps(false), serialIdentityControlFuture()...))
	if p.Postgres != nil {
		pg, err := p.Postgres.Conn(p.Ctx)
		if err != nil {
			t.Fatal(err)
		}
		defer pg.Close()
		if _, err := pg.ExecContext(p.Ctx, `DROP SCHEMA public CASCADE; CREATE SCHEMA public`); err != nil {
			t.Fatal(err)
		}
		defer func() {
			if _, err := pg.ExecContext(p.Ctx, `RESET SESSION AUTHORIZATION; DROP SCHEMA public CASCADE; CREATE SCHEMA public`); err != nil {
				t.Error(err)
			}
		}()
		if _, err := pg.ExecContext(p.Ctx, before.String()); err != nil {
			t.Fatal("PostgreSQL emitted-SQL replay", err)
		}
		if _, err := pg.ExecContext(p.Ctx, `RESET SESSION AUTHORIZATION`); err != nil {
			t.Fatal(err)
		}
		serialIdentityConsumeSteps(t, p, pg, true, append(serialIdentityControlSteps(true), serialIdentityControlFuture()...))
	}
}

func TestReferenceSerialIdentityControls(t *testing.T) {
	serialIdentityScenario(t, func(t *testing.T, p *fixture.Pair, b fixture.Backend, c *sql.Conn) {
		serialIdentityControlSeed(t, p, b, c)
		held := serialIdentityHeld(t, p, b, c)
		for _, s := range serialIdentityControlSteps(b.PG) {
			serialIdentityRun(t, p, b, c, s)
			if s.Query == serialIdentityQuery {
				serialIdentityRun(t, p, b, held, s)
			}
		}
		serialIdentityControlPhase(t, p, b, c, held)
		serialIdentityRun(t, p, b, c, serialIdentityControlFuture()...)
	})
}

func TestReferenceSerialIdentityFeatureSmoke(t *testing.T) {
	serialIdentityScenario(t, func(t *testing.T, p *fixture.Pair, b fixture.Backend, c *sql.Conn) {
		serialIdentityControlSeed(t, p, b, c)
		held := serialIdentityHeld(t, p, b, c)
		for _, s := range serialIdentityControlSteps(b.PG) {
			serialIdentityRun(t, p, b, held, s)
		}
		serialIdentityCheck(t, p, b, c, held, `public."si.Control"`, "ID", `public."si.Serial"`)
		serialIdentityCheck(t, p, b, c, held, `"si.Control"`, "tableoid", nil)
		systemMissing := fixture.ControlsReferenceDiagnostic("42703", `column "tableoid" of relation "si_control_view" does not exist`)
		systemDirect := fixture.ErrorDiagnostic(`SELECT pg_get_serial_sequence('si_control_view','tableoid')`, systemMissing)
		systemDirect.SelectRows, systemDirect.ErrorStage = true, "execute"
		serialIdentityRun(t, p, b, c, systemDirect)
		systemHeld := fixture.ErrorDiagnostic(serialIdentityQuery, systemMissing, "si_control_view", "tableoid")
		systemHeld.SelectRows, systemHeld.ErrorStage = true, "execute"
		serialIdentityRun(t, p, b, held, systemHeld)
		serialIdentityCheck(t, p, b, c, held, `"si.Control"`, "ID", `public."si.Serial"`)
		serialIdentityRun(t, p, b, c, fixture.Exec(`ALTER SEQUENCE "si.Manual" OWNED BY NONE`, 0))
		serialIdentityCheck(t, p, b, c, held, `"si.Control"`, "manual", nil)
		serialIdentityRun(t, p, b, c, fixture.Exec(`ALTER SEQUENCE "si.Manual" OWNED BY "si.Control".manual`, 0))
		serialIdentityCheck(t, p, b, c, held, `"si.Control"`, "manual", `public."si.Manual"`)
		s := fixture.ErrorDiagnostic(`SELECT pg_get_serial_sequence(1,'ID')`, serialIdentityMissingFunction("pg_get_serial_sequence(integer, unknown)", 8))
		s.SelectRows, s.Prepared, s.ErrorStage = true, true, "prepare"
		serialIdentityRun(t, p, b, c, s)
		w := fixture.ControlsReferenceDiagnostic("42703", `column "missing" of relation "si.Control" does not exist`)
		s = fixture.ErrorDiagnostic(serialIdentityQuery, w, `"si.Control"`, "missing")
		s.SelectRows, s.ErrorStage = true, "execute"
		serialIdentityRun(t, p, b, held, s)
		serialIdentityCheck(t, p, b, c, held, `"si.Control"`, "ID", `public."si.Serial"`)
		serialIdentityControlPhase(t, p, b, c, held)
		serialIdentityRun(t, p, b, c, serialIdentityControlFuture()...)
	})
}
