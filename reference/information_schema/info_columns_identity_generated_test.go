package reference_test

import (
	"testing"

	"stuntgres/reference/fixture"
)

func TestReferenceInfoColumnsIdentityGenerated(t *testing.T) {
	icScenario(t, func(c *icCase) {
		c.exec("CREATE TABLE ic_scope.ident(a integer GENERATED BY DEFAULT AS IDENTITY(START WITH 10 INCREMENT BY 2 MINVALUE 2 MAXVALUE 100 CYCLE),b bigint GENERATED ALWAYS AS IDENTITY(START WITH 20 INCREMENT BY 3 MINVALUE 5 MAXVALUE 200 NO CYCLE),s serial,o integer DEFAULT 7)")
		a := icPatch(c.integer("ident", "a", 1), map[string]any{"is_nullable": "NO", "is_identity": "YES", "identity_generation": "BY DEFAULT", "identity_start": "10", "identity_increment": "2", "identity_maximum": "100", "identity_minimum": "2", "identity_cycle": "YES"})
		b := c.row("ident", "b", 2, "bigint", "int8", map[string]any{"numeric_precision": int64(64), "numeric_precision_radix": int64(2), "numeric_scale": int64(0), "is_nullable": "NO", "is_identity": "YES", "identity_generation": "ALWAYS", "identity_start": "20", "identity_increment": "3", "identity_maximum": "200", "identity_minimum": "5", "identity_cycle": "NO"})
		s := icPatch(c.integer("ident", "s", 3), map[string]any{"is_nullable": "NO", "column_default": "nextval('ic_scope.ident_s_seq'::regclass)"})
		o := icPatch(c.integer("ident", "o", 4), map[string]any{"column_default": "7"})
		held := c.hold(icProjection(c.b.PG, "table_schema='ic_scope' AND table_name='ident'", nil).Query)
		check := func() {
			step := icProjection(c.b.PG, "table_schema='ic_scope' AND table_name='ident'", [][]any{a, b, s, o})
			c.run(c.conn, step)
			c.run(c.conn, fixture.Prepared(step))
			c.run(held, step)
		}
		check()
		c.exec("ALTER TABLE ic_scope.ident ALTER COLUMN a SET GENERATED ALWAYS", "ALTER TABLE ic_scope.ident ALTER COLUMN a SET START WITH 12 SET INCREMENT BY 4 SET MINVALUE 4 SET MAXVALUE 120 SET NO CYCLE")
		a = icPatch(a, map[string]any{"identity_generation": "ALWAYS", "identity_start": "12", "identity_increment": "4", "identity_maximum": "120", "identity_minimum": "4", "identity_cycle": "NO"})
		check()
		c.run(c.conn, fixture.Select("SELECT nextval('ic_scope.ident_a_seq') AS n", []string{"n"}, []string{"INT8"}, [][]any{{int64(10)}}))
		check()
		c.run(c.conn, fixture.Select("SELECT nextval('ic_scope.ident_a_seq') AS n", []string{"n"}, []string{"INT8"}, [][]any{{int64(14)}}))
		c.exec("CREATE ROLE ic_reader", "GRANT SELECT(a) ON ic_scope.ident TO ic_reader", "REVOKE ALL ON SEQUENCE ic_scope.ident_a_seq FROM PUBLIC,ic_reader", "SET ROLE ic_reader")
		c.check("ident", a)
		c.exec("RESET ROLE")
		c.exec("CREATE SEQUENCE ic_scope.counter START WITH 40", "CREATE TABLE ic_scope.gen(a integer,b integer GENERATED ALWAYS AS (a + 1) STORED,c integer GENERATED ALWAYS AS (a * 2) VIRTUAL,d integer DEFAULT (1 / 0),e bigint DEFAULT nextval('ic_scope.counter'))")
		ga := c.integer("gen", "a", 1)
		gb := icPatch(c.integer("gen", "b", 2), map[string]any{"is_generated": "ALWAYS", "generation_expression": "(a + 1)"})
		gc := icPatch(c.integer("gen", "c", 3), map[string]any{"is_generated": "ALWAYS", "generation_expression": "(a * 2)"})
		gd := icPatch(c.integer("gen", "d", 4), map[string]any{"column_default": "(1 / 0)"})
		ge := c.row("gen", "e", 5, "bigint", "int8", map[string]any{"numeric_precision": int64(64), "numeric_precision_radix": int64(2), "numeric_scale": int64(0), "column_default": "nextval('ic_scope.counter'::regclass)"})
		c.run(c.conn, fixture.Select("SELECT nextval('ic_scope.counter') AS n", []string{"n"}, []string{"INT8"}, [][]any{{int64(40)}}))
		c.check("gen", ga, gb, gc, gd, ge)
		c.run(c.conn, fixture.Select("SELECT nextval('ic_scope.counter') AS n", []string{"n"}, []string{"INT8"}, [][]any{{int64(41)}}))
		c.exec("ALTER TABLE ic_scope.gen ALTER COLUMN b SET EXPRESSION AS (a + 3)")
		gb = icPatch(gb, map[string]any{"generation_expression": "(a + 3)"})
		c.check("gen", ga, gb, gc, gd, ge)
		c.exec("ALTER TABLE ic_scope.gen RENAME COLUMN a TO \"Odd Name\"")
		ga = icPatch(ga, map[string]any{"column_name": "Odd Name"})
		gb = icPatch(gb, map[string]any{"generation_expression": "(\"Odd Name\" + 3)"})
		gc = icPatch(gc, map[string]any{"generation_expression": "(\"Odd Name\" * 2)"})
		c.check("gen", ga, gb, gc, gd, ge)
		c.exec("SET search_path TO ic_scope,pg_catalog")
		s = icPatch(s, map[string]any{"column_default": "nextval('ident_s_seq'::regclass)"})
		check()
		ge = icPatch(ge, map[string]any{"column_default": "nextval('counter'::regclass)"})
		c.check("gen", ga, gb, gc, gd, ge)
		c.exec("RESET search_path")
	})
}
