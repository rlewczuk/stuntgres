// A separate destination and actual emitted-SQL replay use the same independent
// steps as the primary driver. No equality-only or dump-substring oracle.
func serialIdentityConsumeSteps(t *testing.T, p *referencePair, x referenceExecutor, pg bool, steps []referenceStep) {
	t.Helper()
	stmt, err := x.PrepareContext(p.ctx, serialIdentityQuery)
	if err != nil { t.Fatal(err) }
	defer stmt.Close()
	held := referenceHeldStatement{referenceExecutor: x, statement: stmt, query: serialIdentityQuery}
	for _, s := range steps {
		if s.selectRows {
			rows, err := x.QueryContext(p.ctx, s.query, s.args...)
			if rows != nil && s.checkMetadata != nil { s.checkMetadata(t, rows) }
			deleteReferenceConsume(t, pg, rows, err, s)
			if s.query == serialIdentityQuery {
				rows, err := held.QueryContext(p.ctx, s.query, s.args...)
				if rows != nil && s.checkMetadata != nil { s.checkMetadata(t, rows) }
				deleteReferenceConsume(t, pg, rows, err, s)
			}
		} else {
			result, err := x.ExecContext(p.ctx, s.query, s.args...)
			if s.diagnostic != nil {
				if result != nil { t.Fatal("failed replay write exposed result") }
				referenceCheckDiagnostic(t, err, s, "execute")
				continue
			}
			if err != nil { t.Fatal(err) }
			if n, err := result.RowsAffected(); err != nil || n != s.affected { t.Fatal("affected", n, err, s.affected) }
		}
	}
}

func serialIdentityControlPhase(t *testing.T, p *referencePair, b referenceBackend, c *sql.Conn, held referenceHeldStatement) {
	t.Helper()
	if b.pg { return } // Native API phase, not a discovery bypass.
	var before, after bytes.Buffer
	if err := stuntgres.Dump(p.ctx, p.native, &before); err != nil { t.Fatal(err) }
	for _, s := range serialIdentityControlSteps(false) { serialIdentityRun(t, p, b, held, s) }
	if err := stuntgres.Dump(p.ctx, p.native, &after); err != nil { t.Fatal(err) }
	if !bytes.Equal(before.Bytes(), after.Bytes()) { t.Fatal("inquiry changed dump/state") }
	// Retain actual driver-owned values and descriptors across replacement.
	rows, err := held.statement.QueryContext(p.ctx, `"si.Control"`, "ID")
	if err != nil { t.Fatal(err) }
	types, err := rows.ColumnTypes()
	if err != nil { rows.Close(); t.Fatal(err) }
	if !rows.Next() { rows.Close(); t.Fatal("retained row missing") }
	var value string
	if err := rows.Scan(&value); err != nil { rows.Close(); t.Fatal(err) }
	if rows.Next() || rows.Err() != nil { rows.Close(); t.Fatal("retained cardinality", rows.Err()) }
	if err := rows.Close(); err != nil { t.Fatal(err) }
	if err := stuntgres.Reset(p.ctx, p.native); err != nil { t.Fatal(err) }
	if err := stuntgres.Restore(p.ctx, p.native, bytes.NewReader(before.Bytes())); err != nil { t.Fatal(err) }
	for _, s := range serialIdentityControlSteps(false) {
		serialIdentityRun(t, p, b, c, s)
		if s.query == serialIdentityQuery { serialIdentityRun(t, p, b, held, s) }
	}
	if value != `public."si.Serial"` || len(types) != 1 || types[0].DatabaseTypeName() != "TEXT" || types[0].Name() != "pg_get_serial_sequence" { t.Fatal("retained inquiry changed", value, types) }
	other := updateReturningNativeDestination(t)
	if _, err := other.ExecContext(p.ctx, `CREATE TEMP SEQUENCE si_control_address_shift`); err != nil { t.Fatal(err) }
	if err := stuntgres.Restore(p.ctx, other, bytes.NewReader(before.Bytes())); err != nil { t.Fatal(err) }
	serialIdentityConsumeSteps(t, p, other, false, append(serialIdentityControlSteps(false), serialIdentityControlFuture()...))
	if p.postgres != nil {
		pg, err := p.postgres.Conn(p.ctx)
		if err != nil { t.Fatal(err) }
		defer pg.Close()
		if _, err := pg.ExecContext(p.ctx, `DROP SCHEMA public CASCADE; CREATE SCHEMA public`); err != nil { t.Fatal(err) }
		defer func() { if _, err := pg.ExecContext(p.ctx, `RESET SESSION AUTHORIZATION; DROP SCHEMA public CASCADE; CREATE SCHEMA public`); err != nil { t.Error(err) } }()
		if _, err := pg.ExecContext(p.ctx, before.String()); err != nil { t.Fatal("PostgreSQL emitted-SQL replay", err) }
		if _, err := pg.ExecContext(p.ctx, `RESET SESSION AUTHORIZATION`); err != nil { t.Fatal(err) }
		serialIdentityConsumeSteps(t, p, pg, true, append(serialIdentityControlSteps(true), serialIdentityControlFuture()...))
	}
}

func TestReferenceSerialIdentityControls(t *testing.T) {
	serialIdentityScenario(t, func(t *testing.T, p *referencePair, b referenceBackend, c *sql.Conn) {
		serialIdentityControlSeed(t, p, b, c)
		held := serialIdentityHeld(t, p, b, c)
		for _, s := range serialIdentityControlSteps(b.pg) {
			serialIdentityRun(t, p, b, c, s)
			if s.query == serialIdentityQuery { serialIdentityRun(t, p, b, held, s) }
		}
		serialIdentityControlPhase(t, p, b, c, held)
		serialIdentityRun(t, p, b, c, serialIdentityControlFuture()...)
	})
}

func TestReferenceSerialIdentityFeatureSmoke(t *testing.T) {
	serialIdentityScenario(t, func(t *testing.T, p *referencePair, b referenceBackend, c *sql.Conn) {
		serialIdentityControlSeed(t, p, b, c)
		held := serialIdentityHeld(t, p, b, c)
		for _, s := range serialIdentityControlSteps(b.pg) { serialIdentityRun(t, p, b, held, s) }
		serialIdentityCheck(t, p, b, c, held, `public."si.Control"`, "ID", `public."si.Serial"`)
		serialIdentityCheck(t, p, b, c, held, `"si.Control"`, "tableoid", nil)
		systemMissing := controlsReferenceDiagnostic("42703", `column "tableoid" of relation "si_control_view" does not exist`)
		systemDirect := referenceErrorDiagnostic(`SELECT pg_get_serial_sequence('si_control_view','tableoid')`, systemMissing)
		systemDirect.selectRows, systemDirect.errorStage = true, "execute"
		serialIdentityRun(t, p, b, c, systemDirect)
		systemHeld := referenceErrorDiagnostic(serialIdentityQuery, systemMissing, "si_control_view", "tableoid")
		systemHeld.selectRows, systemHeld.errorStage = true, "execute"
		serialIdentityRun(t, p, b, held, systemHeld)
		serialIdentityCheck(t, p, b, c, held, `"si.Control"`, "ID", `public."si.Serial"`)
		serialIdentityRun(t, p, b, c, referenceExec(`ALTER SEQUENCE "si.Manual" OWNED BY NONE`, 0))
		serialIdentityCheck(t, p, b, c, held, `"si.Control"`, "manual", nil)
		serialIdentityRun(t, p, b, c, referenceExec(`ALTER SEQUENCE "si.Manual" OWNED BY "si.Control".manual`, 0))
		serialIdentityCheck(t, p, b, c, held, `"si.Control"`, "manual", `public."si.Manual"`)
		s := referenceErrorDiagnostic(`SELECT pg_get_serial_sequence(1,'ID')`, serialIdentityMissingFunction("pg_get_serial_sequence(integer, unknown)", 8))
		s.selectRows, s.prepared, s.errorStage = true, true, "prepare"
		serialIdentityRun(t, p, b, c, s)
		w := controlsReferenceDiagnostic("42703", `column "missing" of relation "si.Control" does not exist`)
		s = referenceErrorDiagnostic(serialIdentityQuery, w, `"si.Control"`, "missing")
		s.selectRows, s.errorStage = true, "execute"
		serialIdentityRun(t, p, b, held, s)
		serialIdentityCheck(t, p, b, c, held, `"si.Control"`, "ID", `public."si.Serial"`)
		serialIdentityControlPhase(t, p, b, c, held)
		serialIdentityRun(t, p, b, c, serialIdentityControlFuture()...)
	})
}
