package reference_test

import (
	"database/sql"
	"testing"
)

func TestReferenceAlterIdentityTransactionalAtomicity(t *testing.T) {
	for _, prepared := range []bool{false, true} {
		alterIdentityScenario(t, func(t *testing.T, p *referencePair, b referenceBackend, c *sql.Conn) {
			run := func(s referenceStep) { referenceRunStep(t, p.ctx, c, b.recorder, s) }
			defer c.ExecContext(p.ctx, `ROLLBACK`)
			run(referenceExec(`CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY(CACHE 1),other INT NOT NULL)`, 0))
			run(referenceExec(`INSERT INTO i VALUES(DEFAULT,7)`, 1))
			held := identityHeld(t, p.ctx, c, `INSERT INTO i VALUES(DEFAULT,7)`)
			for _, q := range []string{
				`ALTER TABLE i ALTER id SET GENERATED BY DEFAULT RESTART WITH 100, ALTER other SET GENERATED ALWAYS`,
				`ALTER TABLE i ALTER id DROP IDENTITY, ALTER other SET GENERATED ALWAYS`,
			} {
				before := ""
				if !b.pg {
					before = referenceDDLNativeDump(t, p)
				}
				s := referenceImplicitError(q, referenceDiagnostic{Code: "55000", Message: `column "other" of relation "i" is not an identity column`})
				s.prepared = prepared
				run(s)
				if !b.pg && before != referenceDDLNativeDump(t, p) {
					t.Fatal("late action published partial state")
				}
				run(referenceSelect(`SELECT * FROM i`, []string{"id", "other"}, []string{"INT4", "INT4"}, [][]any{{int64(1), int64(7)}}))
				run(referenceSelect(`SELECT last_value,is_called FROM i_id_seq`, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(1), true}}))
				run(referenceImplicitError(`INSERT INTO i VALUES(99,7)`, identityAlwaysDiagnostic()))
			}
			referenceRunStep(t, p.ctx, held, b.recorder, referenceExec(held.query, 1))
			run(referenceSelect(`SELECT * FROM i ORDER BY id`, []string{"id", "other"}, []string{"INT4", "INT4"}, [][]any{{int64(1), int64(7)}, {int64(2), int64(7)}}))
			// First-action-alone controls establish that the failing action is genuinely later.
			for _, q := range []string{`BEGIN`, `ALTER TABLE i ALTER id SET GENERATED BY DEFAULT RESTART 100`, `ROLLBACK`, `BEGIN`, `ALTER TABLE i ALTER id DROP IDENTITY`, `ROLLBACK`} {
				run(referenceExec(q, 0))
			}
			run(referenceExec(`CREATE TABLE a(id INT NOT NULL)`, 0))
			run(referenceExec(`INSERT INTO a VALUES(40)`, 1))
			before := ""
			if !b.pg {
				before = referenceDDLNativeDump(t, p)
			}
			s := referenceImplicitError(`ALTER TABLE a ALTER id ADD GENERATED ALWAYS AS IDENTITY, ALTER id SET CACHE 0`, referenceDiagnostic{Code: "22023", Message: "CACHE (0) must be greater than zero"})
			s.prepared = prepared
			run(s)
			if !b.pg && before != referenceDDLNativeDump(t, p) {
				t.Fatal("failed ADD published sequence")
			}
			alterIdentityMissing(t, p, b, c, "a_id_seq")
			for _, q := range []string{`BEGIN`, `ALTER TABLE a ALTER id ADD GENERATED ALWAYS AS IDENTITY`} {
				run(referenceExec(q, 0))
			}
			if !b.pg && before != referenceDDLNativeDump(t, p) {
				t.Fatal("Dump included private ADD")
			}
			run(referenceExec(`ROLLBACK`, 0))
			alterIdentityMissing(t, p, b, c, "a_id_seq")
			run(referenceImplicitError(`INSERT INTO a DEFAULT VALUES`, referenceDiagnostic{Code: "23502", Message: `null value in column "id" of relation "a" violates not-null constraint`, Detail: "Failing row contains (null).", Schema: "public", Table: "a", Column: "id"}))
			for _, q := range []string{`BEGIN`, `ALTER TABLE a ALTER id ADD GENERATED ALWAYS AS IDENTITY`, `COMMIT`} {
				run(referenceExec(q, 0))
			}
			peer := identityConnection(t, p.ctx, b.db)
			referenceRunStep(t, p.ctx, peer, b.recorder, referenceExec(`INSERT INTO a DEFAULT VALUES`, 1))
			run(referenceSelect(`SELECT * FROM a ORDER BY id`, []string{"id"}, []string{"INT4"}, [][]any{{int64(1)}, {int64(40)}}))
			for _, q := range []string{`BEGIN`, `ALTER TABLE i ALTER id SET GENERATED BY DEFAULT`, `ROLLBACK`} {
				run(referenceExec(q, 0))
			}
			run(referenceImplicitError(`INSERT INTO i VALUES(99,7)`, identityAlwaysDiagnostic()))
			for _, q := range []string{`BEGIN`, `ALTER TABLE i ALTER id RESTART 100`} {
				run(referenceExec(q, 0))
			}
			privateBaseline := ""
			if !b.pg {
				privateBaseline = referenceDDLNativeDump(t, p)
			}
			referenceRunStep(t, p.ctx, held, b.recorder, referenceExec(held.query, 1))
			if !b.pg && privateBaseline != referenceDDLNativeDump(t, p) {
				t.Fatal("Dump included private restart or row")
			}
			run(referenceExec(`ROLLBACK`, 0))
			// Private generator rollback does not erase physical-session sequence memories.
			run(referenceSelect(`SELECT currval('i_id_seq'),lastval()`, []string{"currval", "lastval"}, []string{"INT8", "INT8"}, [][]any{{int64(100), int64(100)}}))
			for _, q := range []string{`BEGIN`, `SAVEPOINT s`, `ALTER TABLE i ALTER id SET GENERATED BY DEFAULT SET INCREMENT 3 SET START 20 RESTART 20`} {
				run(referenceExec(q, 0))
			}
			referenceRunStep(t, p.ctx, held, b.recorder, referenceExec(held.query, 1))
			for _, q := range []string{`ROLLBACK TO s`, `RELEASE s`, `COMMIT`} {
				run(referenceExec(q, 0))
			}
			run(referenceImplicitError(`INSERT INTO i VALUES(99,7)`, identityAlwaysDiagnostic()))
			run(referenceSelect(`SELECT last_value,is_called FROM i_id_seq`, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{int64(2), true}}))
			referenceRunStep(t, p.ctx, held, b.recorder, referenceExec(held.query, 1))
			run(referenceSelect(`SELECT * FROM i ORDER BY id`, []string{"id", "other"}, []string{"INT4", "INT4"}, [][]any{{int64(1), int64(7)}, {int64(2), int64(7)}, {int64(3), int64(7)}}))
			for _, q := range []string{`BEGIN`, `ALTER TABLE i ALTER id SET GENERATED BY DEFAULT`, `COMMIT`} {
				run(referenceExec(q, 0))
			}
			referenceRunStep(t, p.ctx, peer, b.recorder, referenceExec(`INSERT INTO i VALUES(99,7)`, 1))
		})
	}
}
