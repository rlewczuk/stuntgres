func TestReferenceSerialDeclarations(t *testing.T) {
	for _, tc := range []struct{ query, message, token string }{
		{`CREATE TABLE bad(id SERIAL NULL)`, `conflicting NULL/NOT NULL declarations for column "id" of table "bad"`, "NULL"},
		{`CREATE TABLE bad(id SERIAL DEFAULT 7)`, `multiple default values specified for column "id" of table "bad"`, ""},
		{`CREATE TABLE bad(id SERIAL GENERATED BY DEFAULT AS IDENTITY)`, `both default and identity specified for column "id" of table "bad"`, ""},
		{`CREATE TABLE bad(id SERIAL(2))`, `type modifier is not allowed for type "integer"`, "SERIAL"},
	} {
		t.Run(tc.query, func(t *testing.T) {
			serialReferenceStreams(t, false, func(bool) []referenceStep {
				position := ""
				if tc.token != "" {
					position = fmt.Sprint(strings.Index(tc.query, tc.token) + 1)
				}
				failure := referenceImplicitError(tc.query, referenceDiagnostic{Code: "42601", Message: tc.message, Position: position})
				failure.errorStage = "execute"
				return []referenceStep{failure, referenceExec(`CREATE TABLE bad(id SERIAL)`, 0), referenceExec(`INSERT INTO bad DEFAULT VALUES`, 1), referenceSelect(`SELECT * FROM bad`, []string{"id"}, []string{"INT4"}, [][]any{{int64(1)}}), referenceExec(`DROP TABLE bad RESTRICT`, 0), referenceExec(`CREATE SEQUENCE bad_id_seq`, 0)}
			})
		})
	}
}

func TestReferenceSerialCascadeNotice(t *testing.T) {
	p := newReferenceScenario(t)
	for _, backend := range p.backends() {
		postgres := backend.pg
		t.Run(backend.name, func(t *testing.T) {
			var notices []referenceDiagnostic
			_, conn, record := noticeReferencePool(t, p, postgres, &notices)
			for _, step := range []referenceStep{referenceExec(`CREATE TABLE dep(id SERIAL)`, 0), referenceExec(`DROP SEQUENCE dep_id_seq CASCADE`, 0)} {
				referenceRunStep(t, p.ctx, conn, record, step)
			}
			want := []referenceDiagnostic{{Severity: "NOTICE", SeverityUnlocalized: "NOTICE", Code: "00000", Message: `drop cascades to default value for column id of table dep`}}
			if !reflect.DeepEqual(notices, want) {
				t.Fatalf("notice got %#v want %#v", notices, want)
			}
		})
	}
}
