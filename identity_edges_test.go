func identityState(t *testing.T,err error,code string){t.Helper();var state interface{SQLState()string};if !errors.As(err,&state)||state.SQLState()!=code{t.Fatalf("error=%v want=%s",err,code)}}

func TestIdentityDeclarationAtomicNamesAndLike(t *testing.T){
	db:=openLocal(t,stuntgres.NewDriver(),t.Name())
	tableCoreExec(t,db,false,`CREATE SEQUENCE i_id_seq`,0)
	tableCoreExec(t,db,false,`CREATE TABLE i(id pg_catalog.int4 GENERATED ALWAYS AS IDENTITY,other BIGINT GENERATED BY DEFAULT AS IDENTITY(SEQUENCE NAME public."Quoted Seq" OWNED BY NONE))`,0)
	tableCoreExec(t,db,false,`INSERT INTO i DEFAULT VALUES`,1)
	wantTuples(t,db,`SELECT * FROM i`,[][]any{{int64(1),int64(1)}})
	wantTuples(t,db,`SELECT last_value,is_called FROM i_id_seq1`,[][]any{{int64(1),true}})
	tableCoreExec(t,db,false,`CREATE TABLE clone(LIKE i)`,0)
	_,err:=db.Exec(`INSERT INTO clone DEFAULT VALUES`);identityState(t,err,"23502")
	for _,q:=range []string{`CREATE TABLE bad(id INT GENERATED ALWAYS AS IDENTITY DEFAULT 4)`,`CREATE TABLE bad(id INT DEFAULT 4 GENERATED ALWAYS AS IDENTITY)`,`CREATE TABLE bad(id INT NULL GENERATED ALWAYS AS IDENTITY)`,`CREATE TABLE bad(id INT GENERATED ALWAYS AS IDENTITY GENERATED BY DEFAULT AS IDENTITY)`,`CREATE TABLE bad(id INT GENERATED ALWAYS AS IDENTITY(CACHE 0))`}{
		_,err:=db.Exec(q);if err==nil{t.Fatal("invalid declaration accepted",q)}
		_,err=db.Query(`SELECT * FROM bad`);identityState(t,err,"42P01")
		_,err=db.Query(`SELECT * FROM bad_id_seq`);identityState(t,err,"42P01")
	}
	tableCoreExec(t,db,false,`CREATE SCHEMA nested CREATE TABLE n(id INT GENERATED ALWAYS AS IDENTITY)`,0)
	tableCoreExec(t,db,false,`INSERT INTO nested.n DEFAULT VALUES`,1)
	wantTuples(t,db,`SELECT * FROM nested.n`,[][]any{{int64(1)}})
}

func TestIdentityAlterPassesAndFailureAtomicity(t *testing.T){
	db:=openLocal(t,stuntgres.NewDriver(),t.Name())
	tableCoreExec(t,db,false,`CREATE TABLE a(id INT)`,0);tableCoreExec(t,db,false,`INSERT INTO a VALUES(40)`,1)
	tableCoreExec(t,db,false,`ALTER TABLE a ALTER id ADD GENERATED ALWAYS AS IDENTITY, ALTER id SET NOT NULL`,0)
	tableCoreExec(t,db,false,`INSERT INTO a DEFAULT VALUES`,1)
	_,err:=db.Exec(`ALTER TABLE a ALTER id SET GENERATED BY DEFAULT, ALTER missing SET NOT NULL`);identityState(t,err,"42703")
	_,err=db.Exec(`INSERT INTO a VALUES(99)`);identityState(t,err,"428C9")
	_,err=db.Exec(`ALTER TABLE a ALTER id RESTART WITH 100, ALTER id SET CACHE 0`);identityState(t,err,"22023")
	tableCoreExec(t,db,false,`INSERT INTO a DEFAULT VALUES`,1)
	wantTuples(t,db,`SELECT * FROM a ORDER BY id`,[][]any{{int64(1)},{int64(2)},{int64(40)}})
	tableCoreExec(t,db,false,`ALTER TABLE a ALTER id DROP IDENTITY`,0)
	tableCoreExec(t,db,false,`ALTER TABLE a ALTER id ADD GENERATED BY DEFAULT AS IDENTITY`,0)
	tableCoreExec(t,db,false,`INSERT INTO a DEFAULT VALUES`,1)
	wantTuples(t,db,`SELECT * FROM a ORDER BY id`,[][]any{{int64(1)},{int64(1)},{int64(2)},{int64(40)}})
}

