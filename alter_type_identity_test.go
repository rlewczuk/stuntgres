func TestAlterTypeIdentityPrivateSavepoints(t *testing.T) {
	for _, cache := range []int{1, 5} {
		for _, commit := range []bool{false, true} {
			t.Run(fmt.Sprint(cache, commit), func(t *testing.T) {
				db := openLocal(t, stuntgres.NewDriver(), t.Name())
				c, err := db.Conn(t.Context())
				if err != nil {
					t.Fatal(err)
				}
				defer c.Close()
				for _, q := range []string{fmt.Sprintf("CREATE TABLE t(c INT GENERATED BY DEFAULT AS IDENTITY(CACHE %d))", cache), "INSERT INTO t DEFAULT VALUES", "BEGIN", "SAVEPOINT before_type", "ALTER TABLE t ALTER c TYPE BIGINT", "SAVEPOINT after_type", "INSERT INTO t DEFAULT VALUES"} {
					if _, err = c.ExecContext(t.Context(), q); err != nil {
						t.Fatal(q, err)
					}
				}
				next := int64(2)
				last := int64(1)
				if cache == 5 {
					next = 6
					last = 5
				}
				for _, q := range []string{"ROLLBACK TO before_type", "ROLLBACK TO before_type"} {
					if _, err = c.ExecContext(t.Context(), q); err != nil {
						t.Fatal(err)
					}
				}
				alterTypePublicRows(t, alterTypeIdentityConnection{c, t.Context()}, "SELECT c FROM t", []string{"c"}, []string{"INT4"}, [][]any{{int64(1)}})
				var n int64
				if err = c.QueryRowContext(t.Context(), "SELECT last_value FROM t_c_seq").Scan(&n); err != nil || n != last {
					t.Fatal(n, last, err)
				}
				if err = c.QueryRowContext(t.Context(), "SELECT currval('t_c_seq')").Scan(&n); err != nil || n != next {
					t.Fatal("physical currval lost", n, next, err)
				}
				for _, q := range []string{"ALTER TABLE t ALTER c TYPE BIGINT", "SAVEPOINT type_again", "ALTER TABLE t ALTER c TYPE SMALLINT", "ROLLBACK TO type_again", "INSERT INTO t DEFAULT VALUES"} {
					if _, err = c.ExecContext(t.Context(), q); err != nil {
						t.Fatal(q, err)
					}
				}
				action := "ROLLBACK"
				if commit {
					action = "COMMIT"
				}
				if _, err = c.ExecContext(t.Context(), action); err != nil {
					t.Fatal(err)
				}
				if commit {
					alterTypePublicRows(t, alterTypeIdentityConnection{c, t.Context()}, "SELECT c FROM t ORDER BY c", []string{"c"}, []string{"INT8"}, [][]any{{int64(1)}, {next}})
				} else {
					alterTypePublicRows(t, alterTypeIdentityConnection{c, t.Context()}, "SELECT c FROM t", []string{"c"}, []string{"INT4"}, [][]any{{int64(1)}})
				}
			})
		}
	}
}

func TestAlterTypeIdentityControls(t *testing.T) {
	db := openLocal(t, stuntgres.NewDriver(), t.Name())
	db.SetMaxOpenConns(1)
	for _, q := range []string{"CREATE TABLE t(c INT CONSTRAINT nn GENERATED ALWAYS AS IDENTITY(START 7 INCREMENT 3 CACHE 2) CONSTRAINT ck CHECK(c>0),p INT DEFAULT 4)", "COMMENT ON COLUMN t.c IS 'identity column'", "COMMENT ON SEQUENCE t_c_seq IS 'identity sequence'", "INSERT INTO t DEFAULT VALUES", "ALTER TABLE t ALTER c TYPE BIGINT"} {
		execSQL(t, db, q)
	}
	var dump bytes.Buffer
	if err := stuntgres.Dump(t.Context(), db, &dump); err != nil {
		t.Fatal(err)
	}
	for _, text := range []string{"BIGINT", "GENERATED ALWAYS AS IDENTITY", "CACHE 2", "nn", "ck", "identity column", "identity sequence"} {
		if !strings.Contains(dump.String(), text) {
			t.Fatal(text, dump.String())
		}
	}
	if strings.Contains(dump.String(), "ALTER TABLE") || strings.Contains(dump.String(), "CREATE SEQUENCE") {
		t.Fatal("identity TYPE history or duplicate sequence", dump.String())
	}
	if err := stuntgres.Reset(t.Context(), db); err != nil {
		t.Fatal(err)
	}
	if err := stuntgres.Restore(t.Context(), db, bytes.NewReader(dump.Bytes())); err != nil {
		t.Fatal(err)
	}
	var again bytes.Buffer
	if err := stuntgres.Dump(t.Context(), db, &again); err != nil || again.String() != dump.String() {
		t.Fatal(err, again.String(), dump.String())
	}
	execSQL(t, db, "INSERT INTO t DEFAULT VALUES")
	alterTypePublicRows(t, db, "SELECT * FROM t ORDER BY c", []string{"c", "p"}, []string{"INT8", "INT4"}, [][]any{{int64(7), int64(4)}, {int64(13), int64(4)}})
	_, err := db.Exec("INSERT INTO t VALUES(99,4)")
	notNullDiagnostic(t, err, stuntgres.Error{Code: "428C9", Message: `cannot insert a non-DEFAULT value into column "c"`, Detail: `Column "c" is an identity column defined as GENERATED ALWAYS.`, Hint: "Use OVERRIDING SYSTEM VALUE to override."})
	_, err = db.Exec("INSERT INTO t OVERRIDING SYSTEM VALUE VALUES(-1,4)")
	notNullDiagnostic(t, err, stuntgres.Error{Code: "23514", Message: `new row for relation "t" violates check constraint "ck"`, Detail: "Failing row contains (-1, 4).", Schema: "public", Table: "t", Constraint: "ck"})
	alterTypePublicRows(t, db, "SELECT setval('t_c_seq',2147483647,true)", []string{"setval"}, []string{"INT8"}, [][]any{{int64(2147483647)}})
	execSQL(t, db, "INSERT INTO t DEFAULT VALUES")
	alterTypePublicRows(t, db, "SELECT c FROM t WHERE c=2147483650", []string{"c"}, []string{"INT8"}, [][]any{{int64(2147483650)}})
}

