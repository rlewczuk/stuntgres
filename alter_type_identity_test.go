// Adapt the existing metadata/row fixture to a fixed physical session.
type alterTypeIdentityConnection struct {
	*sql.Conn
	ctx context.Context
}

func (c alterTypeIdentityConnection) Query(q string, args ...any) (*sql.Rows, error) {
	return c.QueryContext(c.ctx, q, args...)
}

func alterTypeIdentityUtility(t *testing.T, c *sql.Conn, q string, prepared bool) error {
	t.Helper()
	var result sql.Result
	var err error
	if prepared {
		s, e := c.PrepareContext(t.Context(), q)
		if e != nil {
			t.Fatal("effect-free native utility Prepare", q, e)
		}
		defer s.Close()
		result, err = s.ExecContext(t.Context())
	} else {
		result, err = c.ExecContext(t.Context(), q)
	}
	if err == nil {
		count, e := result.RowsAffected()
		if e != nil || count != 0 {
			t.Fatal(q, count, e)
		}
	}
	return err
}

func TestAlterTypeIdentityTargets(t *testing.T) {
	for _, prepared := range []bool{false, true} {
		for _, tc := range []struct {
			name, decl, target, typ       string
			seed, next, bound, afterBound int64
		}{
			{"widen", "INT GENERATED BY DEFAULT AS IDENTITY", "BIGINT", "INT8", 1, 2, 2147483647, 2147483648},
			{"always", "INT GENERATED ALWAYS AS IDENTITY", "INT8", "INT8", 1, 2, 2147483647, 2147483648},
			{"narrow", "BIGINT GENERATED BY DEFAULT AS IDENTITY", "SMALLINT", "INT2", 1, 2, 0, 0},
			{"custom", "BIGINT GENERATED BY DEFAULT AS IDENTITY(MINVALUE 1 MAXVALUE 100 START 1)", "INT2", "INT2", 1, 2, 0, 0},
			{"descending", "INT GENERATED BY DEFAULT AS IDENTITY(INCREMENT -1)", "BIGINT", "INT8", -1, -2, -2147483648, -2147483649},
			{"options", "INT GENERATED BY DEFAULT AS IDENTITY(MINVALUE -100 MAXVALUE 100 START 7 INCREMENT 3 CACHE 1 CYCLE)", "BIGINT", "INT8", 7, 10, 0, 0},
		} {
			t.Run(tc.name+fmt.Sprint(prepared), func(t *testing.T) {
				db := openLocal(t, stuntgres.NewDriver(), t.Name())
				c, err := db.Conn(t.Context())
				if err != nil {
					t.Fatal(err)
				}
				defer c.Close()
				for _, q := range []string{"CREATE TABLE t(c " + tc.decl + ")", "INSERT INTO t DEFAULT VALUES"} {
					if _, err = c.ExecContext(t.Context(), q); err != nil {
						t.Fatal(q, err)
					}
				}
				held, err := c.PrepareContext(t.Context(), "INSERT INTO t DEFAULT VALUES")
				if err != nil {
					t.Fatal(err)
				}
				defer held.Close()
				heldSelect, err := c.PrepareContext(t.Context(), "SELECT c FROM t")
				if err != nil {
					t.Fatal(err)
				}
				defer heldSelect.Close()
				old, err := c.QueryContext(t.Context(), "SELECT c FROM t")
				if err != nil {
					t.Fatal(err)
				}
				if err = alterTypeIdentityUtility(t, c, "ALTER TABLE t ALTER c TYPE "+tc.target, prepared); err != nil {
					t.Fatal(err)
				}
				changed, err := heldSelect.QueryContext(t.Context())
				if changed != nil {
					changed.Close()
				}
				notNullDiagnostic(t, err, stuntgres.Error{Code: "0A000", Message: "cached plan must not change result type"})
				if _, err = held.ExecContext(t.Context()); err != nil {
					t.Fatal(err)
				}
				alterTypePublicRows(t, alterTypeIdentityConnection{c, t.Context()}, "SELECT c FROM t ORDER BY c", []string{"c"}, []string{tc.typ}, func() [][]any {
					if tc.seed < tc.next {
						return [][]any{{tc.seed}, {tc.next}}
					}
					return [][]any{{tc.next}, {tc.seed}}
				}())
				sourceType := "INT4"
				if strings.HasPrefix(tc.decl, "BIGINT") {
					sourceType = "INT8"
				}
				types, e := old.ColumnTypes()
				if e != nil || len(types) != 1 || types[0].DatabaseTypeName() != sourceType {
					t.Fatal("eager source metadata changed", types, e)
				}
				nullable, known := types[0].Nullable()
				if !known || nullable {
					t.Fatal("identity NOT NULL metadata lost", nullable, known)
				}
				if !old.Next() {
					t.Fatal(old.Err())
				}
				var original int64
				if err = old.Scan(&original); err != nil || original != tc.seed {
					t.Fatal(original, err)
				}
				old.Close()
				if tc.bound != 0 {
					if err = c.QueryRowContext(t.Context(), "SELECT setval('t_c_seq',$1,true)", tc.bound).Scan(new(int64)); err != nil {
						t.Fatal(err)
					}
					if _, err = held.ExecContext(t.Context()); err != nil {
						t.Fatal("old sequence bound retained", err)
					}
					alterTypePublicRows(t, alterTypeIdentityConnection{c, t.Context()}, "SELECT c FROM t WHERE c="+fmt.Sprint(tc.afterBound), []string{"c"}, []string{tc.typ}, [][]any{{tc.afterBound}})
				}
				if tc.name == "always" {
					_, err = c.ExecContext(t.Context(), "INSERT INTO t VALUES(99)")
					notNullDiagnostic(t, err, stuntgres.Error{Code: "428C9", Message: `cannot insert a non-DEFAULT value into column "c"`, Detail: `Column "c" is an identity column defined as GENERATED ALWAYS.`, Hint: "Use OVERRIDING SYSTEM VALUE to override."})
					if _, err = c.ExecContext(t.Context(), "INSERT INTO t OVERRIDING SYSTEM VALUE VALUES(99)"); err != nil {
						t.Fatal(err)
					}
					if _, err = c.ExecContext(t.Context(), "INSERT INTO t OVERRIDING USER VALUE VALUES(9999)"); err != nil {
						t.Fatal(err)
					}
					alterTypePublicRows(t, alterTypeIdentityConnection{c, t.Context()}, "SELECT c FROM t WHERE c=2147483649", []string{"c"}, []string{"INT8"}, [][]any{{int64(2147483649)}})
				}
			})
		}
	}
}

