package stuntgres_test

import (
	"bytes"
	"context"
	"errors"
	"strings"
	"stuntgres"
	"testing"
)

func TestIdentityControlsDefinitionsSnapshotsAndFailures(t *testing.T) {
	db := openLocal(t, stuntgres.NewDriver(), t.Name())
	ctx := context.Background()
	for _, q := range []string{`CREATE SCHEMA owned`, `CREATE TABLE owned.i(id INT CONSTRAINT id_nn GENERATED ALWAYS AS IDENTITY(START 7 INCREMENT 3 CACHE 2),p INT DEFAULT 4)`, `CREATE TABLE owned.u(id INT GENERATED BY DEFAULT AS IDENTITY(UNLOGGED START 9))`, `COMMENT ON TABLE owned.i IS 'identity table'`, `COMMENT ON COLUMN owned.i.id IS 'identity attribute'`, `COMMENT ON SEQUENCE owned.i_id_seq IS 'identity sequence'`, `INSERT INTO owned.i DEFAULT VALUES`, `INSERT INTO owned.i OVERRIDING SYSTEM VALUE VALUES(99,8)`, `INSERT INTO owned.u VALUES(88)`} {
		if _, err := db.Exec(q); err != nil {
			t.Fatal(q, err)
		}
	}
	old, err := db.Query(`SELECT * FROM owned.i ORDER BY id`)
	if err != nil {
		t.Fatal(err)
	}
	defer old.Close()
	held, err := db.Prepare(`INSERT INTO owned.i DEFAULT VALUES`)
	if err != nil {
		t.Fatal(err)
	}
	defer held.Close()
	var dump bytes.Buffer
	if err := stuntgres.Dump(ctx, db, &dump); err != nil {
		t.Fatal(err)
	}
	if err := stuntgres.Reset(ctx, db); err != nil {
		t.Fatal(err)
	}
	if err := stuntgres.Restore(ctx, db, bytes.NewReader(dump.Bytes())); err != nil {
		t.Fatal(err)
	}
	var redump bytes.Buffer
	if err := stuntgres.Dump(ctx, db, &redump); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(dump.Bytes(), redump.Bytes()) {
		t.Fatalf("definitions/state changed\n%s\n%s", dump.Bytes(), redump.Bytes())
	}
	if !old.Next() {
		t.Fatal(old.Err())
	}
	var id, p int64
	if err := old.Scan(&id, &p); err != nil || id != 7 || p != 4 {
		t.Fatal(id, p, err)
	}
	if !old.Next() {
		t.Fatal(old.Err())
	}
	if err := old.Scan(&id, &p); err != nil || id != 99 || p != 8 {
		t.Fatal(id, p, err)
	}
	if old.Next() || old.Err() != nil {
		t.Fatal("retained rows changed", old.Err())
	}
	old.Close()
	if _, err = held.Exec(); err != nil {
		t.Fatal(err)
	}
	tableCoreExec(t, db, false, `INSERT INTO owned.u DEFAULT VALUES`, 1)
	wantTuples(t, db, `SELECT * FROM owned.i ORDER BY id`, [][]any{{int64(7), int64(4)}, {int64(13), int64(4)}, {int64(99), int64(8)}})
	wantTuples(t, db, `SELECT * FROM owned.u ORDER BY id`, [][]any{{int64(9)}, {int64(88)}})
	for _, script := range []string{
		`CREATE TABLE replacement(id INT GENERATED BY DEFAULT AS IDENTITY); INSERT INTO replacement VALUES(9);`,
		`CREATE TABLE replacement(id INT GENERATED ALWAYS AS IDENTITY); INSERT INTO replacement OVERRIDING USER VALUE VALUES(9);`,
		`CREATE TABLE replacement(id INT GENERATED ALWAYS AS IDENTITY); ALTER SEQUENCE replacement_id_seq CACHE 0;`,
		`CREATE TABLE replacement(id INT GENERATED ALWAYS AS IDENTITY); SELECT setval('replacement_id_seq',0,true);`,
		`CREATE TABLE replacement(id INT GENERATED ALWAYS AS IDENTITY); INSERT INTO replacement OVERRIDING SYSTEM VALUE VALUES(CAST($1 AS integer));`,
	} {
		if err := stuntgres.Restore(ctx, db, strings.NewReader(script)); err == nil {
			t.Fatal("invalid generated reconstruction accepted", script)
		}
	}
	failure := errors.New("identity reader failure")
	if err := stuntgres.Restore(ctx, db, failingReader{failure}); !errors.Is(err, failure) {
		t.Fatal(err)
	}
	canceled, cancel := context.WithCancel(ctx)
	cancel()
	if err := stuntgres.Restore(canceled, db, bytes.NewReader(dump.Bytes())); !errors.Is(err, context.Canceled) {
		t.Fatal(err)
	}
	wantTuples(t, db, `SELECT * FROM owned.i ORDER BY id`, [][]any{{int64(7), int64(4)}, {int64(13), int64(4)}, {int64(99), int64(8)}})
	if _, err = held.Exec(); err != nil {
		t.Fatal(err)
	}
	wantTuples(t, db, `SELECT id FROM owned.i ORDER BY id`, [][]any{{int64(7)}, {int64(13)}, {int64(16)}, {int64(99)}})
}
