package stuntgres_test

import (
	"context"
	"stuntgres"
	"testing"
)

func TestIdentityOverrideSourceShape(t *testing.T) {
	for _, tc := range []struct {
		name, query string
		last        int64
		called      bool
		rows        [][]any
	}{
		{"single", `INSERT INTO i OVERRIDING USER VALUE VALUES(nextval('side'),10)`, 50, false, [][]any{{int64(1), int64(10)}}},
		{"multi", `INSERT INTO i OVERRIDING USER VALUE VALUES(nextval('side'),16),(nextval('side'),17)`, 51, true, [][]any{{int64(1), int64(16)}, {int64(2), int64(17)}}},
		{"select", `INSERT INTO i OVERRIDING USER VALUE SELECT nextval('side'),14`, 50, true, [][]any{{int64(1), int64(14)}}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			db := openLocal(t, stuntgres.NewDriver(), t.Name())
			c := sequenceConn(t, db)
			sequenceExec(t, c, `CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY,p INT)`)
			sequenceExec(t, c, `CREATE SEQUENCE side START 50 CACHE 1`)
			r, err := c.ExecContext(context.Background(), tc.query)
			if err != nil {
				t.Fatal(err)
			}
			if n, err := r.RowsAffected(); err != nil || n != int64(len(tc.rows)) {
				t.Fatal(n, err)
			}
			wantTuples(t, db, `SELECT * FROM i ORDER BY id`, tc.rows)
			rows, err := c.QueryContext(context.Background(), `SELECT last_value,is_called FROM side`)
			queryCoreRows(t, rows, err, []string{"last_value", "is_called"}, []string{"INT8", "BOOL"}, [][]any{{tc.last, tc.called}}, false)
		})
	}
}

func TestIdentityOverrideDiscardedParameters(t *testing.T) {
	db := openLocal(t, stuntgres.NewDriver(), t.Name())
	tableCoreExec(t, db, false, `CREATE TABLE i(id INT GENERATED BY DEFAULT AS IDENTITY)`, 0)
	stmt, err := db.Prepare(`INSERT INTO i OVERRIDING USER VALUE VALUES($1)`)
	if err != nil {
		t.Fatal(err)
	}
	defer stmt.Close()
	_, err = stmt.Exec("bad")
	typeCoreDiagnostic(t, err, stuntgres.Error{Code: "22P02", Message: `invalid input syntax for type integer: "bad"`, Context: "unnamed portal parameter $1 = '...'"})
	if _, err = stmt.Exec(99); err != nil {
		t.Fatal(err)
	}
	wantTuples(t, db, `SELECT * FROM i`, [][]any{{int64(1)}})
}
