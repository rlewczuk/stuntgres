// Package ddl is the contract every package that stages catalog changes
// shares with the engine: the statement authority, the catalog stage, OID
// and revision allocation, and the common host. Feature hosts embed Host and
// keep only their own methods.
package ddl

import (
	"context"

	"stuntgres/internal/engine/access"
	"stuntgres/internal/engine/authorization"
	"stuntgres/internal/engine/catalog"
	"stuntgres/internal/engine/ids"
	"stuntgres/internal/engine/session"
	"stuntgres/internal/parser"
	"stuntgres/internal/sqlstate"
)

// Authority is the statement authority the DDL handlers carry. It is an
// opaque value: handlers keep it by value, and a host method that changes it
// returns a new one and leaves its argument alone, so an authority changed
// inside one helper (an implicit namespace, a peer recapture) stays local to
// that helper.
type Authority interface {
	access.Environment
	DDLAuthority()
}

// Stage is the private catalog change a DDL statement writes. Create and
// Replace keep the engine stage's lifecycle checks.
type Stage interface {
	Create(catalog.Descriptor) error
	Replace(catalog.Descriptor) error
	UpdateDescriptor(catalog.Descriptor)
	Get(ids.ObjectAddress) catalog.Descriptor
	LookupName(ids.NameKey) ids.ObjectAddress
}

// Allocator hands out OIDs and definition revisions in the order asked.
type Allocator interface {
	AllocateOID() (ids.OID, error)
	Revision() (ids.DefinitionRevision, error)
}

// TypeStaging is what staging a type needs beyond the stage: its
// autogenerated array and its creation ACL.
type TypeStaging interface {
	// DisplaceAssociatedArray renames an autogenerated array that holds name
	// in namespace; false when another object holds it.
	DisplaceAssociatedArray(namespace ids.ObjectAddress, name string) (bool, error)
	AssociatedArrayName(namespace ids.ObjectAddress, name string) string
	// CreationTypeACL is the creation ACL of a type and whether it is the
	// synthetic default.
	CreationTypeACL(owner authorization.PrincipalRef, namespace ids.ObjectAddress) (authorization.ACLValue, bool)
}

// Host is what every DDL handler needs from the engine for one statement.
// Every method runs with Engine.mu held; none takes or releases it, and none
// waits on the lock manager.
type Host interface {
	Allocator

	Context() context.Context
	EmitNotice(session.NoticeLevel, sqlstate.Error)

	// AccessView returns the catalog, roles, state and owner of auth.
	AccessView(Authority) access.View
	// Recapture returns auth reading view.
	Recapture(auth Authority, view catalog.Read) Authority

	// CreationNamespace resolves the namespace an object is created in. It may
	// stage implicit namespaces; the returned authority then reads the stage.
	CreationNamespace(Authority, parser.ObjectName) (ids.ObjectRef, Authority, error)
	// ExistingCreationNamespace resolves an existing creation namespace and
	// never stages one.
	ExistingCreationNamespace(Authority, parser.ObjectName) (ids.ObjectRef, error)
	// CheckCreateIn checks CREATE on a namespace, with the trusted Restore
	// exception.
	CheckCreateIn(Authority, ids.ObjectRef) error
	// SearchNamespaces returns the namespaces a name of class searches, in
	// order. Type, conversion and operator names are supported.
	SearchNamespaces(auth Authority, name parser.ObjectName, class ids.OID) ([]ids.ObjectAddress, error)
	// LookupFunction finds the function with exactly signature on the
	// function path; nil without error when there is none.
	LookupFunction(auth Authority, name parser.ObjectName, signature catalog.ProcedureSignature) (*catalog.Procedure, error)
	// DependencyObject describes address as dependency diagnostics do. The
	// description is rendered even when resolving the path fails.
	DependencyObject(Authority, ids.ObjectAddress) (string, error)

	Stage() Stage
	// StageBase is the catalog the stage was begun from.
	StageBase() catalog.Read
	// StageRead reads the stage over its base.
	StageRead() catalog.Read
	CreationACL(owner authorization.PrincipalRef, schema ids.ObjectAddress, class authorization.DefaultACLClass) authorization.ACLValue
	// DropTarget records address as dropped by the statement.
	DropTarget(ids.ObjectAddress)
	// RecordDependencyPath records auth's path for dependency diagnostics.
	RecordDependencyPath(Authority)
}
