func copyReplacement(t *testing.T, format copyFormat) {
	for _, explicit := range []bool{false, true} {
		t.Run(map[bool]string{false: "implicit", true: "explicit"}[explicit], func(t *testing.T) {
			e, _, op, scope := copyUnitStart(t, explicit)
			reader := &copyUnitReader{entered: make(chan struct{}), release: make(chan struct{})}
			syntax := copyUnitSyntax()
			if format == copyFormatBinary {
				syntax = copyBinaryUnitSyntax()
				stream := copyBinaryUnitStream(t)
				split := len(stream) - 5
				reader.first = true
				reader.prefix = strings.NewReader(string(stream[:split]))
				reader.suffix = strings.NewReader(string(stream[split:]))
			}
			done := make(chan error, 1)
			go func() {
				_, err := scope.Copy(syntax, reader, nil)
				err = scope.Finish(err)
				op.Done()
				done <- err
			}()
			released := false
			defer func() {
				if !released {
					close(reader.release)
					<-done
				}
			}()
			select {
			case <-reader.entered:
			case err := <-done:
				released = true
				close(reader.release)
				t.Fatal("COPY failed before replacement barrier", err)
			}
			if err := e.Reset(context.Background()); err != nil {
				t.Fatal(err)
			}
			close(reader.release)
			released = true
			if err := <-done; !errors.Is(err, ErrCatalogReplaced) {
				t.Fatal("COPY rebound replacement", err)
			}
			if scope.stage.rows != nil || scope.owner.copyScope != nil {
				t.Fatal("replacement retained COPY stage/reservation")
			}
			deleteReplacementAdmissionEmpty(t, e)
		})
	}
}
func TestCopyTextTermination(t *testing.T) {
	e, session, op, scope := copyUnitStart(t, false)
	reader := &copyUnitReader{entered: make(chan struct{}), release: make(chan struct{})}
	done := make(chan error, 1)
	go func() {
		_, err := scope.Copy(copyUnitSyntax(), reader, nil)
		err = scope.Finish(err)
		op.Done()
		done <- err
	}()
	released := false
	defer func() {
		if !released {
			close(reader.release)
			<-done
		}
	}()
	select {
	case <-reader.entered:
	case err := <-done:
		released = true
		close(reader.release)
		t.Fatal("COPY failed before termination barrier", err)
	}
	session.RequestEnd(CleanClose)
	if op.Context().Err() == nil {
		t.Fatal("termination could not cancel while I/O blocked")
	}
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	if err := session.WaitEnd(ctx); !errors.Is(err, context.Canceled) {
		t.Fatal("termination overtook leased COPY", err)
	}
	close(reader.release)
	released = true
	if err := <-done; err == nil {
		t.Fatal("terminated COPY succeeded")
	}
	if err := session.WaitEnd(context.Background()); err != nil {
		t.Fatal(err)
	}
	deleteReplacementAdmissionEmpty(t, e)
}
func TestCopyTextPanicCleanup(t *testing.T) {
	e, _, op, scope := copyUnitStart(t, false)
	reader := &copyUnitReader{entered: make(chan struct{}), release: make(chan struct{}), panicValue: "copy panic"}
	close(reader.release)
	func() {
		defer func() {
			value := recover()
			_ = scope.Finish(errors.New("COPY callback panic"))
			op.Done()
			if value != "copy panic" {
				t.Fatalf("panic=%v", value)
			}
		}()
		_, _ = scope.Copy(copyUnitSyntax(), reader, nil)
	}()
	if scope.owner.copyScope != nil || scope.stage.rows != nil {
		t.Fatal("panic leaked reservation/private rows")
	}
	deleteReplacementAdmissionEmpty(t, e)
}
func TestCopyTextCopiedReservation(t *testing.T) {
	_, _, op, scope := copyUnitStart(t, false)
	defer op.Done()
	defer scope.Finish(errors.New("cleanup"))
	if err := scope.gate(copyUnitSyntax()); err != nil {
		t.Fatal(err)
	}
	if err := scope.reserveCopy(); err != nil {
		t.Fatal(err)
	}
	copied := *scope
	copied.releaseCopyReservation()
	if scope.owner.copyScope != scope {
		t.Fatal("copied scope released reservation")
	}
	if _, err := copied.copyIO(func() (int, error) { t.Fatal("copied scope invoked I/O"); return 0, nil }); err == nil {
		t.Fatal("copied reservation admitted")
	}
}
