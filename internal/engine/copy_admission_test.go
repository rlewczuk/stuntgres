func copyFinalCancellationVeto(t *testing.T, csv bool) {
	e, _, op, scope := copyUnitStart(t, false)
	syntax := copyUnitSyntax()
	if csv {
		syntax.Options = []parser.CopyOption{{Name: "format", Value: "csv", HasValue: true, Argument: parser.CopyArgumentScalar}}
	}
	result, err := scope.Copy(syntax, strings.NewReader("1\n"), nil)
	if err != nil || result != 1 {
		t.Fatal(result, err)
	}
	op.cancel(context.Canceled)
	if err = scope.Finish(nil); err == nil {
		t.Fatal("canceled final publication succeeded")
	}
	op.Done()
	peer := sessionStart(t, e, nil)
	observer := transactionOperation(t, peer)
	defer observer.Done()
	rows, readErr := e.Execute(observer, statement(t, "SELECT * FROM t"), 0, nil)
	if readErr != nil {
		t.Fatal(readErr)
	}
	if rows.Rows != nil {
		defer rows.Rows.Close()
	}
	if rows.Count != 0 {
		t.Fatal("canceled COPY published rows", rows.Count)
	}
	if scope.stage.rows != nil || scope.owner.copyScope != nil {
		t.Fatal("final cancellation leaked COPY stage")
	}
}

func TestCopyTextOwnerWaitCompletion(t *testing.T) {
	for _, entry := range []string{"statement", "begin", "commit", "rollback"} {
		t.Run(entry, func(t *testing.T) {
			e, session, op, scope := copyUnitStart(t, true)
			reader := &copyUnitReader{entered: make(chan struct{}), release: make(chan struct{})}
			done := make(chan error, 1)
			go func() {
				_, err := scope.Copy(copyUnitSyntax(), reader, nil)
				err = scope.Finish(err)
				op.Done()
				done <- err
			}()
			released := false
			defer func() {
				if !released {
					close(reader.release)
					<-done
				}
			}()
			select {
			case <-reader.entered:
			case err := <-done:
				released = true
				close(reader.release)
				t.Fatal("COPY did not enter I/O", err)
			}
			before := scope.txRef
			waiter := transactionOperation(t, session)
			defer waiter.Done()
			waiting := &copyWaitContext{Context: waiter.ctx, entered: make(chan struct{})}
			waiter.ctx = waiting
			finished := make(chan error, 1)
			go func() {
				var err error
				switch entry {
				case "statement":
					var next *StatementScope
					next, err = e.StartStatement(waiter)
					if next != nil {
						err = next.Finish(nil)
					}
				case "begin":
					_, err = e.Begin(waiter, TxOptions{})
				case "commit":
					_, err = e.Commit(waiter, before)
				case "rollback":
					_, err = e.Rollback(waiter, before)
				}
				finished <- err
			}()
			select {
			case <-waiting.entered:
			case err := <-finished:
				t.Fatal("owner entry bypassed reserved COPY", entry, err)
			}
			session.transactions.mu.Lock()
			ref, command := session.transactions.ref, session.transactions.command
			session.transactions.mu.Unlock()
			if ref != before || command != scope.command {
				t.Fatal("waiting command changed reserved owner")
			}
			close(reader.release)
			released = true
			if err := <-done; err != nil {
				t.Fatal(err)
			}
			entryErr := <-finished
			if entry == "begin" {
				if entryErr == nil || entryErr.Error() != "stuntgres: transaction already active" {
					t.Fatal("Begin post-COPY active transaction boundary", entryErr)
				}
				var diagnostic interface{ SQLState() string }
				if errors.As(entryErr, &diagnostic) {
					t.Fatal("Begin invented SQL diagnostic", entryErr)
				}
			} else if entryErr != nil {
				t.Fatal("entry failed after COPY reservation release", entry, entryErr)
			}
			peer := sessionStart(t, e, nil)
			result := sessionSQL(t, peer, "SELECT v FROM t")
			want := int64(0)
			if entry == "commit" {
				want = 1
			}
			if result.Count != want {
				t.Fatal("post-COPY end visibility", entry, result.Count, want)
			}
			if result.Rows != nil {
				result.Rows.Close()
			}
		})
	}
}

type copyUnitWriter struct {
	entered, release chan struct{}
	first            bool
}

func (w *copyUnitWriter) Write(p []byte) (int, error) {
	if !w.first {
		w.first = true
		close(w.entered)
		<-w.release
	}
	return len(p), nil
}
