type copyUnitReader struct {
	entered, release chan struct{}
	once             sync.Once
	first            bool
	panicValue       any
	prefix, suffix   io.Reader
}

func (r *copyUnitReader) Read(p []byte) (int, error) {
	if r.prefix != nil {
		n, err := r.prefix.Read(p)
		if err != io.EOF {
			return n, err
		}
		r.prefix = nil
	}
	if !r.first {
		r.first = true
		return copy(p, "1\n"), nil
	}
	r.once.Do(func() { close(r.entered) })
	<-r.release
	if r.panicValue != nil {
		panic(r.panicValue)
	}
	if r.suffix != nil {
		return r.suffix.Read(p)
	}
	return 0, io.EOF
}

type copyWaitContext struct {
	context.Context
	entered chan struct{}
	once    sync.Once
}

func (c *copyWaitContext) Done() <-chan struct{} {
	c.once.Do(func() { close(c.entered) })
	return c.Context.Done()
}
func copyUnitStart(t *testing.T, explicit bool) (*Engine, *Session, *Operation, *StatementScope) {
	t.Helper()
	e := New()
	session := sessionStart(t, e, nil)
	sessionSQL(t, session, "CREATE TABLE t(v INT PRIMARY KEY,i bigint GENERATED BY DEFAULT AS IDENTITY)")
	if explicit {
		sessionSQL(t, session, "BEGIN")
	}
	op := transactionOperation(t, session)
	scope, err := e.StartStatement(op)
	if err != nil {
		op.Done()
		t.Fatal(err)
	}
	return e, session, op, scope
}
func copyUnitSyntax() *parser.Copy {
	return &parser.Copy{Name: parser.ObjectName{Parts: []parser.Identifier{{Text: "t"}}}, Columns: []parser.Identifier{{Text: "v"}}, From: true, Endpoint: parser.CopyStdin}
}
