func TestTableLikeCookedRowRemap(t *testing.T) {
	e := New()
	source := &catalog.Relation{ObjectAddress: ids.ObjectAddress{ClassID: ids.RelationClassID, ObjectID: 20000}, Attributes: []int32{1, 3}}
	destination := &catalog.Relation{ObjectAddress: ids.ObjectAddress{ClassID: ids.RelationClassID, ObjectID: 20001}, Attributes: []int32{1, 2, 3, 4}}
	ref := e.catalog.Domain.Ref(e.CatalogRead().Epoch(), source.Address())
	if err := e.Reset(context.Background()); err != nil {
		t.Fatal(err)
	}
	current := ref
	current.Epoch = e.CatalogRead().Epoch()
	in := createLikeInput{ref: current, source: source, offset: 1}
	in.rowRef, in.slots = in.rowMapper(destination, e.CatalogRead())
	columnRef := ref
	columnRef.Address.SubID = 3
	column := columnExpression{Info: expr.Info{Usage: testUsage(e, sqltype.Int4)}, origin: columnRef, scope: 1, frame: 1, slot: 1}
	mapped, err := in.remap(column, destination, e.CatalogRead())
	if err != nil {
		t.Fatal(err)
	}
	got := mapped.(columnExpression)
	if got.origin.Domain() != e.catalog.Domain || got.origin.Epoch != current.Epoch || got.origin.Address.ObjectID != destination.Address().ObjectID || got.origin.Address.SubID != 3 || got.slot != 2 || column.origin != columnRef || column.slot != 1 {
		t.Fatal(got, column)
	}
	owner := tableOIDExpression{Info: expr.Info{Usage: testUsage(e, sqltype.Oid)}, owner: ref}
	mapped, err = in.remap(owner, destination, e.CatalogRead())
	if err != nil {
		t.Fatal(err)
	}
	if mapped.(tableOIDExpression).owner.Domain() != e.catalog.Domain || mapped.(tableOIDExpression).owner.Epoch != current.Epoch || mapped.(tableOIDExpression).owner.Address != destination.Address() || owner.owner != ref {
		t.Fatal(mapped, owner)
	}
	usage := testUsage(e, sqltype.Regclass)
	literal := literalExpression{Info: expr.Info{Usage: usage, RegclassRef: ref}, value: sqltype.Null(usage.Type)}
	mapped, err = in.remap(literal, destination, e.CatalogRead())
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(mapped, literal) {
		t.Fatal("explicit source literal retargeted", mapped)
	}
	call := functions.SequenceCall{Ref: ref}
	mapped, err = in.remap(call, destination, e.CatalogRead())
	if err != nil {
		t.Fatal(err)
	}
	if mapped.(functions.SequenceCall).Ref != ref {
		t.Fatal("external call retargeted")
	}
}

func TestTableLikeDefinitionIdentities(t *testing.T) {
	e := New()
	run(t, e, "CREATE TABLE src(dead TEXT,a INT NOT NULL DEFAULT 7,id INT GENERATED BY DEFAULT AS IDENTITY,g INT GENERATED ALWAYS AS(a*2) STORED,CONSTRAINT positive CHECK(a>0) NO INHERIT,UNIQUE(a))")
	run(t, e, "ALTER TABLE src DROP COLUMN dead")
	run(t, e, "COMMENT ON COLUMN src.a IS 'exact'")
	before := e.CatalogRead()
	source := before.MustRelation(roleTableRef(t, e, "src").Address)
	op, done := roleOperation(t, e, "postgres")
	defer done()
	stage, destination, err := tableLikeBuild(t, e, op, "CREATE TABLE clone(head TEXT,lead BOOL,LIKE src INCLUDING ALL)")
	if err != nil {
		t.Fatal(err)
	}
	defer e.DiscardCatalogStage(stage)
	if e.catalog.state != before.State() || destination.Address() == source.Address() || destination.RowType == source.RowType || destination.ColumnMeta.Defaults[3].OID == source.ColumnMeta.Defaults[2].OID || destination.ColumnMeta.Generations[5].OID == source.ColumnMeta.Generations[4].OID || destination.Constraints.Check[0].OID == source.Constraints.Check[0].OID {
		t.Fatal("copied provider identities or published early")
	}
	if !destination.Constraints.Check[0].NoInherit || destination.Constraints.Check[0].Name != "positive" || destination.ColumnMeta.Comments[3] != "exact" || len(source.Columns) != 3 || len(destination.Columns) != 5 {
		t.Fatal(destination, source)
	}
	identity := destination.ColumnMeta.Identities[4]
	sequence := stage.Get(identity.Sequence).(*catalog.Relation)
	if identity.Sequence == source.ColumnMeta.Identities[3].Sequence || sequence.Sequence.Owned != (ids.ObjectAddress{ClassID: ids.RelationClassID, ObjectID: destination.Address().ObjectID, SubID: 4}) || sequence.Owner != destination.Owner || sequence.Sequence.Persistence != "logged" || stage.sequence.generator(identity.Sequence).Called {
		t.Fatal("identity copy authority/state", sequence)
	}
	for _, ref := range destination.ColumnMeta.Generations[5].Dependencies {
		if ref.Address.ClassID == ids.RelationClassID && ref.Address.ObjectID == source.Address().ObjectID {
			t.Fatal("generation retained source row", ref)
		}
	}
	for _, dep := range destination.Constraints.Check[0].Dependencies {
		if dep.Ref.Address.ObjectID == source.Address().ObjectID {
			t.Fatal("CHECK retained source row", dep)
		}
	}
	if stage.Get(source.Address()) != nil || before.Get(source.Address()) != source {
		t.Fatal("source descriptor modified")
	}
	prepared, err := e.ValidateCatalogStage(context.Background(), stage)
	if err != nil {
		t.Fatal(err)
	}
	if _, err = e.PublishCatalog(prepared, PublicationToken{Epoch: before.Epoch()}); err != nil {
		t.Fatal(err)
	}
	if len(e.storage.Relations[destination.Address()].Versions) != 0 {
		t.Fatal("source rows imported")
	}
}

func TestTableLikeStageAtomicity(t *testing.T) {
	e := New()
	run(t, e, "CREATE TABLE src(id INT GENERATED BY DEFAULT AS IDENTITY,a INT DEFAULT 7 UNIQUE,CONSTRAINT positive CHECK(a>0))")
	op, done := roleOperation(t, e, "postgres")
	defer done()
	before := e.CatalogRead()
	stores, generators := len(e.storage.Relations), len(e.storage.Sequences)
	for _, query := range []string{"CREATE TABLE bad(LIKE src INCLUDING ALL,a TEXT)", "CREATE TABLE bad(LIKE src INCLUDING ALL,CONSTRAINT positive CHECK(a>0))"} {
		stage, _, err := tableLikeBuild(t, e, op, query)
		if err == nil {
			t.Fatal("invalid candidate accepted")
		}
		e.DiscardCatalogStage(stage)
		if e.catalog.state != before.State() || len(e.storage.Relations) != stores || len(e.storage.Sequences) != generators {
			t.Fatal("failed candidate leaked publication")
		}
	}
	stage, _, err := tableLikeBuild(t, e, op, "CREATE TABLE clone(LIKE src INCLUDING ALL)")
	if err != nil {
		t.Fatal(err)
	}
	canceled, cancel := context.WithCancel(context.Background())
	cancel()
	_, err = e.ValidateCatalogStage(canceled, stage)
	if !errors.Is(err, context.Canceled) {
		t.Fatal(err)
	}
	e.DiscardCatalogStage(stage)
	if e.catalog.state != before.State() || len(e.storage.Relations) != stores || len(e.storage.Sequences) != generators {
		t.Fatal("canceled candidate leaked publication")
	}
}

func TestTableLikePublicationFence(t *testing.T) {
	e := New()
	run(t, e, "CREATE TABLE src(a INT DEFAULT 7)")
	op, done := roleOperation(t, e, "postgres")
	defer done()
	stage, _, err := tableLikeBuild(t, e, op, "CREATE TABLE clone(LIKE src INCLUDING DEFAULTS)")
	if err != nil {
		t.Fatal(err)
	}
	defer e.DiscardCatalogStage(stage)
	prepared, err := e.ValidateCatalogStage(context.Background(), stage)
	if err != nil {
		t.Fatal(err)
	}
	source := e.CatalogRead().MustRelation(roleTableRef(t, e, "src").Address)
	next := *source
	e.mu.Lock()
	next.ObjectRevision, err = e.catalog.revisionLocked()
	e.mu.Unlock()
	if err != nil {
		t.Fatal(err)
	}
	next.Comment = "intervening descriptor"
	update := e.BeginCatalogStage(e.CatalogRead())
	if err := update.Replace(&next); err != nil {
		t.Fatal(err)
	}
	queryCreatePublish(t, e, update)
	incumbent := e.CatalogRead()
	if _, err := e.PublishCatalog(prepared, PublicationToken{Epoch: incumbent.Epoch()}); !errors.Is(err, ids.ErrCatalogReplaced) {
		t.Fatal("stale source silently retargeted", err)
	}
	if e.catalog.state != incumbent.State() {
		t.Fatal("stale candidate partially published")
	}
}

func TestTableLikeInlineSourceProvenance(t *testing.T) {
	e := New()
	op, done := roleOperation(t, e, "postgres")
	defer done()
	syntax := statement(t, "CREATE SCHEMA copied CREATE TABLE src(id INT GENERATED BY DEFAULT AS IDENTITY,a INT DEFAULT 7 UNIQUE) CREATE TABLE clone(LIKE copied.src INCLUDING ALL)").(*parser.CreateSchema)
	e.mu.Lock()
	stage, err := e.stageSchemaLocked(op, syntax, sqltype.InputEnvironment{}, sqltype.OutputEnvironment{})
	e.mu.Unlock()
	if err != nil {
		t.Fatal(err)
	}
	defer e.DiscardCatalogStage(stage)
	if len(stage.likeSources) < 2 {
		t.Fatal("private source/provider provenance absent")
	}
	for _, source := range stage.likeSources {
		if stage.Base.Get(source.Address()) != nil || stage.Get(source.Address()) != source {
			t.Fatal("private input mistaken for incumbent", source)
		}
	}
	if err := stage.validateLikeSources(e.CatalogRead()); err != nil {
		t.Fatal(err)
	}
	queryCreatePublish(t, e, stage)
}
