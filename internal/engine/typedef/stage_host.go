// Authority is the statement authority the stage handlers carry. It is an
// opaque value: handlers keep it by value, and a host method that changes it
// returns a new one and leaves its argument alone, so an authority changed
// inside one helper (an implicit namespace) stays local to the caller that
// takes the result.
type Authority interface {
	access.Environment
	TypedefAuthority()
}

// Stage is the private catalog change a type DDL statement writes. Create and
// Replace keep the engine stage's lifecycle checks.
type Stage interface {
	Create(catalog.Descriptor) error
	Replace(catalog.Descriptor) error
	Get(ids.ObjectAddress) catalog.Descriptor
	LookupName(ids.NameKey) ids.ObjectAddress
}

// StageHost is what the type stage handlers need from the engine for one
// statement. Every method runs with Engine.mu held; none takes or releases
// it, and none waits on the lock manager.
type StageHost interface {
	// AccessView returns the catalog, roles, state and owner of auth.
	AccessView(Authority) access.View
	// CheckCreateIn checks CREATE on a namespace, with the trusted Restore
	// exception.
	CheckCreateIn(Authority, ids.ObjectRef) error
	// TrustedRestoreDestination reports whether the statement replays a
	// trusted Restore destination. It fails, naming what, when the replay
	// authority is not the bootstrap superuser of an import.
	TrustedRestoreDestination(auth Authority, what string) (bool, error)

	Context() context.Context
	EmitNotice(session.NoticeLevel, sqlstate.Error)

	AllocateOID() (ids.OID, error)
	Revision() (ids.DefinitionRevision, error)
	AllocateEnumMember() (int64, error)

	Stage() Stage
	// StageRead reads the stage over its base.
	StageRead() catalog.Read
	// ReplaceUnsynchronized replaces d without re-deriving a row type.
	ReplaceUnsynchronized(catalog.Descriptor) error
	// CreationTypeACL is the creation ACL of a type and whether it is the
	// synthetic default.
	CreationTypeACL(owner authorization.PrincipalRef, schema ids.ObjectAddress) (authorization.ACLValue, bool)
	AddDomainBase(catalog.Descriptor)
	DropTarget(ids.ObjectAddress)
	RecordDependencyPath(Authority)
	RemoveDomainCheck(d *catalog.Type, oid ids.OID) error

	// CreationNamespace resolves the namespace an object is created in. It may
	// stage implicit namespaces; the returned authority then reads the stage.
	CreationNamespace(Authority, parser.ObjectName) (ids.ObjectRef, Authority, error)
	// ExistingCreationNamespace resolves an existing creation namespace and
	// never stages one.
	ExistingCreationNamespace(Authority, parser.ObjectName) (ids.ObjectRef, error)
	// SearchNamespaces returns the namespaces a name of class searches, in
	// order. Only type and conversion names are supported.
	SearchNamespaces(auth Authority, name parser.ObjectName, class ids.OID) ([]ids.ObjectAddress, error)
	// LookupFunction finds the function with exactly signature on the
	// function path; nil without error when there is none.
	LookupFunction(auth Authority, name parser.ObjectName, signature catalog.ProcedureSignature) (*catalog.Procedure, error)
	NamedType(Authority, parser.ObjectName) (*catalog.Type, error)
	FindCollation(Authority, parser.ObjectName) (*catalog.Collation, error)
	ResolveType(parser.TypeName) (sqltype.Usage, error)
	ResolveDomainBase(parser.TypeName) (sqltype.Usage, error)
	ResolveColumnCollation(sqltype.Usage, *parser.ObjectName) (sqltype.Usage, error)

	BindDomainDefault(auth Authority, d *catalog.Type, raw parser.Expr, input sqltype.InputEnvironment, output sqltype.OutputEnvironment) error
	BindDomainChecks(auth Authority, d *catalog.Type, raw []parser.ColumnConstraint, input sqltype.InputEnvironment) error

	// DisplaceAssociatedArray renames an autogenerated array that holds name;
	// false when another type holds it.
	DisplaceAssociatedArray(namespace ids.ObjectAddress, name string) (bool, error)
	AssociatedArrayName(namespace ids.ObjectAddress, name string) string
	NewCompositeRelation(namespace ids.ObjectAddress, name string, owner authorization.PrincipalRef, columns []catalog.Column, index map[string]int) (*catalog.Relation, error)
	StageRowType(*catalog.Relation) error

	// DependencyObject describes address as dependency diagnostics do.
	DependencyObject(Authority, ids.ObjectAddress) (string, error)
}

// Check checks req with auth as both the view and its environment, as the
// engine's authorization view does.
func Check(h StageHost, auth Authority, req access.Requirement) error {
	return h.AccessView(auth).Check(auth, req)
}

// ObjectRef is the provenance-stamped reference to a in auth's catalog.
func ObjectRef(h StageHost, auth Authority, a ids.ObjectAddress) ids.ObjectRef {
	view := h.AccessView(auth)
	return view.Owner.Domain.Ref(view.Catalog.Epoch(), a)
}

// Notice emits a NOTICE, as schema DDL does.
func Notice(h StageHost, code, message string) {
	h.EmitNotice(session.LevelNotice, sqlstate.Error{Severity: "NOTICE", SeverityUnlocalized: "NOTICE", Code: code, Message: message})
}
