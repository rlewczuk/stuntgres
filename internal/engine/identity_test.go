func TestIdentityCatalogReciprocalDefinitions(t *testing.T) {
	e := New()
	run(t, e, `CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY,other INT GENERATED BY DEFAULT AS IDENTITY)`)
	read := e.CatalogRead()
	ref := roleTableRef(t, e, "i")
	old := read.MustRelation(ref.Address)
	if len(old.Identities) != 2 || old.Identities[1].Sequence == old.Identities[2].Sequence {
		t.Fatal(old.Identities)
	}
	if err := (relationProvider{}).Validate(read, old); err != nil {
		t.Fatal(err)
	}
	for _, mutate := range []func(*catalog.Relation){
		func(d *catalog.Relation) {
			identity := d.Identities[1]
			identity.Mode = parser.IdentityNone
			d.Identities[1] = identity
		},
		func(d *catalog.Relation) {
			identity := d.Identities[1]
			identity.Sequence = ids.ObjectAddress{}
			d.Identities[1] = identity
		},
		func(d *catalog.Relation) { d.Identities[99] = d.Identities[1] },
		func(d *catalog.Relation) { d.Identities[1] = d.Identities[2] },
		func(d *catalog.Relation) {
			d.Columns = append([]catalog.Column(nil), d.Columns...)
			d.Columns[0].Nullable = true
		},
	} {
		next := *old
		next.Identities = maps.Clone(old.Identities)
		mutate(&next)
		if err := (relationProvider{}).Validate(read, &next); err == nil {
			t.Fatal("invalid identity admitted")
		}
	}
	sequence := read.MustRelation(old.Identities[1].Sequence)
	next := *sequence
	options := *sequence.Sequence
	options.Owned = ids.ObjectAddress{}
	next.Sequence = &options
	if err := (relationProvider{}).Validate(read, &next); err == nil {
		t.Fatal("unowned internal sequence admitted")
	}
}

func TestIdentityInsertOnlyAuthority(t *testing.T) {
	e := New()
	op, done := roleOperation(t, e, "postgres")
	defer done()
	roleExecute(t, e, op, `CREATE USER identity_writer`)
	roleExecute(t, e, op, `CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY)`)
	table := roleTableRef(t, e, "i")
	writer, _ := e.Roles().Lookup("identity_writer")
	owner := e.roles.root.Read(authorization.PrincipalRef{}).LookupRef("postgres")
	if err := e.SetObjectACL(context.Background(), table, authorization.ACLValue{Explicit: true, Entries: []authorization.ACLEntry{{Grantor: owner, Grantee: authorization.ACLGrantee{Role: writer.Ref}, Privileges: authorization.InsertPrivilege}}}); err != nil {
		t.Fatal(err)
	}
	roleExecute(t, e, op, `SET SESSION AUTHORIZATION identity_writer`)
	r := roleExecute(t, e, op, `INSERT INTO i DEFAULT VALUES`)
	if r.Count != 1 {
		t.Fatal(r.Count)
	}
	roleError(t, e, op, `SELECT nextval('i_id_seq')`, "42501", "permission denied for sequence i_id_seq", "")
	roleExecute(t, e, op, `RESET SESSION AUTHORIZATION`)
	r = roleExecute(t, e, op, `SELECT * FROM i`)
	defer r.Rows.Close()
	if got := tuples(r); got[0][0] != int64(1) {
		t.Fatal(got)
	}
}

