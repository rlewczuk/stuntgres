func TestIdentityEarlyRowFailureConstrainsCompleteProjection(t *testing.T) {
	for _, tc := range []struct{ name, declaration, first, code, message, detail string }{
		{"not_null", "p INT NOT NULL", "NULL", "23502", `null value in column "p" of relation "i" violates not-null constraint`, "Failing row contains (1, null, 50)."},
		{"check", "p INT CONSTRAINT positive CHECK(p>0)", "0", "23514", `new row for relation "i" violates check constraint "positive"`, "Failing row contains (1, 0, 50)."},
	} {
		t.Run(tc.name, func(t *testing.T) {
			e := New()
			op, done := roleOperation(t, e, "postgres")
			defer done()
			roleExecute(t, e, op, `CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY(CACHE 1),`+tc.declaration+`,z INT)`)
			roleExecute(t, e, op, `CREATE SEQUENCE same_row START 50 CACHE 1`)
			roleExecute(t, e, op, `CREATE SEQUENCE later_row START 70 CACHE 1`)
			_, err := e.Execute(op, statement(t, `INSERT INTO i VALUES(DEFAULT,`+tc.first+`,nextval('same_row')),(DEFAULT,nextval('later_row'),nextval('same_row'))`), 0, nil)
			want := &sqlstate.Error{Severity: "ERROR", SeverityUnlocalized: "ERROR", Code: tc.code, Message: tc.message, Detail: tc.detail, Schema: "public", Table: "i"}
			if tc.name == "not_null" {
				want.Column = "p"
			} else {
				want.Constraint = "positive"
			}
			var diagnostic *sqlstate.Error
			if !errors.As(err, &diagnostic) || !reflect.DeepEqual(diagnostic, want) {
				t.Fatalf("diagnostic %#v (%v), want %#v", diagnostic, err, want)
			}
			ref := roleTableRef(t, e, "i")
			if len(e.storage.relations[ref.Address].versions) != 0 {
				t.Fatal("failed batch published rows")
			}
			assertValue := func(query string, want any) {
				t.Helper()
				r := roleExecute(t, e, op, query)
				defer r.Rows.Close()
				rows := tuples(r)
				if len(rows) != 1 || len(rows[0]) != 1 || rows[0][0] != want {
					t.Fatal(query, rows, want)
				}
			}
			assertValue(`SELECT last_value FROM i_id_seq`, int64(1))
			assertValue(`SELECT is_called FROM i_id_seq`, true)
			assertValue(`SELECT currval('i_id_seq')`, int64(1))
			assertValue(`SELECT lastval()`, int64(1))
			assertValue(`SELECT last_value FROM same_row`, int64(50))
			assertValue(`SELECT is_called FROM same_row`, true)
			assertValue(`SELECT currval('same_row')`, int64(50))
			assertValue(`SELECT last_value FROM later_row`, int64(70))
			assertValue(`SELECT is_called FROM later_row`, false)
			roleError(t, e, op, `SELECT currval('later_row')`, "55000", `currval of sequence "later_row" is not yet defined in this session`, "")
			roleExecute(t, e, op, `INSERT INTO i VALUES(DEFAULT,1,nextval('same_row'))`)
			assertValue(`SELECT id FROM i`, int64(2))
			assertValue(`SELECT z FROM i`, int64(51))
		})
	}
}

func TestIdentityDiscardedRuntimeConversionDemandBinding(t *testing.T) {
	for _, tc := range []struct {
		name, source      string
		outputNull, fails bool
	}{
		{"select", `SELECT CAST($1::text AS integer),7`, true, false},
		{"count_cache", `SELECT CAST($1::text AS integer),p FROM inputs LIMIT 1`, true, false},
		{"sort_output_cache", `SELECT CAST($1::text AS integer),p FROM inputs ORDER BY 2 LIMIT 1`, true, false},
		{"sort_key", `SELECT CAST($1::text AS integer),p FROM inputs ORDER BY 1 LIMIT 1`, true, true},
		{"values_single", `VALUES(CAST($1::text AS integer),7) LIMIT 1`, true, false},
		{"values_order_key", `VALUES(CAST($1::text AS integer),7) ORDER BY 1`, true, true},
		{"values_other_key", `VALUES(CAST($1::text AS integer),7) ORDER BY column2+1`, true, false},
		{"values_multi", `VALUES(CAST($1::text AS integer),7),(0,8) LIMIT 1`, false, true},
		{"volatile", `SELECT CAST(CASE WHEN nextval('side')>0 THEN $1::text ELSE '' END AS integer),7`, false, false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			e := New()
			op, done := roleOperation(t, e, "postgres")
			defer done()
			roleExecute(t, e, op, `CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY,p INT)`)
			roleExecute(t, e, op, `CREATE TABLE inputs(p INT)`)
			roleExecute(t, e, op, `CREATE SEQUENCE side START 50 CACHE 1`)
			ref := roleTableRef(t, e, "i")
			e.mu.Lock()
			auth, err := e.authorizationLocked(op)
			var bound binding
			if err == nil {
				bound, err = e.describe(op.ctx, statement(t, `INSERT INTO i OVERRIDING USER VALUE `+tc.source), auth, ref, sqltype.InputEnvironment{}, op, nil, nil)
			}
			e.mu.Unlock()
			if err != nil {
				t.Fatal(err)
			}
			if bound.parameters.Count != 1 || bound.parameters.Types[0].Type.ID() != sqltype.Text {
				t.Fatal("discard erased inferred import signature", bound.parameters)
			}
			project := bound.query.Root.(*projectNode)
			output, isLiteral := project.expressions[0].(literalExpression)
			if got := isLiteral && output.value.IsNull(); got != tc.outputNull {
				t.Fatal("output demand", got, tc.outputNull)
			}
			if project.Schema()[0].Usage.Type.ID() != sqltype.Int4 {
				t.Fatal("discard lost assigned schema", project.Schema())
			}
			value := sqltype.String(bound.parameters.Types[0].Type, "bad")
			_, err = preflightQuery(&EvalContext{Context: op.ctx, Parameters: []sqltype.Value{value}}, bound.query.Root)
			if tc.fails {
				state(t, err, "22P02")
			} else if err != nil {
				t.Fatal("unused or volatile runtime conversion preflighted", err)
			}
			sequence := roleTableRef(t, e, "i_id_seq")
			if generator := e.storage.sequences[sequence.Address]; generator.last != 1 || generator.called {
				t.Fatal("binding/preflight generated identity", generator)
			}
		})
	}
}
