func TestIdentityCatalogReciprocalDefinitions(t *testing.T){
	e:=New();run(t,e,`CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY,other INT GENERATED BY DEFAULT AS IDENTITY)`)
	read:=e.CatalogRead();ref:=roleTableRef(t,e,"i");old:=read.state.descriptors[ref.Address].(*relationDescriptor)
	if len(old.identities)!=2 || old.identities[1].sequence==old.identities[2].sequence{t.Fatal(old.identities)}
	if err:=(relationProvider{}).Validate(read,old);err!=nil{t.Fatal(err)}
	for _,mutate:=range []func(*relationDescriptor){
		func(d *relationDescriptor){identity:=d.identities[1];identity.mode=parser.IdentityNone;d.identities[1]=identity},
		func(d *relationDescriptor){identity:=d.identities[1];identity.sequence=ObjectAddress{};d.identities[1]=identity},
		func(d *relationDescriptor){d.identities[99]=d.identities[1]},
		func(d *relationDescriptor){d.identities[1]=d.identities[2]},
		func(d *relationDescriptor){d.columns=append([]ColumnDescriptor(nil),d.columns...);d.columns[0].Nullable=true},
	}{next:=*old;next.identities=maps.Clone(old.identities);mutate(&next);if err:=(relationProvider{}).Validate(read,&next);err==nil{t.Fatal("invalid identity admitted")}}
	sequence:=read.state.descriptors[old.identities[1].sequence].(*relationDescriptor)
	next:=*sequence;options:=*sequence.sequence;options.owned=ObjectAddress{};next.sequence=&options
	if err:=(relationProvider{}).Validate(read,&next);err==nil{t.Fatal("unowned internal sequence admitted")}
}

func TestIdentityInsertOnlyAuthority(t *testing.T){
	e:=New();op,done:=roleOperation(t,e,"postgres");defer done()
	roleExecute(t,e,op,`CREATE USER identity_writer`);roleExecute(t,e,op,`CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY)`)
	table:=roleTableRef(t,e,"i");writer,_:=e.Roles().Lookup("identity_writer");owner:=e.roles.names["postgres"]
	if err:=e.SetObjectACL(context.Background(),table,ACLValue{Explicit:true,Entries:[]ACLEntry{{Grantor:owner,Grantee:ACLGrantee{Role:writer.Ref},Privileges:InsertPrivilege}}});err!=nil{t.Fatal(err)}
	roleExecute(t,e,op,`SET SESSION AUTHORIZATION identity_writer`)
	r:=roleExecute(t,e,op,`INSERT INTO i DEFAULT VALUES`);if r.Count!=1{t.Fatal(r.Count)}
	roleError(t,e,op,`SELECT nextval('i_id_seq')`,"42501","permission denied for sequence i_id_seq","")
	roleExecute(t,e,op,`RESET SESSION AUTHORIZATION`)
	r=roleExecute(t,e,op,`SELECT * FROM i`);defer r.Rows.Close();if got:=tuples(r);got[0][0]!=int64(1){t.Fatal(got)}
}

func TestIdentityCreateAtomicFailure(t *testing.T){
	e:=New();op,done:=roleOperation(t,e,"postgres");defer done()
	before:=e.state
	roleError(t,e,op,`CREATE TABLE bad(a INT GENERATED ALWAYS AS IDENTITY,b INT GENERATED ALWAYS AS IDENTITY(CACHE 0))`,"22023","CACHE (0) must be greater than zero","")
	if e.state!=before || len(e.sequences)!=0{t.Fatal("failed CREATE published identities")}
	roleExecute(t,e,op,`CREATE TABLE bad(id INT GENERATED ALWAYS AS IDENTITY)`)
	r:=roleExecute(t,e,op,`INSERT INTO bad DEFAULT VALUES`);if r.Count!=1{t.Fatal(r.Count)}
}
