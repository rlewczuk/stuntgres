package engine

import (
	"bytes"
	"context"
	"testing"

	"stuntgres/internal/engine/analyze"
)

func TestSerialDefaultIdentityProviderTemporaryCollision(t *testing.T) {
	for _, restore := range []bool{false, true} {
		t.Run(map[bool]string{false: "ReplaceCatalog", true: "Restore"}[restore], func(t *testing.T) {
			source, dest := New(), New()
			a, b := sessionStart(t, source, nil), sessionStart(t, dest, nil)
			sessionSQL(t, a, `CREATE SCHEMA collision_padding`)
			sessionSQL(t, a, `CREATE SCHEMA portable`)
			sessionSQL(t, a, `CREATE TABLE portable.producer(id BIGINT GENERATED BY DEFAULT AS IDENTITY)`)
			sessionSQL(t, a, `CREATE TABLE portable.consumer(id SERIAL)`)
			sessionSQL(t, a, `ALTER TABLE portable.consumer ALTER id SET DEFAULT nextval('portable.producer_id_seq')`)
			sequenceScalar(t, a, `SELECT setval('portable.producer_id_seq',7,true)`, 7)
			sessionSQL(t, b, `CREATE TABLE displaced(v INT)`)
			sessionSQL(t, b, `CREATE TEMP SEQUENCE kept START 30 CACHE 1`)
			sequenceScalar(t, b, `SELECT nextval('kept')`, 30)
			_, description := sequencePreparedDescription(t, dest, b, `SELECT nextval('kept')`)
			temp := description.Sequences.Constants[0].Ref.Address
			original := source.Catalog.State.MustRelation(roleTableRef(t, source, "portable.consumer").Address)
			leaf := serialLeaf(original.ColumnMeta.Defaults[1].Expression)
			if leaf.Ref.Address != temp {
				t.Fatal("fixture lacks actual identity provider collision", leaf.Ref.Address, temp)
			}
			if restore {
				var dump bytes.Buffer
				if err := Dump(context.Background(), source, &dump); err != nil {
					t.Fatal(err)
				}
				if err := Restore(context.Background(), dest, bytes.NewReader(dump.Bytes())); err != nil {
					t.Fatal(err)
				}
			} else if _, err := dest.ReplaceCatalog(context.Background(), source, source.CatalogRead()); err != nil {
				t.Fatal(err)
			}
			consumer := dest.Catalog.State.MustRelation(roleTableRef(t, dest, "portable.consumer").Address)
			current := serialLeaf(consumer.ColumnMeta.Defaults[1].Expression)
			if current.Ref.Address == temp || !analyze.ClosedSequenceDefault(consumer.ColumnMeta.Defaults[1].Expression) {
				t.Fatal("identity provider reference not remapped", current.Ref)
			}
			provider := dest.Catalog.State.MustRelation(current.Ref.Address)
			if !provider.Sequence.Identity || current.Identity {
				t.Fatal("ordinary default inherited identity privilege/width semantics")
			}
			sessionSQL(t, b, `INSERT INTO portable.consumer DEFAULT VALUES`)
			sequenceScalar(t, b, `SELECT id FROM portable.consumer`, 8)
			sessionSQL(t, b, `INSERT INTO portable.producer DEFAULT VALUES`)
			sequenceScalar(t, b, `SELECT id FROM portable.producer`, 9)
			sequenceScalar(t, b, `SELECT nextval('kept')`, 31)
			if serialLeaf(original.ColumnMeta.Defaults[1].Expression).Ref != leaf.Ref {
				t.Fatal("source provider identity mutated")
			}
			checkReviewDependencyValid(t, dest)
		})
	}
}
