func TestAlterTypeACLAndOwnedSequenceIdentity(t *testing.T) {
	e := New()
	run(t, e, "CREATE USER alter_type_reader")
	run(t, e, "CREATE USER alter_type_outsider")
	reader, _ := e.Roles().Lookup("alter_type_reader")
	run(t, e, "CREATE TABLE t(c INT)")
	run(t, e, "INSERT INTO t VALUES(7)")
	run(t, e, "CREATE SEQUENCE q START 10 CACHE 7 OWNED BY t.c")
	tableRef, sequenceRef := roleTableRef(t, e, "t"), roleTableRef(t, e, "q")
	table := e.state.descriptors[tableRef.Address].(*relationDescriptor)
	acl := authorization.ACLValue{Explicit: true, Entries: []authorization.ACLEntry{{Grantor: table.owner, Grantee: authorization.ACLGrantee{Role: reader.Ref}, Privileges: authorization.SelectPrivilege}}}
	for _, subID := range []int32{0, table.attributes[0]} {
		ref := tableRef
		ref.Address.SubID = subID
		if err := e.SetObjectACL(context.Background(), ref, acl); err != nil {
			t.Fatal(err)
		}
	}
	before := e.state.descriptors[tableRef.Address].(*relationDescriptor)
	sequence := e.state.descriptors[sequenceRef.Address]
	s := sessionStart(t, e, nil)
	sequenceScalar(t, s, "SELECT nextval('q')", 10)
	generator, memory := e.sequences[sequenceRef.Address], s.sequences[sequenceRef.Address]
	generatorValue, memoryValue := *generator, *memory
	run(t, e, "ALTER TABLE t ALTER c TYPE BIGINT USING c+1")
	after := e.state.descriptors[tableRef.Address].(*relationDescriptor)
	if after.address != before.address || after.owner != before.owner || !reflect.DeepEqual(after.attributes, before.attributes) || !reflect.DeepEqual(after.acl, before.acl) || !reflect.DeepEqual(after.columnACL, before.columnACL) {
		t.Fatal("TYPE changed ACL/attribute/owner identity", before, after)
	}
	if e.state.descriptors[sequenceRef.Address] != sequence || e.sequences[sequenceRef.Address] != generator || *generator != generatorValue || s.sequences[sequenceRef.Address] != memory || *memory != memoryValue {
		t.Fatal("TYPE changed owned sequence identity/generator/cache")
	}
	sequenceScalar(t, s, "SELECT nextval('q')", 11)
	if got := tuples(run(t, e, "SELECT c FROM t")); len(got) != 1 || got[0][0] != int64(8) {
		t.Fatal(got)
	}
	readerOp, readerDone := roleOperation(t, e, "alter_type_reader")
	defer readerDone()
	if rows := tuples(roleExecute(t, e, readerOp, "SELECT c FROM t")); len(rows) != 1 || rows[0][0] != int64(8) {
		t.Fatal(rows)
	}
	outsider, outsiderDone := roleOperation(t, e, "alter_type_outsider")
	defer outsiderDone()
	roleError(t, e, outsider, "SELECT c FROM t", "42501", "permission denied for table t", "")
}

func TestAlterTypeIdentitySequenceMetadata(t *testing.T) {
	for _, prepared := range []bool{false, true} {
		for _, tc := range []struct {
			name, declaration, target         string
			typ                               sqltype.ID
			min, max, start, increment, cache int64
			cycle                             bool
		}{
			{"widen", "INT GENERATED BY DEFAULT AS IDENTITY", "BIGINT", sqltype.Int8, 1, math.MaxInt64, 1, 1, 1, false},
			{"same-type", "INT GENERATED ALWAYS AS IDENTITY(CACHE 5)", "INTEGER", sqltype.Int4, 1, math.MaxInt32, 1, 1, 5, false},
			{"narrow", "BIGINT GENERATED BY DEFAULT AS IDENTITY", "SMALLINT", sqltype.Int2, 1, math.MaxInt16, 1, 1, 1, false},
			{"custom", "BIGINT GENERATED BY DEFAULT AS IDENTITY(MAXVALUE 100)", "INT2", sqltype.Int2, 1, 100, 1, 1, 1, false},
			{"descending", "INT GENERATED BY DEFAULT AS IDENTITY(INCREMENT -1)", "BIGINT", sqltype.Int8, math.MinInt64, -1, -1, -1, 1, false},
			{"options", "INT GENERATED BY DEFAULT AS IDENTITY(MINVALUE -100 MAXVALUE 100 START 7 INCREMENT 3 CACHE 2 CYCLE)", "INT8", sqltype.Int8, -100, 100, 7, 3, 2, true},
		} {
			t.Run(tc.name+fmt.Sprint(prepared), func(t *testing.T) {
				e := New()
				s := sessionStart(t, e, nil)
				sessionSQL(t, s, "CREATE TABLE t(c "+tc.declaration+")")
				tableRef := roleTableRef(t, e, "t")
				sessionSQL(t, s, "CREATE USER identity_type_reader")
				reader, _ := e.Roles().Lookup("identity_type_reader")
				initial := e.state.descriptors[tableRef.Address].(*relationDescriptor)
				columnRef := tableRef
				columnRef.Address.SubID = initial.attributes[0]
				sequenceRef := roleTableRef(t, e, "t_c_seq")
				acl := authorization.ACLValue{Explicit: true, Entries: []authorization.ACLEntry{{Grantor: initial.owner, Grantee: authorization.ACLGrantee{Role: reader.Ref}, Privileges: authorization.SelectPrivilege}}}
				for _, ref := range []ObjectRef{tableRef, columnRef, sequenceRef} {
					if err := e.SetObjectACL(context.Background(), ref, acl); err != nil {
						t.Fatal(err)
					}
				}
				before := e.state.descriptors[tableRef.Address].(*relationDescriptor)
				identity := before.identities[before.attributes[0]]
				sequence := e.state.descriptors[identity.sequence].(*relationDescriptor)
				oldGenerator := *e.sequences[identity.sequence]
				notices, err := sequenceCreateRestartCommand(t, e, s, "ALTER TABLE t ALTER c TYPE "+tc.target, prepared)
				if err != nil || len(notices) != 0 {
					t.Fatal(notices, err)
				}
				after := e.state.descriptors[tableRef.Address].(*relationDescriptor)
				nextSequence := e.state.descriptors[identity.sequence].(*relationDescriptor)
				options := nextSequence.sequence
				if after.identities[after.attributes[0]] != identity || !reflect.DeepEqual(after.attributes, before.attributes) || !reflect.DeepEqual(after.acl, before.acl) || !reflect.DeepEqual(after.columnACL, before.columnACL) || after.owner != before.owner || after.address != before.address || after.columns[0].Nullable || after.columns[0].Usage.Type.ID() != tc.typ || len(after.defaults) != 0 {
					t.Fatal("identity/table metadata was lost", before, after)
				}
				if nextSequence.address != sequence.address || nextSequence.owner != sequence.owner || nextSequence.namespace != sequence.namespace || nextSequence.name != sequence.name || !reflect.DeepEqual(nextSequence.acl, sequence.acl) || options.owned != sequence.sequence.owned || !options.identity || options.persistence != sequence.sequence.persistence || options.typ != tc.typ || options.min != tc.min || options.max != tc.max || options.start != tc.start || options.increment != tc.increment || options.cache != tc.cache || options.cycle != tc.cycle {
					t.Fatal("linked sequence AS metadata", options, tc)
				}
				generator := e.sequences[identity.sequence]
				if generator.last != oldGenerator.last || generator.called != oldGenerator.called || generator.generation == oldGenerator.generation || nextSequence.revision <= sequence.revision {
					t.Fatal("AS restarted state or retained generation", oldGenerator, generator, sequence.revision, nextSequence.revision)
				}
				if err := (relationProvider{}).Validate(e.CatalogRead(), after); err != nil {
					t.Fatal(err)
				}
				if err := (relationProvider{}).Validate(e.CatalogRead(), nextSequence); err != nil {
					t.Fatal(err)
				}
			})
		}
	}
}

func TestAlterTypeIdentityFailedMetadataAtomicity(t *testing.T) {
	for _, prepared := range []bool{false, true} {
		for _, tc := range []struct{ name, declaration, setup, action, code, message string }{
			{"max-before-min", "BIGINT GENERATED BY DEFAULT AS IDENTITY(MINVALUE -40000 MAXVALUE 40000 START 1)", "", "ALTER c TYPE SMALLINT", "22023", "MAXVALUE (40000) is out of range for sequence data type smallint"},
			{"start", "BIGINT GENERATED BY DEFAULT AS IDENTITY(START 40000)", "SELECT setval('t_c_seq',1,true)", "ALTER c TYPE SMALLINT", "22023", "START value (40000) cannot be greater than MAXVALUE (32767)"},
			{"state", "BIGINT GENERATED BY DEFAULT AS IDENTITY", "SELECT setval('t_c_seq',40000,true)", "ALTER c TYPE SMALLINT", "22023", "RESTART value (40000) cannot be greater than MAXVALUE (32767)"},
			{"nonintegral", "INT GENERATED BY DEFAULT AS IDENTITY", "", "ALTER c TYPE TEXT USING c::text", "22023", "identity column type must be smallint, integer, or bigint"},
			{"row", "BIGINT GENERATED BY DEFAULT AS IDENTITY", "INSERT INTO t VALUES(32768)", "ALTER c TYPE SMALLINT", "22003", "smallint out of range"},
			{"drop-before", "INT GENERATED BY DEFAULT AS IDENTITY", "", "ALTER c DROP IDENTITY, ALTER c TYPE TEXT USING c::text", "22023", "identity column type must be smallint, integer, or bigint"},
			{"drop-after", "INT GENERATED BY DEFAULT AS IDENTITY", "", "ALTER c TYPE TEXT USING c::text, ALTER c DROP IDENTITY", "22023", "identity column type must be smallint, integer, or bigint"},
		} {
			t.Run(tc.name+fmt.Sprint(prepared), func(t *testing.T) {
				e := New()
				s := sessionStart(t, e, nil)
				sessionSQL(t, s, "CREATE TABLE t(c "+tc.declaration+")")
				if tc.setup != "" {
					r := sessionSQL(t, s, tc.setup)
					if r.Rows != nil {
						r.Rows.Close()
					}
				}
				tableRef := roleTableRef(t, e, "t")
				table := e.state.descriptors[tableRef.Address].(*relationDescriptor)
				identity := table.identities[table.attributes[0]]
				sequence := e.state.descriptors[identity.sequence]
				generator := e.sequences[identity.sequence]
				beforeGenerator := *generator
				storage := e.storage[tableRef.Address]
				notices, err := sequenceCreateRestartCommand(t, e, s, "ALTER TABLE t "+tc.action, prepared)
				if len(notices) != 0 {
					t.Fatal(notices)
				}
				sequenceCreateRestartDiagnostic(t, err, tc.code, tc.message, "")
				if e.state.descriptors[tableRef.Address] != table || e.state.descriptors[identity.sequence] != sequence || e.sequences[identity.sequence] != generator || *generator != beforeGenerator || e.storage[tableRef.Address] != storage {
					t.Fatal("failed table TYPE published sequence/table/storage prefix")
				}
			})
		}
	}
}

func TestAlterTypeIdentitySequenceGrantFreshness(t *testing.T) {
	for _, prepared := range []bool{false, true} {
		t.Run(fmt.Sprint(prepared), func(t *testing.T) {
			e := New()
			a, b := sessionStart(t, e, nil), sessionStart(t, e, nil)
			sessionSQL(t, a, "CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY)")
			tableRef := catalogRef(t, e, e.CatalogRead(), "i")
			originalTable := e.state.descriptors[tableRef.Address].(*relationDescriptor)
			originalIdentity := originalTable.identities[originalTable.attributes[0]]
			ast := statement(t, "ALTER TABLE i ALTER id TYPE BIGINT")
			var expected *StatementDescription
			if prepared {
				var description StatementDescription
				ast, description = sequencePreparedDescription(t, e, b, "ALTER TABLE i ALTER id TYPE BIGINT")
				expected = &description
			}
			tx := transactionBegin(t, a)
			sessionSQL(t, a, "ALTER SEQUENCE i_id_seq INCREMENT 3 RESTART WITH 10")
			ctx, cancel := context.WithCancel(context.Background())
			defer cancel()
			done := ownedLockAsync(e, b, ctx, ast, expected)
			ref := catalogRef(t, e, e.CatalogRead(), "i_id_seq")
			ownedLockQueued(t, e, ref, shareRowExclusive, done)
			transactionEnd(t, a, tx, true)
			lockAwait(t, done, nil)
			options := e.state.descriptors[ref.Address].(*relationDescriptor).sequence
			if options.typ != sqltype.Int8 || options.max != math.MaxInt64 || options.increment != 3 || options.start != 1 {
				t.Fatal("stale lock-grant sequence migration", options)
			}
			table := e.state.descriptors[tableRef.Address].(*relationDescriptor)
			identity := table.identities[table.attributes[0]]
			owned := tableRef.Address
			owned.SubID = originalTable.attributes[0]
			if table.attributes[0] != originalTable.attributes[0] || identity.sequence != originalIdentity.sequence || identity.mode != originalIdentity.mode || table.columns[0].Nullable || options.owned != owned || !options.identity {
				t.Fatal("grant refresh changed reciprocal identity/mode/NN", identity, options)
			}
			sessionSQL(t, b, "INSERT INTO i DEFAULT VALUES")
			transactionRows(t, b, "SELECT id FROM i", 10)
			lockEmpty(t, e)
		})
	}
}

func TestAlterTypeIdentityCanceledSequencePublication(t *testing.T) {
	e := New()
	a, b := sessionStart(t, e, nil), sessionStart(t, e, nil)
	sessionSQL(t, a, "CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY)")
	ref := catalogRef(t, e, e.CatalogRead(), "i_id_seq")
	before := e.state.descriptors[ref.Address]
	generator := e.sequences[ref.Address]
	state := *generator
	tx := transactionBegin(t, a)
	sessionSQL(t, a, "ALTER SEQUENCE i_id_seq RESTART WITH 10")
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	done := lockAsync(e, b, ctx, "ALTER TABLE i ALTER id TYPE BIGINT", false)
	ownedLockQueued(t, e, ref, shareRowExclusive, done)
	cancel()
	lockAwait(t, done, context.Canceled)
	transactionEnd(t, a, tx, false)
	if e.state.descriptors[ref.Address] != before || e.sequences[ref.Address] != generator || *generator != state {
		t.Fatal("canceled TYPE published sequence")
	}
	sessionSQL(t, b, "INSERT INTO i DEFAULT VALUES")
	transactionRows(t, b, "SELECT id FROM i", 1)
	lockEmpty(t, e)
}

