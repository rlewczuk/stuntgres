func TestAlterTypeIdentityHeldExplicitSourceMetadata(t *testing.T) {
	e := New()
	run(t, e, "CREATE TABLE t(c INT GENERATED BY DEFAULT AS IDENTITY)")
	op, cleanup, err := testOperation(e, context.Background())
	if err != nil {
		t.Fatal(err)
	}
	defer cleanup()
	ast := statement(t, "INSERT INTO t VALUES($1)")
	held, err := e.Describe(op, ast)
	if err != nil || len(held.Parameters.Types) != 1 || held.Parameters.Types[0].Type.ID() != sqltype.Int4 {
		t.Fatal(held, err)
	}
	original := held.Parameters.Types[0]
	run(t, e, "ALTER TABLE t ALTER c TYPE BIGINT")
	fresh, err := e.Describe(op, ast)
	if err != nil || len(fresh.Parameters.Types) != 1 || fresh.Parameters.Types[0].Type.ID() != sqltype.Int8 {
		t.Fatal(fresh, err)
	}
	scope, err := e.StartStatement(op)
	if err != nil {
		t.Fatal(err)
	}
	scope.Expected = &held
	_, executeErr := scope.Execute(ast, 1, func(ctx context.Context, p analyze.ParameterInfo, frame []sqltype.Value, input sqltype.InputEnvironment) error {
		if p.Types[0] != original {
			t.Fatal("identity input source changed", p.Types, original)
		}
		value, err := p.Types[0].Type.InputWithEnvironment(ctx, "7", -1, input)
		frame[0] = value
		return err
	})
	if err := scope.Finish(executeErr); err != nil || executeErr != nil {
		t.Fatal(executeErr, err)
	}
	ref := roleTableRef(t, e, "t_c_seq")
	if g := e.storage.Sequences[ref.Address]; g.Last != 1 || g.Called {
		t.Fatal("explicit BY DEFAULT input demanded identity", g)
	}
	run(t, e, "INSERT INTO t DEFAULT VALUES")
	result := run(t, e, "SELECT c FROM t ORDER BY c")
	rows := tuples(result)
	if result.Rows.Schema()[0].Usage.Type.ID() != sqltype.Int8 || len(rows) != 2 || rows[0][0] != int64(1) || rows[1][0] != int64(7) {
		t.Fatal(result, rows)
	}
}

func TestAlterTypeIdentityRefreshedDependencyFences(t *testing.T) {
	for _, name := range []string{"current", "missing-original", "stale-original", "post-grant-change", "plain-auto", "new-identity", "changed-check"} {
		t.Run(name, func(t *testing.T) {
			e := New()
			run(t, e, "CREATE TABLE t(c INT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ck CHECK(c>0))")
			run(t, e, "CREATE SEQUENCE q OWNED BY t.c")
			tableRef := roleTableRef(t, e, "t")
			table := e.catalog.state.MustRelation(tableRef.Address)
			sequence := table.ColumnMeta.Identities[table.Attributes[0]].Sequence
			if name == "plain-auto" {
				sequence = roleTableRef(t, e, "q").Address
			}
			base := e.catalog.state
			old := base.MustRelation(sequence)
			current := *old
			options := *old.Sequence
			options.Increment = 3
			current.Sequence = &options
			e.mu.Lock()
			e.catalog.state = catalog.CloneState(base)
			e.catalog.state.SetDescriptor(sequence, &current)
			changes := session.NewJournal()
			changes.Originals[sequence] = &current
			target := tableRef.Address
			target.SubID = table.Attributes[0]
			observationBase := base
			switch name {
			case "missing-original":
				delete(changes.Originals, sequence)
			case "stale-original":
				changes.Originals[sequence] = old
			case "post-grant-change":
				later := current
				e.catalog.state.SetDescriptor(sequence, &later)
			case "new-identity":
				observationBase = catalog.CloneState(base)
				observationBase.RemoveDescriptor(sequence)
				changes.Originals[sequence] = nil
			case "changed-check":
				changed := *table
				changed.Constraints.Check = append([]catalog.CheckConstraint(nil), table.Constraints.Check...)
				extra := changed.Constraints.Check[0]
				extra.Name = "late_check"
				changed.Constraints.Check = append(changed.Constraints.Check, extra)
				e.catalog.state.SetDescriptor(tableRef.Address, &changed)
				changes.Originals[tableRef.Address] = &changed
			}
			changes.Dependencies = append(changes.Dependencies, catalogDependencyObservation{observationBase, []ids.ObjectAddress{target}})
			err := e.catalogPreflightLocked(changes)
			e.mu.Unlock()
			if name == "current" {
				if err != nil {
					t.Fatal("exact current identity refresh rejected", err)
				}
			} else {
				var conflict catalog.Conflict
				if !errors.As(err, &conflict) {
					t.Fatal("dependency/original fence weakened", name, err)
				}
			}
		})
	}
}
