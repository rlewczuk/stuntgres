func tableLikeTemporaryRelation(t *testing.T, e *Engine, namespace ids.ObjectAddress, name string) *catalog.Relation {
	t.Helper()
	view := e.CatalogRead()
	addresses := view.Lookup(ids.NameKey{ClassID: ids.RelationClassID, Namespace: namespace, Name: name})
	if len(addresses) != 1 {
		t.Fatal(name, addresses)
	}
	return view.MustRelation(addresses[0])
}

func TestTableLikeTemporaryDefaultAuthority(t *testing.T) {
	for _, typ := range []string{"BIGINT", "INT"} {
		t.Run(typ, func(t *testing.T) {
			e := New()
			owner := sessionStart(t, e, nil)
			peer := sessionStart(t, e, nil)
			sessionSQL(t, owner, "CREATE TEMP SEQUENCE seed START 31 CACHE 1")
			sessionSQL(t, peer, "CREATE TEMP SEQUENCE peer_seed START 901 CACHE 1")
			sessionSQL(t, owner, "CREATE TEMP TABLE src(id BIGINT GENERATED BY DEFAULT AS IDENTITY(START 7 INCREMENT 3),v "+typ+" DEFAULT nextval('pg_temp.seed'))")
			source := tableLikeTemporaryRelation(t, e, owner.temporaryNamespace, "src")
			seed := tableLikeTemporaryRelation(t, e, owner.temporaryNamespace, "seed")
			old := source.ColumnMeta.Defaults[2]
			manifest := slices.Clone(old.Dependencies)
			generator := *e.storage.Sequences[seed.Address()]
			var call functions.SequenceCall
			calls := 0
			walkBoundExpression(old.Expression, func(node expr.Expr) {
				if n, ok := node.(functions.SequenceCall); ok {
					call = n
					calls++
				}
			})
			if calls != 1 || call.Temporary != owner.token || call.Ref.Address != seed.Address() || call.Ref.Domain() != e.catalog.Domain {
				t.Fatal("fixture lacks exact temporary sequence authority", call, calls)
			}
			op, err := owner.Acquire(context.Background())
			if err != nil {
				t.Fatal(err)
			}
			defer op.Done()
			stage, destination, err := tableLikeBuild(t, e, op, "CREATE TEMP TABLE own_copy(LIKE pg_temp.src INCLUDING DEFAULTS)")
			defer e.DiscardCatalogStage(stage)
			if err != nil {
				t.Fatal(err)
			}
			copied := destination.ColumnMeta.Defaults[2]
			if !reflect.DeepEqual(copied.Expression, old.Expression) || copied.OID == 0 || copied.OID == old.OID || !slices.Equal(copied.Dependencies, manifest) || len(destination.ColumnMeta.Identities) != 0 {
				t.Fatal("cooked default identity/provider drift", copied)
			}
			if _, err := (scalarRenderer{provenance: destination, capturedManifest: copied.Dependencies}).sql(context.Background(), e.stageRead(stage), copied.Expression); err != nil {
				t.Fatal(err)
			}
			foreign := *destination
			foreign.ObjectNamespace = peer.temporaryNamespace
			foreign.ColumnMeta.Defaults = nil
			e.mu.Lock()
			auth, err := e.authorizationLocked(op)
			if err == nil {
				err = e.stageLikeColumns(op, auth, stage, &foreign, []createLikeInput{{source: source, options: likeDefaults}})
			}
			e.mu.Unlock()
			sequenceOwnerDiagnostic(t, err, "0A000", "temporary sequence DEFAULT is unsupported", "")
			if len(foreign.ColumnMeta.Defaults) != 0 {
				t.Fatal("foreign physical token imported default")
			}
			before := e.catalog.state
			stores, generators := len(e.storage.Relations), len(e.storage.Sequences)
			bad, _, err := tableLikeBuild(t, e, op, "CREATE TABLE public.rejected(LIKE pg_temp.src INCLUDING ALL)")
			defer e.DiscardCatalogStage(bad)
			sequenceOwnerDiagnostic(t, err, "0A000", "temporary sequence DEFAULT is unsupported", "")
			if len(bad.sequence.stagedGenerators()) == 0 {
				t.Fatal("fixture did not stage fresh identity before rejection")
			}
			if e.catalog.state != before || len(e.storage.Relations) != stores || len(e.storage.Sequences) != generators || *e.storage.Sequences[seed.Address()] != generator || !reflect.DeepEqual(source.ColumnMeta.Defaults[2].Expression, old.Expression) || !slices.Equal(source.ColumnMeta.Defaults[2].Dependencies, manifest) {
				t.Fatal("rejected/default cooking evaluated or published source state")
			}
			for _, name := range []string{"rejected", "rejected_id_seq"} {
				if len(e.CatalogRead().Lookup(ids.NameKey{ClassID: ids.RelationClassID, Namespace: ids.ObjectAddress{ClassID: ids.NamespaceClassID, ObjectID: ids.PublicNamespaceOID}, Name: name})) != 0 {
					t.Fatal("failed candidate published", name)
				}
			}
		})
	}
}

func TestTableLikeTemporaryIdentityStage(t *testing.T) {
	for _, sourceTemporary := range []bool{false, true} {
		for _, destinationTemporary := range []bool{false, true} {
			t.Run(map[bool]string{false: "Permanent", true: "Temporary"}[sourceTemporary]+"To"+map[bool]string{false: "Permanent", true: "Temporary"}[destinationTemporary], func(t *testing.T) {
				e := New()
				owner := sessionStart(t, e, nil)
				sessionSQL(t, owner, "CREATE TEMP SEQUENCE marker")
				prefix, sourceName := "", "public.src"
				sourceNamespace := ids.ObjectAddress{ClassID: ids.NamespaceClassID, ObjectID: ids.PublicNamespaceOID}
				if sourceTemporary {
					prefix = "TEMP "
					sourceName = "pg_temp.src"
					sourceNamespace = owner.temporaryNamespace
				}
				sessionSQL(t, owner, "CREATE "+prefix+"TABLE "+sourceName+"(id BIGINT GENERATED BY DEFAULT AS IDENTITY(START 7 INCREMENT 3 MINVALUE 1 MAXVALUE 100 CACHE 1 NO CYCLE))")
				sessionSQL(t, owner, "INSERT INTO "+sourceName+" DEFAULT VALUES")
				sessionSQL(t, owner, "INSERT INTO "+sourceName+" DEFAULT VALUES")
				source := tableLikeTemporaryRelation(t, e, sourceNamespace, "src")
				sourceIdentity := source.ColumnMeta.Identities[1]
				sourceSequence := e.catalog.state.MustRelation(sourceIdentity.Sequence)
				generator := *e.storage.Sequences[sourceIdentity.Sequence]
				op, err := owner.Acquire(context.Background())
				if err != nil {
					t.Fatal(err)
				}
				defer op.Done()
				prefix = ""
				persistence := "logged"
				namespace := ids.ObjectAddress{ClassID: ids.NamespaceClassID, ObjectID: ids.PublicNamespaceOID}
				if destinationTemporary {
					prefix = "TEMP "
					persistence = "temporary"
					namespace = owner.temporaryNamespace
				}
				stage, destination, err := tableLikeBuild(t, e, op, "CREATE "+prefix+"TABLE copied(LIKE "+sourceName+" INCLUDING IDENTITY)")
				defer e.DiscardCatalogStage(stage)
				if err != nil {
					t.Fatal(err)
				}
				identity := destination.ColumnMeta.Identities[1]
				sequence := stage.Get(identity.Sequence).(*catalog.Relation)
				fresh := stage.sequence.generator(identity.Sequence)
				want := *sourceSequence.Sequence
				want.Persistence = persistence
				want.Owned = ids.ObjectAddress{ClassID: ids.RelationClassID, ObjectID: destination.Address().ObjectID, SubID: 1}
				if destination.Namespace() != namespace || sequence.Namespace() != namespace || sequence.Owner != destination.Owner || identity.Sequence == sourceIdentity.Sequence || sequence.Revision() == sourceSequence.Revision() || !reflect.DeepEqual(*sequence.Sequence, want) || fresh == nil || fresh.Called || fresh.Last != 7 || identity.Mode != sourceIdentity.Mode || len(destination.ColumnMeta.Defaults) != 0 {
					t.Fatal("fresh identity destination ownership/persistence/config/state", destination, sequence, fresh)
				}
				if ns := e.catalog.state.MustNamespace(namespace); destinationTemporary && ns.Temporary != owner.token {
					t.Fatal("destination temporary token drift")
				}
				if *e.storage.Sequences[sourceIdentity.Sequence] != generator {
					t.Fatal("identity CREATE advanced source")
				}
			})
		}
	}
}

func TestTableLikeTemporaryRetainedCopy(t *testing.T) {
	e := New()
	owner := sessionStart(t, e, nil)
	sessionSQL(t, owner, "CREATE TEMP SEQUENCE seed START 31 CACHE 1")
	sessionSQL(t, owner, "CREATE TEMP TABLE src(v BIGINT DEFAULT nextval('pg_temp.seed'))")
	source := tableLikeTemporaryRelation(t, e, owner.temporaryNamespace, "src")
	old := source.ColumnMeta.Defaults[1]
	manifest := slices.Clone(old.Dependencies)
	seed := tableLikeTemporaryRelation(t, e, owner.temporaryNamespace, "seed")
	generator := *e.storage.Sequences[seed.Address()]
	var call functions.SequenceCall
	walkBoundExpression(old.Expression, func(node expr.Expr) {
		if n, ok := node.(functions.SequenceCall); ok {
			call = n
		}
	})
	if err := e.Reset(context.Background()); err != nil {
		t.Fatal(err)
	}
	op, err := owner.Acquire(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	defer op.Done()
	scope, err := e.StartStatement(op)
	if err != nil {
		t.Fatal(err)
	}
	finished := false
	defer func() {
		if !finished {
			_ = scope.Finish(context.Canceled)
		}
	}()
	if err := scope.gate(statement(t, "CREATE TEMP TABLE retained_copy(LIKE pg_temp.src INCLUDING DEFAULTS)")); err != nil {
		t.Fatal(err)
	}
	stage, destination, err := tableLikeBuild(t, e, op, "CREATE TEMP TABLE retained_copy(LIKE pg_temp.src INCLUDING DEFAULTS)")
	defer e.DiscardCatalogStage(stage)
	if err != nil {
		op.Done()
		e.DiscardCatalogStage(stage)
		t.Fatal(err)
	}
	copied := destination.ColumnMeta.Defaults[1]
	if !reflect.DeepEqual(copied.Expression, old.Expression) || copied.OID == old.OID || !slices.Equal(copied.Dependencies, manifest) || *e.storage.Sequences[seed.Address()] != generator {
		t.Fatal("retained cooked default lost original manifest/identity or advanced provider", copied)
	}
	view := e.stageRead(stage)
	if call.Ref.Epoch == view.Epoch() || !storedSequenceEpochValid(view, destination, call.Ref, call.Temporary) {
		t.Fatal("retained manifest lacks bounded old-epoch authority", call.Ref)
	}
	if err := e.ValidateObjectRef(view, call.Ref); err == nil {
		t.Fatal("generic stale ObjectRef admitted")
	}
	for _, bad := range []ids.ObjectRef{New().catalog.Domain.Ref(call.Ref.Epoch, call.Ref.Address), e.catalog.Domain.Ref(view.Epoch()+1, call.Ref.Address)} {
		if storedSequenceEpochValid(view, destination, bad, call.Temporary) {
			t.Fatal("foreign/future reference admitted", bad)
		}
	}
	if storedSequenceEpochValid(view, destination, call.Ref, ids.SessionToken{}) {
		t.Fatal("zero token admitted stale temporary sequence")
	}
	var rendered []ids.ObjectRef
	if _, err := (scalarRenderer{provenance: destination, capturedManifest: copied.Dependencies, dependencies: &rendered}).sql(context.Background(), view, copied.Expression); err != nil || !slices.Equal(rendered, manifest) {
		t.Fatal("DEFAULT renderer reminted retained refs", rendered, err)
	}
	// The copied DEFAULT owner must retain its closed-row policy, not borrow a row owner.
	integer, _ := view.LookupType(sqltype.Int8)
	row := columnExpression{Info: expr.Info{Usage: integer.Usage(), Property: expr.Properties{RowDependent: true}}, Origin: e.catalog.Domain.Ref(view.Epoch(), ids.ObjectAddress{ClassID: ids.RelationClassID, ObjectID: destination.Address().ObjectID, SubID: 1}), Scope: 1, Frame: 1, Slot: 0}
	if _, err := (scalarRenderer{provenance: destination}).sql(context.Background(), view, row); err == nil {
		t.Fatal("DEFAULT provenance widened row policy")
	}
	// Admission must prove the original SubID before whole-object lock dedup.
	attribute := e.catalog.Domain.Ref(call.Ref.Epoch, source.Address())
	attribute.Address.SubID = 1
	removed := attribute
	removed.Address.SubID = 2
	foreign := call.Ref
	foreign = New().catalog.Domain.Ref(foreign.Epoch, foreign.Address)
	future := call.Ref
	future.Epoch = stage.Base.Epoch() + 1
	for _, tc := range []struct {
		name      string
		ref       ids.ObjectRef
		permanent bool
		want      bool
	}{
		{"removed attribute", removed, false, false},
		{"foreign owner", foreign, false, false},
		{"future epoch", future, false, false},
		{"permanent consumer", call.Ref, true, false},
		{"live retained attribute", attribute, false, true},
	} {
		candidate := e.BeginCatalogStage(stage.Base)
		consumer := *destination
		if tc.permanent {
			consumer.ObjectNamespace = ids.ObjectAddress{ClassID: ids.NamespaceClassID, ObjectID: ids.PublicNamespaceOID}
		}
		consumer.ColumnMeta.Defaults = map[int32]catalog.ColumnDefault{1: {Dependencies: []ids.ObjectRef{tc.ref}}}
		if err := candidate.Create(&consumer); err != nil {
			t.Fatal(err)
		}
		err := scope.acquireDefinitionProviders(candidate)
		e.DiscardCatalogStage(candidate)
		if (err == nil) != tc.want {
			t.Fatal("retained admission contextual authority", tc.name, err)
		}
	}
	if err := scope.acquireDefinitionProviders(stage); err != nil {
		t.Fatal("retained copied DEFAULT provider admission", err)
	}
	if !slices.Equal(destination.ColumnMeta.Defaults[1].Dependencies, manifest) {
		t.Fatal("admission retagged persisted manifest")
	}
	if err := scope.Finish(context.Canceled); err != context.Canceled {
		t.Fatal("retained admission cleanup", err)
	}
	finished = true
	op.Done()
	e.DiscardCatalogStage(stage)
	sessionSQL(t, owner, "DROP SEQUENCE pg_temp.seed CASCADE")
	sessionSQL(t, owner, "CREATE TEMP SEQUENCE seed START 901")
	if storedSequenceEpochValid(e.CatalogRead(), destination, call.Ref, call.Temporary) {
		t.Fatal("retired reference adopted recreated provider name")
	}
	if !reflect.DeepEqual(source.ColumnMeta.Defaults[1].Expression, old.Expression) || !slices.Equal(old.Dependencies, manifest) {
		t.Fatal("retained source definition mutated")
	}
}
