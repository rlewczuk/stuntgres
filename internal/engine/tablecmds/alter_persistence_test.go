func TestAlterPersistenceMetadata(t *testing.T) {
	e:=engine.New()
	s:=enginetest.StartSession(t,e,nil)
	for _,q:=range []string{"CREATE UNLOGGED TABLE t(id serial PRIMARY KEY,n int GENERATED BY DEFAULT AS IDENTITY,note text DEFAULT 'keep')","CREATE INDEX note_idx ON t(note)","COMMENT ON TABLE t IS 'owned metadata'"} {enginetest.SessionSQL(t,s,q)}
	// COMMENT ON INDEX is not a SQL entry point in this baseline. Seed its
	// representable immutable payload through the incumbent catalog stage.
	indexAddress:=roleTableRef(t,e,"note_idx").Address
	indexOriginal:=e.Catalog.State.MustRelation(indexAddress)
	indexChanged:=*indexOriginal
	indexChanged.Comment="index-comment"
	indexChanged.ObjectRevision=indexOriginal.Revision()+1
	setup:=e.BeginCatalogStage(e.CatalogRead())
	if err:=setup.Replace(&indexChanged);err!=nil {t.Fatal(err)}
	ownershipUnitPublish(t,e,setup)
	e.DiscardCatalogStage(setup)
	seededIndex:=e.Catalog.State.MustRelation(indexAddress)
	ref:=roleTableRef(t,e,"t")
	old:=e.Catalog.State.MustRelation(ref.Address)
	heap:=e.Storage.Relations[ref.Address]
	before:=*old
	enginetest.SessionSQL(t,s,"ALTER TABLE t SET LOGGED")
	next:=e.Catalog.State.MustRelation(ref.Address)
	if next==old || next.Revision()<=old.Revision() || old.Persistence!="unlogged" || next.Persistence!="logged" || !reflect.DeepEqual(*old,before) {t.Fatal("missing immutable descriptor revision transition")}
	if next.RowType!=old.RowType || next.Owner!=old.Owner || next.Comment!=old.Comment || &next.Columns[0]!=&old.Columns[0] || &next.Attributes[0]!=&old.Attributes[0] || !reflect.DeepEqual(next.Security,old.Security) || !reflect.DeepEqual(next.ColumnMeta,old.ColumnMeta) || !reflect.DeepEqual(next.Constraints,old.Constraints) || e.Storage.Relations[ref.Address]!=heap {t.Fatal("persistence changed unrelated metadata/backing/heap")}
	for _,name:=range []string{"t","t_pkey","note_idx","t_id_seq","t_n_seq"} {r:=e.Catalog.State.MustRelation(roleTableRef(t,e,name).Address);if pgcatalog.ClassPersistence(e.CatalogRead(),r)!="p" {t.Fatal(name)}}
	if e.Catalog.State.Get(indexAddress)!=seededIndex || seededIndex.Comment!="index-comment" || indexOriginal.Comment!="" {t.Fatal("persistence replaced index authority/comment or mutated predecessor")}
	enginetest.SessionSQL(t,s,"ALTER TABLE t SET LOGGED")
	if e.Catalog.State.Get(ref.Address)!=next || e.Storage.Relations[ref.Address]!=heap {t.Fatal("no-op replaced table/heap authority")}
}

func TestAlterPersistencePreparation(t *testing.T) {
	e:=engine.New()
	s:=enginetest.StartSession(t,e,nil)
	enginetest.SessionSQL(t,s,"CREATE TABLE t(id int)")
	d:=e.Catalog.State.MustRelation(roleTableRef(t,e,"t").Address)
	view:=e.CatalogRead()
	noop,err:=table.PreparePersistence(view,d,parser.SetLogged,table.PersistencePreparation{})
	if err!=nil || noop.Changed {t.Fatal(noop,err)}
	change,err:=table.PreparePersistence(view,d,parser.SetUnlogged,noop)
	if err!=nil || !change.Changed || change.Destination!="unlogged" {t.Fatal(change,err)}
	for _,action:=range []parser.AlterTableActionKind{parser.SetLogged,parser.SetUnlogged} {if _,err=table.PreparePersistence(view,d,action,change);err==nil {t.Fatal("repeated genuine change admitted")}}
	if d.Persistence!="logged" || e.Catalog.State.Get(d.Address())!=d {t.Fatal("preparation changed catalog")}
}

func TestAlterPersistenceSequenceEffects(t *testing.T) {
	t.Run("self-sequence",func(t *testing.T) {
		e:=engine.New();s:=enginetest.StartSession(t,e,nil)
		enginetest.SessionSQL(t,s,"CREATE SEQUENCE q CACHE 5")
		sequenceScalar(t,s,"SELECT nextval('q')",1)
		ref:=roleTableRef(t,e,"q").Address
		old:=e.Catalog.State.MustRelation(ref)
		generator:=e.Storage.Sequences[ref];state:=*generator
		memory:=core.PayloadOf(s).Sequences.Memory(ref);saved:=*memory
		enginetest.SessionSQL(t,s,"ALTER TABLE q SET LOGGED")
		if e.Catalog.State.Get(ref)!=old || e.Storage.Sequences[ref]!=generator || *memory!=saved {t.Fatal("self no-op replaced authority")}
		enginetest.SessionSQL(t,s,"ALTER TABLE q SET UNLOGGED")
		next:=e.Catalog.State.MustRelation(ref)
		replacement:=e.Storage.Sequences[ref]
		if next==old || next.Sequence.Persistence!="unlogged" || next.Persistence!=old.Persistence || next.SequencePlanStamp==old.SequencePlanStamp || replacement.Generation==state.Generation || replacement.Last!=state.Last || replacement.Called!=state.Called || *memory!=saved || *generator!=state || e.Storage.Relations[ref]!=nil {t.Fatal("self target changed wrong property/backing/generation/cache")}
		sequenceScalar(t,s,"SELECT nextval('q')",6)
	})
	t.Run("no-demand-rollback",func(t *testing.T) {
		e:=engine.New();s:=enginetest.StartSession(t,e,nil)
		enginetest.SessionSQL(t,s,"CREATE TABLE t(id int)")
		enginetest.SessionSQL(t,s,"CREATE SEQUENCE q CACHE 5 OWNED BY t.id")
		sequenceScalar(t,s,"SELECT nextval('q')",1)
		ref:=roleTableRef(t,e,"q").Address
		original:=e.Catalog.State.Get(ref)
		generator:=e.Storage.Sequences[ref]
		before:=*generator
		memory:=core.PayloadOf(s).Sequences.Memory(ref)
		saved:=*memory
		tx:=enginetest.TransactionBegin(t,s)
		enginetest.SessionSQL(t,s,"ALTER TABLE t SET UNLOGGED")
		if *memory!=saved || e.Storage.Sequences[ref]!=generator || *generator!=before {t.Fatal("private persistence eagerly adopted or published generator")}
		enginetest.TransactionEnd(t,s,tx,false)
		if e.Catalog.State.Get(ref)!=original || e.Storage.Sequences[ref]!=generator || *memory!=saved {t.Fatal("rollback without demand changed cache/backing")}
		sequenceScalar(t,s,"SELECT nextval('q')",2)
	})
	for _,prealigned:=range []bool{false,true} {
		t.Run(map[bool]string{false:"ordinary",true:"prealigned"}[prealigned],func(t *testing.T) {
			e:=engine.New();s:=enginetest.StartSession(t,e,nil)
			enginetest.SessionSQL(t,s,"CREATE TABLE t(id int)")
			prefix:="";if prealigned {prefix="UNLOGGED "}
			enginetest.SessionSQL(t,s,"CREATE "+prefix+"SEQUENCE q CACHE 5 OWNED BY t.id")
			enginetest.SessionSQL(t,s,"CREATE SEQUENCE unrelated")
			sequenceScalar(t,s,"SELECT nextval('q')",1)
			ref:=roleTableRef(t,e,"q").Address
			old:=e.Catalog.State.MustRelation(ref)
			generator:=e.Storage.Sequences[ref];state:=*generator
			memory:=core.PayloadOf(s).Sequences.Memory(ref);saved:=*memory
			unrelated:=e.Catalog.State.Get(roleTableRef(t,e,"unrelated").Address)
			enginetest.SessionSQL(t,s,"ALTER TABLE t SET LOGGED")
			if e.Catalog.State.Get(ref)!=old || e.Storage.Sequences[ref]!=generator || *memory!=saved {t.Fatal("same-state table touched divergent owned sequence")}
			enginetest.SessionSQL(t,s,"ALTER TABLE t SET UNLOGGED")
			next:=e.Catalog.State.MustRelation(ref);replacement:=e.Storage.Sequences[ref]
			if next==old || next.SequencePlanStamp==old.SequencePlanStamp || replacement==generator || replacement.Generation==state.Generation || replacement.Last!=state.Last || replacement.Called!=state.Called || next.Sequence.Persistence!="unlogged" || *memory!=saved || *generator!=state {t.Fatal("forced owned rewrite/eager cache/immutable generator violation")}
			if e.Catalog.State.Get(unrelated.Address())!=unrelated {t.Fatal("unrelated sequence changed")}
			sequenceScalar(t,s,"SELECT nextval('q')",6)
			if memory.Generation()!=replacement.Generation {t.Fatal("demand failed lazy adoption")}
		})
	}
}

func TestAlterPersistenceDump(t *testing.T) {
	e:=engine.New();s:=enginetest.StartSession(t,e,nil)
	enginetest.SessionSQL(t,s,"CREATE UNLOGGED TABLE t(id int GENERATED BY DEFAULT AS IDENTITY)")
	enginetest.SessionSQL(t,s,"ALTER SEQUENCE t_id_seq SET LOGGED")
	var dump bytes.Buffer
	if err:=engine.Dump(context.Background(),e,&dump);err!=nil {t.Fatal(err)}
	if !strings.Contains(dump.String(),`CREATE UNLOGGED TABLE "public"."t"`) || !strings.Contains(dump.String(),`ALTER SEQUENCE "public"."t_id_seq" SET LOGGED;`) {t.Fatal(dump.String())}
}
