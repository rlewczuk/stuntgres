func TestIdentityAlterSequenceGrantFreshness(t *testing.T) {
	for _, action := range []string{`ALTER TABLE i ALTER id SET CACHE 2`, `ALTER TABLE i ALTER id RESTART WITH 20`, `ALTER TABLE i ALTER id DROP IDENTITY`} {
		t.Run(action, func(t *testing.T) {
			e := engine.New()
			a, b := enginetest.StartSession(t, e, nil), enginetest.StartSession(t, e, nil)
			enginetest.SessionSQL(t, a, `CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY)`)
			tx := enginetest.TransactionBegin(t, a)
			enginetest.SessionSQL(t, a, `ALTER SEQUENCE i_id_seq INCREMENT 3 RESTART WITH 10`)
			ctx, cancel := context.WithCancel(context.Background())
			defer cancel()
			done := enginetest.LockAsync(e, b, ctx, action, false)
			ref := enginetest.CatalogRef(t, e, e.CatalogRead(), "i_id_seq")
			mode := lock.ShareRowExclusive
			if action == `ALTER TABLE i ALTER id DROP IDENTITY` {
				mode = lock.AccessExclusive
			}
			ownedLockQueued(t, e, ref, mode, done)
			enginetest.TransactionEnd(t, a, tx, true)
			enginetest.LockAwait(t, done, nil)
			if action == `ALTER TABLE i ALTER id DROP IDENTITY` {
				table := e.Catalog.State.MustRelation(enginetest.CatalogRef(t, e, e.CatalogRead(), "i").Address)
				if len(table.ColumnMeta.Identities) != 0 || e.Catalog.State.Get(ref.Address) != nil {
					t.Fatal("drop lost exact linked identity")
				}
				enginetest.SessionSQL(t, b, `INSERT INTO i VALUES(55)`)
			} else {
				d := e.Catalog.State.MustRelation(ref.Address)
				if d.Sequence.Increment != 3 {
					t.Fatal("stale option overwrite", d.Sequence.Increment)
				}
				enginetest.SessionSQL(t, b, `INSERT INTO i DEFAULT VALUES`)
				want := int64(10)
				if action == `ALTER TABLE i ALTER id RESTART WITH 20` {
					want = 20
				}
				enginetest.TransactionRows(t, b, `SELECT id FROM i`, want)
			}
			enginetest.LockEmpty(t, e)
		})
	}
}

func TestIdentityAlterCanceledPublication(t *testing.T) {
	for _, action := range []string{
		`ALTER TABLE i ALTER id DROP IDENTITY`,
		`ALTER TABLE i ALTER id SET CACHE 2`,
		`ALTER TABLE i ALTER id RESTART 100`,
		`ALTER TABLE i ALTER id SET GENERATED BY DEFAULT, ALTER id RESTART 100`,
	} {
		t.Run(action, func(t *testing.T) {
			e := engine.New()
			a, b := enginetest.StartSession(t, e, nil), enginetest.StartSession(t, e, nil)
			enginetest.SessionSQL(t, a, `CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY)`)
			tableRef := enginetest.CatalogRef(t, e, e.CatalogRead(), "i")
			sequenceRef := enginetest.CatalogRef(t, e, e.CatalogRead(), "i_id_seq")
			state, storage := e.Catalog.State, e.Storage.Relations[tableRef.Address]
			generator := *e.Storage.Sequences[sequenceRef.Address]
			tx := enginetest.TransactionBegin(t, a)
			enginetest.SessionSQL(t, a, `ALTER SEQUENCE i_id_seq RESTART WITH 10`)
			ctx, cancel := context.WithCancel(context.Background())
			defer cancel()
			done := enginetest.LockAsync(e, b, ctx, action, false)
			mode := lock.ShareRowExclusive
			if action == `ALTER TABLE i ALTER id DROP IDENTITY` {
				mode = lock.AccessExclusive
			}
			ownedLockQueued(t, e, sequenceRef, mode, done)
			cancel()
			enginetest.LockAwait(t, done, context.Canceled)
			if e.Catalog.State != state || e.Storage.Relations[tableRef.Address] != storage || *e.Storage.Sequences[sequenceRef.Address] != generator {
				t.Fatal("canceled exact linked wait published its private prefix")
			}
			enginetest.TransactionEnd(t, a, tx, false)
			enginetest.LockEmpty(t, e)
			enginetest.SessionSQL(t, b, `INSERT INTO i DEFAULT VALUES`)
			enginetest.TransactionRows(t, b, `SELECT id FROM i`, 1)
			enginetest.LockEmpty(t, e)
		})
	}
}
