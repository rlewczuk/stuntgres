package tablecmds_test

import (
	"context"
	"database/sql/driver"
	"errors"
	"reflect"
	"testing"

	"stuntgres/internal/engine"
	"stuntgres/internal/engine/catalog"
	"stuntgres/internal/engine/core"
	"stuntgres/internal/engine/enginetest"
	"stuntgres/internal/engine/ids"
	"stuntgres/internal/engine/stored"
)

func TestAlterTypeGrowingDependencyClosure(t *testing.T) {
	for _, tc := range []struct {
		declaration, seed, action string
		value                     driver.Value
	}{
		{"c VARCHAR(5)", "('seven')", "ALTER c TYPE VARCHAR(8)", "seven"},
		{"c VARCHAR(5)", "('seven')", "ALTER c TYPE VARCHAR(5)", "seven"},
		{"c VARCHAR(5)", "('seven')", `ALTER c TYPE VARCHAR(5) COLLATE "C"`, "seven"},
		{"c INT GENERATED BY DEFAULT AS IDENTITY", "(7)", "ALTER c TYPE BIGINT", int64(7)},
		{"c INT GENERATED BY DEFAULT AS IDENTITY", "(7)", "ALTER c TYPE INT", int64(7)},
	} {
		action := tc.action
		t.Run(action, func(t *testing.T) {
			e := engine.New()
			enginetest.Run(t, e, "CREATE TABLE t("+tc.declaration+")")
			enginetest.Run(t, e, "INSERT INTO t VALUES"+tc.seed)
			enginetest.Run(t, e, "CREATE VIEW template AS SELECT c FROM t")
			table := enginetest.RoleTableRef(t, e, "t")
			view := enginetest.RoleTableRef(t, e, "template")
			old, store := e.Catalog.State.Get(table.Address), e.Storage.Relations[table.Address]
			originalView := e.Catalog.State.MustRelation(view.Address)
			removeView := func(ref ids.ObjectRef) {
				t.Helper()
				stage := e.BeginCatalogStage(e.CatalogRead())
				defer e.DiscardCatalogStage(stage)
				if err := stage.Remove(ref); err != nil {
					t.Fatal(err)
				}
				prepared, err := e.ValidateCatalogStage(context.Background(), stage)
				if err != nil {
					t.Fatal(err)
				}
				if _, err := enginetest.PublishCatalog(e, prepared, core.PublicationToken{Epoch: ref.Epoch}); err != nil {
					t.Fatal(err)
				}
			}
			removeView(view)
			provider := e.Catalog.Providers[ids.RelationClassID]
			var added ids.ObjectAddress
			e.Catalog.Providers[ids.RelationClassID] = alterDropProvider{provider, func() {
				e.Catalog.Providers[ids.RelationClassID] = provider
				e.Mu.Lock()
				oid, allocationErr := e.Catalog.AllocateOIDLocked()
				if allocationErr != nil {
					e.Mu.Unlock()
					t.Fatal(allocationErr)
				}
				rule, allocationErr := e.Catalog.AllocateOIDLocked()
				if allocationErr != nil {
					e.Mu.Unlock()
					t.Fatal(allocationErr)
				}
				revision, allocationErr := e.Catalog.RevisionLocked()
				e.Mu.Unlock()
				if allocationErr != nil {
					t.Fatal(allocationErr)
				}
				next := *originalView
				next.ObjectAddress.ObjectID, next.ObjectName, next.ObjectRevision = oid, "late_view", revision
				next.RowType = 0
				next.View = stored.ViewOf(originalView).With(func(p *stored.ViewParts) { p.Rule = rule })
				next.Columns = append([]catalog.Column(nil), originalView.Columns...)
				for i := range next.Columns {
					next.Columns[i].OriginTable = uint32(oid)
				}
				stage := e.BeginCatalogStage(e.CatalogRead())
				defer e.DiscardCatalogStage(stage)
				e.Mu.Lock()
				allocationErr = e.StageRowTypeLocked(stage, &next)
				e.Mu.Unlock()
				if allocationErr != nil {
					t.Fatal(allocationErr)
				}
				if err := stage.Create(&next); err != nil {
					t.Fatal(err)
				}
				prepared, err := e.ValidateCatalogStage(context.Background(), stage)
				if err != nil {
					t.Fatal(err)
				}
				if _, err := enginetest.PublishCatalog(e, prepared, core.PublicationToken{Epoch: table.Epoch}); err != nil {
					t.Fatal(err)
				}
				added = next.Address()
			}}
			_, err := enginetest.Execute(e, context.Background(), enginetest.Statement(t, "ALTER TABLE t "+action), nil)
			var conflict catalog.Conflict
			if !errors.As(err, &conflict) {
				t.Fatal("expected dependency publication conflict", err)
			}
			if added == (ids.ObjectAddress{}) || e.Catalog.State.Get(added) == nil || e.Catalog.State.Get(table.Address) != old || e.Storage.Relations[table.Address] != store {
				t.Fatal("failed TYPE published a prefix", err)
			}
			if got := enginetest.Tuples(enginetest.Run(t, e, "SELECT * FROM late_view")); !reflect.DeepEqual(got, [][]driver.Value{{tc.value}}) {
				t.Fatal(got)
			}
			removeView(enginetest.RoleTableRef(t, e, "late_view"))
			enginetest.Run(t, e, "ALTER TABLE t "+action)
			if got := enginetest.Tuples(enginetest.Run(t, e, "SELECT * FROM t")); !reflect.DeepEqual(got, [][]driver.Value{{tc.value}}) {
				t.Fatal(got)
			}
		})
	}
}
