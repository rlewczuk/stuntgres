func TestSerialSequenceAuthority(t *testing.T) {
	e := New()
	op, done := roleOperation(t, e, "postgres")
	defer done()
	roleExecute(t, e, op, `CREATE USER serial_writer`)
	roleExecute(t, e, op, `CREATE TABLE t(id SERIAL)`)
	table := roleTableRef(t, e, "t")
	sequence := roleTableRef(t, e, "t_id_seq")
	writer, _ := e.Roles().Lookup("serial_writer")
	owner := e.RoleStore.Published.Root.Read(authorization.PrincipalRef{}).LookupRef("postgres")
	if err := e.SetObjectACL(context.Background(), table, authorization.ACLValue{Explicit: true, Entries: []authorization.ACLEntry{{Grantor: owner, Grantee: authorization.ACLGrantee{Role: writer.Ref}, Privileges: authorization.InsertPrivilege}}}); err != nil {
		t.Fatal(err)
	}
	roleExecute(t, e, op, `SET SESSION AUTHORIZATION serial_writer`)
	roleError(t, e, op, `INSERT INTO t DEFAULT VALUES`, "42501", "permission denied for sequence t_id_seq", "")
	if e.Storage.Sequences[sequence.Address].Called {
		t.Fatal("denied serial consumed")
	}
	roleExecute(t, e, op, `RESET SESSION AUTHORIZATION`)
	if err := e.SetObjectACL(context.Background(), sequence, authorization.ACLValue{Explicit: true, Entries: []authorization.ACLEntry{{Grantor: owner, Grantee: authorization.ACLGrantee{Role: writer.Ref}, Privileges: authorization.UsagePrivilege}}}); err != nil {
		t.Fatal(err)
	}
	roleExecute(t, e, op, `SET SESSION AUTHORIZATION serial_writer`)
	if r := roleExecute(t, e, op, `INSERT INTO t DEFAULT VALUES`); r.Count != 1 {
		t.Fatal(r.Count)
	}
	roleError(t, e, op, `SELECT setval('t_id_seq',9)`, "42501", "permission denied for sequence t_id_seq", "")
	roleExecute(t, e, op, `RESET SESSION AUTHORIZATION`)
	r := roleExecute(t, e, op, `SELECT * FROM t`)
	defer r.Rows.Close()
	if got := tuples(r); len(got) != 1 || got[0][0] != int64(1) {
		t.Fatal(got)
	}
}

func TestSerialAtomicDeclarationsAndNaming(t *testing.T) {
	e := New()
	op, done := roleOperation(t, e, "postgres")
	defer done()
	for _, tc := range []struct{ query, message string }{
		{`CREATE TABLE bad(id SERIAL DEFAULT 7)`, `multiple default values specified for column "id" of table "bad"`},
		{`CREATE TABLE bad(id SERIAL GENERATED BY DEFAULT AS IDENTITY)`, `both default and identity specified for column "id" of table "bad"`},
	} {
		before := e.Catalog.State
		roleError(t, e, op, tc.query, "42601", tc.message, "")
		if e.Catalog.State != before || len(e.Storage.Sequences) != 0 {
			t.Fatal("failed CREATE published serial objects")
		}
	}
	roleExecute(t, e, op, `CREATE SEQUENCE bad_id_seq START 20`)
	roleExecute(t, e, op, `CREATE TABLE bad_id_seq1(v INT)`)
	roleExecute(t, e, op, `CREATE TABLE bad(id SERIAL)`)
	roleExecute(t, e, op, `INSERT INTO bad DEFAULT VALUES`)
	if e.Storage.Sequences[roleTableRef(t, e, "bad_id_seq").Address].Called {
		t.Fatal("adopted preexisting sequence")
	}
	if !e.Storage.Sequences[roleTableRef(t, e, "bad_id_seq2").Address].Called {
		t.Fatal("generated suffix sequence unused")
	}
}
