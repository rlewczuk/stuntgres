// CreateOptions are the WITH options of CREATE VIEW, checked by
// CheckCreate.
type CreateOptions struct {
	Barrier, Invoker bool
	CheckOption      stored.CheckMode
}

// CheckColumnCollations rejects a CREATE VIEW query with an output column
// whose collation cannot be determined (42P22). root is the bound query's
// root, which must be its final projection.
func CheckColumnCollations(root plan.Node) error {
	projection, ok := root.(*plan.ProjectNode)
	if !ok {
		return fmt.Errorf("stuntgres: view lacks final projection")
	}
	for i, expression := range projection.Expressions {
		if expression.CollationIndeterminate() {
			return &sqlstate.Error{Severity: "ERROR", SeverityUnlocalized: "ERROR", Code: "42P22", Message: fmt.Sprintf(`could not determine which collation to use for view column "%s"`, projection.Schema()[i].Name), Hint: "Use the COLLATE clause to set the collation explicitly."}
		}
	}
	return nil
}

// CreateTarget looks up the relation CREATE VIEW s names in namespace ns
// and returns the view it replaces, or nil for a new view. locked is the
// admitted identity: a replaced view must be it, and a new view must have
// none. Without OR REPLACE an existing name is 42P07; the replaced relation
// must be an owned view.
func CreateTarget(v access.View, env access.Environment, s *parser.CreateView, ns, locked ids.ObjectRef) (*catalog.Relation, error) {
	name := s.Name.Parts[len(s.Name.Parts)-1].Text
	address, exists := v.Catalog.LookupName(ids.NameKey{ClassID: ids.RelationClassID, Namespace: ns.Address, Name: name})
	if !exists {
		if locked.Domain() != nil {
			return nil, ids.ErrCatalogReplaced
		}
		return nil, nil
	}
	if !s.Replace {
		return nil, sqlError("42P07", fmt.Sprintf(`relation "%s" already exists`, name))
	}
	old := v.Catalog.MustRelation(address)
	ref := v.Ref(address)
	if ref != locked {
		return nil, ids.ErrCatalogReplaced
	}
	if err := v.Check(env, access.Requirement{Object: ref, OwnerOnly: true}); err != nil {
		return nil, err
	}
	if old.RelationKind != catalog.ViewRelation {
		return nil, sqlError("42809", fmt.Sprintf(`"%s" is not a view`, name))
	}
	return old, nil
}

// CheckCreate checks the bound query b of CREATE VIEW s against the view
// old it replaces (nil for a new view), in PostgreSQL's order: the check
// option declaration, the replaced output names and prefix, record
// pseudo-types, the VOID boundary of OR REPLACE, the WITH options and the
// output names of a new view.
func CheckCreate(catalogView catalog.Read, s *parser.CreateView, b analyze.Binding, old *catalog.Relation) (CreateOptions, error) {
	// CREATE checks local declaration shape before options and replacement prefix.
	for _, option := range s.Options {
		if option.Name.Text == "check_option" {
			if err := stored.ValidateViewCheckDeclaration(stored.NewView(stored.ViewParts{Syntax: s.Query, Query: b.Query})); err != nil {
				return CreateOptions{}, err
			}
			break
		}
	}
	schema := b.Query.Root.Schema()
	if old != nil {
		if err := CheckViewOutputNames(schema, old); err != nil {
			return CreateOptions{}, err
		}
		if err := CheckViewPrefix(catalogView, old.Columns, schema); err != nil {
			return CreateOptions{}, err
		}
	}
	for _, column := range schema {
		if sqltype.OccurrenceRecordArray(column.Usage.Type) || column.Usage.Type.ID() == 2249 && column.Usage.Type.IsComposite() {
			typeName := "record"
			if sqltype.OccurrenceRecordArray(column.Usage.Type) {
				typeName = "record[]"
			}
			return CreateOptions{}, sqlError("42P16", fmt.Sprintf(`column "%s" has pseudo-type %s`, column.Name, typeName))
		}
	}
	// Existing replacement shape errors precede the creation-only VOID
	// boundary. Appended VOID columns and CREATE OR REPLACE of a missing
	// destination still fail before a catalog stage can publish anything.
	if s.Replace {
		if err := analyze.CheckViewOutputTypes(schema); err != nil {
			return CreateOptions{}, err
		}
	}
	barrier, invoker, mode, err := stored.ViewOptions(s.Options)
	if err != nil {
		return CreateOptions{}, err
	}
	if old == nil {
		if err := CheckViewOutputNames(schema, nil); err != nil {
			return CreateOptions{}, err
		}
	}
	return CreateOptions{Barrier: barrier, Invoker: invoker, CheckOption: mode}, nil
}

// StageCreate stages CREATE VIEW s in namespace ns: for a new view it
// displaces an autogenerated array that holds the name and allocates the
// relation and rule OIDs; then it freezes the definition, builds the
// descriptor (copied from old when replacing), stages the row type, creates or
// replaces the relation and reowns displaced types. A temporary view consumes
// its own temporary sources.
func StageCreate(h StageHost, auth ddl.Authority, s *parser.CreateView, old *catalog.Relation, ns ids.ObjectRef, b analyze.Binding, options CreateOptions, temporary bool) error {
	name := s.Name.Parts[len(s.Name.Parts)-1].Text
	catalogAccess := h.AccessView(auth)
	if old == nil {
		persistence := ""
		if temporary {
			persistence = "temporary"
		}
		if err := ddl.CheckDefaultTablespaceCreation(catalogAccess, auth, h.DefaultTablespace(), persistence, false); err != nil {
			return err
		}
		available, err := h.DisplaceAssociatedArray(ns.Address, name)
		if err != nil {
			return err
		}
		if !available {
			return &sqlstate.Error{Severity: "ERROR", SeverityUnlocalized: "ERROR", Code: "42710", Message: fmt.Sprintf(`type "%s" already exists`, name), Hint: "A relation has an associated type of the same name, so you must use a name that doesn't conflict with any existing type."}
		}
	}
	var oid, rule ids.OID
	var err error
	if old != nil {
		oid, rule = old.Address().ObjectID, stored.ViewOf(old).RuleOID()
	} else {
		oid, err = h.AllocateOID()
		if err == nil {
			rule, err = h.AllocateOID()
		}
		if err != nil {
			return err
		}
	}
	revision, err := h.Revision()
	if err != nil {
		return err
	}
	definition, err := FreezeDefinition(h, catalogAccess.Catalog, h.TemporaryOwner(auth), s.Query, b, options.Barrier, options.Invoker, rule, catalog.ViewRelation, temporary)
	if err != nil {
		return err
	}
	definition = definition.With(func(p *stored.ViewParts) {
		p.CheckOption = options.CheckOption
		p.Options = TransformViewOptions(nil, s.Options, false)
		p.DefinitionRevision = revision
	})
	d := &catalog.Relation{ObjectAddress: ids.ObjectAddress{ClassID: ids.RelationClassID, ObjectID: oid}, ObjectNamespace: ns.Address, ObjectName: name, ObjectRevision: revision, Owner: catalogAccess.State.CurrentUser, RelationKind: catalog.ViewRelation, View: stored.ViewPayload(definition), Columns: append([]catalog.Column(nil), b.Query.Root.Schema()...), Index: make(map[string]int), Attributes: make([]int32, len(b.Query.Root.Schema()))}
	if old != nil {
		*d = *old
		d.ObjectRevision, d.View = revision, stored.ViewPayload(definition)
		d.Columns = append([]catalog.Column(nil), b.Query.Root.Schema()...)
		d.Attributes = make([]int32, len(d.Columns))
		copy(d.Attributes, old.Attributes)
		d.Index = make(map[string]int, len(d.Columns))
	}
	if old == nil {
		d.Security.ACL = h.CreationACL(d.Owner, d.Namespace(), authorization.DefaultTables)
	}
	if temporary {
		definition = definition.With(func(p *stored.ViewParts) { p.Consumer = d.Address() })
		d.View = stored.ViewPayload(definition)
	}
	attribute := d.ColumnMeta.HighWater
	for _, id := range d.Attributes {
		if id > attribute {
			attribute = id
		}
	}
	for i := range d.Columns {
		d.Index[d.Columns[i].Name] = i
		if old == nil || i >= len(old.Attributes) {
			attribute++
			d.Attributes[i] = attribute
		}
		d.Columns[i].OriginTable = uint32(oid)
		d.Columns[i].OriginAttribute = int16(d.Attributes[i])
		d.Columns[i].DeclaredDimensions = 0
	}
	d.ColumnMeta.HighWater = attribute
	if err := h.StageRowType(d); err != nil {
		return err
	}
	if old != nil {
		return ddl.ReplaceCommand(h.Stage(), "CREATE VIEW", d)
	}
	if err := ddl.CreateCommand(h.Stage(), "CREATE VIEW", d); err != nil {
		return err
	}
	return h.ReownDisplacedTypes()
}
