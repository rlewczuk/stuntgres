// Host is what the view, rule and policy decisions made before a catalog
// stage exists need from the engine for one statement. Every method runs
// with Engine.mu held, never takes or releases it, never waits on the lock
// manager and never reads a catalog stage.
type Host interface {
	ddl.Allocator

	Context() context.Context
	// AccessView returns the catalog, roles, state and owner of auth.
	AccessView(ddl.Authority) access.View
	// ResolveRelation resolves a relation name, missing ones included in the
	// error.
	ResolveRelation(auth ddl.Authority, name parser.ObjectName) (ids.ObjectRef, error)
	// TemporaryOwner is the session whose temporary objects auth may read
	// when a definition is frozen; zero without a session.
	TemporaryOwner(auth ddl.Authority) ids.SessionToken

	// DescribeRule binds stmt inside a rule namespace, without lock
	// admission: the ON SELECT view query and each rule action.
	DescribeRule(auth ddl.Authority, stmt parser.Statement, target ids.ObjectRef, input sqltype.InputEnvironment, ns *analyze.RuleNamespace) (analyze.Binding, error)
	// BindRuleCondition binds a rule's WHERE condition. It returns the bound
	// condition, the synthetic SELECT that presents it and that SELECT's
	// capture binding, with frozen source attributes.
	BindRuleCondition(auth ddl.Authority, ns *analyze.RuleNamespace, raw parser.Expr, input sqltype.InputEnvironment) (expr.Expr, *parser.Select, analyze.Binding, error)
	// BindPolicyExpression binds and freezes a USING or WITH CHECK expression
	// of a policy on relation; nil for a nil expression.
	BindPolicyExpression(auth ddl.Authority, relation *catalog.Relation, raw parser.Expr, input sqltype.InputEnvironment) (*stored.Policy, error)
	// SelectFunction selects the functions named name with exactly
	// signature on auth's function search path; the int is the match count.
	SelectFunction(auth ddl.Authority, name parser.ObjectName, signature catalog.ProcedureSignature) (catalog.RoutineIdentity, int, error)
	// BindTriggerWhen binds a trigger's WHEN condition in a trigger
	// namespace, returning what BindRuleCondition returns.
	BindTriggerWhen(auth ddl.Authority, ns *analyze.RuleNamespace, raw parser.Expr, input sqltype.InputEnvironment) (expr.Expr, *parser.Select, analyze.Binding, error)
}

// StageHost is what CREATE VIEW staging needs: the decisions host and the
// shared DDL host over the statement's stage, row-type staging, array
// displacement and the reownership of displaced types.
type StageHost interface {
	Host
	ddl.Host

	// StageRowType stages the row type of relation.
	StageRowType(relation *catalog.Relation) error
	// DisplaceAssociatedArray renames an autogenerated array that holds name
	// in namespace; false when another object holds it.
	DisplaceAssociatedArray(namespace ids.ObjectAddress, name string) (bool, error)
	// ReownDisplacedTypes reowns the type generations a displacement renamed;
	// it does nothing when the stage renamed no names.
	ReownDisplacedTypes() error
}

// RelationChange is a planned RULE, POLICY or TRIGGER change of one
// relation. A non-empty Skip is the NOTICE text of an IF EXISTS miss, and
// nothing else is set. Otherwise Next replaces the relation Ref names
// (Ref.Epoch is the publication token), Sources are the descriptors the stage
// records as its query sources, and Replacement names the definition a
// CREATE OR REPLACE TRIGGER replaces (zero otherwise).
type RelationChange struct {
	Skip        string
	Ref         ids.ObjectRef
	Next        *catalog.Relation
	Sources     []catalog.Descriptor
	Replacement TriggerReplacement
	Deleted     ids.ObjectAddress // Actual payload deletion; replacement/rename never sets this fact.
}

// TriggerReplacement authorizes local-child replacement only for the exact
// CREATE OR REPLACE definition and its descendant clone lineage in this stage.
type TriggerReplacement struct {
	Relation ids.ObjectAddress
	OID      ids.OID
}
