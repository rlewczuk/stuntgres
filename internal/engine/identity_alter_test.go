func TestIdentityAddCandidatePrivateBeforeGuards(t *testing.T) {
	for _, tc := range []struct {
		name, create  string
		cache         int64
		code, message string
	}{
		{"nullable_bad_cache", `CREATE TABLE i(id INT)`, 0, "22023", "CACHE (0) must be greater than zero"},
		{"default_bad_cache", `CREATE TABLE i(id INT NOT NULL DEFAULT 7)`, 0, "22023", "CACHE (0) must be greater than zero"},
		{"existing_bad_cache", `CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY)`, 0, "22023", "CACHE (0) must be greater than zero"},
		{"nullable_guard", `CREATE TABLE i(id INT)`, 1, "55000", `column "id" of relation "i" must be declared NOT NULL before identity can be added`},
		{"existing_guard", `CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY)`, 1, "55000", `column "id" of relation "i" is already an identity column`},
		{"success", `CREATE TABLE i(id INT NOT NULL)`, 1, "", ""},
	} {
		t.Run(tc.name, func(t *testing.T) {
			e := New()
			run(t, e, tc.create)
			base := e.CatalogRead()
			ref := catalogRef(t, e, base, "i")
			old := base.MustRelation(ref.Address)
			identities := maps.Clone(old.Identities)
			columns := append([]ColumnDescriptor(nil), old.Columns...)
			state, storage := e.catalog.state, e.storage[ref.Address]
			stage := e.BeginCatalogStage(base)
			defer e.DiscardCatalogStage(stage)
			action := parser.AlterTableAction{Action: parser.AddIdentity, Column: parser.Identifier{Text: "id"}, Identity: &parser.IdentityDefinition{Mode: parser.IdentityAlways, Options: []parser.SequenceOption{{Name: "cache", Value: tc.cache}}}}
			next, err := e.identityCandidate(nil, AuthorizationView{}, stage, old, action)
			if tc.code != "" {
				var d *sqlstate.Error
				if !errors.As(err, &d) || d.Code != tc.code || d.Message != tc.message {
					t.Fatal(err)
				}
				if next != old {
					t.Fatal("failed candidate replaced old descriptor")
				}
			} else {
				if err != nil {
					t.Fatal(err)
				}
				identity := next.Identities[1]
				sequence := stage.Descriptors[identity.Sequence].(*relationDescriptor)
				want := ref.Address
				want.SubID = 1
				if sequence.Sequence.Owned != want || !sequence.Sequence.Identity || stage.generators[identity.Sequence] == nil {
					t.Fatal("staged link is not reciprocal")
				}
				if identity.Mode != parser.IdentityAlways {
					t.Fatal(identity.Mode)
				}
			}
			if e.catalog.state != state || e.storage[ref.Address] != storage || !reflect.DeepEqual(old.Identities, identities) || !reflect.DeepEqual(old.Columns, columns) {
				t.Fatal("candidate changed published metadata or row backing")
			}
			for address := range stage.generators {
				if e.catalog.state.Get(address) != nil || e.sequences[address] != nil {
					t.Fatal("private generator published")
				}
			}
			if tc.name == "existing_guard" && len(stage.generators) != 1 {
				t.Fatal("sequence before-command was not privately staged")
			}
		})
	}
}

func TestIdentityAlterPublicationRetainsRowBackingAndExactLink(t *testing.T) {
	e := New()
	op, done := roleOperation(t, e, "postgres")
	defer done()
	roleExecute(t, e, op, `CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY,other INT NOT NULL)`)
	roleExecute(t, e, op, `INSERT INTO i VALUES(DEFAULT,7)`)
	ref := roleTableRef(t, e, "i")
	old := e.catalog.state.MustRelation(ref.Address)
	storage := e.storage[ref.Address]
	identity := old.Identities[1]
	before := e.catalog.state
	generator := *e.sequences[identity.Sequence]
	_, err := e.Execute(op, statement(t, `ALTER TABLE i ALTER id SET GENERATED BY DEFAULT RESTART 100, ALTER other SET GENERATED ALWAYS`), 0, nil)
	if err == nil {
		t.Fatal("late failure accepted")
	}
	if e.catalog.state != before || e.storage[ref.Address] != storage || *e.sequences[identity.Sequence] != generator {
		t.Fatal("late failure published descriptor/scalar/row backing")
	}
	roleExecute(t, e, op, `ALTER TABLE i ALTER id SET GENERATED BY DEFAULT RESTART 20`)
	next := e.catalog.state.MustRelation(ref.Address)
	if next.Identities[1].Sequence != identity.Sequence || old.Identities[1] != identity || e.storage[ref.Address] != storage {
		t.Fatal("SET rewrote rows or old metadata/link")
	}
	roleExecute(t, e, op, `ALTER TABLE i ALTER id DROP IDENTITY`)
	next = e.catalog.state.MustRelation(ref.Address)
	if len(next.Identities) != 0 || e.catalog.state.Get(identity.Sequence) != nil || e.sequences[identity.Sequence] != nil || e.storage[ref.Address] != storage {
		t.Fatal("DROP did not remove exact descriptor/generator without row rewrite")
	}
}

func TestIdentityModeConflictCandidateUnchanged(t *testing.T) {
	e := New()
	run(t, e, `CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY)`)
	base := e.CatalogRead()
	ref := catalogRef(t, e, base, "i")
	old := base.MustRelation(ref.Address)
	identity := old.Identities[1]
	stage := e.BeginCatalogStage(base)
	defer e.DiscardCatalogStage(stage)
	next, err := e.identityCandidate(nil, AuthorizationView{}, stage, old, parser.AlterTableAction{
		Action: parser.SetIdentity, Column: parser.Identifier{Text: "id"},
		Identity: &parser.IdentityDefinition{Mode: parser.IdentityByDefault, ConflictingModes: true},
	})
	var diagnostic *sqlstate.Error
	want := sqlstate.Error{Severity: "ERROR", SeverityUnlocalized: "ERROR", Code: "42601", Message: "conflicting or redundant options"}
	if !errors.As(err, &diagnostic) || *diagnostic != want {
		t.Fatal(err)
	}
	if next != old || old.Identities[1] != identity || len(stage.Descriptors) != 0 || len(stage.generators) != 0 || e.catalog.state != base.State() {
		t.Fatal("mode conflict changed candidate or published metadata")
	}
}
