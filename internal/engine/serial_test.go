func serialLeaf(node expr.Expr) sequenceCallExpression {
	for {
		if wrapper, ok := node.(coercionExpression); ok {
			node = wrapper.child
			continue
		}
		return node.(sequenceCallExpression)
	}
}

func TestSerialStoredDefaultInvariants(t *testing.T) {
	e := New()
	run(t, e, `CREATE TABLE t(a SMALLSERIAL,b SERIAL,c BIGSERIAL)`)
	view := e.CatalogRead()
	d := view.MustRelation(roleTableRef(t, e, "t").Address)
	for slot, attribute := range d.Attributes {
		definition := d.ColumnMeta.Defaults[attribute]
		leaf := serialLeaf(definition.Expression)
		if leaf.identity || len(d.ColumnMeta.Identities) != 0 || leaf.ResultUsage().Type.ID() != sqltype.Int8 || !closedSequenceDefault(definition.Expression) {
			t.Fatal("serial became identity", definition)
		}
		seq := view.MustRelation(leaf.ref.Address)
		owner := d.Address()
		owner.SubID = attribute
		if seq.Sequence.Identity || seq.Sequence.Owned != owner || seq.Sequence.SQLType != d.Columns[slot].Usage.Type.ID() {
			t.Fatal("serial ownership/width", seq.Sequence)
		}
		if e.storage.Sequences[seq.Address()].Called || e.storage.Sequences[seq.Address()].Last != 1 {
			t.Fatal("CREATE evaluated nextval")
		}
		if err := (relationProvider{}).Validate(view, d); err != nil {
			t.Fatal(err)
		}
		for _, mutate := range []func(sequenceCallExpression) sequenceCallExpression{
			func(n sequenceCallExpression) sequenceCallExpression { n.identity = true; return n },
			func(n sequenceCallExpression) sequenceCallExpression { n.name = "currval"; return n },
			func(n sequenceCallExpression) sequenceCallExpression { n.ref.Epoch++; return n },
			func(n sequenceCallExpression) sequenceCallExpression { n.args = nil; return n },
			func(n sequenceCallExpression) sequenceCallExpression { n.Property.Volatility = expr.Stable; return n },
			func(n sequenceCallExpression) sequenceCallExpression {
				arg := n.args[0].(literalExpression)
				arg.value = sqltype.String(arg.Usage.Type, "999")
				n.args = []expr.Expr{arg}
				return n
			},
		} {
			if _, err := defaultSQL(context.Background(), view, mutate(leaf)); err == nil {
				t.Fatal("malformed serial default admitted")
			}
		}
	}
	for _, query := range []string{`CREATE TABLE bad(id SERIAL NULL)`, `CREATE TABLE bad(id SERIAL DEFAULT 7)`, `CREATE TABLE bad(id SERIAL GENERATED BY DEFAULT AS IDENTITY)`} {
		_, err := testExecute(e, context.Background(), statement(t, query), nil)
		state(t, err, "42601")
		if len(view.Lookup(ids.NameKey{ClassID: ids.RelationClassID, Namespace: d.Namespace(), Name: "bad_id_seq"})) != 0 {
			t.Fatal("failed CREATE leaked sequence")
		}
	}
	for _, query := range []string{`CREATE TABLE bad(id INT DEFAULT (nextval('t_b_seq')+1))`, `CREATE TABLE bad(id BIGINT DEFAULT currval('t_b_seq'))`, `CREATE TABLE bad(id BIGINT DEFAULT nextval(NULL))`} {
		_, err := testExecute(e, context.Background(), statement(t, query), nil)
		state(t, err, "0A000")
	}
	// Rename does not replace the bound identity or stale-name cached SQL.
	run(t, e, `ALTER SEQUENCE t_b_seq RENAME TO renamed`)
	if err := (relationProvider{}).Validate(e.CatalogRead(), d); err != nil {
		t.Fatal(err)
	}
	text, err := defaultSQL(context.Background(), e.CatalogRead(), d.ColumnMeta.Defaults[2].Expression)
	if err != nil || !strings.Contains(text, "renamed") {
		t.Fatal(text, err)
	}
}

func TestSerialControlsTemporaryCollision(t *testing.T) {
	for _, mode := range []string{"ReplaceCatalog", "Restore"} {
		t.Run(mode, func(t *testing.T) {
			source, dest := New(), New()
			a, b := sessionStart(t, source, nil), sessionStart(t, dest, nil)
			sessionSQL(t, a, `CREATE SCHEMA collision_padding`)
			sessionSQL(t, a, `CREATE SCHEMA portable`)
			sessionSQL(t, a, `CREATE TABLE portable.t(id SERIAL)`)
			sequenceScalar(t, a, `SELECT setval('portable.t_id_seq',7,true)`, 7)
			sessionSQL(t, b, `CREATE TABLE displaced(v INT)`)
			sessionSQL(t, b, `CREATE TEMP SEQUENCE kept START 30 CACHE 1`)
			sequenceScalar(t, b, `SELECT nextval('kept')`, 30)
			_, description := sequencePreparedDescription(t, dest, b, `SELECT nextval('kept')`)
			temp := description.sequences.constants[0].ref.Address
			original := source.catalog.state.MustRelation(roleTableRef(t, source, "portable.t").Address)
			leaf := serialLeaf(original.ColumnMeta.Defaults[1].Expression)
			if leaf.ref.Address != temp {
				t.Fatal("fixture lacks actual persistent sequence collision", leaf.ref.Address, temp)
			}
			definition, generator, memory := dest.catalog.state.Get(temp), dest.storage.Sequences[temp], b.sequences[temp]
			if mode == "Restore" {
				var dump bytes.Buffer
				if err := source.Dump(context.Background(), &dump); err != nil {
					t.Fatal(err)
				}
				if err := dest.Restore(context.Background(), bytes.NewReader(dump.Bytes())); err != nil {
					t.Fatal(err)
				}
			} else if _, err := dest.ReplaceCatalog(context.Background(), source, source.CatalogRead()); err != nil {
				t.Fatal(err)
			}
			if dest.catalog.state.Get(temp) != definition || dest.storage.Sequences[temp] != generator || b.sequences[temp] != memory {
				t.Fatal("retained TEMP changed")
			}
			d := dest.catalog.state.MustRelation(roleTableRef(t, dest, "portable.t").Address)
			next := serialLeaf(d.ColumnMeta.Defaults[1].Expression)
			if next.ref.Address == temp || next.ref.Domain() != dest.catalog.Domain || next.ref.Epoch != dest.catalog.state.Epoch() || !closedSequenceDefault(d.ColumnMeta.Defaults[1].Expression) {
				t.Fatal("default not remapped", next.ref)
			}
			if err := (relationProvider{}).Validate(dest.CatalogRead(), d); err != nil {
				t.Fatal(err)
			}
			sessionSQL(t, b, `INSERT INTO portable.t DEFAULT VALUES`)
			sequenceScalar(t, b, `SELECT id FROM portable.t`, 8)
			sequenceScalar(t, b, `SELECT nextval('kept')`, 31)
			sessionSQL(t, b, `DROP TABLE portable.t RESTRICT`)
			if dest.catalog.state.Get(next.ref.Address) != nil {
				t.Fatal("remapped AUTO dependency remained")
			}
			if serialLeaf(original.ColumnMeta.Defaults[1].Expression).ref != leaf.ref {
				t.Fatal("source default mutated")
			}
			if err := (relationProvider{}).Validate(source.CatalogRead(), original); err != nil {
				t.Fatal(err)
			}
		})
	}
}
