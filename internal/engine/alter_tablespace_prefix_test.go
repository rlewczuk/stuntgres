// These are internal lifecycle invariants, not PostgreSQL expectations for a
// multi-TYPE SQL combination. SQL is used only to construct ordinary providers;
// the witnesses call preparation, AS staging, the locked controller and Finish.
func tablespacePrefixScope(t *testing.T, declaration, actions string) *inheritanceAlterAdmissionCase {
	t.Helper()
	e := New()
	s := sessionStart(t, e, nil)
	sessionSQL(t, s, "CREATE TABLE t("+declaration+")")
	sequenceScalar(t, s, "SELECT nextval('t_a_seq')", 1)
	sequenceScalar(t, s, "SELECT nextval('t_b_seq')", 1)
	sequenceScalar(t, s, "SELECT nextval('t_c_seq')", 1)
	op, err := s.Acquire(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(op.Done)
	raw := statement(t, "ALTER TABLE t "+actions).(*parser.AlterTable)
	scope, err := e.StartStatement(op)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { scope.Finish(context.Canceled) })
	if err := scope.gate(raw); err != nil {
		t.Fatal(err)
	}
	if err := scope.acquireRelation(raw, true); err != nil {
		t.Fatal(err)
	}
	e.mu.Lock()
	auth, err := e.statementAuthorizationLocked(op, raw)
	e.mu.Unlock()
	if err != nil {
		t.Fatal(err)
	}
	return &inheritanceAlterAdmissionCase{e: e, op: op, scope: scope, raw: raw, auth: auth}
}

const tablespacePrefixDeclaration = "a INT GENERATED BY DEFAULT AS IDENTITY(CACHE 5), b INT GENERATED BY DEFAULT AS IDENTITY(CACHE 5), c INT GENERATED BY DEFAULT AS IDENTITY(CACHE 5)"

func tablespacePrefixPrepare(c *inheritanceAlterAdmissionCase, old *catalog.Relation, actions []parser.AlterTableAction) (alterTablePreparation, error) {
	c.e.mu.Lock()
	defer c.e.mu.Unlock()
	return c.e.prepareAlterTableActions(c.scope, c.op, c.auth, old, c.scope.lockedRef, actions)
}

func tablespacePrefixCode(t *testing.T, err error, code string) *sqlstate.Error {
	t.Helper()
	var diagnostic *sqlstate.Error
	if !errors.As(err, &diagnostic) || diagnostic.Code != code {
		t.Fatalf("want %s, got %v", code, err)
	}
	return diagnostic
}

func TestAlterTablespaceAdmittedTypePrefix(t *testing.T) {
	c := tablespacePrefixScope(t, tablespacePrefixDeclaration, "ALTER a TYPE BIGINT, ALTER c TYPE BIGINT, SET TABLESPACE pg_default, ALTER a TYPE SMALLINT USING a::text, ALTER b TYPE TEXT USING b::text, ALTER absent TYPE BIGINT")
	e, scope := c.e, c.scope
	old := scope.lockedDescriptor.(*catalog.Relation)
	before, storage := e.catalog.state, e.storage.relations[old.Address()]
	a := old.ColumnMeta.Identities[old.Attributes[0]].Sequence
	b := old.ColumnMeta.Identities[old.Attributes[1]].Sequence
	third := old.ColumnMeta.Identities[old.Attributes[2]].Sequence
	generatorC := e.storage.sequences[third]
	valueC, cacheC := *generatorC, *c.op.session.sequences[third]
	generatorA, generatorB := e.storage.sequences[a], e.storage.sequences[b]
	valueA, valueB := *generatorA, *generatorB
	memoryA, memoryB := c.op.session.sequences[a], c.op.session.sequences[b]
	cacheB := *memoryB
	if memoryA.remaining != 4 || memoryB.remaining != 4 {
		t.Fatal("fixture did not reserve actual cache tails", memoryA, memoryB)
	}
	prepared, completionErr := tablespacePrefixPrepare(c, old, c.raw.Actions)
	tablespacePrefixCode(t, completionErr, "42804")
	if len(prepared.types) != 3 || prepared.types[0].usage.Type.ID() != sqltype.Int8 || prepared.types[1].usage.Type.ID() != sqltype.Int8 || prepared.types[2].usage.Type.ID() != sqltype.Int2 {
		t.Fatal("missing admitted failing occurrence", prepared.types)
	}
	stage, err := e.stageAlterIdentityTypes(scope, c.op, c.auth, old, c.raw.Actions, prepared.types)
	if err != nil || stage == nil {
		t.Fatal("bounded staging visited an unadmitted TYPE", stage, err)
	}
	t.Cleanup(func() { e.DiscardCatalogStage(stage) })
	// Repeated occurrences target the same original identity. The actual final
	// AS descriptor must reflect the second occurrence, not the first; its
	// generator must be the replacement belonging to that final descriptor.
	sequence := stage.Descriptors[a].(*catalog.Relation)
	if sequence.Sequence.SQLType != sqltype.Int2 || stage.generators[a] == nil || stage.generators[a].generation != sequence.Revision() || stage.generators[a].last != valueA.last || stage.generators[a].called != valueA.called {
		t.Fatal("AS occurrence order/failing occurrence was lost", sequence.Sequence, stage.generators[a])
	}
	prior := stage.Descriptors[third].(*catalog.Relation)
	if prior.Sequence.SQLType != sqltype.Int8 || prior.Revision() >= sequence.Revision() || stage.generators[third] == nil || stage.generators[third].generation != prior.Revision() || cacheC.remaining != 4 || c.op.session.sequences[third].remaining != 0 {
		t.Fatal("distinct identity AS order/cache effects were lost", prior, sequence, stage.generators[third])
	}
	if stage.Descriptors[b] != nil || stage.generators[b] != nil || memoryA.remaining != 0 || !reflect.DeepEqual(*memoryB, cacheB) {
		t.Fatal("later unadmitted identity had effects", memoryA, memoryB, stage.generators)
	}
	if e.catalog.state != before || e.storage.relations[old.Address()] != storage || e.storage.sequences[a] != generatorA || e.storage.sequences[b] != generatorB || *generatorA != valueA || *generatorB != valueB || e.storage.sequences[third] != generatorC || *generatorC != valueC {
		t.Fatal("private AS published catalog/storage/generator state")
	}
	e.DiscardCatalogStage(stage)
	if stage.lifecycle != catalogDiscarded {
		t.Fatal("ordinary stage owner failed to discard")
	}
	if err := scope.Finish(completionErr); err == nil {
		t.Fatal("Finish lost completion failure")
	}
	if e.catalog.state != before || e.storage.relations[old.Address()] != storage || *generatorA != valueA || *generatorB != valueB || *generatorC != valueC {
		t.Fatal("failed Finish published a prefix")
	}
	lockEmpty(t, e)
}

func TestAlterTablespaceAdmissionFailureNoPrefix(t *testing.T) {
	for _, tc := range []struct {
		name, actions, code string
		kind                catalog.RelationKind
	}{
		{name: "set", actions: "ALTER a TYPE BIGINT, SET TABLESPACE ats_missing, ALTER a TYPE SMALLINT USING a::text", code: "42704"},
		{name: "column", actions: "ALTER a TYPE BIGINT, ALTER absent TYPE BIGINT", code: "42703"},
		{name: "type", actions: "ALTER a TYPE BIGINT, ALTER a TYPE ats_missing_type", code: "42704"},
		{name: "collation", actions: "ALTER a TYPE BIGINT, ALTER a TYPE INT COLLATE \"C\"", code: "42804"},
		{name: "missing-collation", actions: "ALTER a TYPE BIGINT, ALTER a TYPE TEXT COLLATE ats_missing_collation", code: "42704"},
		{name: "raw-using", actions: "ALTER a TYPE BIGINT, ALTER a TYPE BIGINT USING absent", code: "42703"},
		{name: "kind", actions: "SET TABLESPACE pg_default", code: "42809", kind: catalog.ViewRelation},
	} {
		t.Run(tc.name, func(t *testing.T) {
			c := tablespacePrefixScope(t, tablespacePrefixDeclaration, tc.actions)
			old := c.scope.lockedDescriptor.(*catalog.Relation)
			original := old
			if tc.kind != catalog.TableRelation {
				copy := *old
				copy.RelationKind = tc.kind
				old = &copy
			}
			before := c.e.catalog.state
			a := original.ColumnMeta.Identities[original.Attributes[0]].Sequence
			memory := *c.op.session.sequences[a]
			generator := *c.e.storage.sequences[a]
			prepared, err := tablespacePrefixPrepare(c, old, c.raw.Actions)
			tablespacePrefixCode(t, err, tc.code)
			if len(prepared.types) != 0 {
				t.Fatal("admission failure exposed a stageable prefix", prepared.types)
			}
			stage, stageErr := c.e.stageAlterIdentityTypes(c.scope, c.op, c.auth, original, c.raw.Actions, prepared.types)
			if stage != nil || stageErr != nil || *c.op.session.sequences[a] != memory || *c.e.storage.sequences[a] != generator || c.e.catalog.state != before {
				t.Fatal("failed admission staged AS", stage, stageErr)
			}
			c.scope.Finish(err)
			lockEmpty(t, c.e)
		})
	}
}

func TestAlterTablespacePrefixErrorOwnership(t *testing.T) {
	for _, shared := range []bool{false, true} {
		for _, invalidAS := range []bool{false, true} {
			name := "ordinary"
			if shared {
				name = "shared"
			}
			if invalidAS {
				name += "-invalid-AS"
			}
			t.Run(name, func(t *testing.T) {
				declaration := tablespacePrefixDeclaration
				if invalidAS {
					declaration = "a INT GENERATED BY DEFAULT AS IDENTITY(MAXVALUE 40000 CACHE 5), b INT GENERATED BY DEFAULT AS IDENTITY(CACHE 5), c INT GENERATED BY DEFAULT AS IDENTITY(CACHE 5)"
				}
				c := tablespacePrefixScope(t, declaration, "ALTER a TYPE SMALLINT USING a::text, ALTER b TYPE TEXT USING b::text")
				e, scope := c.e, c.scope
				old := scope.lockedDescriptor.(*catalog.Relation)
				before, storage := e.catalog.state, e.storage.relations[old.Address()]
				a := old.ColumnMeta.Identities[old.Attributes[0]].Sequence
				b := old.ColumnMeta.Identities[old.Attributes[1]].Sequence
				generatorA, generatorB := e.storage.sequences[a], e.storage.sequences[b]
				valueA, valueB := *generatorA, *generatorB
				memoryA, memoryB := c.op.session.sequences[a], c.op.session.sequences[b]
				cacheA, cacheB := *memoryA, *memoryB
				_, saved := tablespacePrefixPrepare(c, old, c.raw.Actions)
				tablespacePrefixCode(t, saved, "42804")
				var stage *CatalogStage
				if shared {
					// Supply the existing shared-stage contract at descendant
					// reentry: this branch must leave disposal to its outer owner.
					stage = e.BeginCatalogStage(c.auth.catalog)
					stage.authorizeLocked(c.auth, c.op.session)
					scope.inheritanceAlter = &inheritanceAlterState{stage: stage, descendant: true}
					t.Cleanup(func() { scope.inheritanceAlter = nil; e.DiscardCatalogStage(stage) })
				}
				e.mu.Lock()
				_, err := e.alterTableLocked(scope, c.op, c.auth, c.raw, 0)
				if invalidAS {
					diagnostic := tablespacePrefixCode(t, err, "22023")
					if diagnostic.Message != "MAXVALUE (40000) is out of range for sequence data type smallint" || *memoryA != cacheA {
						t.Fatal("real AS validation must win without clearing cache", diagnostic, memoryA)
					}
				} else {
					diagnostic := tablespacePrefixCode(t, err, "42804")
					if diagnostic.Message != saved.(*sqlstate.Error).Message || memoryA.remaining != 0 {
						t.Fatal("saved completion error/cache disposal lost", diagnostic, memoryA)
					}
				}
				if *memoryB != cacheB || e.catalog.state != before || e.storage.relations[old.Address()] != storage || e.storage.sequences[a] != generatorA || e.storage.sequences[b] != generatorB || *generatorA != valueA || *generatorB != valueB || scope.catalog != nil || scope.owner.catalog != nil {
					t.Fatal("failed controller published a prefix or visited later TYPE")
				}
				if shared {
					if stage.lifecycle == catalogDiscarded || stage.lifecycle == catalogPublished {
						t.Fatal("inner failure took shared cleanup ownership", stage.lifecycle)
					}
					if !invalidAS && (stage.generators[a] == nil || stage.Descriptors[a].(*catalog.Relation).Sequence.SQLType != sqltype.Int2) {
						t.Fatal("shared owner lost actual staged AS")
					}
					// The existing outer-owner disposal API, not Finish or the
					// descendant, owns this private stage's transition.
					scope.inheritanceAlter = nil
					e.DiscardCatalogStage(stage)
					if stage.lifecycle != catalogDiscarded {
						t.Fatal("shared owner failed to dispose")
					}
				}
				if finishErr := scope.Finish(err); finishErr == nil {
					t.Fatal("failed Finish became successful")
				}
				if e.catalog.state != before || *generatorA != valueA || *generatorB != valueB {
					t.Fatal("Finish published failed metadata/generators")
				}
				lockEmpty(t, e)
			})
		}
	}
}
