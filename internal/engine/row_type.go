package engine

import (
	"fmt"
	"stuntgres/internal/engine/authorization"
	"stuntgres/internal/sqltype"
	"unicode/utf8"
)

func associatedArrayName(stage *CatalogStage, namespace ObjectAddress, name string) string {
	return chooseAssociatedArrayName(name, func(candidate string) bool {
		return stage.lookupName(NameKey{ClassID: TypeClassID, Namespace: namespace, Name: candidate}) != (ObjectAddress{})
	})
}

func chooseAssociatedArrayName(name string, occupied func(string) bool) string {
	prefix := name
	for len(prefix) > 62 {
		_, width := utf8.DecodeLastRuneInString(prefix)
		prefix = prefix[:len(prefix)-width]
	}
	arrayName := "_" + prefix
	for suffix := 1; occupied(arrayName); suffix++ {
		tail := fmt.Sprintf("_%d", suffix)
		prefix := name
		for len(prefix) > 62-len(tail) {
			_, width := utf8.DecodeLastRuneInString(prefix)
			prefix = prefix[:len(prefix)-width]
		}
		arrayName = "_" + prefix + tail
	}
	return arrayName
}

// Only reciprocal autogenerated arrays may yield a requested creation name.
// The descriptor and its codec are copied, never mutated in an older generation.
func (e *Engine) displaceAssociatedArrayLocked(stage *CatalogStage, namespace ObjectAddress, name string) (bool, error) {
	key := NameKey{ClassID: TypeClassID, Namespace: namespace, Name: name}
	address := stage.lookupName(key)
	if address == (ObjectAddress{}) {
		return true, nil
	}
	descriptor := stage.descriptors[address]
	if descriptor == nil {
		descriptor = stage.base.state.descriptors[address]
	}
	array, ok := descriptor.(*typeDescriptor)
	if !ok || !array.typ.IsArray() {
		return false, nil
	}
	elementAddress := ObjectAddress{ClassID: TypeClassID, ObjectID: OID(array.typ.Element().ID())}
	elementDescriptor := stage.descriptors[elementAddress]
	if elementDescriptor == nil {
		elementDescriptor = stage.base.state.descriptors[elementAddress]
	}
	element, ok := elementDescriptor.(*typeDescriptor)
	if !ok || element.array != array.typ.ID() || element.typ != array.typ.Element() || element.Namespace() != namespace {
		return false, nil
	}
	revision, err := e.revisionLocked()
	if err != nil {
		return false, err
	}
	next := *array
	next.revision = revision
	// The catalog name also owns the array's database metadata label. A plain
	// name-only copy leaves that label in the previous descriptor generation.
	arrayName := associatedArrayName(stage, namespace, array.Name())
	if array.typ.Concrete() {
		next.typ, err = sqltype.Array(array.typ.ID(), arrayName, array.typ.Element())
		if err != nil {
			return false, err
		}
	} else {
		next.typ = sqltype.LookupArray(array.typ.ID(), arrayName, array.typ.Element())
	}
	if stage.base.state.descriptors[address] == nil {
		delete(stage.names, key)
		stage.descriptors[address] = &next
		nextKey := descriptorNameKey(&next)
		nextKey.Namespace = namespace
		stage.names[nextKey] = address
		stage.touched[nextKey] = stage.base.state.names[nextKey]
		return true, e.reownStagedTypeGenerationsLocked(stage)
	}
	if err := stage.Replace(&next); err != nil {
		return false, err
	}
	return true, e.reownStagedTypeGenerationsLocked(stage)
}

// The executable projection shares one authority with named and supported user
// rows; catalog/builtin row identities remain lookup-only.
func compositeMembers(relation *relationDescriptor) []sqltype.CompositeMember {
	members := make([]sqltype.CompositeMember, len(relation.columns))
	for i, c := range relation.columns {
		members[i] = sqltype.CompositeMember{Attribute: relation.attributes[i], Name: c.Name, Usage: c.Usage}
	}
	return members
}

func (e *Engine) stageRowTypeLocked(stage *CatalogStage, relation *relationDescriptor) error {
	if !relation.relationKind.stored() && relation.relationKind != partitionedRelation && relation.relationKind != viewRelation && relation.relationKind != compositeRelation || relation.rowType != 0 {
		return nil
	}
	arrayID, err := e.allocateOIDLocked()
	if err != nil {
		return err
	}
	id, err := e.allocateOIDLocked()
	if err != nil {
		return err
	}
	ns := stage.descriptors[relation.namespace]
	if ns == nil {
		ns = stage.base.state.descriptors[relation.namespace]
	}
	declaration := dependencyIdentifier(ns.Name()) + "." + dependencyIdentifier(relation.name)
	typ, err := sqltype.Composite(sqltype.ID(id), relation.name, declaration, sqltype.ID(arrayID), compositeMembers(relation))
	if err != nil {
		return err
	}
	array, err := sqltype.Array(sqltype.ID(arrayID), associatedArrayName(stage, relation.namespace, relation.name), typ)
	if err != nil {
		return err
	}
	relation.rowType = typ.ID()
	baseline := authorization.DefaultBaseline(relation.owner, authorization.DefaultTypes, false)
	acl := baseline
	if relation.relationKind == compositeRelation {
		acl = stage.creationACL(relation.owner, relation.namespace, authorization.DefaultTypes)
	}
	if err := stage.Create(&typeDescriptor{typ: typ, namespace: relation.namespace, revision: relation.revision, owner: relation.owner, acl: acl, array: array.ID(), owningRelation: relation.address}); err != nil {
		return err
	}
	return stage.Create(&typeDescriptor{typ: array, namespace: relation.namespace, revision: relation.revision, owner: relation.owner, acl: baseline, owningRelation: relation.address})
}

func (stage *CatalogStage) synchronizeRowType(relation *relationDescriptor) error {
	if relation.rowType == 0 {
		return nil
	}
	address := ObjectAddress{ClassID: TypeClassID, ObjectID: OID(relation.rowType)}
	row, ok := stage.base.state.descriptors[address].(*typeDescriptor)
	if !ok {
		return nil
	}
	if staged, ok := stage.descriptors[address].(*typeDescriptor); ok {
		row = staged
	}
	same := row.Namespace() == relation.namespace && row.Name() == relation.name
	if row.typ.IsComposite() {
		same = same && row.typ.CompositeLen() == len(relation.columns)
		if same {
			for i, column := range relation.columns {
				member := row.typ.CompositeMember(i)
				if member.Attribute != relation.attributes[i] || member.Name != column.Name || member.Usage != column.Usage {
					same = false
					break
				}
			}
		}
	}
	if same && row.owner == relation.owner {
		return nil
	}
	next := *row
	if row.owner != relation.owner {
		next.acl = authorization.SchemaACLOwner(row.acl, row.owner, relation.owner)
	}
	next.namespace, next.owner, next.revision = relation.namespace, relation.owner, relation.revision
	if same {
		// Ownership is metadata, not a new codec or composite signature.
		next.typ = row.typ
	} else if row.typ.IsComposite() {
		ns := stage.descriptors[relation.namespace]
		if ns == nil {
			ns = stage.base.state.descriptors[relation.namespace]
		}
		var err error
		next.typ, err = sqltype.Composite(row.typ.ID(), relation.name, dependencyIdentifier(ns.Name())+"."+dependencyIdentifier(relation.name), row.array, compositeMembers(relation))
		if err != nil {
			return err
		}
	} else {
		next.typ = sqltype.LookupOnly(row.typ.ID(), relation.name, row.array)
	}
	if err := stage.Replace(&next); err != nil {
		return err
	}
	if row.array != 0 {
		array := stage.base.state.descriptors[ObjectAddress{ClassID: TypeClassID, ObjectID: OID(row.array)}].(*typeDescriptor)
		if staged, ok := stage.descriptors[array.Address()].(*typeDescriptor); ok {
			array = staged
		}
		copy := *array
		if array.owner != relation.owner {
			copy.acl = authorization.SchemaACLOwner(array.acl, array.owner, relation.owner)
		}
		copy.namespace, copy.owner, copy.revision = relation.namespace, relation.owner, relation.revision
		arrayName := array.Name()
		if row.Name() != relation.name {
			arrayName = associatedArrayName(stage, relation.namespace, relation.name)
		}
		if !same {
			if next.typ.IsComposite() {
				var err error
				copy.typ, err = sqltype.Array(array.typ.ID(), arrayName, next.typ)
				if err != nil {
					return err
				}
			} else {
				copy.typ = sqltype.LookupArray(array.typ.ID(), arrayName, next.typ)
			}
		}
		return stage.Replace(&copy)
	}
	return nil
}
