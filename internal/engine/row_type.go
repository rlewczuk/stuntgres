package engine

import (
	"fmt"
	"stuntgres/internal/sqltype"
	"unicode/utf8"
)

func associatedArrayName(stage *CatalogStage, namespace ObjectAddress, name string) string {
	return chooseAssociatedArrayName(name, func(candidate string) bool {
		return stage.lookupName(NameKey{ClassID: TypeClassID, Namespace: namespace, Name: candidate}) != (ObjectAddress{})
	})
}

func chooseAssociatedArrayName(name string, occupied func(string) bool) string {
	prefix := name
	for len(prefix) > 62 {
		_, width := utf8.DecodeLastRuneInString(prefix)
		prefix = prefix[:len(prefix)-width]
	}
	arrayName := "_" + prefix
	for suffix := 1; occupied(arrayName); suffix++ {
		tail := fmt.Sprintf("_%d", suffix)
		prefix := name
		for len(prefix) > 62-len(tail) {
			_, width := utf8.DecodeLastRuneInString(prefix)
			prefix = prefix[:len(prefix)-width]
		}
		arrayName = "_" + prefix + tail
	}
	return arrayName
}

// Only reciprocal autogenerated arrays may yield a requested creation name.
// The descriptor and its codec are copied, never mutated in an older generation.
func (e *Engine) displaceAssociatedArrayLocked(stage *CatalogStage, namespace ObjectAddress, name string) (bool, error) {
	key := NameKey{ClassID: TypeClassID, Namespace: namespace, Name: name}
	address := stage.lookupName(key)
	if address == (ObjectAddress{}) {
		return true, nil
	}
	descriptor := stage.descriptors[address]
	if descriptor == nil {
		descriptor = stage.base.state.descriptors[address]
	}
	array, ok := descriptor.(*typeDescriptor)
	if !ok || !array.typ.IsArray() {
		return false, nil
	}
	elementAddress := ObjectAddress{ClassID: TypeClassID, ObjectID: OID(array.typ.Element().ID())}
	elementDescriptor := stage.descriptors[elementAddress]
	if elementDescriptor == nil {
		elementDescriptor = stage.base.state.descriptors[elementAddress]
	}
	element, ok := elementDescriptor.(*typeDescriptor)
	if !ok || element.array != array.typ.ID() || element.typ != array.typ.Element() || element.Namespace() != namespace {
		return false, nil
	}
	revision, err := e.revisionLocked()
	if err != nil {
		return false, err
	}
	next := *array
	next.revision = revision
	// The catalog name also owns the array's database metadata label. A plain
	// name-only copy leaves that label in the previous descriptor generation.
	arrayName := associatedArrayName(stage, namespace, array.Name())
	if array.typ.Concrete() {
		next.typ, err = sqltype.Array(array.typ.ID(), arrayName, array.typ.Element())
		if err != nil {
			return false, err
		}
	} else {
		next.typ = sqltype.LookupArray(array.typ.ID(), arrayName, array.typ.Element())
	}
	if stage.base.state.descriptors[address] == nil {
		delete(stage.names, key)
		stage.descriptors[address] = &next
		nextKey := NameKey{ClassID: TypeClassID, Namespace: namespace, Name: next.Name()}
		stage.names[nextKey] = address
		stage.touched[nextKey] = stage.base.state.names[nextKey]
		return true, e.reownStagedTypeGenerationsLocked(stage)
	}
	if err := stage.Replace(&next); err != nil {
		return false, err
	}
	return true, e.reownStagedTypeGenerationsLocked(stage)
}

// Relation identity and executable composite capability are independent. The
// type/array are staged with the owning relation, before its stored definitions.
func (e *Engine) stageRowTypeLocked(stage *CatalogStage, relation *relationDescriptor) error {
	if relation.relationKind != tableRelation && relation.relationKind != viewRelation {
		return nil
	}
	if relation.rowType != 0 {
		return nil
	}
	arrayID, err := e.allocateOIDLocked()
	if err != nil {
		return err
	}
	id, err := e.allocateOIDLocked()
	if err != nil {
		return err
	}
	typ := sqltype.LookupOnly(sqltype.ID(id), relation.name, sqltype.ID(arrayID))
	array := sqltype.LookupArray(sqltype.ID(arrayID), associatedArrayName(stage, relation.namespace, relation.name), typ)
	relation.rowType = typ.ID()
	if err := stage.Create(&typeDescriptor{typ: typ, namespace: relation.namespace, revision: relation.revision, owner: relation.owner, array: array.ID(), owningRelation: relation.address}); err != nil {
		return err
	}
	return stage.Create(&typeDescriptor{typ: array, namespace: relation.namespace, revision: relation.revision, owner: relation.owner, owningRelation: relation.address})
}

func (stage *CatalogStage) synchronizeRowType(relation *relationDescriptor) error {
	if relation.rowType == 0 {
		return nil
	}
	address := ObjectAddress{ClassID: TypeClassID, ObjectID: OID(relation.rowType)}
	row, ok := stage.base.state.descriptors[address].(*typeDescriptor)
	if !ok {
		return nil
	} // New relation/type pairs are staged together.
	if row.Namespace() == relation.namespace && row.owner == relation.owner && row.Name() == relation.name {
		return nil
	}
	next := *row
	next.namespace, next.owner, next.revision = relation.namespace, relation.owner, relation.revision
	if row.Name() != relation.name {
		next.typ = sqltype.LookupOnly(row.typ.ID(), relation.name, row.array)
	}
	if err := stage.Replace(&next); err != nil {
		return err
	}
	if row.array != 0 {
		array := stage.base.state.descriptors[ObjectAddress{ClassID: TypeClassID, ObjectID: OID(row.array)}].(*typeDescriptor)
		copy := *array
		copy.namespace, copy.owner, copy.revision = relation.namespace, relation.owner, relation.revision
		if next.typ != row.typ {
			name := associatedArrayName(stage, relation.namespace, relation.name)
			copy.typ = sqltype.LookupArray(array.typ.ID(), name, next.typ)
		}
		if err := stage.Replace(&copy); err != nil {
			return err
		}
	}
	return nil
}
