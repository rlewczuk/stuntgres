#!/usr/bin/env python3
"""Extract immutable multibyte collation data; no host locale or native code.

Run from any directory: python3 internal/xml/xsltcollationdata/generate.py
Inputs are checked in, hash-pinned Debian locale data, not an oracle capture.
The output deliberately retains the complete multibyte lookup representation,
including contractions, ranges, indirect entries, rule selectors and expansions.
"""

import hashlib
import lzma
from pathlib import Path
import struct

HERE = Path(__file__).resolve().parent
INPUTS = {
    "en_US.LC_COLLATE.xz": "f062bf818ec7c394208e4b12db855fbe3765ca1463b2e0cfe05e434f1c293981",
    "en_US": "38e3102344829f4ef998db66d064c0082b4bd1c8cf95e35ac3de12bb9f1d62f5",
    "iso14651_t1": "368b462ba34ace172f685f7a4cdeefb95a093432e504a686912d5784a3bc85f3",
    "iso14651_t1_common.xz": "e1941ce316bb5b1a987553e67728089475453a5225c24f8a88e8df2c1dccbfc5",
}


def load(name, expected):
    data = (HERE / name).read_bytes()
    if name.endswith(".xz"):
        data = lzma.decompress(data)
    if hashlib.sha256(data).hexdigest() != expected:
        raise ValueError("changed pinned input: " + name)
    return data


def generate():
    inputs = {name: load(name, digest) for name, digest in INPUTS.items()}
    data = inputs["en_US.LC_COLLATE.xz"]
    magic, count = struct.unpack_from("<II", data)
    if (magic, count) != (0x20051017, 19):
        raise ValueError("unexpected little-endian glibc locale format")
    offsets = struct.unpack_from("<19I", data, 8)
    if list(offsets) != sorted(offsets) or offsets[-1] >= len(data):
        raise ValueError("invalid section directory")
    sections = [data[offsets[i]:offsets[i + 1]] for i in range(6)]
    if sections[0] != struct.pack("<I", 4):
        raise ValueError("unexpected number of collation levels")
    # SPECIAL has a backward secondary; all other sections are forward.
    # Position applies only to the fourth level in both rule sets.
    if sections[1] != bytes.fromhex("0102010501010105"):
        raise ValueError("changed en_US ordering rules")
    if len(sections[2]) != 256 * 4 or len(sections[5]) % 4:
        raise ValueError("invalid multibyte lookup alignment")
    lines = [
        "// Code generated by xsltcollationdata/generate.py; DO NOT EDIT.",
        "// Data: Debian glibc 2.36-9+deb12u14 en_US.utf8 LC_COLLATE.",
        "// The Free Software Foundation does not claim any copyright interest",
        "// in the locale data. See xsltcollationdata/PROVENANCE.md and sources.",
        "", "package xml", "",
    ]
    names = ["xsltCollationRules", "xsltCollationTable", "xsltCollationWeights",
             "xsltCollationExtra", "xsltCollationIndirect"]
    for name, section in zip(names, sections[1:]):
        lines.append("const " + name + " = \"\" +")
        for start in range(0, len(section), 32):
            chunk = section[start:start + 32]
            suffix = " +" if start + 32 < len(section) else ""
            lines.append('\t"' + ''.join('\\x%02x' % c for c in chunk) + '"' + suffix)
        lines.append("")
    (HERE.parent / "xslt_collation_table.go").write_text("\n".join(lines), encoding="ascii")


if __name__ == "__main__":
    generate()
