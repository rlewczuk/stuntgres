package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"strconv"
	"strings"
	"unicode/utf8"

	"stuntgres/internal/sqltype/pgencoding18"
)

type cns1Fact struct { cell uint16; scalar rune }

// Only this licensed three-record extract is an input, not a full second CNS
// map. Every fact must still be absent from the independently qualified PG map.
func parseCNS1Supplement(data []byte)([3]cns1Fact,error) {
	var facts [3]cns1Fact
	want:=[3]cns1Fact{{0x2728,0x4ea0},{0x272f,0x51ab},{0x2734,0x52f9}}
	count:=0
	scan:=bufio.NewScanner(bytes.NewReader(data))
	for line:=1;scan.Scan();line++ {
		s:=scan.Text();if s==""||strings.HasPrefix(s,"#"){continue}
		fields:=strings.Split(s,"\t")
		if len(fields)!=3 || len(fields[0])!=6 || !strings.HasPrefix(fields[0],"U+") || fields[1]!="kIRG_TSource" || len(fields[2])!=7 || !strings.HasPrefix(fields[2],"T1-") {return facts,fmt.Errorf("CNS1 line %d: malformed record",line)}
		scalar,e1:=strconv.ParseUint(fields[0][2:],16,32);cell,e2:=strconv.ParseUint(fields[2][3:],16,16)
		if e1!=nil||e2!=nil||scalar==0||!utf8.ValidRune(rune(scalar))||cell>>8<0x21||cell>>8>0x7e||cell&255<0x21||cell&255>0x7e {return facts,fmt.Errorf("CNS1 line %d: invalid cell/scalar",line)}
		fact:=cns1Fact{uint16(cell),rune(scalar)}
		if count>=len(facts)||fact!=want[count] {return facts,fmt.Errorf("CNS1 line %d: source inventory/order drift",line)}
		first,second:=pgencoding18.LookupUTF8(4,uint32(cell)|0x8080,2)
		if first!=0||second!=0 {return facts,fmt.Errorf("CNS1 line %d: existing release mapping at %04X",line,cell)}
		facts[count]=fact;count++
	}
	if err:=scan.Err();err!=nil{return facts,err}
	if count!=len(facts){return facts,fmt.Errorf("CNS1: inventory %d, want 3",count)}
	return facts,nil
}

func generateCNS1Supplement(facts [3]cns1Fact) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/xml/generate; DO NOT EDIT.\n// Unicode 16.0.0 Unihan_IRGSources.txt minimal extract.\n// Copyright 2024 Unicode, Inc.; Unicode License V3: data/LICENSE-Unicode.\npackage xml\n\n// rawCNS1Supplement contains only qualified additions absent from the PG map.\nfunc rawCNS1Supplement(cell uint16) rune {\n switch cell {\n")
	for _,fact:=range facts{fmt.Fprintf(&b," case 0x%04x: return 0x%04x\n",fact.cell,fact.scalar)}
	b.WriteString(" }; return 0\n}\n")
	out,err:=format.Source(b.Bytes());if err!=nil{panic(err)};return out
}
