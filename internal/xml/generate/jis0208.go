package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"strconv"
	"strings"
	"unicode/utf8"
)

// parseJIS0208 consumes the original Unicode Format A source, not a host codec.
// Zero is the unassigned-cell sentinel. Every assigned JIS0208 scalar is BMP.
func parseJIS0208(data []byte) ([94 * 94]uint16, error) {
	var table [94 * 94]uint16
	count := 0
	var previousCell uint64
	scan := bufio.NewScanner(bytes.NewReader(data))
	for line := 1; scan.Scan(); line++ {
		text := strings.TrimSpace(scan.Text())
		if text == "" || strings.HasPrefix(text, "#") { continue }
		row, comment, ok := strings.Cut(text, "#")
		fields := strings.Fields(row)
		if !ok || comment == "" || len(fields) != 3 { return table, fmt.Errorf("JIS0208 line %d: malformed row", line) }
		var values [3]uint64
		for i, field := range fields {
			if !strings.HasPrefix(field, "0x") { return table, fmt.Errorf("JIS0208 line %d: nonhex field", line) }
			v, err := strconv.ParseUint(field[2:], 16, 16)
			if err != nil { return table, fmt.Errorf("JIS0208 line %d: %w", line, err) }
			values[i] = v
		}
		sjisLead,sjisTrail:=int(values[0]>>8),int(values[0]&255)
		if !(sjisLead>=0x81&&sjisLead<=0x9f||sjisLead>=0xe0&&sjisLead<=0xef)||sjisTrail<0x40||sjisTrail>0xfc||sjisTrail==0x7f {
			return table,fmt.Errorf("JIS0208 line %d: invalid Shift-JIS source code",line)
		}
		cell, scalar := values[1], values[2]
		lead, trail := int(cell >> 8), int(cell & 255)
		if lead < 0x21 || lead > 0x7e || trail < 0x21 || trail > 0x7e || scalar == 0 || !utf8.ValidRune(rune(scalar)) {
			return table, fmt.Errorf("JIS0208 line %d: invalid cell/scalar", line)
		}
		at := (lead-0x21)*94 + trail-0x21
		if table[at] != 0 { return table, fmt.Errorf("JIS0208 line %d: duplicate cell", line) }
		if cell<=previousCell {return table,fmt.Errorf("JIS0208 line %d: cells out of order",line)}
		previousCell=cell
		table[at] = uint16(scalar)
		count++
	}
	if err := scan.Err(); err != nil { return table, err }
	if count != 6879 { return table, fmt.Errorf("JIS0208: assigned inventory %d, want 6879", count) }
	at := (0x21-0x21)*94 + 0x40-0x21
	if table[at] != 0x005c { return table, fmt.Errorf("JIS0208: original 2140 must be U+005C") }
	// Exhaustive independent PostgreSQL 18.6/libxml2 raw-reader qualification:
	// exactly this source cell differs. Preserve the original source unchanged.
	table[at] = 0xff3c
	return table, nil
}

func generateJIS0208(table [94 * 94]uint16) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/xml/generate; DO NOT EDIT.\n// Unicode JIS0208.TXT (2015), Unicode License V3: data/LICENSE-Unicode.\n// Pinned raw-reader correction: 2140 U+005C -> U+FF3C.\npackage xml\n\n// jis0208Data is an immutable big-endian BMP table; zero denotes a hole.\nconst jis0208Data = \"\" +\n")
	for at := 0; at < len(table); at += 32 {
		b.WriteByte('"')
		for _, value := range table[at:min(at+32, len(table))] { fmt.Fprintf(&b, "\\x%02x\\x%02x", value>>8, value&255) }
		b.WriteString("\" +\n")
	}
	b.WriteString("\"\"\n")
	out, err := format.Source(b.Bytes())
	if err != nil { panic(err) }
	return out
}
