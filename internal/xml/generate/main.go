// Command generate emits recognition-only switches from the pinned inventory.
package main

import (
 "bufio"
 "bytes"
 "fmt"
 "go/format"
 "os"
 "sort"
 "strconv"
 "strings"
)

type alias struct {canonical string; available,ambiguous bool}
type inventory struct {
 glibc,direct,algorithmic map[string]bool
 aliases map[string]alias
 observations map[string]bool
}
func parse(data []byte,complete bool)(inventory,error) {
 v:=inventory{map[string]bool{},map[string]bool{},map[string]bool{},map[string]alias{},map[string]bool{}}
 seen:=map[string]bool{}
 scan:=bufio.NewScanner(bytes.NewReader(data));scan.Buffer(make([]byte,4096),1<<20)
 line:=0
 for scan.Scan() {
  line++;s:=scan.Text();if s==""||strings.HasPrefix(s,"#"){continue}
  f:=strings.Split(s,"\t")
  bad:=func()(inventory,error){return v,fmt.Errorf("invalid recognition row %d",line)}
  if len(f)<2||f[1]==""||seen[f[0]+"\t"+f[1]] {return bad()};seen[f[0]+"\t"+f[1]]=true
  switch f[0] {
  case "G","D","K":
   if len(f)!=2||!encName(f[1]) {return bad()}
   switch f[0] {case "G":if strings.ToUpper(f[1])!=f[1]{return bad()};v.glibc[f[1]]=true;case "D":v.direct[f[1]]=true;case "K":v.algorithmic[normalize(f[1])]=true}
  case "A":
   if len(f)!=6||!printable(f[1])||!canonicalName(f[3])||f[2]==""||f[5]!="yes"&&f[5]!="no"||normalize(f[1])!=f[2] {return bad()}
   available:=false
   switch f[4] {case "shipped-cnv","algorithmic":available=true;case "not-in-cnv-or-algorithmic":default:return bad()}
   a:=alias{f[3],available,f[5]=="yes"}
   if _,ok:=v.aliases[f[2]];ok {return bad()};v.aliases[f[2]]=a
  case "O":
   if len(f)!=3||!encName(f[1])||f[2]!="ACCEPT"&&f[2]!="REJECT" {return bad()};v.observations[f[1]]=f[2]=="ACCEPT"
  default:return bad()
  }
 }
 if err:=scan.Err();err!=nil{return v,err}
 if complete {
  accepted:=0;for _,ok:=range v.observations {if ok {accepted++}}
  if len(v.glibc)!=1118||len(v.direct)!=190||len(v.aliases)!=1548||len(v.observations)!=2514||accepted!=2153 {return v,fmt.Errorf("incomplete pinned inventory")}
  for _,a:=range v.aliases {
   base,options,optioned:=strings.Cut(a.canonical,",")
   loadable:=v.direct[base]||v.algorithmic[normalize(base)]||normalize(base)=="iso2022"&&optioned&&strings.Contains(options,"locale=")
   if a.available!=loadable {return v,fmt.Errorf("unresolved preferred converter %q",a.canonical)}
  }
  for name:=range v.glibc {if !v.observations[name]{return v,fmt.Errorf("missing glibc observation %q",name)}}
  for name:=range v.direct {if !v.observations[name]{return v,fmt.Errorf("missing exact data observation %q",name)}}
 }
 return v,nil
}
func encName(s string) bool {
 for i:=range len(s) {b:=s[i];letter:=b>='A'&&b<='Z'||b>='a'&&b<='z';if !letter&&(i==0||!(b>='0'&&b<='9'||b=='.'||b=='_'||b=='-')) {return false}}
 return s!=""
}
func printable(s string) bool {if s==""{return false};for i:=range len(s){if s[i]<32||s[i]>126{return false}};return true}
func canonicalName(s string) bool {
 fields:=strings.Split(s,",")
 if !encName(fields[0]) {return false}
 seen:=map[string]bool{}
 for _,option:=range fields[1:] {
  if seen[option]{return false};seen[option]=true
  if option=="swaplfnl"{continue}
  key,value,ok:=strings.Cut(option,"=")
  if !ok||key!="locale"&&key!="version"||value==""{return false}
  if seen[key]{return false};seen[key]=true
  for i:=range len(value){b:=value[i];if !(b>='a'&&b<='z'||b>='A'&&b<='Z'||b>='0'&&b<='9'||b=='_'||b=='-'||b=='.'){return false}}
 }
 return true
}
func normalize(s string) string {
 var b strings.Builder;digit:=false
 for i:=range len(s) {
  c:=s[i];if c>='A'&&c<='Z'{c+='a'-'A'}
  if c>='a'&&c<='z' {b.WriteByte(c);digit=false}else if c>='0'&&c<='9' {
   if c=='0'&&!digit&&i+1<len(s)&&s[i+1]>='0'&&s[i+1]<='9' {continue};b.WriteByte(c);digit=true
  }else{digit=false}
 }
 return b.String()
}
func keys[V any](m map[string]V) []string {a:=make([]string,0,len(m));for k:=range m {a=append(a,k)};sort.Strings(a);return a}
func generate(v inventory) []byte {
 var b bytes.Buffer
 b.WriteString("// Code generated by internal/xml/generate; DO NOT EDIT.\n// Recognition names only: libxml2 2.9.14, glibc 2.36, ICU 72.1.\npackage xml\n\n")
 for _,set:=range []struct{name string;values map[string]bool}{{"glibcEncoding",v.glibc},{"directEncoding",v.direct},{"algorithmicEncoding",v.algorithmic}} {
  fmt.Fprintf(&b,"func %s(name string) bool {\n switch name {\n",set.name)
  for _,s:=range keys(set.values) {fmt.Fprintf(&b," case %s: return true\n",strconv.Quote(s))}
  b.WriteString(" }; return false\n}\n\n")
 }
 b.WriteString("func icuAlias(key string) (canonical string, available, ambiguous, found bool) {\n switch key {\n")
 for _,k:=range keys(v.aliases) {a:=v.aliases[k];fmt.Fprintf(&b," case %s: return %s, %t, %t, true\n",strconv.Quote(k),strconv.Quote(a.canonical),a.available,a.ambiguous)}
 b.WriteString(" }; return \"\", false, false, false\n}\n")
 formatted,err:=format.Source(b.Bytes());if err!=nil{panic(err)}
 return formatted
}
func main() {
 data,err:=os.ReadFile("internal/xml/data/recognition.tsv");if err!=nil{panic(err)}
 v,err:=parse(data,true);if err!=nil{panic(err)}
 if err=os.WriteFile("internal/xml/declaration_names_generated.go",generate(v),0644);err!=nil{panic(err)}
}
