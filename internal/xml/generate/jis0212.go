package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"strconv"
	"strings"
	"unicode/utf8"
)

// parseJIS0212 consumes the original Unicode Format A forward repertoire.
// The original file stays intact; one independently qualified scalar correction
// is applied only after validating its original value and complete inventory.
func parseJIS0212(data []byte) ([94 * 94]uint16,error) {
	var table [94 * 94]uint16
	count:=0
	var previous uint64
	scan:=bufio.NewScanner(bytes.NewReader(data))
	for line:=1;scan.Scan();line++ {
		text:=strings.TrimSpace(scan.Text())
		if text=="" || strings.HasPrefix(text,"#") { continue }
		row,comment,ok:=strings.Cut(text,"#")
		fields:=strings.Fields(row)
		if !ok || comment=="" || len(fields)!=2 { return table,fmt.Errorf("JIS0212 line %d: malformed row",line) }
		var values [2]uint64
		for i,field:=range fields {
			if !strings.HasPrefix(field,"0x") { return table,fmt.Errorf("JIS0212 line %d: nonhex field",line) }
			v,err:=strconv.ParseUint(field[2:],16,16)
			if err!=nil { return table,fmt.Errorf("JIS0212 line %d: %w",line,err) }
			values[i]=v
		}
		cell,scalar:=values[0],values[1]
		lead,trail:=int(cell>>8),int(cell&255)
		if lead<0x21 || lead>0x7e || trail<0x21 || trail>0x7e || scalar==0 || !utf8.ValidRune(rune(scalar)) { return table,fmt.Errorf("JIS0212 line %d: invalid cell/scalar",line) }
		at:=(lead-0x21)*94+trail-0x21
		if table[at]!=0 { return table,fmt.Errorf("JIS0212 line %d: duplicate cell",line) }
		if cell<=previous { return table,fmt.Errorf("JIS0212 line %d: cells out of order",line) }
		previous=cell;table[at]=uint16(scalar);count++
	}
	if err:=scan.Err();err!=nil { return table,err }
	if count!=6067 { return table,fmt.Errorf("JIS0212: assigned inventory %d, want 6067",count) }
	at:=(0x22-0x21)*94+0x37-0x21
	if table[at]!=0x007e { return table,fmt.Errorf("JIS0212: original 2237 must be U+007E") }
	// Sole difference in exhaustive pinned PostgreSQL18.6/libxml2 input proof.
	// Independently confirmed by matching glibc2.36 jis0212.c, first interval
	// start006C/index0 (222F), ninth forward entry FF5E (2237).
	table[at]=0xff5e
	return table,nil
}

func generateJIS0212(table [94 * 94]uint16) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/xml/generate; DO NOT EDIT.\n// Unicode JIS0212.TXT (2015), Unicode License V3: data/LICENSE-Unicode.\n// Pinned raw-reader correction: 2237 U+007E -> U+FF5E.\npackage xml\n\n// jis0212Data is an immutable big-endian BMP table; zero denotes a hole.\nconst jis0212Data = \"\" +\n")
	for at:=0;at<len(table);at+=32 {
		b.WriteByte('"')
		for _,value:=range table[at:min(at+32,len(table))] { fmt.Fprintf(&b,"\\x%02x\\x%02x",value>>8,value&255) }
		b.WriteString("\" +\n")
	}
	b.WriteString("\"\"\n")
	out,err:=format.Source(b.Bytes())
	if err!=nil { panic(err) }
	return out
}
