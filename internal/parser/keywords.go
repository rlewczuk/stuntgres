type keywordCategory byte

const (
	Unreserved       keywordCategory = 'U'
	ColumnName       keywordCategory = 'C'
	TypeFunctionName keywordCategory = 'T'
	Reserved         keywordCategory = 'R'
)

type keyword struct {
	word      string
	category  keywordCategory
	bareLabel bool
	token     int
}

func (k *keyword) columnName() bool {
	return k == nil || k.category == Unreserved || k.category == ColumnName
}
func (k *keyword) typeFunctionName() bool {
	return k == nil || k.category == Unreserved || k.category == TypeFunctionName
}
func (k *keyword) label() bool { return k == nil || k.bareLabel }

// lookupKeyword expects the scanner's ASCII-folded full spelling, before clipping.
func lookupKeyword(word string) *keyword {
	lo, hi := 0, len(keywords)
	for lo < hi {
		mid := lo + (hi-lo)/2
		if keywords[mid].word < word {
			lo = mid + 1
		} else {
			hi = mid
		}
	}
	if lo < len(keywords) && keywords[lo].word == word {
		return &keywords[lo]
	}
	return nil
}

// IdentifierNeedsQuotes follows PostgreSQL's identifier output rules, using
// the same keyword inventory as input rather than a second display inventory.
func IdentifierNeedsQuotes(name string) bool {
	quoted, _ := identifierNeedsQuotes(nil, name)
	return quoted
}

// IdentifierNeedsQuotesContext applies the same canonical inventory while
// bounding cancellation work for runtime identifier output.
func IdentifierNeedsQuotesContext(ctx context.Context, name string) (bool, error) {
	return identifierNeedsQuotes(ctx, name)
}

func identifierNeedsQuotes(ctx context.Context, name string) (bool, error) {
	if ctx != nil {
		if err := ctx.Err(); err != nil {
			return false, err
		}
	}
	if name == "" || !(name[0] >= 'a' && name[0] <= 'z' || name[0] == '_') {
		return true, nil
	}
	for i := 1; i < len(name); i++ {
		if ctx != nil && i&255 == 0 {
			if err := ctx.Err(); err != nil {
				return false, err
			}
		}
		c := name[i]
		if !(c >= 'a' && c <= 'z' || c >= '0' && c <= '9' || c == '_') {
			return true, nil
		}
	}
	// Comparisons are bounded by keyword spelling length, not payload length.
	k := lookupKeyword(name)
	return k != nil && k.category != Unreserved, nil
}

