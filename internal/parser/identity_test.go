package parser

import (
	"errors"
	"stuntgres/internal/sqlstate"
	"testing"
)

func TestIdentityGrammar(t *testing.T) {
	for _, query := range []string{
		`CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY)`,
		`CREATE TABLE i(id pg_catalog.int2 CONSTRAINT named GENERATED BY DEFAULT AS IDENTITY(SEQUENCE NAME public."actual" START 7 INCREMENT BY 3 CACHE 2 OWNED BY NONE))`,
		`INSERT INTO i OVERRIDING SYSTEM VALUE VALUES(99)`,
		`INSERT INTO i(id) OVERRIDING USER VALUE (VALUES(99))`,
		`ALTER TABLE i ALTER id ADD GENERATED ALWAYS AS IDENTITY`,
		`ALTER TABLE i ALTER id DROP IDENTITY IF EXISTS`,
		`ALTER TABLE i ALTER id SET GENERATED BY DEFAULT SET INCREMENT 3 RESTART WITH 20`,
		`ALTER TABLE i ALTER id RESTART 4`,
	} {
		statements, err := Parse(query)
		if err != nil || len(statements) != 1 {
			t.Fatal(query, statements, err)
		}
	}
	for _, query := range []string{`INSERT INTO i OVERRIDING SYSTEM VALUE DEFAULT VALUES`, `INSERT INTO i(id) DEFAULT VALUES`, `CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY) trailing junk`} {
		if _, err := Parse(query); err == nil {
			t.Fatal("invalid complete syntax admitted", query)
		}
	}
}
func TestIdentityGrammarOptionDiagnostics(t *testing.T) {
	for _, tc := range []struct{ query, name string }{
		{`ALTER TABLE i ALTER id SET OWNED BY NONE`, "owned_by"},
		{`ALTER TABLE i ALTER id SET RESTART WITH 4`, "restart"},
		{`ALTER TABLE i ALTER id SET AS bigint`, "as"},
	} {
		_, err := Parse(tc.query)
		var got *sqlstate.Error
		want := sqlstate.Error{Severity: "ERROR", SeverityUnlocalized: "ERROR", Code: "42601", Message: `sequence option "` + tc.name + `" not supported here`, Position: "28"}
		if !errors.As(err, &got) || *got != want {
			t.Fatalf("%s got=%#v want=%#v", tc.query, got, want)
		}
	}
}
