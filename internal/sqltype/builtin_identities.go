func completeBuiltinIdentities(supported []*Descriptor) []*Descriptor {
	byID := make(map[ID]*Descriptor, len(builtinIdentities))
	for _, d := range supported {
		byID[d.id] = d
	}
	result := make([]*Descriptor, 0, len(builtinIdentities))
	for _, fact := range builtinIdentities {
		d := byID[fact.id]
		if d == nil {
			d = &Descriptor{id: fact.id, name: fact.name, sql: fact.name, database: strings.ToUpper(fact.name), lookupOnly: true}
			byID[fact.id] = d
		}
		d.associatedArray, d.namespace = fact.array, fact.namespace
		if fact.id == 603 {
			d.delimiter = ';'
		}
		result = append(result, d)
	}
	for i, fact := range builtinIdentities {
		d := result[i]
		if fact.base != 0 {
			d.base = byID[fact.base].Usage()
			d.base.Typmod = fact.typmod
		}
		if fact.element != 0 {
			d.element = byID[fact.element]
			d.delimiter = d.element.Delimiter()
			d.sql = d.element.SQLName() + "[]"
			d.lookupOnly = d.element.ID() == Money || !d.element.Concrete() || !d.element.IsDomain() && !StoredScalarCastType(d.element.ID()) && d.element.ID() != Regclass
		}
	}
	return result
}

// NamespaceName is initialization provenance; catalog wrappers own namespace IDs.
func (d *Descriptor) NamespaceName() string { return d.namespace }

// LookupOnly creates a real identity without granting NULL, codec or storage authority.
func LookupOnly(id ID, name string, array ID) *Descriptor {
	return &Descriptor{id: id, name: name, sql: name, database: strings.ToUpper(name), lookupOnly: true, associatedArray: array}
}

// LookupArray constructs the identity association independently of stored arrays.
func LookupArray(id ID, name string, element *Descriptor) *Descriptor {
	return &Descriptor{id: id, name: name, sql: element.SQLName() + "[]", database: strings.ToUpper(name), element: element, lookupOnly: true, delimiter: element.Delimiter()}
}
