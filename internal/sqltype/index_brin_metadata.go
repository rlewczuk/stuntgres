func LookupBrinIndexClass(name string) (IndexClass, bool) {
	for _, f := range brinIndexClasses {
		if f.Name == name {
			family, _ := IndexFamilyMetadataByOID(f.Family)
			return NewIndexClass(IndexClassDefinition{OID: f.OID, Method: f.Method, Family: f.Family, Input: f.Input, Storage: f.KeyType, Name: f.Name, FamilyName: family.Name, Brin: true}), true
		}
	}
	return IndexClass{}, false
}
