package smoke_test

import (
	"bytes"
	"context"
	"fmt"
	"reflect"
	"stuntgres"
	"testing"
)

func TestSerialSmoke(t *testing.T) {
	db := identitySmokeDB(t)
	exec := func(q string,n int64) { identitySmokeExec(t,db,q,n) }
	exec(`CREATE TABLE widths(a SMALLSERIAL,b SERIAL,c BIGSERIAL)`,0)
	rows,err := db.Query(`SELECT * FROM widths`)
	if err != nil { t.Fatal(err) }
	metadata,err := rows.ColumnTypes()
	if err != nil || len(metadata) != 3 { t.Fatal(metadata,err) }
	for i,typ := range []string{"INT2","INT4","INT8"} {
		nullable,known := metadata[i].Nullable()
		if metadata[i].DatabaseTypeName() != typ || !known || nullable || metadata[i].ScanType() != reflect.TypeFor[int64]() { t.Fatal(metadata[i],nullable,known) }
	}
	rows.Close()
	held,err := db.Prepare(`INSERT INTO widths DEFAULT VALUES`)
	if err != nil { t.Fatal(err) }; defer held.Close()
	for range 2 {
		r,err := held.Exec()
		if err != nil { t.Fatal(err) }
		if n,err := r.RowsAffected(); err != nil || n != 1 { t.Fatal(n,err) }
	}
	exec(`INSERT INTO widths VALUES(100,100,100),(100,100,100)`,2)
	exec(`INSERT INTO widths DEFAULT VALUES`,1)
	identitySmokeRows(t,db,`SELECT * FROM widths ORDER BY a`,[][]any{{int64(1),int64(1),int64(1)},{int64(2),int64(2),int64(2)},{int64(3),int64(3),int64(3)},{int64(100),int64(100),int64(100)},{int64(100),int64(100),int64(100)}})
	_,err = db.Exec(`INSERT INTO widths VALUES(NULL,100,100)`)
	identitySmokeState(t,err,"23502")
	identitySmokeRows(t,db,`SELECT last_value FROM widths_a_seq`,[][]any{{int64(3)}})
	exec(`CREATE TABLE queried(id SERIAL,v TEXT)`,0)
	exec(`CREATE TABLE source(v TEXT)`,0)
	exec(`INSERT INTO queried(v) SELECT v FROM source`,0)
	exec(`INSERT INTO source VALUES('a'),('b')`,2)
	exec(`INSERT INTO queried(v) SELECT v FROM source ORDER BY v`,2)
	identitySmokeRows(t,db,`SELECT * FROM queried ORDER BY id`,[][]any{{int64(1),"a"},{int64(2),"b"}})
	for i,width := range []struct{alias string;max int64}{{"SMALLSERIAL",32767},{"SERIAL",2147483647},{"BIGSERIAL",9223372036854775807}} {
		name := fmt.Sprintf("endpoint%d",i)
		exec(`CREATE TABLE `+name+`(id `+width.alias+`)`,0)
		identitySmokeRows(t,db,fmt.Sprintf(`SELECT setval('%s_id_seq',%d,false)`,name,width.max),[][]any{{width.max}})
		exec(`INSERT INTO `+name+` DEFAULT VALUES`,1)
		_,err := db.Exec(`INSERT INTO `+name+` DEFAULT VALUES`)
		identitySmokeState(t,err,"2200H")
		_,err = db.Exec(fmt.Sprintf(`SELECT setval('%s_id_seq',0)`,name))
		identitySmokeState(t,err,"22003")
		identitySmokeRows(t,db,`SELECT * FROM `+name,[][]any{{width.max}})
	}
	exec(`CREATE TABLE owned(gone INT,id SERIAL,v TEXT)`,0)
	exec(`ALTER TABLE owned DROP COLUMN gone`,0)
	exec(`ALTER TABLE owned DROP COLUMN id RESTRICT`,0)
	exec(`CREATE SEQUENCE owned_id_seq`,0)
	exec(`CREATE TABLE dropped(id SERIAL)`,0)
	exec(`DROP TABLE dropped RESTRICT`,0)
	exec(`CREATE SEQUENCE dropped_id_seq`,0)
	exec(`CREATE TABLE dep(id SERIAL)`,0)
	_,err = db.Exec(`DROP SEQUENCE dep_id_seq RESTRICT`)
	identitySmokeState(t,err,"2BP01")
	exec(`DROP SEQUENCE dep_id_seq CASCADE`,0)
	_,err = db.Exec(`INSERT INTO dep DEFAULT VALUES`)
	identitySmokeState(t,err,"23502")
	exec(`CREATE TABLE called(id SERIAL)`,0)
	exec(`CREATE TABLE untouched(id SMALLSERIAL)`,0)
	exec(`INSERT INTO called VALUES(100),(100),(0),(-1)`,4)
	identitySmokeRows(t,db,`SELECT setval('called_id_seq',7,true)`,[][]any{{int64(7)}})
	exec(`ALTER SEQUENCE called_id_seq RENAME TO renamed`,0)
	// The consumer was created first, but its current default needs an inline
	// identity provider belonging to the later producer table during replay.
	exec(`CREATE TABLE consumer(id SERIAL)`,0)
	exec(`CREATE TABLE producer(id BIGINT GENERATED BY DEFAULT AS IDENTITY)`,0)
	exec(`ALTER TABLE consumer ALTER id SET DEFAULT nextval('producer_id_seq')`,0)
	exec(`INSERT INTO consumer DEFAULT VALUES`,1)
	exec(`INSERT INTO producer DEFAULT VALUES`,1)
	var dump bytes.Buffer
	ctx := context.Background()
	if err := stuntgres.Dump(ctx,db,&dump); err != nil { t.Fatal(err) }
	identitySmokeRows(t,db,`SELECT last_value FROM renamed`,[][]any{{int64(7)}})
	if err := stuntgres.Reset(ctx,db); err != nil { t.Fatal(err) }
	if err := stuntgres.Restore(ctx,db,bytes.NewReader(dump.Bytes())); err != nil { t.Fatal(err) }
	exec(`INSERT INTO consumer DEFAULT VALUES`,1)
	exec(`INSERT INTO producer DEFAULT VALUES`,1)
	identitySmokeRows(t,db,`SELECT id FROM consumer ORDER BY id`,[][]any{{int64(1)},{int64(3)}})
	identitySmokeRows(t,db,`SELECT id FROM producer ORDER BY id`,[][]any{{int64(2)},{int64(4)}})
	exec(`INSERT INTO called DEFAULT VALUES`,1)
	exec(`INSERT INTO untouched DEFAULT VALUES`,1)
	identitySmokeRows(t,db,`SELECT * FROM called ORDER BY id`,[][]any{{int64(-1)},{int64(0)},{int64(8)},{int64(100)},{int64(100)}})
	identitySmokeRows(t,db,`SELECT * FROM untouched`,[][]any{{int64(1)}})
}
