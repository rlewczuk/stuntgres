func identitySmokeDB(t *testing.T)*sql.DB{t.Helper();connector,err:=stuntgres.NewDriver().OpenConnector(t.Name());if err!=nil{t.Fatal(err)};db:=sql.OpenDB(connector);t.Cleanup(func(){db.Close()});return db}
func identitySmokeExec(t *testing.T,db *sql.DB,q string,n int64){t.Helper();r,err:=db.Exec(q);if err!=nil{t.Fatal(q,err)};if got,err:=r.RowsAffected();err!=nil||got!=n{t.Fatal(q,got,err)}}
func identitySmokeRows(t *testing.T,db *sql.DB,q string,want [][]any){t.Helper();rows,err:=db.Query(q);if err!=nil{t.Fatal(q,err)};defer rows.Close();columns,err:=rows.Columns();if err!=nil{t.Fatal(err)};var got [][]any;for rows.Next(){v:=make([]any,len(columns));dest:=make([]any,len(v));for i:=range v{dest[i]=&v[i]};if err:=rows.Scan(dest...);err!=nil{t.Fatal(err)};got=append(got,v)};if err:=rows.Err();err!=nil{t.Fatal(err)};if !reflect.DeepEqual(got,want){t.Fatalf("%s got=%v want=%v",q,got,want)}}
func identitySmokeState(t *testing.T,err error,code string){t.Helper();var state interface{SQLState()string};if !errors.As(err,&state)||state.SQLState()!=code{t.Fatalf("error=%v want=%s",err,code)}}

func TestIdentitySmoke(t *testing.T){
	db:=identitySmokeDB(t)
	identitySmokeExec(t,db,`CREATE TABLE a(id INT GENERATED ALWAYS AS IDENTITY,p INT DEFAULT 7)`,0)
	held,err:=db.Prepare(`INSERT INTO a DEFAULT VALUES`);if err!=nil{t.Fatal(err)};defer held.Close()
	if r,err:=held.Exec();err!=nil{t.Fatal(err)}else if n,err:=r.RowsAffected();err!=nil||n!=1{t.Fatal(n,err)}
	identitySmokeExec(t,db,`INSERT INTO a VALUES(DEFAULT,DEFAULT)`,1)
	_,err=db.Exec(`INSERT INTO a VALUES(99,9)`);identitySmokeState(t,err,"428C9")
	identitySmokeExec(t,db,`INSERT INTO a OVERRIDING SYSTEM VALUE VALUES(99,9)`,1)
	identitySmokeExec(t,db,`INSERT INTO a DEFAULT VALUES`,1)
	identitySmokeExec(t,db,`INSERT INTO a OVERRIDING USER VALUE VALUES(99,8)`,1)
	identitySmokeRows(t,db,`SELECT * FROM a ORDER BY id`,[][]any{{int64(1),int64(7)},{int64(2),int64(7)},{int64(3),int64(7)},{int64(4),int64(8)},{int64(99),int64(9)}})
	rows,err:=db.Query(`SELECT id FROM a WHERE false`);if err!=nil{t.Fatal(err)};types,err:=rows.ColumnTypes();if err!=nil{t.Fatal(err)};nullable,known:=types[0].Nullable();if types[0].DatabaseTypeName()!="INT4"||nullable||!known||types[0].ScanType()!=reflect.TypeOf(int64(0)){t.Fatal(types[0],nullable,known)};rows.Close()
	identitySmokeExec(t,db,`CREATE TABLE b(id INT GENERATED BY DEFAULT AS IDENTITY)`,0)
	for _,q:=range []string{`INSERT INTO b DEFAULT VALUES`,`INSERT INTO b VALUES(99)`,`INSERT INTO b VALUES(DEFAULT)`}{identitySmokeExec(t,db,q,1)}
	identitySmokeRows(t,db,`SELECT * FROM b ORDER BY id`,[][]any{{int64(1)},{int64(2)},{int64(99)}})
	identitySmokeExec(t,db,`CREATE TABLE opt(id INT GENERATED ALWAYS AS IDENTITY(START 7 INCREMENT 3))`,0)
	for range 2{identitySmokeExec(t,db,`INSERT INTO opt DEFAULT VALUES`,1)}
	identitySmokeRows(t,db,`SELECT * FROM opt ORDER BY id`,[][]any{{int64(7)},{int64(10)}})
	for _,tc:=range []struct{query string;last int64;called bool;n int64}{
		{`INSERT INTO shape OVERRIDING USER VALUE VALUES(nextval('side'),10)`,50,false,1},
		{`INSERT INTO shape OVERRIDING USER VALUE VALUES(nextval('side'),16),(nextval('side'),17)`,51,true,2},
		{`INSERT INTO shape OVERRIDING USER VALUE SELECT nextval('side'),14`,50,true,1},
	}{
		identitySmokeExec(t,db,`CREATE TABLE shape(id INT GENERATED ALWAYS AS IDENTITY,p INT)`,0);identitySmokeExec(t,db,`CREATE SEQUENCE side START 50 CACHE 1`,0)
		identitySmokeExec(t,db,tc.query,tc.n)
		identitySmokeRows(t,db,`SELECT last_value,is_called FROM side`,[][]any{{tc.last,tc.called}})
		identitySmokeExec(t,db,`DROP TABLE shape`,0);identitySmokeExec(t,db,`DROP SEQUENCE side`,0)
	}
	parameter,err:=db.Prepare(`INSERT INTO b OVERRIDING USER VALUE VALUES($1)`);if err!=nil{t.Fatal(err)};defer parameter.Close();_,err=parameter.Exec("bad");identitySmokeState(t,err,"22P02")
}

func TestIdentityLifecycleSmoke(t *testing.T){
	db:=identitySmokeDB(t);ctx:=context.Background();c,err:=db.Conn(ctx);if err!=nil{t.Fatal(err)};defer c.Close()
	exec:=func(q string){t.Helper();if _,err:=c.ExecContext(ctx,q);err!=nil{t.Fatal(q,err)}}
	exec(`CREATE TABLE a(id INT NOT NULL)`);exec(`INSERT INTO a VALUES(40)`);exec(`ALTER TABLE a ALTER id ADD GENERATED BY DEFAULT AS IDENTITY`)
	held,err:=c.PrepareContext(ctx,`INSERT INTO a DEFAULT VALUES`);if err!=nil{t.Fatal(err)};defer held.Close();if _,err=held.ExecContext(ctx);err!=nil{t.Fatal(err)}
	exec(`ALTER TABLE a ALTER id SET GENERATED ALWAYS SET INCREMENT 3 RESTART WITH 20`);if _,err=held.ExecContext(ctx);err!=nil{t.Fatal(err)}
	_,err=c.ExecContext(ctx,`DROP SEQUENCE a_id_seq CASCADE`);identitySmokeState(t,err,"2BP01")
	_,err=c.ExecContext(ctx,`ALTER SEQUENCE a_id_seq OWNED BY NONE`);identitySmokeState(t,err,"0A000")
	exec(`BEGIN`);exec(`SAVEPOINT s`);exec(`ALTER TABLE a ALTER id RESTART WITH 100`);exec(`ROLLBACK TO s`);exec(`ALTER TABLE a ALTER id DROP IDENTITY`);exec(`ROLLBACK`)
	if _,err=held.ExecContext(ctx);err!=nil{t.Fatal(err)}
	identitySmokeRows(t,db,`SELECT * FROM a ORDER BY id`,[][]any{{int64(1)},{int64(20)},{int64(23)},{int64(40)}})
	exec(`ALTER TABLE a ALTER id DROP IDENTITY`);_,err=held.ExecContext(ctx);identitySmokeState(t,err,"23502");exec(`INSERT INTO a VALUES(55)`)
	exec(`DROP TABLE a`)
	_,err=c.ExecContext(ctx,`SELECT nextval('a_id_seq')`);identitySmokeState(t,err,"42P01")
}

func TestIdentityControlsSmoke(t *testing.T){
	db:=identitySmokeDB(t);ctx:=context.Background()
	for _,q:=range []string{`CREATE TABLE narrow(id SMALLINT GENERATED ALWAYS AS IDENTITY)`,`ALTER SEQUENCE narrow_id_seq AS bigint MAXVALUE 100000 RESTART WITH 32768`,`COMMENT ON SEQUENCE narrow_id_seq IS 'divergent generator'`,`CREATE TABLE uncalled(id INT GENERATED BY DEFAULT AS IDENTITY(START 7 CACHE 2))`}{identitySmokeExec(t,db,q,0)}
	identitySmokeExec(t,db,`INSERT INTO narrow DEFAULT VALUES`,1)
	identitySmokeExec(t,db,`INSERT INTO uncalled VALUES(99)`,1)
	var dump bytes.Buffer;if err:=stuntgres.Dump(ctx,db,&dump);err!=nil{t.Fatal(err)}
	if err:=stuntgres.Reset(ctx,db);err!=nil{t.Fatal(err)};if err:=stuntgres.Restore(ctx,db,bytes.NewReader(dump.Bytes()));err!=nil{t.Fatal(err)}
	var again bytes.Buffer;if err:=stuntgres.Dump(ctx,db,&again);err!=nil{t.Fatal(err)};if !bytes.Equal(dump.Bytes(),again.Bytes()){t.Fatalf("redump mismatch\n%s\n%s",dump.Bytes(),again.Bytes())}
	identitySmokeExec(t,db,`INSERT INTO narrow DEFAULT VALUES`,1);identitySmokeExec(t,db,`INSERT INTO uncalled DEFAULT VALUES`,1)
	identitySmokeRows(t,db,`SELECT * FROM narrow ORDER BY id`,[][]any{{int64(-32768)},{int64(-32767)}})
	identitySmokeRows(t,db,`SELECT * FROM uncalled ORDER BY id`,[][]any{{int64(7)},{int64(99)}})
	if err:=stuntgres.Restore(ctx,db,bytes.NewBufferString(`CREATE TABLE bad(id INT GENERATED ALWAYS AS IDENTITY); INSERT INTO bad VALUES(4);`));err==nil{t.Fatal("invalid import accepted")}
	identitySmokeRows(t,db,`SELECT * FROM narrow ORDER BY id`,[][]any{{int64(-32768)},{int64(-32767)}})
}
