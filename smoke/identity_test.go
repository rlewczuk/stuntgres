func identitySmokeDB(t *testing.T) *sql.DB {
	t.Helper()
	connector, err := stuntgres.NewDriver().OpenConnector(t.Name())
	if err != nil {
		t.Fatal(err)
	}
	db := sql.OpenDB(connector)
	t.Cleanup(func() { db.Close() })
	return db
}
func identitySmokeExec(t *testing.T, db *sql.DB, q string, n int64) {
	t.Helper()
	r, err := db.Exec(q)
	if err != nil {
		t.Fatal(q, err)
	}
	if got, err := r.RowsAffected(); err != nil || got != n {
		t.Fatal(q, got, err)
	}
}
func identitySmokeRows(t *testing.T, db *sql.DB, q string, want [][]any) {
	t.Helper()
	rows, err := db.Query(q)
	if err != nil {
		t.Fatal(q, err)
	}
	defer rows.Close()
	columns, err := rows.Columns()
	if err != nil {
		t.Fatal(err)
	}
	var got [][]any
	for rows.Next() {
		v := make([]any, len(columns))
		dest := make([]any, len(v))
		for i := range v {
			dest[i] = &v[i]
		}
		if err := rows.Scan(dest...); err != nil {
			t.Fatal(err)
		}
		got = append(got, v)
	}
	if err := rows.Err(); err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("%s got=%v want=%v", q, got, want)
	}
}
func identitySmokeState(t *testing.T, err error, code string) {
	t.Helper()
	var state interface{ SQLState() string }
	if !errors.As(err, &state) || state.SQLState() != code {
		t.Fatalf("error=%v want=%s", err, code)
	}
}

func TestIdentitySmoke(t *testing.T) {
	db := identitySmokeDB(t)
	identitySmokeExec(t, db, `CREATE TABLE a(id INT GENERATED ALWAYS AS IDENTITY,p INT DEFAULT 7)`, 0)
	held, err := db.Prepare(`INSERT INTO a DEFAULT VALUES`)
	if err != nil {
		t.Fatal(err)
	}
	defer held.Close()
	if r, err := held.Exec(); err != nil {
		t.Fatal(err)
	} else if n, err := r.RowsAffected(); err != nil || n != 1 {
		t.Fatal(n, err)
	}
	identitySmokeExec(t, db, `INSERT INTO a VALUES(DEFAULT,DEFAULT)`, 1)
	_, err = db.Exec(`INSERT INTO a VALUES(99,9)`)
	identitySmokeState(t, err, "428C9")
	identitySmokeExec(t, db, `INSERT INTO a OVERRIDING SYSTEM VALUE VALUES(99,9)`, 1)
	identitySmokeExec(t, db, `INSERT INTO a DEFAULT VALUES`, 1)
	identitySmokeExec(t, db, `INSERT INTO a OVERRIDING USER VALUE VALUES(99,8)`, 1)
	identitySmokeRows(t, db, `SELECT * FROM a ORDER BY id`, [][]any{{int64(1), int64(7)}, {int64(2), int64(7)}, {int64(3), int64(7)}, {int64(4), int64(8)}, {int64(99), int64(9)}})
	rows, err := db.Query(`SELECT id FROM a WHERE false`)
	if err != nil {
		t.Fatal(err)
	}
	types, err := rows.ColumnTypes()
	if err != nil {
		t.Fatal(err)
	}
	nullable, known := types[0].Nullable()
	if types[0].DatabaseTypeName() != "INT4" || nullable || !known || types[0].ScanType() != reflect.TypeOf(int64(0)) {
		t.Fatal(types[0], nullable, known)
	}
	rows.Close()
	identitySmokeExec(t, db, `CREATE TABLE b(id INT GENERATED BY DEFAULT AS IDENTITY)`, 0)
	for _, q := range []string{`INSERT INTO b DEFAULT VALUES`, `INSERT INTO b VALUES(99)`, `INSERT INTO b VALUES(DEFAULT)`} {
		identitySmokeExec(t, db, q, 1)
	}
	identitySmokeRows(t, db, `SELECT * FROM b ORDER BY id`, [][]any{{int64(1)}, {int64(2)}, {int64(99)}})
	identitySmokeExec(t, db, `CREATE TABLE opt(id INT GENERATED ALWAYS AS IDENTITY(START 7 INCREMENT 3))`, 0)
	for range 2 {
		identitySmokeExec(t, db, `INSERT INTO opt DEFAULT VALUES`, 1)
	}
	identitySmokeRows(t, db, `SELECT * FROM opt ORDER BY id`, [][]any{{int64(7)}, {int64(10)}})
	for _, tc := range []struct {
		query  string
		last   int64
		called bool
		n      int64
	}{
		{`INSERT INTO shape OVERRIDING USER VALUE VALUES(nextval('side'),10)`, 50, false, 1},
		{`INSERT INTO shape OVERRIDING USER VALUE VALUES(nextval('side'),16),(nextval('side'),17)`, 51, true, 2},
		{`INSERT INTO shape OVERRIDING USER VALUE SELECT nextval('side'),14`, 50, true, 1},
	} {
		identitySmokeExec(t, db, `CREATE TABLE shape(id INT GENERATED ALWAYS AS IDENTITY,p INT)`, 0)
		identitySmokeExec(t, db, `CREATE SEQUENCE side START 50 CACHE 1`, 0)
		identitySmokeExec(t, db, tc.query, tc.n)
		identitySmokeRows(t, db, `SELECT last_value,is_called FROM side`, [][]any{{tc.last, tc.called}})
		identitySmokeExec(t, db, `DROP TABLE shape`, 0)
		identitySmokeExec(t, db, `DROP SEQUENCE side`, 0)
	}
	parameter, err := db.Prepare(`INSERT INTO b OVERRIDING USER VALUE VALUES($1)`)
	if err != nil {
		t.Fatal(err)
	}
	defer parameter.Close()
	_, err = parameter.Exec("bad")
	identitySmokeState(t, err, "22P02")
}

func TestIdentityLifecycleSmoke(t *testing.T) {
	db := identitySmokeDB(t)
	ctx := context.Background()
	c, err := db.Conn(ctx)
	if err != nil {
		t.Fatal(err)
	}
	defer c.Close()
	exec := func(q string) {
		t.Helper()
		if _, err := c.ExecContext(ctx, q); err != nil {
			t.Fatal(q, err)
		}
	}
	exec(`CREATE TABLE a(id INT NOT NULL)`)
	exec(`INSERT INTO a VALUES(40)`)
	exec(`ALTER TABLE a ALTER id ADD GENERATED BY DEFAULT AS IDENTITY`)
	held, err := c.PrepareContext(ctx, `INSERT INTO a DEFAULT VALUES`)
	if err != nil {
		t.Fatal(err)
	}
	defer held.Close()
	if _, err = held.ExecContext(ctx); err != nil {
		t.Fatal(err)
	}
	exec(`ALTER TABLE a ALTER id SET GENERATED ALWAYS SET INCREMENT 3 RESTART WITH 20`)
	if _, err = held.ExecContext(ctx); err != nil {
		t.Fatal(err)
	}
	_, err = c.ExecContext(ctx, `DROP SEQUENCE a_id_seq CASCADE`)
	identitySmokeState(t, err, "2BP01")
	_, err = c.ExecContext(ctx, `ALTER SEQUENCE a_id_seq OWNED BY NONE`)
	identitySmokeState(t, err, "0A000")
	exec(`BEGIN`)
	exec(`SAVEPOINT s`)
	exec(`ALTER TABLE a ALTER id RESTART WITH 100`)
	exec(`ROLLBACK TO s`)
	exec(`ALTER TABLE a ALTER id DROP IDENTITY`)
	exec(`ROLLBACK`)
	if _, err = held.ExecContext(ctx); err != nil {
		t.Fatal(err)
	}
	identitySmokeRows(t, db, `SELECT * FROM a ORDER BY id`, [][]any{{int64(1)}, {int64(20)}, {int64(23)}, {int64(40)}})
	exec(`ALTER TABLE a ALTER id DROP IDENTITY`)
	_, err = held.ExecContext(ctx)
	identitySmokeState(t, err, "23502")
	exec(`INSERT INTO a VALUES(55)`)
	exec(`DROP TABLE a`)
	_, err = c.ExecContext(ctx, `SELECT nextval('a_id_seq')`)
	identitySmokeState(t, err, "42P01")
}

func TestIdentityControlsSmoke(t *testing.T) {
	db := identitySmokeDB(t)
	ctx := context.Background()
	for _, q := range []string{`CREATE TABLE narrow(id SMALLINT GENERATED ALWAYS AS IDENTITY)`, `ALTER SEQUENCE narrow_id_seq AS bigint MAXVALUE 100000 RESTART WITH 32768`, `COMMENT ON SEQUENCE narrow_id_seq IS 'divergent generator'`, `CREATE TABLE uncalled(id INT GENERATED BY DEFAULT AS IDENTITY(START 7 CACHE 2))`} {
		identitySmokeExec(t, db, q, 0)
	}
	identitySmokeExec(t, db, `INSERT INTO narrow DEFAULT VALUES`, 1)
	identitySmokeExec(t, db, `INSERT INTO uncalled VALUES(99)`, 1)
	var dump bytes.Buffer
	if err := stuntgres.Dump(ctx, db, &dump); err != nil {
		t.Fatal(err)
	}
	if err := stuntgres.Reset(ctx, db); err != nil {
		t.Fatal(err)
	}
	if err := stuntgres.Restore(ctx, db, bytes.NewReader(dump.Bytes())); err != nil {
		t.Fatal(err)
	}
	var again bytes.Buffer
	if err := stuntgres.Dump(ctx, db, &again); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(dump.Bytes(), again.Bytes()) {
		t.Fatalf("redump mismatch\n%s\n%s", dump.Bytes(), again.Bytes())
	}
	identitySmokeExec(t, db, `INSERT INTO narrow DEFAULT VALUES`, 1)
	identitySmokeExec(t, db, `INSERT INTO uncalled DEFAULT VALUES`, 1)
	identitySmokeRows(t, db, `SELECT * FROM narrow ORDER BY id`, [][]any{{int64(-32768)}, {int64(-32767)}})
	identitySmokeRows(t, db, `SELECT * FROM uncalled ORDER BY id`, [][]any{{int64(7)}, {int64(99)}})
	if err := stuntgres.Restore(ctx, db, bytes.NewBufferString(`CREATE TABLE bad(id INT GENERATED ALWAYS AS IDENTITY); INSERT INTO bad VALUES(4);`)); err == nil {
		t.Fatal("invalid import accepted")
	}
	identitySmokeRows(t, db, `SELECT * FROM narrow ORDER BY id`, [][]any{{int64(-32768)}, {int64(-32767)}})
}

func identitySmokeDiagnostic(t *testing.T, err error, want stuntgres.Error) {
	t.Helper()
	want.Severity, want.SeverityUnlocalized = "ERROR", "ERROR"
	var got *stuntgres.Error
	if !errors.As(err, &got) || *got != want {
		t.Fatalf("error=%#v (%v), want=%#v", got, err, want)
	}
}

func TestIdentityFailureDemandSmoke(t *testing.T) {
	for _, side := range []bool{false, true} {
		for _, prepared := range []bool{false, true} {
			t.Run(fmt.Sprintf("early/side=%t/prepared=%t", side, prepared), func(t *testing.T) {
				db := identitySmokeDB(t)
				ctx := t.Context()
				c, err := db.Conn(ctx)
				if err != nil {
					t.Fatal(err)
				}
				defer c.Close()
				options := "MINVALUE 0 MAXVALUE 1 START 1 CACHE 1"
				later := "$2"
				args := []any{nil, 8}
				if side {
					options = "MINVALUE 0 MAXVALUE 10 START 1 CACHE 1"
					later = "nextval('side')"
					args = args[:1]
				}
				for _, q := range []string{`CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY(` + options + `),p INT NOT NULL)`, `CREATE SEQUENCE side START 50 CACHE 1`} {
					if _, err = c.ExecContext(ctx, q); err != nil {
						t.Fatal(q, err)
					}
				}
				query := `INSERT INTO i VALUES(DEFAULT,$1),(DEFAULT,` + later + `)`
				var held *sql.Stmt
				if prepared {
					held, err = c.PrepareContext(ctx, query)
					if err != nil {
						t.Fatal(err)
					}
					defer held.Close()
				}
				run := func() (sql.Result, error) {
					if prepared {
						return held.ExecContext(ctx, args...)
					}
					return c.ExecContext(ctx, query, args...)
				}
				identitySmokeRows(t, db, `SELECT last_value,is_called FROM i_id_seq`, [][]any{{int64(1), false}})
				result, err := run()
				if result != nil {
					t.Fatal("failed batch returned a result")
				}
				identitySmokeDiagnostic(t, err, stuntgres.Error{Code: "23502", Message: `null value in column "p" of relation "i" violates not-null constraint`, Detail: "Failing row contains (1, null).", Schema: "public", Table: "i", Column: "p"})
				identitySmokeRows(t, db, `SELECT * FROM i`, nil)
				identitySmokeRows(t, db, `SELECT last_value,is_called FROM i_id_seq`, [][]any{{int64(1), true}})
				identitySmokeRows(t, db, `SELECT last_value,is_called FROM side`, [][]any{{int64(50), false}})
				var memory int64
				for _, q := range []string{`SELECT currval('i_id_seq')`, `SELECT lastval()`} {
					if err = c.QueryRowContext(ctx, q).Scan(&memory); err != nil || memory != 1 {
						t.Fatal(q, memory, err)
					}
				}
				identitySmokeDiagnostic(t, c.QueryRowContext(ctx, `SELECT currval('side')`).Scan(&memory), stuntgres.Error{Code: "55000", Message: `currval of sequence "side" is not yet defined in this session`})
				first := int64(2)
				payload := int64(50)
				if !side {
					if _, err = c.ExecContext(ctx, `ALTER TABLE i ALTER id RESTART WITH 0`); err != nil {
						t.Fatal(err)
					}
					first = 0
					payload = 8
				}
				args[0] = 7
				result, err = run()
				if err != nil {
					t.Fatal("healthy reuse", err)
				}
				if n, err := result.RowsAffected(); err != nil || n != 2 {
					t.Fatal(n, err)
				}
				identitySmokeRows(t, db, `SELECT * FROM i ORDER BY id`, [][]any{{first, int64(7)}, {first + 1, payload}})
				for _, q := range []string{`SELECT currval('i_id_seq')`, `SELECT lastval()`} {
					if err = c.QueryRowContext(ctx, q).Scan(&memory); err != nil || memory != first+1 {
						t.Fatal(q, memory, err)
					}
				}
			})
		}
	}
	for _, tc := range []struct {
		name, source string
		fails, side  bool
		payloads     []int64
	}{
		{"multi_values", `VALUES(CAST($1::text AS integer),7),(0,8)`, true, false, []int64{7, 8}},
		{"ordered_select", `SELECT CAST($1::text AS integer),p FROM inputs ORDER BY 1`, true, false, []int64{7}},
		{"ordered_values", `VALUES(CAST($1::text AS integer),7),(0,8) ORDER BY 1`, true, false, []int64{8, 7}},
		{"single_values", `VALUES(CAST($1::text AS integer),7)`, false, false, []int64{7}},
		{"select", `SELECT CAST($1::text AS integer),7`, false, false, []int64{7}},
		{"single_decorated", `VALUES(CAST($1::text AS integer),7) LIMIT 1`, false, false, []int64{7}},
		{"volatile_select", `SELECT CAST(CASE WHEN nextval('side')>0 THEN $1::text ELSE '' END AS integer),7`, true, true, []int64{7}},
	} {
		for _, prepared := range []bool{false, true} {
			t.Run(fmt.Sprintf("conversion/%s/prepared=%t", tc.name, prepared), func(t *testing.T) {
				db := identitySmokeDB(t)
				ctx := t.Context()
				c, err := db.Conn(ctx)
				if err != nil {
					t.Fatal(err)
				}
				defer c.Close()
				for _, q := range []string{`CREATE TABLE i(id INT GENERATED ALWAYS AS IDENTITY(CACHE 1),p INT)`, `CREATE SEQUENCE side START 50 CACHE 1`, `CREATE TABLE inputs(p INT)`, `INSERT INTO inputs VALUES(7)`} {
					if _, err = c.ExecContext(ctx, q); err != nil {
						t.Fatal(q, err)
					}
				}
				query := `INSERT INTO i OVERRIDING USER VALUE ` + tc.source
				var held *sql.Stmt
				if prepared {
					held, err = c.PrepareContext(ctx, query)
					if err != nil {
						t.Fatal("Prepare demanded conversion", err)
					}
					defer held.Close()
				}
				run := func(value string) (sql.Result, error) {
					if prepared {
						return held.ExecContext(ctx, value)
					}
					return c.ExecContext(ctx, query, value)
				}
				identitySmokeRows(t, db, `SELECT last_value,is_called FROM i_id_seq`, [][]any{{int64(1), false}})
				result, err := run("bad")
				var want [][]any
				if tc.fails {
					if result != nil {
						t.Fatal("failed conversion returned result")
					}
					identitySmokeDiagnostic(t, err, stuntgres.Error{Code: "22P02", Message: `invalid input syntax for type integer: "bad"`})
					identitySmokeRows(t, db, `SELECT * FROM i`, nil)
					identitySmokeRows(t, db, `SELECT last_value,is_called FROM i_id_seq`, [][]any{{int64(1), false}})
					var memory int64
					identitySmokeDiagnostic(t, c.QueryRowContext(ctx, `SELECT currval('i_id_seq')`).Scan(&memory), stuntgres.Error{Code: "55000", Message: `currval of sequence "i_id_seq" is not yet defined in this session`})
					if tc.side {
						if err = c.QueryRowContext(ctx, `SELECT lastval()`).Scan(&memory); err != nil || memory != 50 {
							t.Fatal(memory, err)
						}
					} else {
						identitySmokeDiagnostic(t, c.QueryRowContext(ctx, `SELECT lastval()`).Scan(&memory), stuntgres.Error{Code: "55000", Message: "lastval is not yet defined in this session"})
					}
				} else {
					if err != nil {
						t.Fatal("pruned conversion ran", err)
					}
					if n, err := result.RowsAffected(); err != nil || n != int64(len(tc.payloads)) {
						t.Fatal(n, err)
					}
					want = [][]any{{int64(1), int64(7)}}
					identitySmokeRows(t, db, `SELECT * FROM i`, want)
				}
				identitySmokeRows(t, db, `SELECT last_value,is_called FROM side`, [][]any{{int64(50), tc.side}})
				result, err = run("8")
				if err != nil {
					t.Fatal("healthy reuse", err)
				}
				if n, err := result.RowsAffected(); err != nil || n != int64(len(tc.payloads)) {
					t.Fatal(n, err)
				}
				for _, p := range tc.payloads {
					want = append(want, []any{int64(len(want) + 1), p})
				}
				identitySmokeRows(t, db, `SELECT * FROM i ORDER BY id`, want)
				var memory int64
				for _, q := range []string{`SELECT currval('i_id_seq')`, `SELECT lastval()`} {
					if err = c.QueryRowContext(ctx, q).Scan(&memory); err != nil || memory != int64(len(want)) {
						t.Fatal(q, memory, err)
					}
				}
				last := int64(50)
				if tc.side {
					last = 51
				}
				identitySmokeRows(t, db, `SELECT last_value,is_called FROM side`, [][]any{{last, tc.side}})
			})
		}
	}
}
